<h2 id="earnings">How much can you make on Fiverr?</h2>
<p>Fiverr does not publish typical seller earnings, and results vary enormously by skill and effort, so think in terms of your own math. Your take-home is orders per month times average order value times 0.8. Ten $60 orders a month is $480 after Fiverr's cut; twenty $150 orders is $2,400. The fastest lever is usually average order value, not volume: better packages, extras and repeat clients lift income without adding hours. Use the <a href="/tools/freelance-rate-calculator/">freelance rate calculator</a> to work backward from a monthly goal to the price and order count you need.</p>
<p>Also track your effective hourly rate. A $50 gig that takes four hours of revisions pays $10 an hour after fees. If a package routinely runs over, tighten the scope, limit revisions, or raise the price.</p>

<h2 id="account-risks">Rules that can get your account in trouble</h2>
<ul>
  <li><strong>Taking payment off Fiverr.</strong> Asking a buyer you met on Fiverr to pay you directly violates the terms of service and is one of the quickest ways to lose your account.</li>
  <li><strong>Sharing contact details early.</strong> Fiverr's message system flags email addresses and phone numbers. Keep communication on the platform.</li>
  <li><strong>Fake or swapped reviews.</strong> Buying reviews or trading orders with other sellers is detectable and can lead to a ban.</li>
  <li><strong>Missing deadlines and cancellations.</strong> Late deliveries and cancellations drag down your Success Score. Set realistic delivery times and use the "extend delivery" request when needed, before the deadline passes.</li>
  <li><strong>Undisclosed AI use where it matters.</strong> If you use AI tools in your workflow, be honest with buyers about what they are getting and check the current Fiverr policies for your category.</li>
</ul>

