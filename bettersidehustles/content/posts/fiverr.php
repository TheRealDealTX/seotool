<p>If you have an audience of business owners or creators, Fiverr Affiliates pays when someone you refer places their first order. Fiverr's partner pages describe commission as a share of that first order (25% for marketplace gigs, 70% for Fiverr Pro) plus a 10% revenue share on that buyer's purchases for 12 months, with other plans for specific products. Terms vary by plan and change, so confirm in your dashboard. Project your earnings with the <a href="/tools/affiliate-commission-calculator/">affiliate commission calculator</a>.</p>

<h2 id="taxes">Taxes on Fiverr income</h2>
<p>Fiverr earnings are self-employment income. Fiverr collects tax information from US sellers and may issue a 1099 form depending on your earnings, but you owe tax on all of it either way. Set aside money for income and self-employment tax from every withdrawal; the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a> shows how much. Software, equipment and a share of your internet bill are often deductible.</p>

