<h2 id="nebraska-taxes">Nebraska taxes and rules for side income</h2>
<ul>
  <li><strong>State income tax:</strong> Nebraska's top rate is 4.55% for 2026, down from 5.2% for 2025, and more cuts are scheduled. Lower brackets apply to the first slice of income.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit, plus federal income tax. Estimate your set-aside with the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a>.</li>
  <li><strong>Sales tax on goods and some services:</strong> Nebraska's state rate is 5.5%, and Omaha adds a local sales tax on top. Unlike many states, Nebraska taxes building cleaning and maintenance (including residential cleaning) and pest control.</li>
  <li><strong>Licensing:</strong> there's no general statewide business license. Register a trade name with the Secretary of State if you use one, and check for city permits for food, trades and other regulated activities.</li>
</ul>
