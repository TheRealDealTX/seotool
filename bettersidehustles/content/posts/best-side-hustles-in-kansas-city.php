<h2 id="missouri-taxes">Missouri taxes and other rules</h2>
<ul>
  <li><strong>State income tax:</strong> Missouri's top rate is 4.7%, with further cuts possible if revenue triggers are met.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit. Estimate your set-aside with the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a>.</li>
  <li><strong>Business license:</strong> KCMO requires businesses operating in the city to register and get a license unless exempt by state law. Home-based businesses may need zoning clearance.</li>
  <li><strong>Sales tax:</strong> selling physical products requires a Missouri sales tax license. Most personal services aren't taxed.</li>
  <li><strong>Kansas side:</strong> if you live in Overland Park, Olathe or another Kansas suburb, Kansas income tax and city rules apply instead.</li>
</ul>

