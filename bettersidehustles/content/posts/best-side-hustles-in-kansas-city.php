<h2 id="earnings-tax">The KCMO earnings tax: what side hustlers need to know</h2>
<p>Kansas City, Missouri, is one of the few cities in the region with a local income tax. It's a 1% earnings tax, and it applies to:</p>
<ul>
  <li><strong>Residents of KCMO</strong> on their earned income, wherever they earn it.</li>
  <li><strong>Nonresidents</strong> on income they earn working inside the city limits.</li>
  <li><strong>Businesses operating in the city</strong> on their net profits, including self-employed people and sole proprietors. The city even publishes a tax guide aimed at rideshare drivers.</li>
</ul>
<p>Voters renewed the tax in April 2026, so it stays in place for at least another five years. If you run a side hustle in KCMO, expect to register with the city and file a profits return in addition to your state and federal returns. The city's Revenue Division has forms and guides.</p>
<div class="callout callout-warn"><strong>Watch out:</strong> Kansas City is split across Missouri and Kansas, and parts of KCMO sit in Jackson, Clay, Platte and Cass counties. Your address determines whether the earnings tax applies to you, so check before you assume.</div>

