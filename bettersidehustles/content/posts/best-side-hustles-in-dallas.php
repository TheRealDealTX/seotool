<h2 id="dallas-taxes">Texas taxes and Dallas rules</h2>
<ul>
  <li><strong>No state income tax.</strong> Texas doesn't tax personal income, so you owe federal income tax plus 15.3% self-employment tax on net profit. Estimate it with the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a> and pay quarterly if you'll owe $1,000 or more.</li>
  <li><strong>Sales tax.</strong> Dallas's combined rate is typically 8.25%. Texas also taxes some services, including many lawn, landscaping and cleaning jobs. Register for a free sales tax permit from the Comptroller if yours is taxable.</li>
  <li><strong>Assumed name.</strong> File a DBA with the Dallas County Clerk (or Collin or Denton County) if you use a business name.</li>
  <li><strong>Short-term rentals.</strong> Dallas's 2023 ordinance limiting STRs in single-family zones has been blocked by court injunctions while litigation continues, so check the city's current status. Hosts owe state and city hotel occupancy taxes.</li>
  <li><strong>Notaries.</strong> Commissions run four years and are issued by the Texas Secretary of State.</li>
</ul>
