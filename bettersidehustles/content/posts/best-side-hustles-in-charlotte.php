<h2 id="nc-taxes">North Carolina taxes and Charlotte rules</h2>
<ul>
  <li><strong>State income tax:</strong> a flat 3.99% for 2026, with further reductions scheduled in coming years.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit, on top of federal income tax. Use the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a> to estimate your set-aside.</li>
  <li><strong>Sales tax:</strong> the state rate is 4.75%, plus county taxes. North Carolina also taxes many repair, maintenance and installation services, so handymen and detailers should check whether their work is taxable.</li>
  <li><strong>Business license:</strong> Charlotte has no general business license requirement, but zoning rules apply to home-based businesses, and some trades need state licensing.</li>
</ul>
<div class="callout"><strong>Quick tip:</strong> Keep receipts for supplies, phone service and every business mile. Those deductions reduce both your income tax and your self-employment tax.</div>

