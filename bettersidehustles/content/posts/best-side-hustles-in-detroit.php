<h2 id="michigan-detroit-taxes">Michigan and Detroit taxes on side income</h2>
<ul>
  <li><strong>Michigan income tax:</strong> a flat 4.25% for the 2026 tax year, confirmed by the Michigan Department of Treasury.</li>
  <li><strong>Detroit city income tax:</strong> 2.4% for residents on all income, including net profit from a side business, and 1.2% for nonresidents on income earned in Detroit. Most suburbs do not have a city income tax, though a few Michigan cities do.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit, on top of federal income tax. The <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a> estimates your set-aside.</li>
  <li><strong>Sales tax:</strong> Michigan's 6% sales tax applies to most goods, with no local add-ons. If you sell products, register with the state for a sales tax license.</li>
  <li><strong>Licensing:</strong> Detroit licenses certain business types and short-term rentals, and residential building and repair work above minor jobs can require a state license.</li>
</ul>
<div class="callout callout-warn"><strong>Watch out:</strong> Detroit residents combine 4.25% state and 2.4% city tax, plus federal income and self-employment tax. Set aside roughly 30% of side hustle profit until you know your real number.</div>

