<h2 id="ohio-tax-rules">Ohio, Cincinnati and Kentucky tax rules</h2>
<ul>
  <li><strong>Cincinnati income tax:</strong> 1.8% on wages and on net profit from self-employment, for residents and for people who work in the city. Suburbs set their own rates.</li>
  <li><strong>Ohio income tax:</strong> a flat 2.75% on nonbusiness income above $26,050 starting in 2026. Self-employment profit is generally business income, and Ohio's business income deduction exempts the first $250,000, so many side hustlers owe little state tax on it. City tax still applies.</li>
  <li><strong>Federal self-employment tax:</strong> 15.3% on net profit, plus federal income tax. Run your numbers in the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a>.</li>
  <li><strong>Sales tax:</strong> selling taxable goods requires an Ohio vendor's license; Ohio's state rate is 5.75% plus a county add-on.</li>
  <li><strong>Across the river:</strong> Kentucky cities and counties such as Covington and Newport levy occupational license taxes on work done there. If you regularly work in Northern Kentucky, check those local rules.</li>
</ul>

