<h2 id="oklahoma-taxes">Oklahoma taxes and rules for side hustlers</h2>
<ul>
  <li><strong>State income tax:</strong> Oklahoma lowered its top rate to 4.5% for 2026 and cut the number of brackets, with possible further cuts tied to revenue triggers.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit, on top of federal income tax. The <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a> estimates your set-aside.</li>
  <li><strong>Sales tax:</strong> if you sell physical products, you'll need an Oklahoma sales tax permit. Most personal services aren't taxed, but check before you sell anything tangible.</li>
  <li><strong>Licensing:</strong> there's no general state business license. Home-based businesses in Oklahoma City need to follow home occupation zoning rules, and food, trades and short-term rentals have their own permits. Confirm with the city's development center.</li>
</ul>
<div class="callout callout-warn"><strong>Watch out:</strong> After big hail storms, OKC fills with out-of-town roofing crews. Don't promise homeowners anything about insurance claims, and don't take roofing work unless you're properly registered for it.</div>

