<h2 id="taxes-rules">Colorado taxes and Aurora rules</h2>
<ul>
  <li><strong>State income tax:</strong> Colorado's flat rate is 4.4% for 2025 returns; it can drop in surplus years, so check the current rate.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit. The <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a> shows how much to save.</li>
  <li><strong>Sales tax:</strong> Aurora is a home-rule city that collects its own sales tax. Selling taxable products means registering with the city as well as the state.</li>
  <li><strong>No OPT:</strong> Aurora's occupational privilege tax was repealed as of January 1, 2025. Denver's still exists if you work inside Denver.</li>
  <li><strong>Licensed activities:</strong> short-term rentals, food sales and regulated trades have their own rules. Check the city's business services office.</li>
</ul>
<div class="callout callout-warn"><strong>Watch out:</strong> Aurora crosses three counties (Arapahoe, Adams and Douglas), and HOA rules vary a lot from one subdivision to the next. Read your HOA covenants before running a business that brings clients or vehicles to your home.</div>

