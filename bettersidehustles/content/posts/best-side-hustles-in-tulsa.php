<h2 id="oklahoma-rules">Oklahoma taxes and Tulsa rules</h2>
<ul>
  <li><strong>State income tax:</strong> Oklahoma's top rate fell to 4.5% for 2026, with fewer brackets than before.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit. Use the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a> to estimate quarterly payments.</li>
  <li><strong>Sales tax:</strong> selling physical products requires an Oklahoma sales tax permit. Most personal services aren't taxed.</li>
  <li><strong>Licensing:</strong> there's no general state business license, and most simple service gigs don't need a general city license. Home businesses must follow zoning rules, and food, trades and short-term rentals have their own requirements. Check with the City of Tulsa.</li>
</ul>
