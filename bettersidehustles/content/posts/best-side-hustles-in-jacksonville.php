<h2 id="taxes-rules">Florida taxes and Jacksonville rules</h2>
<ul>
  <li><strong>No state income tax:</strong> Florida doesn't tax personal income.</li>
  <li><strong>Federal taxes:</strong> income tax plus 15.3% self-employment tax on net profit. Pay quarterly estimates once you expect to owe $1,000 or more.</li>
  <li><strong>Local business tax receipt:</strong> Jacksonville's consolidated city-county government issues it through the Duval County Tax Collector. The independent beach cities and neighboring counties have their own rules.</li>
  <li><strong>Sales tax:</strong> product sellers register with the Florida Department of Revenue and collect the state rate plus the Duval County surtax.</li>
  <li><strong>Short-term rentals:</strong> hosts owe state and county tourist taxes unless the platform remits them, and should check local zoning before listing.</li>
</ul>

