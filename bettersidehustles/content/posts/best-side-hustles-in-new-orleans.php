<h2 id="louisiana-taxes">Louisiana taxes and New Orleans rules</h2>
<ul>
  <li><strong>State income tax:</strong> Louisiana moved to a flat 3% income tax starting in 2025 and raised its standard deduction.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit. Use the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a> to estimate quarterly payments.</li>
  <li><strong>Occupational license:</strong> most New Orleans businesses, including home-based ones, need a city occupational license, which renews every year.</li>
  <li><strong>Tour guides:</strong> paid guides need a city tour guide license.</li>
  <li><strong>Short-term rentals:</strong> residential permits generally require owner-occupancy with a homestead exemption, and the rules have changed often. Verify permits before cleaning or co-hosting for anyone.</li>
  <li><strong>Sales tax:</strong> if you sell goods, register with the Louisiana Department of Revenue and the city. Combined state and local sales tax in Orleans Parish is high, so build it into your prices.</li>
</ul>
