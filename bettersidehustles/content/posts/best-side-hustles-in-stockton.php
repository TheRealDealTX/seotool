<h2 id="taxes">Stockton and California tax rules</h2>
<ul>
  <li><strong>California income tax:</strong> progressive rates from 1% to 12.3%, plus 1% on income above $1 million.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit. Run your numbers with the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a>.</li>
  <li><strong>Stockton business license tax:</strong> the city requires a business license, and self-employed people and independent contractors owe the business tax. Depending on your activity, it's an annual registration tax plus a gross-receipts or flat amount.</li>
  <li><strong>Home Occupation Permit:</strong> required for home-based businesses in Stockton, alongside the business license.</li>
  <li><strong>Seller's permit:</strong> if you sell physical goods, register with the CDTFA and collect sales tax.</li>
  <li><strong>AB5:</strong> hiring helpers? California's ABC test usually makes them employees. App drivers are generally contractors under Proposition 22.</li>
</ul>

