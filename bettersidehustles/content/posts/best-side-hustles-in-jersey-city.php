<h2 id="nj-taxes">New Jersey taxes and Jersey City rules</h2>
<ul>
  <li><strong>State income tax:</strong> graduated rates from 1.4% to 10.75%, with the top rate reserved for income above $1 million.</li>
  <li><strong>No resident city income tax:</strong> Jersey City's payroll tax applies to employers, not to self-employed residents' income.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit. Estimate it with the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a>.</li>
  <li><strong>Sales tax:</strong> 6.625% on most goods; register for a sales tax certificate if you sell products. Some Jersey City businesses qualify for reduced Urban Enterprise Zone rates.</li>
  <li><strong>Working in New York:</strong> side income earned while physically working in New York can trigger New York nonresident tax, with a credit on your New Jersey return.</li>
</ul>

