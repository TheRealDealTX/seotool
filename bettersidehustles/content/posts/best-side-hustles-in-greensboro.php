<h2 id="nc-taxes">North Carolina taxes and Greensboro rules</h2>
<ul>
  <li><strong>State income tax:</strong> a flat 3.99% for 2026, with further cuts scheduled in later years.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit, plus federal income tax. Use the <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a> to estimate it.</li>
  <li><strong>Sales tax:</strong> the state rate is 4.75%, plus local tax. Resale goods and many repair and installation services are taxable in North Carolina.</li>
  <li><strong>Business license:</strong> there's no general city business license, but home occupation zoning rules apply, and you'll need an assumed business name filing if you use a brand.</li>
</ul>

