<h2 id="oregon-taxes">Oregon, Portland and Multnomah County taxes</h2>
<ul>
  <li><strong>Oregon income tax:</strong> progressive, from 4.75% to 9.9%. Most side income lands in the 8.75% bracket or higher. Make quarterly estimated payments if you expect to owe $1,000 or more.</li>
  <li><strong>Self-employment tax:</strong> 15.3% federal on net profit. Our <a href="/tools/self-employment-tax-calculator/">self-employment tax calculator</a> helps you plan.</li>
  <li><strong>Portland Business License Tax:</strong> 2.6% of net business income. You're exempt if total gross receipts are under $75,000 for 2026, rising to $100,000 from 2027.</li>
  <li><strong>Multnomah County Business Income Tax:</strong> 2% of net business income, with an exemption for gross receipts under $100,000.</li>
  <li><strong>Registration:</strong> required within 60 days of starting business in Portland or Multnomah County, including rideshare driving, even if you fall under the exemption.</li>
  <li><strong>Other local taxes:</strong> Portland residents pay the $35 Arts Tax, and higher earners also pay Metro's Supportive Housing Services tax and Multnomah County's Preschool for All tax.</li>
</ul>
<div class="callout callout-warn"><strong>Watch out:</strong> Live in Vancouver, Washington and work in Portland? Washington has no income tax, but Oregon still taxes income you earn in Oregon, including side-hustle income from Oregon clients and jobs. Check with a tax professional.</div>

