<h1>Roommate safety tips</h1>
<ul class="checklist">
<li><strong>Chat here first.</strong> Keep early conversations on <?= e(setting('site_name')) ?> until you feel comfortable sharing a phone number.</li>
<li><strong>Video call before meeting.</strong> It confirms they are who they say they are.</li>
<li><strong>Meet in public</strong> the first time, and tell a friend where you’ll be.</li>
<li><strong>Never send money</strong> for a deposit or “holding fee” to someone you haven’t met, or for a unit you haven’t toured with the leasing office.</li>
<li><strong>Tour with the property.</strong> Confirm availability and pricing directly with the apartment community’s leasing office.</li>
<li><strong>Get it in writing.</strong> Both roommates should be on the lease, and agree on rent split, bills, chores and guests up front.</li>
<li><strong>Trust your gut.</strong> If something feels off, block and report the profile — our team reviews every report.</li>
</ul>
