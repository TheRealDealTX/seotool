<li><strong>Climbing the roof yourself.</strong> Wet or granule-covered shingles are slippery, and walking on damaged shingles can make things worse.</li>
<li><strong>Making permanent repairs before documenting.</strong> Temporary tarping is fine, but take photos first and keep the damaged materials if you can.</li>
<li><strong>Assuming no leak means no damage.</strong> Functional hail damage often shows up as shortened roof life rather than an immediate drip.</li>
