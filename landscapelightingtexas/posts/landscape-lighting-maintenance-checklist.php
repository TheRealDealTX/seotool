<h2>When to Call a Professional</h2>

<ul>
<li>The GFCI or transformer breaker keeps tripping.</li>
<li>A whole zone is out and the cause is not obvious.</li>
<li>The transformer hums loudly, smells hot or shows burn marks.</li>
<li>Several fixtures are corroded, filling with water or failing repeatedly.</li>
<li>You want to add fixtures, move lights or change the design.</li>
<li>Anything involves the 120-volt outlet, circuit or hardwired connection.</li>
</ul>

