<h2>Annual Professional Tune-Up</h2>

<p>Even if you keep up with the checklist, a yearly professional visit catches what is hard to see from the lawn. Whether you hire Landscape Lighting Texas or another qualified installer, a thorough tune-up typically includes:</p>

<ul>
<li>Measuring voltage at fixtures and adjusting transformer taps where runs have drifted.</li>
<li>Opening and resealing connections that show corrosion, especially in humid and coastal areas.</li>
<li>Replacing worn gaskets, cracked lenses and damaged fixture stems or stakes.</li>
<li>Re-aiming and repositioning fixtures as trees and beds have matured.</li>
<li>Re-burying exposed cable and checking cable under new plantings or hardscape.</li>
<li>Inspecting the transformer, timer and photocell, and updating schedules.</li>
<li>Recommending upgrades such as LED retrofits, added zones or <a href="/services/smart-lighting-systems/">smart controls</a>.</li>
</ul>

