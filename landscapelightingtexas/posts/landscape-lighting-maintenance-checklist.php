<p class="lead-p">A good low-voltage system is built to last, but Texas weather works on it every day: hail and freezes, 100-degree afternoons, sprinkler overspray, oak pollen and plants that double in size in a single summer. This landscape lighting maintenance checklist breaks the year into Texas seasons, adds a five-minute monthly walkaround, and finishes with a troubleshooting table so you can tell a quick fix from a job for a professional.</p>

<p>None of this takes long. Most homeowners can handle the seasonal items in an evening or two a year, and catching small problems early, such as a fixture knocked off aim or a green, corroded connection, keeps them from turning into a dark zone or a failed transformer.</p>

<h2>Before You Start: Tools and Safety</h2>

<p>You do not need much. A soft cloth, a bucket of water with a little mild dish soap, a soft brush, pruners, a flashlight, a replacement lamp or two if your fixtures use them, and a basic digital multimeter if you are comfortable using one.</p>

