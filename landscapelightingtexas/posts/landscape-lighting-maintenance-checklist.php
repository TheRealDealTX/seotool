<h2>Frequently Asked Questions</h2>

<h3>How often should landscape lighting be maintained?</h3>
<p>Do a quick walkaround once a month, a seasonal check four times a year, and schedule a professional tune-up once a year. Properties near the coast or with heavy irrigation may benefit from more frequent connection checks.</p>

<h3>How do I clean landscape lighting fixtures?</h3>
<p>Turn the system off, then wipe lenses with a soft cloth and water with a little mild soap. Use a little white vinegar on hard-water spots and rinse. Avoid abrasive pads, pressure washers and harsh chemicals, which can damage finishes and seals.</p>

<h3>Why did my landscape lights stop working after it rained?</h3>
<p>Water may have tripped the GFCI outlet, or found its way into a poorly sealed connection or fixture. Reset the GFCI first. If it trips again or a section stays dark, a connection or fixture likely needs to be found and resealed.</p>

<h3>Do I need to change my landscape lighting timer for daylight saving time?</h3>
<p>Mechanical and basic digital timers need resetting twice a year. Astronomical timers and most smart controllers follow sunset automatically. Our <a href="/tools/dusk-timer/">Texas dusk timer</a> shows sunset times by month for your city.</p>

