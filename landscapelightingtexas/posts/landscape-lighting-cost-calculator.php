<h2>How to Read the Calculator Results</h2>

<h3>Estimated Project Range</h3>
<p>The headline result is a range, for example $5,200–$6,500, covering fixtures, labor, transformer, basic wiring, connectors, selected controls and options. It is a range because several costs remain unknown until the property is inspected: actual cable distances, transformer location, soil, fixture brand, access, existing electrical capacity, hardscape, irrigation conflicts, final beam angles and scheduling. Use it to judge affordability and compare versions of the project.</p>

<h3>Total Fixture Count</h3>
<p>Fewer than 10 fixtures usually covers one entry, facade or patio. Fifteen to 25 fixtures may cover the front yard or several features. Larger properties can need 30 or more when the design includes architecture, trees, paths, pool and security. More fixtures do not automatically produce a better result; placement matters more than quantity.</p>

<h3>Recommended Transformer Size</h3>
<p>A low-voltage transformer steps household 120V power down to about 12V for the outdoor system. The calculator recommends a size based on total wattage plus a safe operating margin. If your fixtures draw 120 watts, it will suggest a larger transformer, commonly a 150- or 200-watt unit, rather than matching the load exactly, so the transformer never runs at its limit and has room to grow. A professional still has to confirm cable lengths, voltage drop, load distribution and zones. Check the details with the <a href="/tools/transformer-calculator/">transformer and voltage drop calculator</a>.</p>

<h3>Connected LED Load</h3>
<p>The connected load is the combined wattage of all fixtures. For example, six uplights at 6 watts (36 W), six path lights at 4 watts (24 W) and four tree lights at 7 watts (28 W) total 88 watts before adding anything else. Connected load drives both transformer selection and energy use.</p>

<h3>Monthly and Annual Energy Cost</h3>
<p>The simplified formula is:</p>
<p><strong>Total watts × nightly hours × 30 days ÷ 1,000 = monthly kWh</strong>, then multiply by your rate.</p>
<p>Actual use varies with seasonal schedules, dimming, photocells, timers and zones, but the estimate is ideal for comparing a six-hour schedule with dusk to dawn.</p>

<h3>Itemized Cost Breakdown</h3>
<p>The breakdown separates fixtures and equipment, professional installation, transformer, wiring and materials, controls and options, and the subtotal. That shows which decisions move the number most: architectural-grade fixtures raise equipment cost, while difficult trenching raises labor.</p>

