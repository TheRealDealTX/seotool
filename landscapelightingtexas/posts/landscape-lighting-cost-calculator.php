<h3>Add the Appropriate System Options</h3>
<p><strong>Smart lighting controls</strong> add scheduling, zone management, remote operation, dimming and smart-home integration. They shine when areas need different schedules, for instance keeping the entry lit later than the backyard. Learn more about <a href="/services/smart-lighting-systems/">smart lighting systems</a>.</p>
<p><strong>Additional lighting zone.</strong> A zone lets part of the system run independently. Common zones include the front yard, backyard, pool and patio, security fixtures, trees and entertainment settings. Zones add flexibility but may need extra controls, cable or transformer capacity.</p>
<p><strong>Existing-system removal.</strong> Select this when damaged, outdated or abandoned fixtures and wire must come out first. It can take longer than expected when the original cable routes are unclear.</p>
<p><strong>Difficult hardscape or trenching.</strong> Choose this when cable must pass under or around pavers, concrete, stone paths, retaining walls, driveways or heavily compacted ground. It often requires boring or sleeving to avoid damage.</p>
<p><strong>Future expansion allowance.</strong> This adds about 20% spare transformer capacity for a later phase such as the backyard, pool or trees. Spare capacity alone does not guarantee the cable layout can support every addition; the design still needs to account for voltage drop, wire gauge and future fixture locations.</p>

