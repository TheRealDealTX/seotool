<h2>What the Calculator Cannot See</h2>
<p>No online tool can fully evaluate a property. The calculator cannot inspect exact cable routes, buried utilities, irrigation lines, drainage, mature roots, existing electrical faults, transformer mounting locations, voltage-drop conditions, hardscape thickness, fixture glare, neighboring properties, final aiming angles or local requirements such as HOA rules.</p>
