<h3>Operating Cost: The Math</h3>
<p>Take a 20-fixture LED system averaging 5 watts per fixture: 100 watts. At six hours a night, that is 0.6 kWh per night, or about 18 kWh per month. At 15 cents per kWh, that is roughly $2.70 a month for the lighting itself. Whole-property systems with more fixtures, higher-output floods, all-night zones and transformer losses land higher; they typically run <strong>$10–$25 a month</strong>. The same layout on 20-watt halogen lamps would draw about 400 watts and cost four to five times as much, since LEDs use about 75–80% less energy. Compare your own numbers with the <a href="/tools/energy-savings-calculator/">LED energy savings calculator</a>.</p>

