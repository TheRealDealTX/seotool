<h2>Best color temperature by material</h2>

<h3>Limestone and Austin stone</h3>
<p>Texas limestone has cream, honey and buff tones. 2700K warms those tones and makes the texture glow when grazed with a narrow beam. Cooler light can make limestone look gray or chalky. Our <a href="/services/architectural-uplighting/">architectural uplighting</a> service covers grazing techniques in detail.</p>

<h3>Red and brown brick</h3>
<p>Red brick looks rich and inviting under 2700K. Under 4000K and above it can turn dull and slightly pink. For painted white brick, 3000K is usually the better choice, because it keeps the paint looking clean rather than yellow.</p>

<h3>Stucco</h3>
<p>White and light stucco can look yellow under very warm light. 3000K keeps it crisp while still feeling warm. Earth-toned or tan stucco often suits 2700K. Test both on your wall at dusk before you commit.</p>

<h3>Trees and foliage</h3>
<p>For live oaks, cedar elms and most green foliage, 2700K brings out bark texture and rich green tones. Plants with blue-gray or silver leaves, such as agave, Texas sage or olive, can look striking at 3000K, and occasionally a single 4000K accent on a silver specimen plant works. Keep any cooler accent subtle. Our guide to <a href="/how-to-light-live-oak-trees/">how to light live oak trees</a> covers tree-specific choices.</p>

