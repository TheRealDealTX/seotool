<h2>CRI: how true colors look</h2>

<p>Color Rendering Index (CRI) measures how accurately a light source shows colors compared with natural light, on a scale up to 100. Cheap LEDs can sit in the low 80s or below, which makes foliage look dull and brick look muddy. For landscape lighting, look for a CRI of 90 or higher. High-CRI fixtures show the true red of brick, the cream of limestone and the green of leaves, and they make the same lumens look better.</p>

<h2>Dark-sky and wildlife-friendly warm light</h2>

<p>Texas has some of the darkest skies in the country, especially in the Hill Country and West Texas, and several communities have adopted dark-sky lighting rules. Warm light is part of the solution. Light at 3000K and below contains less blue light, which scatters more in the atmosphere and affects insects, birds and other wildlife more than warm light.</p>
<ul>
  <li>Use 2700K or warmer in rural and Hill Country settings; 2200K suits very dark sites.</li>
  <li>Shield every fixture and aim it at its target, not the sky.</li>
  <li>Use the lowest output that does the job, and dim zones late at night.</li>
  <li>Put zones on timers so lights turn off when nobody is outside. The <a href="/tools/dusk-timer/">Texas Dusk Timer</a> helps set schedules.</li>
</ul>

<h2>Regional considerations across Texas</h2>

<p>The same Kelvin number can feel different depending on where you live and what surrounds your home.</p>
<ul>
  <li><strong>Hill Country and Central Texas.</strong> Limestone, live oaks and dark rural skies all point to 2700K, or 2200K on very dark acreage. Several Hill Country communities encourage or require dark-sky friendly lighting.</li>
  <li><strong>Houston and the Gulf Coast.</strong> Humid air scatters light, so cooler fixtures can look hazy. Warm 2700K–3000K keeps palms, pools and lush beds looking natural.</li>
  <li><strong>Dallas–Fort Worth.</strong> Red and brown brick is common, and 2700K flatters it. Newer modern builds with white brick or stucco often look sharper at 3000K.</li>
  <li><strong>West Texas.</strong> Desert plantings with silver and blue-gray foliage can take 3000K well, while wide-open night skies reward warm, well-shielded light.</li>
</ul>

<h2>How to test color temperature on your home</h2>

<p>Photos and product swatches only go so far. The most reliable way to choose is to see the options on your own walls and plants after dark.</p>
<ol>
  <li><strong>Test at full dark, not dusk.</strong> Light looks different against a bright evening sky than it does at 9pm.</li>
  <li><strong>Compare side by side.</strong> Place a 2700K and a 3000K fixture a few feet apart on the same wall or tree.</li>
  <li><strong>View from where it matters.</strong> Look from the street, the driveway and the patio, not just up close.</li>
  <li><strong>Check your paint and stone colors.</strong> Warm whites can push cream paint toward yellow and gray paint toward beige.</li>
  <li><strong>Think about the whole property.</strong> The choice for the facade should work for the trees and paths too.</li>
</ol>
<p>If you are replacing old halogen lamps, remember that most halogen landscape lamps sit near 2700K–2900K. Choosing 2700K LEDs keeps the familiar look while cutting energy use by roughly 75–80%. Our <a href="/led-vs-halogen-landscape-lighting/">LED vs halogen comparison</a> covers the switch in detail.</p>

<h2>Color-changing RGBW fixtures: when to use them</h2>

<p>RGBW fixtures combine red, green, blue and white LEDs, so you can choose any color or dial a white from warm to cool. They are tempting, but most of the time a well-designed warm white system looks better and costs less.</p>
<p>Color-changing fixtures make sense for:</p>
<ul>
  <li><strong>Holidays and events.</strong> Red and green for Christmas, orange for fall, team colors on game day.</li>
  <li><strong>Pools, fountains and water features.</strong> Color scenes look natural in water.</li>
  <li><strong>Tunable white.</strong> Adjusting from 2700K to 3000K to match a new paint color or a change in plants.</li>
</ul>
