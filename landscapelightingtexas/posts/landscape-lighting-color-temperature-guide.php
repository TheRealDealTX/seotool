<h3>Water</h3>
<p>Pool water already looks blue-green from the pool light, so the surrounding landscape usually looks best at 2700K–3000K for contrast. Submerged fountain and pond lights are often fine at 3000K, which keeps the water clear and sparkling without turning it icy.</p>

<h2>Consistency and binning</h2>

<p>Not every "2700K" LED is the same. Manufacturers sort LED chips into bins by their measured color, and lower-quality fixtures may come from wider bins. The result is fixtures that look slightly pink, green or yellow side by side, even though the box says the same number.</p>
<ul>
  <li>Choose fixtures from one manufacturer and one product line for each area.</li>
  <li>Look for tight color tolerance; quality brands specify a 3-step MacAdam ellipse or better.</li>
  <li>When replacing or adding fixtures later, match the original brand and color temperature.</li>
  <li>Avoid mixing old halogen lamps with new LEDs in the same view.</li>
</ul>

