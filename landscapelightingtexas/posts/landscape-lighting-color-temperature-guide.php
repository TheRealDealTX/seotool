<h2>What color temperature means</h2>

<p>Color temperature describes how warm or cool white light looks, measured in Kelvin (K). Lower numbers look warmer, more amber and candle-like. Higher numbers look cooler, whiter and eventually bluish.</p>
<ul>
  <li><strong>2200K</strong> is close to candlelight or an old-fashioned filament bulb.</li>
  <li><strong>2700K</strong> matches the warm glow of a classic halogen landscape lamp.</li>
  <li><strong>3000K</strong> is a soft, clean warm white.</li>
  <li><strong>4000K</strong> is a neutral white, common in offices and parking lots.</li>
  <li><strong>5000K</strong> is a cool, daylight white with a blue cast at night.</li>
</ul>
<p>Kelvin describes the look of the light, not its brightness. A 2700K fixture and a 4000K fixture can put out the same lumens. At night, though, our eyes are more sensitive to cooler light, so cool fixtures often feel brighter and harsher than their numbers suggest.</p>

