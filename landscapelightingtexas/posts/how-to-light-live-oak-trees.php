<h2>Frequently Asked Questions</h2>

<h3>How many lights does it take to light a large live oak?</h3>
<p>Most mature live oaks with a 35–50 foot canopy look best with three to four uplights and two or three optional moonlights. Smaller trees may only need one or two fixtures.</p>

<h3>Does landscape lighting harm live oak trees?</h3>
<p>Not when installed properly. Use hand trenching near roots, avoid the critical root zone, mount fixtures without girdling and avoid wounding oaks from February through June because of oak wilt.</p>

<h3>What beam angle is best for uplighting a tree?</h3>
<p>A 25° beam is the most versatile choice for oak limbs and inner canopy. Use 10–15° for the trunk or very tall trees and 36–60° for broad, low canopies.</p>

<h3>Is moonlighting worth it?</h3>
<p>For large oaks over a patio, lawn or driveway, yes. Moonlighting creates the most natural-looking effect in landscape lighting and adds gentle, useful light to the space below the tree.</p>

