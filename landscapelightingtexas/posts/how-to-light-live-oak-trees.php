<h3>Mount fixtures without girdling</h3>
<p>Tree-mount fixtures should be attached with a single stainless lag or an adjustable strap that leaves room for growth. Never wrap wire tightly around a limb. Run wire up the trunk in a UV-stable conduit or a loose channel and leave a service loop so the tree can grow without pulling on the cable.</p>

