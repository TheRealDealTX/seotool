<h2>Uplighting vs moonlighting vs downlighting</h2>

<p>Each technique creates a different effect. Most great live oak designs combine at least two.</p>

<h3>Uplighting</h3>
<p>Fixtures sit on the ground and aim up into the tree. Uplighting shows off the trunk, the sweep of the main limbs and the underside of the canopy. It is the most common technique and the easiest to adjust. On a live oak, the goal is to light the structure, not just the leaves: aim some fixtures at the trunk and inner limbs and others toward the outer canopy.</p>

<h3>Moonlighting</h3>
<p>Fixtures mount high in the tree, typically 20–30 feet up, and aim down through the branches. The light passes through the leaves and casts soft, dappled shadows on the lawn, patio or driveway below, like moonlight through the canopy. Moonlighting is subtle and natural, and it doubles as useful ambient light for outdoor living spaces under the tree.</p>

<h3>Downlighting</h3>
<p>Downlighting is a broader term for any fixture aimed down from above, from a tree, an eave or a pergola. In a tree it is usually a more focused version of moonlighting, used to light a specific area such as a seating group, a path or a driveway turnaround.</p>

