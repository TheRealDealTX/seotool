<h2>Wiring tree lights the right way</h2>

<p>Large oaks often sit far from the house, so the wire runs are long. Voltage drop over a long run makes the farthest fixtures dimmer and can shift their color. Use 12- or 10-gauge low-voltage cable for longer runs, consider hub wiring so every fixture in the tree gets the same voltage, and power the zone from a multi-tap transformer so you can compensate for distance. Keep connections above grade or in sealed, waterproof connectors, since Texas clay holds water after heavy rain. Our <a href="/tools/transformer-calculator/">transformer and voltage drop calculator</a> helps size the run.</p>

<h2>Glare control</h2>

<p>Glare is the most common complaint about tree lighting. A bright lamp seen directly from the street, a window or the patio is uncomfortable and ruins the effect.</p>
<ul>
  <li>Use fixtures with deep shrouds or glare cowls so the light source is recessed.</li>
  <li>Aim uplights away from the main viewing direction.</li>
  <li>Use well lights flush with the ground in lawn areas so there is nothing to see or trip over.</li>
  <li>Use honeycomb louvers on high-output fixtures near patios and pools.</li>
  <li>Check every fixture from the street, the driveway and inside the house before calling the job done.</li>
</ul>

<h2>Color temperature for live oak foliage</h2>

<p>2700K is the default choice for live oaks. It brings out the warm browns and grays of the bark and gives the dark green leaves a rich, natural tone. 3000K works on oaks near a modern or white facade where the whole design runs a little cooler. Avoid 4000K and above on trees; the leaves turn bluish and flat, and cool light is harder on night skies and wildlife. Our <a href="/landscape-lighting-color-temperature-guide/">color temperature guide</a> goes into more detail.</p>

<h2>Common mistakes to avoid</h2>
<ol>
  <li><strong>One light on a big tree.</strong> It lights a single face and makes the oak look flat.</li>
  <li><strong>Over-lighting.</strong> A tree brighter than the house pulls the eye away from everything else.</li>
  <li><strong>Aiming into the lens line of sight.</strong> Glare from the street or the patio.</li>
  <li><strong>Trenching through roots.</strong> Machine trenchers cut feeder roots and can damage the tree for years.</li>
  <li><strong>Wounding oaks in spring.</strong> Mounting fixtures between February and June raises oak wilt risk.</li>
  <li><strong>Mixing color temperatures.</strong> A cool fixture next to warm ones stands out immediately.</li>
  <li><strong>Forgetting growth.</strong> Fixtures that are perfect today may be buried in branches in three years.</li>
</ol>

<h2>Maintenance as the tree grows</h2>

<p>Live oaks keep growing, and a lighting design needs to grow with them. Plan for a check-up once or twice a year:</p>
<ul>
  <li>Re-aim uplights as the canopy widens or limbs drop with weight.</li>
  <li>Trim foliage around fixtures, and leave openings where moonlights shine through.</li>
  <li>Loosen straps and check tree mounts for any sign of growing into the bark.</li>
  <li>Clean lenses after the spring leaf drop, when live oaks shed old leaves and pollen.</li>
  <li>Move or add fixtures as the tree expands past the original layout.</li>
</ul>
