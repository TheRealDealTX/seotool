<p class="lead-p">Knowing how to light live oak trees well is one of the most valuable skills in Texas landscape lighting. A mature live oak is often the single biggest feature on a property: wide, low, twisting limbs and a dense evergreen canopy that looks good every month of the year. Light it carelessly and it becomes a flat green blob with a hot spot on the trunk. Light it with care and it becomes the centerpiece of your whole night scene.</p>

<p>This guide covers the three main techniques, how many fixtures you need for a given canopy, which beam angles and outputs to use, where to place fixtures, and how to protect the roots and the tree itself during installation.</p>

