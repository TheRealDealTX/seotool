<p>These are planning ranges, not rules. A tree viewed mainly from one side, such as a front-yard oak seen from the street, can often be lit with fewer fixtures concentrated on the visible face. An oak in the middle of a backyard that you see from all sides needs fixtures all the way around it.</p>

<h2>Choosing beam angles</h2>

<p>The beam angle controls how wide the light spreads. Narrow beams reach high and pick out the trunk and limbs; wide beams fill the canopy with softer light.</p>

<div class="table-wrap"><table>
  <thead><tr><th>Beam angle</th><th>Best use on a live oak</th></tr></thead>
  <tbody>
    <tr><td>10–15° (spot)</td><td>Grazing the trunk, picking out one dramatic limb, reaching tall canopies</td></tr>
    <tr><td>25° (narrow flood)</td><td>Main limbs and the inner canopy; the workhorse for most oaks</td></tr>
    <tr><td>36–40° (flood)</td><td>Filling the underside of a broad canopy from a few feet back</td></tr>
