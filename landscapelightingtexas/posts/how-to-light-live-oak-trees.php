<h2>How many lumens?</h2>

<p>LED landscape fixtures for trees typically range from 300 to 1,200 lumens. Live oak leaves are small, dark and glossy, so they absorb more light than a pale-barked tree. That said, more is rarely better. A tree that outshines the house throws off the whole design. Start in the middle of the range and use dimmable fixtures or a multi-tap transformer so you can fine-tune output on-site after dark. Our post on <a href="/led-vs-halogen-landscape-lighting/">LED vs halogen landscape lighting</a> explains why LEDs give you more control at a fraction of the running cost.</p>

<h2>Fixture placement: distance from the trunk</h2>

<p>Where you put the fixture matters as much as what you put in it.</p>
<ul>
  <li><strong>Trunk grazing:</strong> 1–2 feet from the trunk, aimed nearly straight up with a narrow beam. This brings out bark texture and the twist of the trunk.</li>
  <li><strong>Limb and canopy lighting:</strong> 3–6 feet from the trunk, aimed outward and up into the main limbs.</li>
  <li><strong>Outer canopy:</strong> near the drip line or just inside it, aimed back toward the center so the edge of the canopy glows.</li>
  <li><strong>Moonlights:</strong> high on main limbs, 20–30 feet up, aimed down through gaps in the foliage rather than through solid leaf mass.</li>
</ul>
<p>Place most uplights on the side of the tree that faces the main viewing points (the street, the patio, the main windows), aimed away from viewers and into the tree. That way people see the lit trunk and canopy, not the lamp.</p>

<h2>Protecting live oak roots and health</h2>

<p>Live oaks are long-lived, valuable and sensitive. A good lighting installation leaves no lasting mark on the tree.</p>

<h3>Hand-trench near the tree</h3>
<p>Most of an oak's feeder roots are in the top 12–18 inches of soil and extend well past the drip line. Low-voltage landscape lighting wire typically only needs to be buried a few inches deep, so there is no reason to use a trencher near a tree. Near the trunk, we hand-dig narrow slits or pull wire through with a flat spade, working around roots rather than cutting them.</p>

<h3>No trenching inside the critical root zone</h3>
<p>A common rule of thumb for the critical root zone is a radius of about 1 foot for every inch of trunk diameter. Inside that zone, avoid trenching, heavy equipment and soil compaction. Bring wire to the fixture with a shallow slit or route it along the edge of a bed, and keep transformers, junction points and hubs outside the zone.</p>

<h3>Respect oak wilt season</h3>
<p>Oak wilt is a serious fungal disease in Central Texas and the Hill Country, and live oaks are especially vulnerable. Texas A&amp;M Forest Service guidance is to avoid pruning or wounding oaks from February through June, when the insects that spread the fungus are most active. In practice that means no new tree mounts, no lag screws in limbs and no root cutting during those months. If a wound is unavoidable at any time of year, paint it immediately with a wound dressing or latex paint.</p>

