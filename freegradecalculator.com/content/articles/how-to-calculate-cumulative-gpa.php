<h2 id="what-is-cumulative-gpa">What is cumulative GPA?</h2>

<p>Your <strong>cumulative GPA</strong> (also called overall GPA or CGPA) is your grade point average across every graded class you have taken at your school, from your first term to now. Your <strong>term GPA</strong> (or semester GPA) covers just one term. If you are new to the idea of grade points, start with <a href="/blog/what-is-gpa">what is GPA</a>.</p>

<p>Cumulative GPA is the number that shows up on transcripts and the one colleges, scholarship committees, and employers usually ask for. It also decides academic standing, graduation eligibility, and Latin honors at many colleges.</p>

<h2 id="cumulative-gpa-formula">The cumulative GPA formula</h2>

<div class="formula">Cumulative GPA = Σ (grade points × credits) ÷ Σ credits</div>

<p>The Σ (sigma) just means "add up all of them." Every class contributes its grade points times its credits to the top of the fraction, and its credits to the bottom. Here is the standard 4.0 scale most US colleges use (schools vary, and some count an A+ as 4.3):</p>

