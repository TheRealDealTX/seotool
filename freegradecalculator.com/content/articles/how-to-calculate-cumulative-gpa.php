<h3>How an F and a retake change the math</h3>
<p>Failing a class hurts twice: it adds credits to the denominator and nothing to the numerator. Retaking it can help, but how much depends on your school's repeat policy.</p>

<div class="example-box"><h4>Worked example: F, then a retake</h4>
<p>Starting point: 3.00 GPA on 30 credits = 90 quality points</p>
<p><strong>After an F in a 3-credit class:</strong> 90 ÷ 33 = 2.727… ≈ <strong>2.73</strong></p>
<p><strong>Retake with a B (3.0 × 3 = 9 points):</strong><br>
If the school replaces the F: (90 + 9) ÷ 33 = 99 ÷ 33 = <strong>3.00</strong><br>
If both attempts count: (90 + 0 + 9) ÷ (33 + 3) = 99 ÷ 36 = <strong>2.75</strong></p>
</div>

<p>Same student, same B, but a 0.25 difference in cumulative GPA depending on policy. Some schools limit how many classes you can replace, or only allow replacement for D and F grades, so check before you register.</p>

<h2 id="how-fast-gpa-changes">How much can one semester change your cumulative GPA?</h2>

<p>Because cumulative GPA is weighted by credits, each new term matters less as your credit total grows. Compare two students who both have a 2.80 and then earn a perfect 4.0 on 15 credits:</p>

<div class="example-box"><h4>Worked example: same semester, different starting points</h4>
<p><strong>Freshman with 15 credits:</strong> (2.80 × 15 + 4.0 × 15) ÷ 30 = (42 + 60) ÷ 30 = 102 ÷ 30 = <strong>3.40</strong><br>
<strong>Junior with 60 credits:</strong> (2.80 × 60 + 4.0 × 15) ÷ 75 = (168 + 60) ÷ 75 = 228 ÷ 75 = <strong>3.04</strong></p>
<p>And if the junior earns a 3.5 instead of a 4.0: (168 + 52.5) ÷ 75 = 220.5 ÷ 75 = <strong>2.94</strong></p>
</div>

