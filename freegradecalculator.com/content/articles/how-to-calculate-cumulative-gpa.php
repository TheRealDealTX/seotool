<h2 id="worked-example">Worked example: two semesters from scratch</h2>

<p>Let's calculate cumulative GPA for a first-year college student with two semesters of classes.</p>

<div class="example-box"><h4>Fall semester</h4>
<p>Composition I: A (4.0) × 3 = 12.0<br>
Calculus I: B (3.0) × 4 = 12.0<br>
Chemistry I: C+ (2.3) × 4 = 9.2<br>
Intro to Psychology: A- (3.7) × 3 = 11.1</p>
<p>Fall quality points = 44.3 &nbsp;·&nbsp; Fall credits = 14<br>
Fall term GPA = 44.3 ÷ 14 = 3.164… ≈ <strong>3.16</strong></p>
</div>

<div class="example-box"><h4>Spring semester</h4>
<p>Composition II: A- (3.7) × 3 = 11.1<br>
Calculus II: B- (2.7) × 4 = 10.8<br>
Chemistry II: B (3.0) × 4 = 12.0<br>
Sociology: A (4.0) × 3 = 12.0<br>
First-year seminar: B+ (3.3) × 1 = 3.3</p>
<p>Spring quality points = 49.2 &nbsp;·&nbsp; Spring credits = 15<br>
Spring term GPA = 49.2 ÷ 15 = <strong>3.28</strong></p>
</div>

<div class="example-box"><h4>Cumulative GPA</h4>
<p>Total quality points = 44.3 + 49.2 = 93.5<br>
Total credits = 14 + 15 = 29<br>
Cumulative GPA = 93.5 ÷ 29 = 3.224… ≈ <strong>3.22</strong></p>
</div>

