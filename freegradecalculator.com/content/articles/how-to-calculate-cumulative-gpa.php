<h2 id="shortcut-with-term-gpas">The shortcut: using term GPAs you already know</h2>

<p>You do not need to re-enter every class from freshman year. If your transcript shows your current cumulative GPA and credits, treat them as one big "term" and add the new term to it.</p>

<div class="formula">New cumulative GPA = (old GPA × old credits + term GPA × term credits) ÷ (old credits + term credits)</div>

<div class="example-box"><h4>Worked example: adding a new semester</h4>
<p>Current cumulative GPA: 3.40 on 45 credits → 3.40 × 45 = 153.0 quality points<br>
New semester: 2.80 on 15 credits → 2.80 × 15 = 42.0 quality points</p>
<p>New cumulative GPA = (153.0 + 42.0) ÷ (45 + 15) = 195.0 ÷ 60 = <strong>3.25</strong></p>
<p>A simple average of 3.40 and 2.80 would give 3.10, which understates this student's GPA by 0.15.</p>
</div>

