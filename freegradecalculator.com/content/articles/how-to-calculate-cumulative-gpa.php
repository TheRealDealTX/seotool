<h2 id="step-by-step">How to calculate cumulative GPA step by step</h2>

<ol class="steps">
<li><strong>Gather your transcripts.</strong> Pull up every term's grades and credits from your student portal or unofficial transcript.</li>
<li><strong>Convert each grade to points.</strong> Use your school's scale; the table above is typical.</li>
<li><strong>Find quality points for each class.</strong> Grade points × credits.</li>
<li><strong>Add all quality points.</strong> Include every graded class from every term.</li>
<li><strong>Add all GPA credits.</strong> Count only classes that receive a letter grade (including F's).</li>
<li><strong>Divide.</strong> Total quality points ÷ total GPA credits. Round to two decimals unless your school says otherwise.</li>
</ol>

