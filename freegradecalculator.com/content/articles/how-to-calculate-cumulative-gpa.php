<h2 id="high-school-cumulative-gpa">Cumulative GPA in high school</h2>

<p>The method is the same in high school, with two differences. First, credits are usually smaller: a full-year class is often 1.0 credit and a semester class 0.5. Some schools give every class equal weight, which turns the calculation into a simple average of grade points. Second, many high schools report both an <strong>unweighted</strong> and a <strong>weighted</strong> cumulative GPA, where honors and AP classes earn extra points.</p>

<div class="example-box"><h4>Worked example: high school, two years</h4>
<p>9th grade: 3.50 GPA on 7.0 credits → 3.50 × 7.0 = 24.5<br>
10th grade: 3.75 GPA on 7.5 credits → 3.75 × 7.5 = 28.125</p>
<p>Cumulative GPA = (24.5 + 28.125) ÷ (7.0 + 7.5) = 52.625 ÷ 14.5 = 3.629… ≈ <strong>3.63</strong></p>
</div>

<p>Calculate weighted and unweighted cumulative GPAs separately, using the same credits but different grade points. The <a href="/high-school-gpa-calculator">high school GPA calculator</a> shows both at once, and our guide to <a href="/blog/weighted-vs-unweighted-gpa">weighted vs. unweighted GPA</a> explains how the extra points work. Keep in mind that colleges may recalculate your GPA with their own rules, such as counting only certain grades or core subjects.</p>

