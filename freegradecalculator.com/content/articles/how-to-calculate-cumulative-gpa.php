<h2 id="spreadsheet-method">How to calculate cumulative GPA in a spreadsheet</h2>

<p>If you like to keep your own records, a spreadsheet makes cumulative GPA automatic. Put one class per row with three columns: the class name, the grade points (4.0, 3.7, and so on), and the credits. Then one formula does the rest.</p>

<div class="formula">=SUMPRODUCT(B2:B40, C2:C40) / SUM(C2:C40)</div>

<p><code>SUMPRODUCT</code> multiplies each grade point by its credits and adds the results, which is exactly the top of the cumulative GPA formula. <code>SUM</code> adds the credits for the bottom. This works the same way in Google Sheets, Excel, and Numbers. Add a fourth column for the term, and you can filter by term to see each semester's GPA as well.</p>

<p>Two tips: leave pass/fail and withdrawn classes out of the sheet (or give them a separate tab), and type F grades as 0, not blank, so their credits still count.</p>

<h2 id="other-gpas">Major GPA, institutional GPA, and other GPAs on your transcript</h2>

<p>Your transcript may list more than one cumulative number. They all use the same formula; the difference is which classes are included.</p>

<ul>
<li><strong>Institutional GPA:</strong> only classes taken at your current college. This is usually the official cumulative GPA on your transcript.</li>
<li><strong>Overall or combined GPA:</strong> some schools and applications combine institutional and transfer grades. Many medical, law, and graduate applications recalculate a GPA from every college course you have ever taken.</li>
<li><strong>Major GPA:</strong> only the classes that count toward your major. Some departments require a minimum major GPA, often 2.0 or higher, to graduate in the major.</li>
<li><strong>Science or core GPA:</strong> a subset used by some programs, such as pre-health advising, that looks only at certain subjects.</li>
</ul>

<p>To calculate any of these, pick the classes that belong in that group and run the same steps: grade points × credits, add them up, divide by the credits in that group.</p>

<div class="callout callout-info"><strong>Quarter vs. semester credits</strong><p>Schools on the quarter system usually award more credits per class than semester schools (for example, 4 quarter units for a class that might be 3 semester credits elsewhere). That does not change the formula. Just keep all your numbers in the same unit, and convert transfer credits the way your registrar does if you need to combine them.</p></div>

<h2 id="common-mistakes">Common cumulative GPA mistakes</h2>

<ol class="steps">
<li><strong>Averaging term GPAs.</strong> Weight each term by its credits, or the answer will be off whenever credit loads differ.</li>
<li><strong>Counting pass/fail or withdrawn classes.</strong> These usually carry no grade points and should be left out of both the top and bottom of the formula.</li>
<li><strong>Leaving out F's.</strong> An F still counts its credits. Skipping it makes your GPA look higher than your transcript will show.</li>
<li><strong>Mixing scales.</strong> Do not combine weighted high school points with unweighted ones, or a 4.3-scale A+ with a 4.0-scale transcript.</li>
<li><strong>Including transfer grades.</strong> Most colleges leave them out of your institutional GPA, even though they count toward your degree.</li>
<li><strong>Rounding too early.</strong> Keep full decimals until the final step; round only the final GPA.</li>
</ol>

