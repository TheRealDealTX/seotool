<h2 id="what-is-a-good-gpa">What is a good weighted or unweighted GPA?</h2>

<p>"Good" depends on your goals and your school, but some general reference points help:</p>

<ul>
<li><strong>Unweighted 3.0</strong> is a B average. It meets the minimum for many scholarships and colleges.</li>
<li><strong>Unweighted 3.5 and above</strong> means mostly A's and some B's, competitive at many colleges.</li>
<li><strong>Unweighted 3.8–4.0</strong> is nearly straight A's, typical among applicants to highly selective colleges.</li>
<li><strong>Weighted above 4.0</strong> means you took weighted classes and earned strong grades in them. How far above depends heavily on how many advanced classes your school offers.</li>
</ul>

<p>Because weighted scales vary so much, a weighted GPA is most meaningful when compared with students at your own school. For more context, read <a href="/blog/what-is-a-good-gpa">what is a good GPA</a> and <a href="/blog/is-a-3-0-gpa-good">is a 3.0 GPA good</a>.</p>

