<h2 id="which-gpa-do-colleges-use">Which GPA do colleges look at?</h2>

<p>This is the part that surprises most families: colleges often use <em>neither</em> number exactly as your high school reports it. Because every school weights differently, admissions offices commonly do some or all of the following:</p>

<ul>
<li><strong>Read both GPAs on your transcript</strong> along with your school profile, which explains your school's grading and weighting policies.</li>
<li><strong>Recalculate a GPA</strong> using their own rules, for example counting only core academic classes (English, math, science, social studies, world language) and leaving out PE or electives.</li>
<li><strong>Apply their own weighting.</strong> The University of California, for example, calculates its own GPA from 10th- and 11th-grade courses and adds extra points only for a limited number of approved honors-level semesters. Check each school's current rules.</li>
<li><strong>Look at rigor directly.</strong> Admissions readers see which classes you took relative to what your school offers, so an AP-heavy schedule is visible even if a college strips out the weighting.</li>
</ul>

<p>The practical takeaway: you cannot game the system by picking the GPA that looks better. Strong grades in the most challenging classes you can handle well is the combination that reads best under any method.</p>

