<h2 id="ap-b-or-regular-a">Should you take the AP class and risk a B?</h2>

<p>This is the real-world version of the weighted vs. unweighted GPA debate. Here is how the two options score on a typical scale:</p>

<div class="table-wrap"><table class="data-table"><thead><tr><th>Option</th><th>Unweighted points</th><th>Weighted points</th></tr></thead><tbody>
<tr><td>A in regular class</td><td>4.0</td><td>4.0</td></tr>
<tr><td>B in AP class</td><td>3.0</td><td>4.0</td></tr>
<tr><td>A in AP class</td><td>4.0</td><td>5.0</td></tr>
<tr><td>C in AP class</td><td>2.0</td><td>3.0</td></tr>
</tbody></table></div>

<p>On a weighted scale, a B in AP ties an A in a regular class. On an unweighted scale, the regular A wins. But colleges also weigh rigor, and AP exam scores can sometimes earn college credit, depending on the college and the score.</p>

<p>A reasonable rule of thumb: take advanced classes in subjects you are strong in or plan to study, and do not overload to the point where your grades slip across the board. A C in AP is a weaker result under both scales than an A in the regular version. A balanced schedule you can succeed in usually beats a maxed-out one you cannot sustain.</p>

