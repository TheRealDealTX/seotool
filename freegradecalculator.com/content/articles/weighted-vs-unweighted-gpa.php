<h2 id="conclusion">The bottom line on weighted vs. unweighted GPA</h2>

<p>The weighted vs. unweighted GPA difference is simple: unweighted measures your grades on a 4.0 scale, while weighted adds extra points for honors, AP, and IB classes and often tops out at 5.0. Your school's policy decides the exact bonus, and colleges frequently recalculate your GPA their own way while looking closely at the classes you chose.</p>

