<h2 id="class-rank-and-honors">How weighting affects class rank, honors, and scholarships</h2>

<p>Your high school's choice of GPA can matter for more than college applications. Many schools that rank students use weighted GPA, so that students taking advanced classes are not pushed down the list. Others do not rank at all, or report rank only to colleges. Valedictorian and salutatorian selection, honor roll, and National Honor Society eligibility each follow local rules, and some use unweighted GPA even when rank uses weighted.</p>

<p>Scholarships are similar. A state or private scholarship that requires a "3.0 GPA" may specify weighted, unweighted, or its own recalculation. If the application does not say, ask the scholarship provider which GPA to report, and never report a weighted GPA as if it were unweighted.</p>

<h2 id="myths">Common myths about weighted and unweighted GPA</h2>

<ul>
<li><strong>"A 4.0 is the highest GPA possible."</strong> Only on an unweighted scale. Weighted GPAs commonly go up to 5.0.</li>
<li><strong>"Colleges only care about weighted GPA."</strong> Many recalculate on their own scale and look at your grades and rigor separately.</li>
<li><strong>"Taking AP always raises your GPA."</strong> It helps only if your grade stays high enough. A C in AP counts 3.0 on a typical weighted scale, the same as a B in a regular class, and on an unweighted scale it is a full point lower (2.0 vs. 3.0).</li>
<li><strong>"Weighted GPAs are the same everywhere."</strong> They are not. A 4.3 at one school and a 4.3 at another can mean very different things.</li>
</ul>

<h2 id="converting-between-scales">Can you convert weighted GPA to unweighted?</h2>

<p>Not from the number alone. A 4.2 weighted GPA could come from straight A's with a few honors classes or from a B+ average with many AP classes. To convert accurately, you need your course list:</p>

<ol class="steps">
<li><strong>List each class with its grade and credits.</strong> Mark which ones are honors, AP, or IB.</li>
<li><strong>Remove the bonus.</strong> Subtract 0.5 from honors grades and 1.0 from AP/IB grades (or whatever your school adds).</li>
<li><strong>Recalculate.</strong> Multiply each unweighted value by credits, add them up, and divide by total credits.</li>
</ol>

