<h3>Before you write your GPA on an application</h3>
<p>Applications and scholarship forms often have a single GPA box. Run through this quick checklist so you report the right number:</p>
<ul>
<li><strong>Read the instructions.</strong> If the form asks for unweighted GPA, report unweighted, even if your weighted number is higher.</li>
<li><strong>Name the scale.</strong> When there is a field for it, write the scale too, such as "4.09 on a 5.0 scale."</li>
<li><strong>Use your transcript, not your own math.</strong> Your official transcript is what the college or scholarship will verify against.</li>
<li><strong>Do not round up.</strong> A 3.47 is a 3.47, not a 3.5. Report the exact figure your school shows.</li>
</ul>

<h2 id="weighted-gpa-in-college">Do colleges weight GPA once you are there?</h2>

<p>Generally, no. Most US colleges use an unweighted 4.0 scale for every course, with credits doing the weighting. A 4-credit class counts more than a 1-credit class, but an advanced seminar is not worth more points per grade than an intro course. That means the weighted-GPA question is mostly a high school one. Once you are in college, the focus shifts to your term and cumulative GPA; see <a href="/blog/how-to-calculate-cumulative-gpa">how to calculate cumulative GPA</a>.</p>

