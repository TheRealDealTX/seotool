<h3>A 3.0 in a tough major</h3>

<p>College grading isn't uniform across departments. Engineering, physics, chemistry, and pre-med science courses are often graded more strictly than many other fields, so a 3.0 in one of those majors can represent very strong work. Employers and graduate programs that recruit from those fields generally know this, and many look at your grades in key courses and your major GPA, not just the overall figure.</p>

<p>If your major GPA is higher than your overall GPA, it's common and acceptable to list both on a resume (for example, "Major GPA: 3.4; Overall GPA: 3.0").</p>

<h3>Should you put a 3.0 on your resume?</h3>

<p>Generally, yes. A 3.0 meets the most common employer cutoff, so listing it can help you get past an automated screen for internships and entry-level jobs. If an application asks for your GPA, always give the accurate figure from your transcript. After you've worked for a few years, most people drop GPA from their resume entirely.</p>

<h2 id="raise-a-3-0">How to raise a 3.0 GPA</h2>

<p>If you want to move from good to great, the path depends on two numbers: your current GPA and how many credits you've already earned. The more credits behind you, the more weight your past grades carry.</p>

<div class="formula">Required GPA = (target GPA × total credits − current GPA × credits earned) ÷ remaining credits</div>

<div class="example-box"><h4>Worked example: college, 3.0 to 3.3</h4>
<p>You have a 3.0 GPA after 60 credits and plan to take 60 more. You want to graduate with a 3.3.</p>
<p>Quality points needed at graduation: 3.3 × 120 = 396.</p>
<p>Quality points you have now: 3.0 × 60 = 180.</p>
<p>Quality points still needed: 396 − 180 = 216, over 60 credits.</p>
<p>Required GPA: 216 ÷ 60 = <strong>3.6</strong> for the rest of college.</p>
<p>What about 3.5? 3.5 × 120 = 420; 420 − 180 = 240; 240 ÷ 60 = <strong>4.0</strong>. Possible only with straight A's, which shows why starting early matters.</p></div>

<div class="example-box"><h4>Worked example: high school, 3.0 after sophomore year</h4>
<p>You have a 3.0 after two years with 12 credits (six one-credit classes per year). If you earn a 3.6 over your next 12 credits:</p>
<p>(3.0 × 12) + (3.6 × 12) = 36 + 43.2 = 79.2 quality points.</p>
<p>79.2 ÷ 24 credits = <strong>3.3</strong> by graduation.</p></div>

<p>Run your own numbers with the <a href="/target-gpa-calculator">target GPA calculator</a>. If it tells you the required GPA is above 4.0, the target isn't reachable in that time frame, so adjust the goal or extend the timeline.</p>

