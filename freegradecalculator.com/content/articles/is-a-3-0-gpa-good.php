<h3>Practical ways to pull a 3.0 up</h3>

<ol class="steps">
<li><strong>Target your weakest high-credit class.</strong> Turning a C into a B in a 4-credit class adds 4 quality points, more than the same jump in a 1-credit class.</li>
<li><strong>Go to office hours early.</strong> Teachers and professors can tell you exactly what they're looking for, and asking in week three beats asking in week twelve.</li>
<li><strong>Protect the easy points.</strong> Homework, participation, and quizzes add up. Missing them is the fastest way to lose a letter grade.</li>
<li><strong>Study in short, spaced sessions.</strong> Reviewing material over several days beats one long cram session the night before.</li>
<li><strong>Use retake policies wisely.</strong> Many colleges let you replace or average a low grade by retaking the course. Policies vary, so check with your registrar.</li>
<li><strong>Plan your schedule.</strong> Balance hard classes with ones you're confident in, rather than stacking every tough course in one term.</li>
</ol>

