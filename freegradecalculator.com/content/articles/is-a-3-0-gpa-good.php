<h2 id="keeping-a-3-0">Keeping a 3.0 when a scholarship depends on it</h2>

<p>Many renewable scholarships require you to keep a 3.0 cumulative GPA. When you're sitting right at the line, one weaker semester can push you under it, so it's worth knowing the math before grades come out.</p>

<div class="example-box"><h4>Worked example: dipping below 3.0 and recovering</h4>
<p>You have exactly a 3.0 after 45 credits (135 quality points). This semester you take 15 credits and earn a 2.8.</p>
<p>New quality points: 135 + (2.8 × 15) = 135 + 42 = 177. New credits: 60.</p>
<p>New GPA: 177 ÷ 60 = <strong>2.95</strong>, just under the 3.0 requirement.</p>
<p>To get back to 3.0 after another 15 credits, you need 3.0 × 75 = 225 quality points. That means 225 − 177 = 48 more points over 15 credits, or 48 ÷ 15 = <strong>3.2</strong> next semester.</p></div>

<p>Two lessons from that example: a small slip below 3.0 is very recoverable, and the recovery is faster the sooner it happens. Also read your award's rules closely. Some scholarships allow a probation semester, some check term GPA as well as cumulative GPA, and some only review once a year.</p>

<h2 id="common-mistakes">Common mistakes when judging a 3.0</h2>

<ul>
<li><strong>Comparing a weighted GPA to an unweighted cutoff.</strong> A weighted 3.0 can hide a raw average below a B. Check which number an application asks for.</li>
<li><strong>Ignoring the trend.</strong> A 3.0 that climbs from 2.6 to 3.4 tells a better story than a 3.0 that falls from 3.4 to 2.6.</li>
<li><strong>Rounding up.</strong> A 2.96 is not a 3.0. If a program has a hard 3.0 minimum, report the exact GPA from your transcript.</li>
<li><strong>Forgetting the major GPA.</strong> If yours is higher, it may matter more to employers in your field than the overall number.</li>
</ul>

<div class="callout callout-info"><strong>For parents and teachers</strong><p>A 3.0 is a solid foundation, so treat it as a starting point for a conversation rather than a problem. Ask which classes feel hardest, look at where points are being lost (missing work, tests, or projects), and help set one specific goal for the next grading period, such as raising one class by a letter grade.</p></div>

