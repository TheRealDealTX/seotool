<h3>What is a 2.5 GPA?</h3>

<p>A 2.5 GPA falls halfway between a C+ (2.3) and a B- (2.7), which works out to roughly 78–80%. It's above the 2.0 floor for good standing, so it's not a failing GPA. But it's below the 3.0 line that many employers and scholarships use, and some four-year colleges set 2.5 as their minimum for admission or transfer. If you're at 2.5, the good news is that moving to a 3.0 is very achievable with a couple of strong terms, especially early on.</p>

<h3>Is a 3.5 GPA good?</h3>

<p>Yes, a 3.5 is a strong GPA. It sits between a B+ and an A-, and it often meets the threshold for the dean's list, honors programs, and competitive scholarships. Many employers that screen at 3.5 will consider you. For the most selective colleges or graduate programs, 3.5 is competitive but not a guarantee.</p>

<h3>Is a 3.7 GPA good?</h3>

<p>A 3.7 is an A- average and is considered very good to excellent. It's competitive for selective colleges, honors programs, and graduate schools, and it stands out on internship applications.</p>

<h2 id="weighted-and-major">A 3.0 weighted vs. unweighted, and by major</h2>

<p>Before you judge your 3.0, check which kind of 3.0 it is. The same number can mean different things depending on how it was calculated and what classes went into it.</p>

<h3>Unweighted 3.0 vs. weighted 3.0</h3>

<p>An <strong>unweighted</strong> 3.0 means your raw grades average a B. A <strong>weighted</strong> 3.0 is a little different: if your school adds bonus points for Honors or AP classes, a weighted 3.0 may mean your raw grades were actually below a B. So an unweighted 3.0 is usually the stronger result of the two.</p>

<div class="example-box"><h4>Worked example: the same grades, two GPAs</h4>
<p>A student takes six one-credit classes and earns a B in every one. Two of the classes are AP, and the school adds 1.0 point for AP.</p>
<p>Unweighted: six B's = 6 × 3.0 = 18 ÷ 6 = <strong>3.0</strong>.</p>
<p>Weighted: four regular B's (4 × 3.0 = 12) plus two AP B's (2 × 4.0 = 8) = 20 ÷ 6 = <strong>3.33</strong> (3.333, rounded).</p></div>

<p>Weighting rules vary by school, which is why many colleges recalculate GPAs their own way. When a college or scholarship lists a 3.0 minimum, it usually means unweighted unless it says otherwise. Our <a href="/high-school-gpa-calculator">high school GPA calculator</a> shows both numbers side by side.</p>

