<h2 id="if-your-gpa-is-low">What if your GPA isn't where you want it?</h2>

<p>A GPA below your goal is a problem to solve, not a verdict. Here's a practical plan:</p>

<ol class="steps">
<li><strong>Find out exactly where you stand.</strong> Calculate your current cumulative GPA and total credits so you're working with real numbers, not guesses.</li>
<li><strong>Set a target and do the math.</strong> Use the <a href="/target-gpa-calculator">target GPA calculator</a> to see what GPA you need on your remaining credits. If the answer is above 4.0, adjust the timeline or the target.</li>
<li><strong>Focus on the biggest-credit classes.</strong> A 4-credit course moves your GPA more than a 1-credit course, so put extra effort where the credits are.</li>
<li><strong>Look into grade replacement.</strong> Many colleges let you retake a course and replace (or average) the old grade. Policies vary widely, so check with your registrar.</li>
<li><strong>Build habits, not just willpower.</strong> Office hours, spaced practice, and a weekly planning session do more over a semester than a few all-nighters.</li>
</ol>

