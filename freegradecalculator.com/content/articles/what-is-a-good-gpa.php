<h2 id="how-gpa-moves">Why early grades matter more than you think</h2>

<p>Your cumulative GPA is an average weighted by credits. Every new grade gets averaged in with everything before it, so the more credits you have, the harder it is to move the number. That's great news if you start strong, and a good reason to take your first semesters seriously.</p>

<div class="formula">Cumulative GPA = Σ (grade points × credits) ÷ Σ credits</div>

<div class="example-box"><h4>Worked example: the same semester, two different impacts</h4>
<p><strong>Student A</strong> has a 3.0 GPA after 15 credits (one semester). She earns a 3.8 over her next 15 credits.</p>
<p>(3.0 × 15) + (3.8 × 15) = 45 + 57 = 102 quality points. 102 ÷ 30 credits = <strong>3.40</strong>.</p>
<p><strong>Student B</strong> has a 3.0 GPA after 90 credits (three years). He earns the same 3.8 over his next 15 credits.</p>
<p>(3.0 × 90) + (3.8 × 15) = 270 + 57 = 327 quality points. 327 ÷ 105 credits = <strong>3.11</strong> (3.114, rounded).</p>
<p>Same great semester, but Student A's GPA jumps 0.40 points while Student B's rises about 0.11.</p></div>

