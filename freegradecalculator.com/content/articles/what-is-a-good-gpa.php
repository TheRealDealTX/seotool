<h2 id="good-gpa-high-school">What is a good GPA in high school?</h2>

<p>In high school, a GPA tells colleges how consistently you've performed over several years. As a starting point, the U.S. Department of Education's most recent High School Transcript Study (2009 graduates) put the average GPA of graduates at about 3.0. That makes a B average a reasonable "middle of the pack" benchmark.</p>

<p>Here is a practical way to read your high school GPA:</p>

<div class="table-wrap"><table class="data-table"><thead><tr><th>Unweighted GPA</th><th>Grade average</th><th>How it generally reads</th></tr></thead><tbody>
<tr><td>3.8–4.0</td><td>Mostly A's</td><td>Excellent; competitive for the most selective schools if paired with rigorous classes</td></tr>
<tr><td>3.5–3.7</td><td>A's and B's</td><td>Very good; competitive at many selective colleges</td></tr>
<tr><td>3.0–3.4</td><td>Mostly B's</td><td>Good; opens doors at a wide range of four-year colleges</td></tr>
<tr><td>2.5–2.9</td><td>B's and C's</td><td>Fair; many colleges admit students in this range, especially with an upward trend</td></tr>
<tr><td>Below 2.5</td><td>Mostly C's or lower</td><td>Limits options; community college and an upward trend can help a lot</td></tr>
</tbody></table></div>

<h3>Course rigor matters as much as the number</h3>

<p>Admissions officers don't just read your GPA. They read your transcript. A 3.6 earned in AP Calculus, AP Chemistry, and Honors English often looks stronger than a 3.9 in the easiest available classes. Many colleges also recalculate GPAs using only core academic subjects, so a strong grade in a fun elective may not carry much weight.</p>

<p>That's why the best answer to "Is my GPA good?" in high school is: good <em>for the classes you took</em>, and good <em>for the colleges you're targeting</em>.</p>

<h3>Upward trends count</h3>

<p>A rough freshman year doesn't have to define you. Colleges generally look favorably on students whose grades improve over time. A transcript that moves from C's in ninth grade to A's and B's in eleventh grade tells a story of growth that a single cumulative GPA hides.</p>

