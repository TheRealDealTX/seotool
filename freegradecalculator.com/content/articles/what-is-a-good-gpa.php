<h2 id="good-gpa-college">What is a good GPA in college?</h2>

<p>College grading is often tougher than high school grading, and the classes get harder as you move into your major. Even so, the same scale applies, and a few benchmarks come up again and again:</p>

<ul>
<li><strong>2.0:</strong> The usual minimum to stay in good academic standing and graduate. Falling below it can lead to academic probation.</li>
<li><strong>3.0:</strong> A widely used cutoff for internships, many employers, and many graduate programs. Clearing 3.0 keeps most doors open.</li>
<li><strong>3.5:</strong> A common threshold for the dean's list or for Latin honors at some schools (the exact numbers vary by college).</li>
<li><strong>3.7+:</strong> Very strong; helpful for competitive grad programs, prestigious fellowships, and selective employers.</li>
</ul>

<p>Keep in mind that GPAs often differ by major. Engineering, chemistry, and math courses are frequently graded more harshly than some other fields. Many graduate programs and employers understand this and look at your major GPA and your grades in key courses, not just the overall number.</p>

<div class="callout callout-info"><strong>Major GPA vs. overall GPA</strong><p>Your major GPA counts only courses in your field. If your overall GPA is dragged down by an early gen-ed course, a strong major GPA can show employers and grad schools what you can do in the work that matters to them. Many students list both on a resume when the major GPA is higher.</p></div>

