<h3>Transfer students and community college</h3>

<p>If you start at a community college and plan to transfer, your college GPA usually becomes the main academic factor in transfer admissions. Four-year schools often publish a minimum transfer GPA, and competitive universities or high-demand majors typically expect well above the minimum. Some states have transfer agreements that guarantee admission to certain public universities for students who meet a set GPA and complete specific courses. Requirements vary widely, so check with your community college's transfer office early.</p>

<h2 id="weighted-gpa-context">What about weighted GPAs above 4.0?</h2>

<p>If your high school uses weighted GPAs, you might see numbers like 4.2 or 4.5. Typically, Honors classes add 0.5 points and AP or IB classes add 1.0 point, so an A in an AP class counts as a 5.0. Our <a href="/high-school-gpa-calculator">high school GPA calculator</a> uses exactly that convention, though your school's rules may differ.</p>

<p>Because every district weights differently, a 4.3 at one school is not directly comparable to a 4.3 at another. That's why many colleges strip out the weighting and recalculate on their own scale. When you compare yourself to a college's published GPA range, check whether the range is weighted or unweighted.</p>

