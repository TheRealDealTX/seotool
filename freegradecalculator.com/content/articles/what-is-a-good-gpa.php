<h2 id="good-gpa-by-goal">What is a good GPA for your goal?</h2>

<p>"Good" is easiest to answer when you know what the GPA is for. Here's how to think about the most common goals. Requirements change and differ widely by institution, so treat these as general patterns and always check the specific school, scholarship, or employer.</p>

<h3>College admissions</h3>

<p>Colleges fall roughly into tiers by how selective they are. Rather than quoting precise numbers (which change every year), here's how GPA tends to fit each tier:</p>

<div class="table-wrap"><table class="data-table"><thead><tr><th>Type of college</th><th>What a competitive GPA usually looks like</th></tr></thead><tbody>
<tr><td>Most selective (very low admit rates)</td><td>Near-perfect grades, typically mostly A's in the most rigorous courses your school offers</td></tr>
<tr><td>Selective</td><td>Mostly A's and B's, often 3.5 or higher, with a challenging schedule</td></tr>
<tr><td>Moderately selective</td><td>Mostly B's, often around 3.0 or higher</td></tr>
<tr><td>Less selective / open admission</td><td>Many admit students with a 2.0–2.5 or higher; community colleges are generally open admission</td></tr>
</tbody></table></div>

<p>The best way to know where you stand is to look up each college's published admissions data. Many colleges report the middle 50% GPA range of admitted students in their Common Data Set or on their admissions website. If your GPA falls in or above that range, you're competitive on grades.</p>

<h3>Scholarships</h3>

<p>Merit scholarships often require a minimum GPA, and many also require you to <em>maintain</em> a minimum GPA in college to keep the award. Minimums commonly fall somewhere between 2.5 and 3.5, with the most competitive awards looking for much higher. Some state-funded programs set their own cutoffs. Read the fine print, because "maintain a 3.0" can mean cumulative GPA, term GPA, or both.</p>

<h3>Federal financial aid</h3>

<p>To keep receiving federal student aid, colleges must confirm you're making Satisfactory Academic Progress (SAP). For programs longer than two years, that generally means at least a C average, usually a 2.0 GPA, by the end of your second year, plus a minimum pace of completed credits. Your college's financial aid office publishes its exact SAP policy.</p>

<h3>Graduate and professional school</h3>

<p>Many master's and PhD programs list a minimum GPA, and 3.0 is a common one. Meeting the minimum gets your application read; competitive programs usually admit students above it. Medical, law, and other professional schools weigh GPA heavily alongside entrance exams like the MCAT or LSAT, and admitted students at top programs typically have very high GPAs. Most graduate programs also look closely at your last two years and your grades in courses related to the field.</p>

<h3>Jobs and internships</h3>

<p>Some employers, particularly in finance, consulting, engineering, and large corporate internship programs, screen applicants by GPA, and 3.0 or 3.5 cutoffs are common. Many other employers never ask. GPA usually matters most for your first internship or first job; after a few years of experience, your work record matters far more.</p>

<div class="callout callout-tip"><strong>Pro tip</strong><p>If your GPA is 3.0 or higher, it's generally worth listing on your resume for internships and entry-level roles. If it's below 3.0, you can leave it off unless the application specifically asks for it, and let your projects, experience, and skills do the talking.</p></div>

