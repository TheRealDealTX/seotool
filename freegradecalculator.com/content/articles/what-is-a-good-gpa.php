<h2 id="bottom-line">The bottom line: what is a good GPA?</h2>

<p>So, what is a good GPA? For most students, a 3.0 is a solid, door-opening baseline, a 3.5 or higher is strong, and a 3.8 or higher is excellent. In high school, "good" also means good for the rigor of your classes and the colleges on your list. In college, 3.0 is the most common cutoff you'll run into for jobs, grad schools, and scholarships, while 2.0 is the floor for good standing and federal aid.</p>

