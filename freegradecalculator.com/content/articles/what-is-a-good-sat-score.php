<h2 id="scholarships-placement">Scores, scholarships, and placement</h2>

<p>Even at test-optional colleges, SAT scores can still matter after admission. Some colleges use test scores as one factor in merit scholarships, and some use them for course placement, such as deciding whether you can skip an introductory math class. Some states also offer the SAT free during the school day and use it as part of their state testing. Check the financial aid and placement pages of each college to see whether scores play a role there.</p>

<h2 id="sat-vs-act">SAT vs. ACT</h2>

<p>Virtually every US college that accepts the SAT also accepts the ACT, and most say they have no preference between them. Some students score noticeably better on one test, so it's worth taking a practice test of each. If you're weighing the ACT, our <a href="/act-score-calculator">ACT score calculator</a> shows how composite scores are calculated.</p>

<h2 id="raise-your-score">How to raise your SAT score</h2>

<ul>
<li><strong>Take an official practice test first.</strong> The College Board offers free full-length practice tests in Bluebook that match the real adaptive format.</li>
<li><strong>Study your mistakes, not just your score.</strong> Sort missed questions by skill (for example, linear equations or transitions) and practice those skills.</li>
<li><strong>Practice under timed conditions.</strong> Pacing matters on both sections, especially Reading and Writing, where you get just over a minute per question.</li>
<li><strong>Learn the built-in calculator.</strong> Knowing how to use the graphing calculator in Bluebook can save time on Math.</li>
<li><strong>Schedule your test dates.</strong> Leave time for a retake. Many students take the SAT in the spring of junior year and again in the summer or fall.</li>
</ul>

