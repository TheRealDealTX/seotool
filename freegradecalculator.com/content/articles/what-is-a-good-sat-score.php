<h2 id="section-scores">What is a good section score?</h2>

<p>Colleges see your two section scores, not just the total, so it helps to know how each one compares. The College Board's class of 2025 averages were 521 in Reading and Writing and 508 in Math, and its college readiness benchmarks are 480 and 530.</p>

<ul>
<li><strong>Meeting the benchmark</strong> (480+ in Reading and Writing, 530+ in Math) means you're on track for first-year college coursework in that subject, by the College Board's definition.</li>
<li><strong>600+ in a section</strong> is well above the national average and typically strong for many colleges.</li>
<li><strong>700+ in a section</strong> is near the top of the scale and in line with what highly selective colleges often see.</li>
</ul>

<p>Balance matters less than you might think, but context matters more. Applicants to engineering, computer science, or other math-heavy programs often find that admissions readers pay close attention to the Math score. If one section is much weaker, it's usually the fastest place to gain points.</p>

<h2 id="score-ranges">What is a good SAT score by range?</h2>

<p>Using the national average and the College Board's percentiles, here's a rough, general way to think about score ranges. These labels are our shorthand, not official College Board categories.</p>

<ul>
<li><strong>Below 1000:</strong> below the national average. Many colleges, including many open-admission and test-optional schools, still admit students in this range, and focused practice can raise it.</li>
<li><strong>1000–1190:</strong> around to solidly above average. Competitive at a wide range of public and private colleges.</li>
<li><strong>1200–1390:</strong> strong. Roughly the 75th to low-90s percentile among test takers, and competitive at many selective colleges.</li>
<li><strong>1400–1600:</strong> excellent. Top 7% or so of test takers, and in range for the most selective schools.</li>
</ul>

