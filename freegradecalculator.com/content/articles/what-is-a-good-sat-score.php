<h2 id="test-optional">Test-optional policies and when to submit</h2>

<p>Many colleges became test-optional during the pandemic, and a large number have kept that policy. At test-optional schools, you choose whether to send scores, and applications without them are reviewed without penalty according to those colleges' stated policies.</p>

<p>The landscape has shifted, though. Several highly selective universities, including MIT, Dartmouth, Yale, Brown, and Harvard, have reinstated testing requirements in recent years, and some accept alternatives such as AP or IB scores. Other colleges are test-blind and won't look at scores at all. Policies change, so check each college's current rules for your application year.</p>

