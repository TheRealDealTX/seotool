<h2 id="set-your-target">How to set your target score</h2>

<p>The national average tells you how you compare with everyone. Your college list tells you what you actually need. The key number is each college's <strong>middle 50% range</strong>: the scores between the 25th and 75th percentile of admitted or enrolled students.</p>

<ol class="steps">
<li><strong>List 6–10 colleges.</strong> Include reach, match, and likely schools.</li>
<li><strong>Find each school's middle 50% range.</strong> Look on the admissions website or the school's Common Data Set (section C9 lists SAT score ranges).</li>
<li><strong>Note the 75th percentile.</strong> A score at or above it makes the SAT a strength in your application.</li>
<li><strong>Set your target.</strong> Aim for the 75th percentile of your reach schools if it's realistic, or at least the midpoint of your match schools.</li>
<li><strong>Compare with your practice score.</strong> The gap tells you how much prep time to plan.</li>
</ol>

<div class="example-box"><h4>Worked example: turning ranges into a target</h4>
<p>Suppose your three top choices report middle 50% ranges of 1180–1350, 1250–1420, and 1300–1460. The midpoints are (1180 + 1350) ÷ 2 = 1265, (1250 + 1420) ÷ 2 = 1335, and (1300 + 1460) ÷ 2 = 1380.</p>
<p>A target of about <strong>1380</strong> puts you at or above the middle of all three ranges. Your latest practice test was 1290, so you're aiming for a 90-point gain.</p>
</div>

<p>These ranges are hypothetical. Real ranges change every year, so always look up current numbers for the schools on your list.</p>

<p>Keep in mind what a middle 50% range really means: one in four admitted students scored below the bottom number, and one in four scored above the top. A score near the 25th percentile doesn't rule you out, especially with strong grades and activities. It just means the SAT won't be the part of your application that stands out. A score above the 75th percentile, on the other hand, turns testing into a clear strength.</p>

<h2 id="superscoring">Superscoring and Score Choice</h2>

<p><strong>Superscoring</strong> means a college takes your highest Reading and Writing score and your highest Math score, even if they came from different test dates, and adds them together. Many colleges superscore the SAT, though policies vary by school.</p>

<div class="example-box"><h4>Worked example: superscore</h4>
<p><strong>March:</strong> Reading and Writing 610, Math 590 = 1200<br>
<strong>May:</strong> Reading and Writing 580, Math 650 = 1230</p>
<p>Best Reading and Writing: 610. Best Math: 650. <strong>Superscore: 610 + 650 = 1260.</strong></p>
<p>Your best single sitting is 1230, so superscoring adds 30 points at colleges that use it.</p>
</div>

