<h2 id="how-sat-scoring-works">How SAT scoring works</h2>

<p>The SAT has two sections: <strong>Reading and Writing</strong> and <strong>Math</strong>. Each is scored from 200 to 800 in 10-point steps, and your total score is the sum, from 400 to 1600. There is no penalty for wrong answers, so you should answer every question.</p>

