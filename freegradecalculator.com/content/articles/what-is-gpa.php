<h2 id="gpa-scales-and-scores">Other GPA scales you might see</h2>

<p>The 4.0 scale is standard in the US, but your GPA score can look different depending on where you study:</p>
<ul>
<li><strong>4.3 scale:</strong> Some colleges give an A+ 4.3 points, so the maximum is 4.3.</li>
<li><strong>5.0 (weighted) scale:</strong> High schools that weight AP and IB classes often top out at 5.0.</li>
<li><strong>100-point scale:</strong> Some high schools report a numeric average (like 91.4) instead of a 4.0 GPA.</li>
<li><strong>10-point CGPA:</strong> Common in India and some other countries. You can convert it with our <a href="/cgpa-to-percentage-calculator">CGPA to percentage calculator</a>, but each university may publish its own formula.</li>
</ul>

<p>Because scales differ, a 3.8 at one school is not always identical to a 3.8 at another. That is one reason colleges look at your transcript and course rigor, not just the number.</p>

<h2 id="why-gpa-matters">Why your GPA matters</h2>

<p>GPA is not the only measure of what you know, but it is one of the first numbers people look at. Here is where it typically comes up:</p>
<ul>
<li><strong>College admissions:</strong> Your high school GPA, along with your course choices, is a major part of most applications.</li>
<li><strong>Scholarships:</strong> Many merit scholarships set a minimum GPA to apply and to keep the award each year.</li>
<li><strong>Honors:</strong> Honor roll, dean's list, honor societies, and Latin honors at graduation all use GPA cutoffs that vary by school.</li>
<li><strong>Eligibility:</strong> Sports, clubs, study abroad, and some majors require a minimum GPA.</li>
<li><strong>Jobs and internships:</strong> Some employers ask for GPA on early-career applications, often with a 3.0 cutoff.</li>
</ul>

