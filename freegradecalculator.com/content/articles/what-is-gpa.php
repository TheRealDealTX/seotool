<h2 id="term-vs-cumulative-gpa">Term GPA vs. cumulative (overall) GPA</h2>

<p>Your transcript may show several different GPAs. The two you will see most are term GPA and cumulative GPA.</p>

<h3>What is term GPA?</h3>
<p><strong>Term GPA</strong> is your GPA for a single grading term: one semester, quarter, or trimester. The example above, 3.52, is a term GPA. It resets each term and tells you how that particular stretch went. Colleges often use term GPA for the dean's list, and some high schools use it for honor roll.</p>

<h3>What is overall GPA?</h3>
<p><strong>Overall GPA</strong>, more often called <strong>cumulative GPA</strong>, combines every graded class you have taken at your school. It is the number colleges, scholarships, and employers usually ask for. You calculate it the same way as term GPA, just with all terms included, or by weighting each term's GPA by its credits.</p>

<div class="example-box"><h4>Worked example: combining two terms</h4>
<p>Fall: 3.50 GPA on 14 credits → 3.50 × 14 = 49.0 quality points<br>
Spring: 3.00 GPA on 16 credits → 3.00 × 16 = 48.0 quality points</p>
<p>Cumulative GPA = (49.0 + 48.0) ÷ (14 + 16) = 97.0 ÷ 30 = 3.233… ≈ <strong>3.23</strong></p>
<p>If you had simply averaged 3.50 and 3.00, you would get 3.25, which is slightly too high because spring had more credits.</p>
</div>

<div class="callout callout-tip"><strong>Pro tip</strong><p>To add a new term to an existing cumulative GPA, use the <a href="/cumulative-gpa-calculator">cumulative GPA calculator</a>. For a full walkthrough, read <a href="/blog/how-to-calculate-cumulative-gpa">how to calculate cumulative GPA</a>.</p></div>

<h3>Academic GPA vs. total GPA</h3>
<p>Some high schools report two cumulative numbers. <strong>Total GPA</strong> (sometimes called overall GPA) includes every graded course, electives included. <strong>Academic GPA</strong> (sometimes called core GPA) only includes core academic subjects, usually English, math, science, social studies, and world languages, and leaves out classes like PE, health, or some electives.</p>

<p>Which classes count as "academic" is a school decision, and many schools only report one GPA. Colleges may also recalculate your GPA using their own rules, so do not panic if their number does not match your report card. You may also see an <strong>institutional GPA</strong> in college, which counts only classes taken at that college and leaves out transfer credits.</p>

