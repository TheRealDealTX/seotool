<h2 id="how-to-calculate-gpa">How to calculate GPA</h2>

<p>Once you know the scale, the math takes about two minutes. The formula looks like this:</p>

<div class="formula">GPA = Σ (grade points × credits) ÷ Σ credits</div>

<ol class="steps">
<li><strong>List your classes.</strong> Write down each class, its letter grade, and its credits.</li>
<li><strong>Convert letters to points.</strong> Use your school's scale (the table above is typical).</li>
<li><strong>Multiply.</strong> For each class, multiply grade points by credits to get quality points.</li>
<li><strong>Add it all up.</strong> Total the quality points and total the credits.</li>
<li><strong>Divide.</strong> Total quality points ÷ total credits = your GPA. Most schools round to two decimals.</li>
</ol>

<div class="example-box"><h4>Worked example: one semester</h4>
<p>English: A (4.0) × 3 credits = 12.0<br>
Biology: B+ (3.3) × 4 credits = 13.2<br>
Algebra: B (3.0) × 3 credits = 9.0<br>
History: A- (3.7) × 3 credits = 11.1<br>
PE: A (4.0) × 1 credit = 4.0</p>
<p>Total quality points = 12.0 + 13.2 + 9.0 + 11.1 + 4.0 = <strong>49.3</strong><br>
Total credits = 3 + 4 + 3 + 3 + 1 = <strong>14</strong><br>
GPA = 49.3 ÷ 14 = 3.521… ≈ <strong>3.52</strong></p>
</div>

