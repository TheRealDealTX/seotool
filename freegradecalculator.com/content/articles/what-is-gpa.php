<h2 id="weighted-and-unweighted-gpa">Weighted and unweighted GPA</h2>

<p>Everything above describes an <strong>unweighted GPA</strong>, where an A is worth 4.0 no matter how hard the class is. Many high schools also calculate a <strong>weighted GPA</strong> that adds extra points for honors, AP, IB, or dual-enrollment classes. A common setup adds 0.5 for honors and 1.0 for AP or IB, so an A in AP Biology counts as 5.0. That is how students end up with GPAs like 4.3.</p>

<p>Weighting policies vary widely by school and district. Some do not weight at all, some cap the number of weighted classes, and colleges often recalculate on their own scale. Our full guide to <a href="/blog/weighted-vs-unweighted-gpa">weighted vs. unweighted GPA</a> covers the details, and the <a href="/high-school-gpa-calculator">high school GPA calculator</a> shows both numbers side by side.</p>

