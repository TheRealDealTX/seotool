<h2 id="what-is-a-passing-gpa">What is a passing GPA?</h2>

<p>This is one of the most searched GPA questions, and the honest answer has two parts: what it takes to <em>pass your classes</em> and what it takes to <em>stay in good standing</em>.</p>

<h3>Passing your classes</h3>
<p>At most US schools, the lowest passing letter grade is a <strong>D-</strong> or <strong>D</strong>, which is worth 0.7 or 1.0 grade points. So in the narrowest sense, a GPA of about <strong>1.0</strong> means you passed your classes, just barely. An F (0.0) is the only failing grade, and it adds credits to your GPA calculation with zero points, which drags the average down hard.</p>

<p>However, a D does not always "count." Many colleges require a C or C- in courses for your major or in prerequisites, and some high schools require a C to move on to the next level of a subject. A class can be passed on your transcript and still need to be retaken for your program.</p>

<h3>Staying in good standing</h3>
<p>In practice, the number most schools treat as passing is <strong>2.0</strong>, a C average. Here are common thresholds. These are typical, not universal, so check your own school's policies.</p>

<div class="table-wrap"><table class="data-table"><thead><tr><th>Situation</th><th>Common minimum GPA</th></tr></thead><tbody>
