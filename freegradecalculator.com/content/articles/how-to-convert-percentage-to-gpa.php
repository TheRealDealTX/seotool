<h2 id="how-to-convert">How to convert percentage to GPA, step by step</h2>

<ol class="steps">
<li><strong>Find your school's grading scale.</strong> Check whether it uses plus/minus grades and where each cutoff falls. If you can't find it, the standard chart above is a reasonable default.</li>
<li><strong>Round the way your school rounds.</strong> Many teachers round 89.5% up to 90%, but not all do. Use the final percentage on your report card when you have it.</li>
<li><strong>Convert each class to a letter grade.</strong> Use the chart to match each percentage to its letter.</li>
<li><strong>Convert each letter to grade points.</strong> A = 4.0, A- = 3.7, B+ = 3.3, and so on.</li>
<li><strong>Multiply by credits.</strong> Grade points × credits = quality points for that class.</li>
<li><strong>Add and divide.</strong> Total quality points ÷ total credits = your GPA.</li>
</ol>

<div class="formula">GPA = Σ (grade points × credits) ÷ Σ credits</div>

