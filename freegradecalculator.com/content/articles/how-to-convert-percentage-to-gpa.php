<h3>A note for teachers and parents</h3>

<p>Gradebook software usually stores percentages, while transcripts and college applications use letters and GPA points. If you're checking a student's GPA by hand, convert each final course percentage with the school's official scale before averaging, and confirm whether the school reports weighted, unweighted, or both. When the school's own cutoffs differ from the standard chart, the school's cutoffs always win.</p>

<h2 id="common-mistakes">Common mistakes to avoid</h2>

<ul>
<li><strong>Using the wrong scale.</strong> Plus/minus and 10-point scales give different GPAs for the same percentage.</li>
<li><strong>Averaging percentages first.</strong> Convert each class, then average the grade points.</li>
<li><strong>Ignoring credits.</strong> A 4-credit class counts more than a 1-credit class.</li>
<li><strong>Mixing weighted and unweighted.</strong> Honors and AP bonuses apply only to weighted GPA. See <a href="/blog/weighted-vs-unweighted-gpa">weighted vs. unweighted GPA</a>.</li>
<li><strong>Treating shortcuts as official.</strong> Formula estimates are for quick checks only.</li>
<li><strong>Leaving out failed classes.</strong> An F earns 0 points but its credits still count, so skipping it inflates your GPA.</li>
<li><strong>Converting test scores instead of final grades.</strong> GPA uses each course's final grade, not individual quizzes or exams.</li>
<li><strong>Counting pass/fail courses.</strong> At most schools, a pass earns credit but isn't included in GPA. Check your school's policy for failing pass/fail grades.</li>
<li><strong>Rounding too early.</strong> Keep full decimals in quality points and round only the final GPA, usually to two decimal places.</li>
</ul>

