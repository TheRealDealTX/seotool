<h3>Why a straight-line formula can't match the chart</h3>

<p>Real grading scales work in steps: every percentage from 83% to 86% earns exactly 3.0, then the value jumps to 3.3 at 87%. Any single formula draws a smooth line through those steps, so it will always be too high in some places and too low in others. That's why the official chart, not a formula, is the only reliable way to convert a grade.</p>

<div class="callout callout-warn"><strong>Don't put a shortcut number on an application</strong><p>If a college, scholarship, or employer asks for your GPA, report the official GPA from your transcript. If your school doesn't calculate one, convert each class with the official scale. Never submit a formula estimate as your GPA.</p></div>

