<h2 id="international-cgpa">International grades and 10-point CGPA</h2>

<p>Many countries don't use the US 4.0 scale. India, for example, commonly uses a 10-point CGPA (cumulative grade point average). Under the CBSE convention, you convert a 10-point CGPA to a percentage by multiplying by 9.5.</p>

<div class="formula">Percentage = CGPA × 9.5 (CBSE convention)</div>

<div class="example-box"><h4>Example 4: CGPA to percentage and back</h4>
