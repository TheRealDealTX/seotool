<h2 id="target-percentage">What percentage do you need for a target GPA?</h2>

<p>You can also run the conversion in reverse for a single class. If you want a class to count as a 3.0, you need a B, which starts at <strong>83%</strong> on the plus/minus scale or <strong>80%</strong> on a 10-point scale. For a 3.7 (A-), you need 90%; for a full 4.0, you need 93% on the plus/minus scale or 90% on a 10-point scale.</p>

<p>Mid-semester, your current percentage only estimates where you'll land. Tests, projects, and the final exam can still move it. To see what you need on the remaining work, try the <a href="/raise-my-grade-calculator">raise my grade calculator</a> or the <a href="/final-grade-calculator">final grade calculator</a>.</p>

<div class="example-box"><h4>Example: one F changes everything</h4>
<p>Take the 15-credit semester from Example 2 (49.3 quality points, a 3.29 GPA) and add a 3-credit class that ended at 55%, an F worth 0 points.</p>
<p>Quality points stay at 49.3 + (0 × 3) = 49.3, but credits rise to 18.</p>
<p>GPA = 49.3 ÷ 18 = <strong>2.74</strong> (2.739, rounded). Leaving the F out would overstate the GPA by more than half a point.</p></div>

<h3>Check your work in three quick ways</h3>

<p>After converting a list of grades, run a few sanity checks before you trust the result. First, your GPA should land between your lowest and highest class grade points; if it doesn't, a multiplication or addition slipped. Second, your total credits should match the credits shown on your report card or transcript, including any failed classes. Third, compare the result with your school's official GPA if one is printed. A small gap usually comes from a different scale or rounding rule, while a big gap usually means a class was missed or weighted incorrectly. When in doubt, your school counselor or registrar can confirm which scale and rounding rules apply.</p>

<h2 id="gpa-to-percentage">Converting GPA back to a percentage</h2>

<p>Going the other way is trickier, because a GPA like 3.5 is an <em>average</em> of many grades rather than one grade. The best you can do is give a range.</p>

<h3>What is a 3.5 GPA in percentage?</h3>

<p>A 3.5 sits halfway between a B+ (3.3, 87–89%) and an A- (3.7, 90–92%). That makes a 3.5 roughly equivalent to <strong>89–90%</strong>. The ÷ 20 − 1 shortcut lands on 90% when you solve it in reverse: (3.5 + 1) × 20 = 90.</p>

