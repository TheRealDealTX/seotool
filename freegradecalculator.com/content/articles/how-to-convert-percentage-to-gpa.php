<h2 id="summary">Summary: how to convert percentage to GPA</h2>

<p>To recap how to convert percentage to GPA: look up your school's grading scale, convert each class percentage to a letter grade, turn each letter into grade points, multiply by credits, and divide total quality points by total credits. On the standard US scale, 93%+ is a 4.0, 90–92% is a 3.7, 87–89% is a 3.3, and 83–86% is a 3.0. Shortcuts like "percentage ÷ 20 − 1" are rough estimates only, and 10-point CGPAs follow their own rules, such as CBSE's CGPA × 9.5.</p>

