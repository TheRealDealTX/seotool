<h2 id="worked-examples">Worked examples</h2>

<div class="example-box"><h4>Example 1: a single class</h4>
<p>You finished Chemistry with an 88%.</p>
<p>On the plus/minus scale, 88% falls in the 87–89% band, so it's a <strong>B+</strong>, worth <strong>3.3</strong> grade points.</p>
<p>On a 10-point scale, 88% is a <strong>B</strong>, worth <strong>3.0</strong>.</p></div>

<div class="example-box"><h4>Example 2: a full semester</h4>
<p>Here are five classes on the plus/minus scale:</p>
<ul>
<li>Biology: 91% → A- (3.7) × 4 credits = 14.8</li>
<li>English: 85% → B (3.0) × 3 credits = 9.0</li>
<li>Algebra II: 78% → C+ (2.3) × 3 credits = 6.9</li>
<li>History: 95% → A (4.0) × 3 credits = 12.0</li>
<li>Spanish: 88% → B+ (3.3) × 2 credits = 6.6</li>
</ul>
<p>Total quality points: 14.8 + 9.0 + 6.9 + 12.0 + 6.6 = 49.3.</p>
<p>Total credits: 4 + 3 + 3 + 3 + 2 = 15.</p>
<p>GPA = 49.3 ÷ 15 = <strong>3.29</strong> (3.287, rounded).</p></div>

<div class="example-box"><h4>Example: a full year of high school</h4>
<p>High schools often give 1 credit for a year-long class and 0.5 credit for a semester class. Here's a ninth-grade year on the plus/minus scale:</p>
<ul>
<li>English: 94% → A (4.0) × 1 = 4.0</li>
<li>Algebra I: 86% → B (3.0) × 1 = 3.0</li>
<li>Biology: 79% → C+ (2.3) × 1 = 2.3</li>
<li>World History: 90% → A- (3.7) × 1 = 3.7</li>
<li>PE (one semester): 98% → A+ (4.0) × 0.5 = 2.0</li>
<li>Art (one semester): 84% → B (3.0) × 0.5 = 1.5</li>
</ul>
<p>Total quality points: 4.0 + 3.0 + 2.3 + 3.7 + 2.0 + 1.5 = 16.5. Total credits: 1 + 1 + 1 + 1 + 0.5 + 0.5 = 5.</p>
<p>GPA = 16.5 ÷ 5 = <strong>3.30</strong>.</p>
<p>If this school counted an A+ as 4.3 instead, PE would contribute 4.3 × 0.5 = 2.15, giving 16.65 ÷ 5 = <strong>3.33</strong>.</p></div>

<h3>What about 4.3 and 5.0 scales?</h3>

<p>A few schools reward an A+ with 4.3 points, which lets an unweighted GPA climb slightly above 4.0. Others use a 5.0 scale for weighted GPAs, where an A in an AP or Honors class can earn 5.0. The conversion process is the same in every case: percentage to letter, letter to points on <em>that</em> school's scale, then a credit-weighted average. What changes is only the number of points each letter is worth, so always confirm the scale before you compare your GPA with someone else's.</p>

<h3>Why you shouldn't convert your average percentage</h3>

<p>It's tempting to average all your percentages first and convert that one number. But GPA is calculated from letter grades, so the shortcut can give a different answer.</p>

<div class="example-box"><h4>Example 3: same classes, different method</h4>
<p>Credit-weighted average percentage for Example 2:</p>
<p>(91 × 4 + 85 × 3 + 78 × 3 + 95 × 3 + 88 × 2) ÷ 15 = (364 + 255 + 234 + 285 + 176) ÷ 15 = 1,314 ÷ 15 = 87.6%.</p>
<p>87.6% converts to a B+, or 3.3. That's close to the correct 3.29 here, but with a wider spread of grades the gap can be much larger, because letter grades group percentages into bands. Always convert class by class.</p></div>

