<h3>How rounding changes the result</h3>

<p>Rounding policies can move a grade across a cutoff. Suppose you finish a class with 89.5%.</p>

<ul>
<li>If your teacher rounds to the nearest whole percent, 89.5% becomes 90%, an A- worth <strong>3.7</strong>.</li>
<li>If your teacher doesn't round, 89.5% stays in the 87–89% band, a B+ worth <strong>3.3</strong>.</li>
</ul>

<p>That's a 0.4-point difference for one class. Rounding rules vary by teacher and school, so use the final letter on your report card or transcript whenever you have it.</p>

<h2 id="weighted-classes">Converting Honors and AP percentages</h2>

<p>If your school uses a <strong>weighted</strong> GPA, the conversion has one extra step: convert the percentage to standard grade points first, then add the bonus for the course level. A common convention is +0.5 for Honors and +1.0 for AP or IB, though every school sets its own rules (and many give no boost to an F).</p>

<div class="example-box"><h4>Example 5: weighted vs. unweighted from percentages</h4>
<p>Three one-credit classes on the plus/minus scale:</p>
<ul>
<li>AP U.S. History: 88% → B+ (3.3), weighted 3.3 + 1.0 = 4.3</li>
<li>Honors English: 92% → A- (3.7), weighted 3.7 + 0.5 = 4.2</li>
<li>Geometry (regular): 81% → B- (2.7), weighted 2.7</li>
</ul>
<p>Unweighted GPA: (3.3 + 3.7 + 2.7) ÷ 3 = 9.7 ÷ 3 = <strong>3.23</strong> (3.233, rounded).</p>
<p>Weighted GPA: (4.3 + 4.2 + 2.7) ÷ 3 = 11.2 ÷ 3 = <strong>3.73</strong> (3.733, rounded).</p></div>

