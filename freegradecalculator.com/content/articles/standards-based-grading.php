<h3 id="for-teachers">For teachers</h3>

<p>The biggest workload is upfront: unpacking standards, writing clear scales, and tagging assessments. Teachers who make SBG work usually keep the number of standards per unit small (often a handful, not dozens), use the same rubric language across assessments, and set clear reassessment rules, such as requiring corrections or practice before a retake.</p>

<p>A decision about homework is also needed. Many SBG teachers treat homework as practice that's reported under work habits, then use quizzes and tasks as the evidence for standards. Whatever the choice, consistency within a grade level or department reduces confusion.</p>

<h3 id="for-parents">For parents</h3>

<p>When you see a standards-based report card, read the standard descriptions, not just the numbers. A 3 is good news. A 2 tells you exactly which skill to support at home, and a 4 means your child is stretching beyond grade level.</p>

