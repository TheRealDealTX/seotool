<h2 id="converting-to-letter-grades">Converting standards-based grades to traditional grades</h2>

<p>Many middle and high schools that use SBG still need letter grades for transcripts, GPA, honor rolls, or athletic eligibility. There is no single official conversion. Districts and schools publish their own, and the methods below are common examples. For each, we'll use the same student, whose final scores on five standards are:</p>

<div class="formula">Standard scores: 3, 4, 2, 3, 3.5</div>

<h3 id="method-average-table">Method 1: Average, then use a conversion table</h3>

<p>Average the standard scores, then look up the result in a table set by the school.</p>

<div class="example-box"><h4>Worked example: average and table</h4>
<p>Average: (3 + 4 + 2 + 3 + 3.5) ÷ 5 = 15.5 ÷ 5 = <strong>3.1</strong></p>
<p>Example table: 3.5–4.0 = A, 3.0–3.49 = B, 2.5–2.99 = C, 2.0–2.49 = D, below 2.0 = F.</p>
<p>Result: <strong>B</strong>.</p>
</div>

<p>This is simple, but the table is where all the judgment lives. Some schools set the A cutoff at 3.25 or 3.5, others at 3.75. The same 3.1 could be an A- in one district and a B in another.</p>

<h3 id="method-linear">Method 2: Straight percentage (and why it's a problem)</h3>

<div class="example-box"><h4>Worked example: dividing by 4</h4>
<p>3.1 ÷ 4 = 0.775 = <strong>77.5%</strong>, which is a C+ on the standard US scale.</p>
<p>Under the same logic, a perfectly proficient student with straight 3s gets 3 ÷ 4 = 75% (a C), and a student who is "approaching" with 2s gets 50% (an F).</p>
</div>

<p>Because 3 means "meets the standard," most SBG guides advise against dividing by 4. It treats the proficiency scale like a points scale, and it punishes students who are exactly where they should be. If you do need a percentage from a rubric score for some other reason, our <a href="/rubric-grade-calculator">rubric grade calculator</a> shows the straight conversion, but SBG systems usually use one of the other methods instead.</p>

<h3 id="method-point-conversion">Method 3: Convert each level to a percentage</h3>

<p>Some gradebooks map each proficiency level to a fixed percentage, then average those percentages like a traditional grade. Here's one example mapping (schools set their own):</p>

<div class="table-wrap"><table class="data-table"><thead><tr><th>SBG score</th><th>4</th><th>3.5</th><th>3</th><th>2.5</th><th>2</th><th>1.5</th><th>1</th></tr></thead><tbody>
<tr><td>Example %</td><td>100</td><td>95</td><td>85</td><td>78</td><td>70</td><td>65</td><td>60</td></tr>
</tbody></table></div>

<div class="example-box"><h4>Worked example: level-to-percent mapping</h4>
<p>3 → 85, 4 → 100, 2 → 70, 3 → 85, 3.5 → 95</p>
<p>Average: (85 + 100 + 70 + 85 + 95) ÷ 5 = 435 ÷ 5 = <strong>87%</strong>, a B+ on the standard US scale.</p>
</div>

<p>This keeps a proficient student in B territory and fits into gradebooks built for percentages. The trade-off is that the mapping itself is a policy decision, and it should be published so families can see how it works. You can look up where any percentage lands with the <a href="/letter-grade-calculator">letter grade calculator</a>.</p>

