<h2 id="myths">Common myths about standards based grading</h2>

<p><strong>"A 3 is like a C."</strong> No. A 3 means the student meets the standard, which is the goal. Reading it as 75% is the most common misunderstanding families have.</p>

<p><strong>"Nothing counts, so students won't try."</strong> Assessments still count toward each standard, and work habits are usually reported on the same report card. What changes is that practice mistakes don't permanently drag down the academic score.</p>

<p><strong>"Everyone gets unlimited retakes."</strong> Some classrooms allow frequent reassessment, but many set limits or require corrections and extra practice first. Reassessment rules vary by teacher and school.</p>

<p><strong>"It's easier to get a 4."</strong> Usually the opposite. A 4 means going beyond the standard, and many teachers award it only when a student applies the skill in a new or more complex situation, not just for getting every question right.</p>

