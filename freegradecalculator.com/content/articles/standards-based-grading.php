<h2 id="how-sbg-works">How standards-based grading works in the classroom</h2>

<ol class="steps">
<li><strong>Define the standards.</strong> Teachers or the district choose a manageable set of standards per unit, usually based on state standards.</li>
<li><strong>Write a proficiency scale for each.</strong> Each level gets a short description so students know what a 3 or 4 looks like.</li>
<li><strong>Tag assessments to standards.</strong> A quiz might assess two standards, so it produces two scores instead of one percentage.</li>
<li><strong>Score the evidence.</strong> The teacher compares the student's work to the scale, often using a rubric.</li>
<li><strong>Update the score over time.</strong> As new evidence comes in, the standard's score reflects the student's current level, not just the first attempt.</li>
<li><strong>Report separately.</strong> Academic standards go on one part of the report card, and work habits such as effort, participation, and homework completion go on another.</li>
</ol>

<p>Separating behavior from achievement is one of the biggest shifts. In traditional grading, a late penalty or missing homework lowers the academic grade. In many SBG systems, those things are tracked and reported, but they don't change the score that says whether a student can solve the math.</p>

<h2 id="combining-evidence">How scores combine over time</h2>

<p>Suppose a student is assessed on the same standard four times during a unit and scores 1, 2, 3, then 4. What's their score? It depends on the method the teacher or school uses.</p>

<div class="example-box"><h4>Worked example: four ways to summarize 1, 2, 3, 4</h4>
<p><strong>Mean (simple average):</strong> (1 + 2 + 3 + 4) ÷ 4 = <strong>2.5</strong></p>
<p><strong>Most recent:</strong> <strong>4</strong></p>
<p><strong>Highest:</strong> <strong>4</strong></p>
<p><strong>Decaying average (65% weight on the newest score):</strong><br>
Start: 1<br>
After 2nd: 0.35 × 1 + 0.65 × 2 = 1.65<br>
After 3rd: 0.35 × 1.65 + 0.65 × 3 = 2.53<br>
After 4th: 0.35 × 2.53 + 0.65 × 4 ≈ <strong>3.48</strong></p>
</div>

<p>The mean says this student is "approaching," even though they clearly mastered the skill by the end. That's why many SBG systems avoid simple averages. The decaying average is a compromise: it leans on recent work but still counts earlier evidence a little. (Carrying full decimals instead of rounding to 2.53 gives 3.4846, which also rounds to 3.48.)</p>

