<h2 id="what-is-standards-based-grading">What is standards-based grading?</h2>

<p>In a traditional class, a quiz on fractions, a homework packet, a group project, and a late penalty all get blended into one number. A 78% tells you the overall average, but not which skills a student has nailed and which still need work.</p>

<p>Standards-based grading breaks that number apart. Teachers identify the learning standards for a unit, such as "adds and subtracts fractions with unlike denominators" or "cites textual evidence to support an analysis." Each assessment is tied to one or more standards, and the student gets a proficiency score for each one.</p>

<p>The result is a report card that reads more like a skills checklist. Instead of "Math: B", a parent might see eight or ten math standards, each with its own score. SBG is most common in elementary schools, but many middle and high schools use it too, sometimes alongside traditional letter grades.</p>

