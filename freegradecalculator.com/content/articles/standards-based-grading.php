<h2 id="practical-tips">Practical tips for making SBG work</h2>

<ul>
<li><strong>Start small.</strong> Pilot SBG in one unit or one course before switching an entire grade level.</li>
<li><strong>Write student-friendly scales.</strong> "I can…" statements help students know what a 3 looks like.</li>
<li><strong>Publish the conversion.</strong> Share the exact method for turning scores into letters at the start of the year.</li>
<li><strong>Use a consistent tracker.</strong> A gradebook with one column per standard keeps evidence organized, and color-coded pens make level feedback quick to read.</li>
<li><strong>Communicate early.</strong> Send families a one-page guide to the scale before the first report card.</li>
</ul>

