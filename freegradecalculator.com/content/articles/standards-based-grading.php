<h3 id="method-logic-rules">Method 4: Logic rules</h3>

<p>Instead of averaging, some schools define each letter by a pattern of scores. An example rule set:</p>

<ul>
<li><strong>A:</strong> every standard at 3 or higher, and at least half at 3.5 or 4.</li>
<li><strong>B:</strong> at least 80% of standards at 3 or higher, and none below 2.</li>
<li><strong>C:</strong> at least 60% of standards at 3 or higher, and none below 1.5.</li>
<li><strong>D/F:</strong> defined by the school for anything below the C rule.</li>
</ul>

<div class="example-box"><h4>Worked example: logic rules</h4>
<p>Scores: 3, 4, 2, 3, 3.5. Four of five standards (80%) are at 3 or higher, and the lowest is a 2.</p>
<p>The A rule fails (one score is below 3). The B rule passes. Result: <strong>B</strong>.</p>
</div>

<p>Logic rules stop a single very high score from hiding a weak one. They're harder to explain at first, but they match the spirit of SBG: an A should mean proficiency across the board, not an average that balances a gap with an extra-strong skill.</p>

