<h2 id="mistakes-to-avoid">Mistakes that keep GPAs from rising</h2>

<p>Many students work hard and still see little change because a few habits quietly undo their effort. Watch out for these:</p>

<ul>
<li><strong>Spreading effort evenly.</strong> Giving every class the same time ignores credits and weights. Your 4-credit lab science and its 50%-weight exams deserve more hours than a 1-credit seminar.</li>
<li><strong>Waiting until the final.</strong> By the time the final arrives, most of the grade is already locked in. Check your standing after every major test, while there's still time to adjust.</li>
<li><strong>Taking on too many credits at once.</strong> An overloaded semester can drag down every class. If you're rebuilding your GPA, a manageable load you can excel in often beats a heavy one you can only survive.</li>
<li><strong>Retaking without checking the policy.</strong> If your school averages attempts instead of replacing them, a retake helps less than you might expect (see Worked example 4).</li>
<li><strong>Studying passively.</strong> Highlighting and rereading feel productive, but self-testing and practice problems do far more for exam scores.</li>
<li><strong>Not asking for help.</strong> Tutoring centers, office hours, and study groups exist for exactly this. Using them early is a sign of a smart student, not a struggling one.</li>
</ul>

