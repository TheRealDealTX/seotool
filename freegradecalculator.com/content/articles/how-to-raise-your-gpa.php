<h3>A quick rule of thumb</h3>

<p>To raise your cumulative GPA by 0.1 point in one term, you need a term GPA of roughly:</p>

<div class="formula">Term GPA needed ≈ current GPA + 0.1 × (old credits + new credits) ÷ new credits</div>

<p>For example, with a 3.0 after 60 credits and a 15-credit term: 3.0 + 0.1 × 75 ÷ 15 = 3.0 + 0.5 = 3.5. Check it: (180 + 3.5 × 15) ÷ 75 = (180 + 52.5) ÷ 75 = 232.5 ÷ 75 = 3.10. It works.</p>

