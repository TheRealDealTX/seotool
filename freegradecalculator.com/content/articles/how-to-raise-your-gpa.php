<h2 id="gpa-math">The math: how your GPA actually moves</h2>

<p>Every grade earns grade points (A = 4.0, B = 3.0, and so on). Multiply those points by the course's credits and you get <strong>quality points</strong>. Your cumulative GPA is total quality points divided by total credits. If any of this is new, read <a href="/blog/what-is-gpa">What is GPA?</a> first.</p>

<div class="formula">Cumulative GPA = Σ (grade points × credits) ÷ Σ credits</div>

<p>When you add a new term, you simply combine the old quality points with the new ones:</p>

<div class="formula">New cumulative GPA = (old GPA × old credits + term GPA × term credits) ÷ (old credits + term credits)</div>

<p>That second formula explains everything about raising a GPA. The old credits act like an anchor. The bigger the anchor, the less any single term can pull the average.</p>

