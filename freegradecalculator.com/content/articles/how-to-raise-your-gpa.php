<h3>Working backward from a target</h3>

<p>Most students don't want to know what their GPA <em>will</em> be. They want to know what they <em>need</em>. Rearranging the formula gives you that:</p>

<div class="formula">Required GPA = (target GPA × total credits − current GPA × current credits) ÷ remaining credits</div>

<div class="example-box"><h4>Worked example 3: hitting a 3.3</h4>
<p>You have a 3.0 GPA after 60 credits, with 30 credits left in the next two semesters. You want a 3.3 by then.</p>
<p>Target quality points: 3.3 × 90 = 297.</p>
<p>Current quality points: 3.0 × 60 = 180.</p>
<p>Needed: 297 − 180 = 117 quality points over 30 credits.</p>
<p>Required GPA: 117 ÷ 30 = <strong>3.9</strong>. That's nearly straight A's, so it's possible but demanding. A target of 3.2 would need (288 − 180) ÷ 30 = <strong>3.6</strong>.</p></div>

