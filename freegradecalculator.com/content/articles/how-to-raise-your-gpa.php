<h2 id="high-school-students">Tips for high school students</h2>

<p>The same math applies in high school, usually with one credit per year-long class. A student with a 3.2 unweighted GPA after 18 credits who earns straight A's on the next 6 credits would reach (3.2 × 18 + 4.0 × 6) ÷ 24 = (57.6 + 24) ÷ 24 = 81.6 ÷ 24 = <strong>3.4</strong>.</p>

<p>Keep in mind that colleges usually see your grades through junior year (and sometimes first-semester senior grades) when you apply, so improvements in ninth through eleventh grade have the biggest effect on admissions. An upward trend is valuable on its own: many admissions offices notice students who get stronger over time.</p>

<p>If your school weights Honors and AP classes, taking a harder class can raise your weighted GPA, but only if you can earn a solid grade in it. See <a href="/blog/weighted-vs-unweighted-gpa">weighted vs. unweighted GPA</a> and try the <a href="/high-school-gpa-calculator">high school GPA calculator</a> to compare scenarios.</p>

