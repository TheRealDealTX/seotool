<h3>10. Never leave easy points on the table</h3>

<p>Homework, participation, labs, and quizzes are usually the most controllable part of your grade. A missing 10-point assignment costs the same as a wrong answer on a test, without any of the difficulty. Turn everything in, even if it's late and partial, unless your teacher says late work gets zero.</p>

<h3>11. Read the syllabus like a contract</h3>

<p>The syllabus tells you how your grade is weighted. If exams are 60% of the grade, an extra hour of exam prep is worth far more than an extra hour polishing a 5% assignment. Our guide to <a href="/blog/how-to-calculate-weighted-grades">calculating weighted grades</a> shows how each category affects your final number.</p>

<h3>12. Take care of the basics</h3>

<p>Sleep, food, and exercise aren't extras. Being well rested improves focus and memory, and studying while exhausted tends to be slow and error-prone. If stress, health, or life events are hurting your grades, reach out to your school's counseling or student support services. Many colleges also have tutoring centers and writing centers that are free to use.</p>

