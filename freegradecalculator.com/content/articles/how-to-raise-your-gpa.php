<h2 id="study-strategies">Study strategies that actually improve grades</h2>

<p>The math tells you where you need to go. These habits get you there. They're simple, but most students don't use them consistently.</p>

<h3>6. Go to office hours and ask specific questions</h3>

<p>Teachers and professors can tell you exactly what an A answer looks like. Bring a specific problem or a graded test and ask, "What would have made this answer stronger?" Students who go early in the term get the most out of it.</p>

<h3>7. Practice retrieving, don't just reread</h3>

<p>Rereading notes feels productive but isn't very effective. Instead, close the book and test yourself: flashcards, practice problems, or explaining a concept out loud. Pulling information from memory makes it stick far better than passively reviewing it.</p>

<h3>8. Space out your studying</h3>

<p>Four 30-minute sessions over a week beat one two-hour session the night before. Spacing gives your brain time to consolidate what you learned. Put review sessions on your calendar as soon as a test is announced.</p>

<h3>9. Work in focused blocks</h3>

<p>Phones and open tabs quietly drain study time. Try the Pomodoro method: 25 minutes of focused work, then a 5-minute break. Our free <a href="/pomodoro-timer">Pomodoro timer</a> tracks sessions for you.</p>

