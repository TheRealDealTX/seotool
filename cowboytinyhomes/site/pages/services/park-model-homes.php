  <h2>Popular Park Model Layouts</h2>
  <h3>The porch cabin</h3>
  <p>A single main floor with a full-width covered front porch, open kitchen and living space, a bathroom with a real shower and a bedroom at the back. Simple, durable and easy to cool.</p>
  <h3>The loft cabin</h3>
  <p>A main-floor bedroom plus a sleeping loft over the bathroom and kitchen for kids or guests. Lofts add sleeping space without adding to the counted floor area.</p>
  <h3>The rental getaway</h3>
  <p>A vaulted great room with big windows facing the view, a kitchenette, a spa-style bathroom and a deck sized for an outdoor dining table.</p>
