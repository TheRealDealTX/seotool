  <h2>What Is a Park Model Home?</h2>
  <p>A park model home — sometimes called a park model RV or park model tiny home — is a small, cabin-like dwelling usually designed at or just under 400 square feet. Most are built on a chassis so they can be delivered to a site, then set up semi-permanently with skirting, porches and utility hookups. They are typically parked in RV parks or on rural property situated outside city limits.</p>
  <p>The 400-square-foot line matters. Park model RVs are commonly built to the <strong>ANSI A119.5</strong> standard, which applies to units with no more than 400 square feet of floor area in the set-up mode. That is why so many park models are designed at about 399 square feet. Lofts generally do not count toward that floor area, which is how a well-designed park model can still sleep four.</p>
  <p>Cowboy Tiny Homes designs park model homes that feel like real cabins, not campers: higher ceilings, real porches and finishes that suit Texas land.</p>

