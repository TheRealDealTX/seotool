  <h2>ADU Rules in Texas: What to Check First</h2>
  <p>Texas has no single statewide ADU law for homeowners — rules come from your city, and outside city limits from your county, utility providers and any deed restrictions. Before design starts, our feasibility study looks at:</p>
  <ul>
    <li><strong>Whether ADUs are allowed</strong> in your zoning district, and whether by right or only through a special exception or permit.</li>
    <li><strong>Size limits,</strong> often expressed as a maximum square footage or a percentage of the main house.</li>
    <li><strong>Setbacks, height and lot coverage,</strong> which decide where the ADU can go and whether a second story is possible.</li>
    <li><strong>Parking, utilities and addressing,</strong> including whether the ADU can share the main home’s water, sewer and electric meters.</li>
    <li><strong>Occupancy and rental rules,</strong> such as owner-occupancy requirements or short-term rental permits.</li>
    <li><strong>HOA deed restrictions,</strong> which can prohibit or limit second dwellings even when the city allows them.</li>
  </ul>
  <p>Rules differ a lot between cities. Austin’s HOME code changes allow more units on many residential lots, San Antonio permits ADUs in many residential districts with size and design standards, Houston has no traditional zoning but deed restrictions matter, and parts of Dallas have historically required a special exception. Local details are on our <a href="/tiny-home-builders-austin/">Austin</a>, <a href="/tiny-home-builders-san-antonio/">San Antonio</a>, <a href="/tiny-home-builders-houston/">Houston</a>, <a href="/tiny-home-builders-dallas/">Dallas</a> and <a href="/tiny-home-builders-fort-worth/">Fort Worth</a> pages, and the bigger picture is in our <a href="/guides/tiny-house-laws-texas/">Texas tiny house laws guide</a>. Always confirm current rules with your city, because ADU codes are changing quickly.</p>

