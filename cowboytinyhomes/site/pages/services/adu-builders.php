  <h2>Designing an ADU That Works for Everyone on the Lot</h2>
  <p>A backyard home changes how the whole property works, so we design the ADU and its surroundings together. Privacy comes first: window placement, entry location and landscaping keep the main house and the casita from looking straight into each other. Then come the practical details — a separate path from the street or driveway, a spot for trash bins, outdoor lighting and a small private patio for the ADU occupant.</p>
  <p>If the ADU is for an aging parent, we plan for aging in place from the start: a zero-step entry, a curbless shower, wider doorways and blocking in the walls for future grab bars. If it is a rental, we focus on durable finishes, efficient heating and cooling, and a layout that rents well. If it is a studio or office, we prioritize natural light, sound separation and plenty of outlets.</p>

