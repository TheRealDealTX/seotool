  <h2>What Is an ADU?</h2>
  <p>An accessory dwelling unit (ADU) is a second, smaller home on a lot that already has a main house. In Texas you will hear them called backyard homes, granny flats, mother-in-law suites, guest homes, casitas, pool houses and garage apartments. Whatever the name, an ADU is a permanent structure with its own living space — usually a kitchen or kitchenette, a bathroom and a place to sleep — built to the International Residential Code (IRC) and the zoning code of the city where it sits.</p>
  <p>Cowboy Tiny Homes works as both designer and builder on ADU projects, which means the same team that checks your setbacks also draws the plans and manages construction. Fewer handoffs means fewer surprises.</p>

