      <h2 id="per-sqft">Why tiny homes cost more per square foot</h2>
      <p>People are often surprised that a tiny house can cost more per square foot than a big suburban home. The reason is simple: the expensive parts of any house — the kitchen, the bathroom, the electrical panel, the water heater, the HVAC system, windows and doors — do not shrink much when the house does. A 300-square-foot home still needs a full kitchen and bath. Spread those fixed costs over fewer square feet and the per-foot number climbs.</p>
      <p>Tiny homes on wheels add their own costs: a heavy-duty trailer, extra structural tie-downs, lightweight materials and building to an RV standard for certification. ADUs and foundation homes add slab or pier foundations, permit fees and code inspections.</p>

