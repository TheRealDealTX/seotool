      <h2 id="definitions">What each one is</h2>
      <h3>Accessory dwelling unit (ADU)</h3>
      <p>An ADU is a second, permanent home on the same lot as a main house — often called a casita, granny flat, guest house, backyard cottage or mother-in-law suite. It sits on a foundation, is built to the International Residential Code and is permitted and inspected by the city. Some ADUs are detached; others are attached or built over a garage.</p>
      <h3>Park model home</h3>
      <p>A park model RV is a cabin-style home built on a chassis and designed for long-term placement, typically at under 400 square feet when set up. It is built to the ANSI A119.5 standard, legally treated as a recreational vehicle, and usually moved once — to its site — then skirted, connected to utilities and often given a porch.</p>
      <h3>Tiny house on wheels (THOW)</h3>
      <p>A THOW is built on a bumper-pull or gooseneck trailer and designed to be towed. Most are 8 feet 6 inches wide or less so they can travel without oversize permits, and up to roughly 40 feet long. When built to an RV standard and certified by RVIA or an inspector like NOAH, it is titled as an RV.</p>

