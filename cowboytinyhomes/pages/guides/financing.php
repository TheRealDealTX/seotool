      <h2 id="approval">How to improve your chances of approval</h2>
      <ul>
        <li><strong>Choose a certified or code-built home.</strong> RVIA/NOAH certification for homes on wheels, or IRC-compliant plans and permits for foundation homes.</li>
        <li><strong>Get detailed plans and a written quote.</strong> Lenders want to see exactly what they are financing.</li>
        <li><strong>Check your credit</strong> and pay down high-interest debt before applying.</li>
        <li><strong>Save a down payment.</strong> Even 10–20% can improve your rate and approval odds.</li>
        <li><strong>Talk to credit unions.</strong> Local Texas credit unions can be more flexible with unusual properties.</li>
        <li><strong>Get pre-qualified</strong> before you finalize your design, so your plans fit your budget.</li>
      </ul>

