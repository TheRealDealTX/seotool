      <h2 id="why-hard">Why tiny home financing is different</h2>
      <p>Traditional mortgages are designed for real estate: a house permanently attached to land that a lender can appraise against comparable sales. Many tiny homes do not fit that box. A tiny house on wheels is legally a vehicle. A park model is usually personal property. Even a foundation tiny home can be hard to appraise when there are few similar sales nearby, and some lenders set minimum loan amounts or square footage.</p>
      <p>So the first step is knowing what you are building. Our <a href="/guides/adu-vs-park-model-vs-tiny-house-on-wheels/">ADU vs park model vs tiny house on wheels guide</a> explains the categories; the options below are matched to each.</p>

      <h2 id="options">The 7 main financing options</h2>
      <h3 id="rv">1. RV loans</h3>
      <p><strong>Best for:</strong> tiny houses on wheels and park models that are RVIA certified or inspected to an RV standard. RV loans are secured by the home itself, work much like auto loans and often offer longer terms than personal loans. Lenders usually require proof of certification, a down payment and good credit. Without certification, many RV lenders will decline.</p>

      <h3 id="personal">2. Personal loans</h3>
      <p><strong>Best for:</strong> smaller budgets, uncertified builds, DIY materials or filling a gap. Personal loans are usually unsecured, fund quickly and do not care what you build. The trade-offs are typically higher interest rates, shorter terms and lower maximum amounts than secured loans, which can make monthly payments steep on a larger home.</p>

      <h3 id="equity">3. Home equity loan, HELOC or cash-out refinance</h3>
      <p><strong>Best for:</strong> backyard ADUs and casitas when you already own a home with equity. Borrowing against your house often brings lower rates than unsecured loans, and a HELOC lets you draw money as construction progresses. Texas has its own home equity rules: in most cases, total borrowing against a homestead is capped at 80% of the home's value, and there are required waiting periods and disclosures. Talk with a Texas lender who knows these rules well.</p>

      <h3 id="construction">4. Construction loans</h3>
      <p><strong>Best for:</strong> custom tiny or small homes on a foundation and larger ADUs. A construction loan pays the builder in draws as work is completed and inspected, then often converts to a permanent mortgage at the end (a "construction-to-permanent" loan). Expect the lender to want detailed plans, a fixed-price contract, a builder they approve and a down payment.</p>

      <h3 id="mortgage">5. Traditional mortgage</h3>
      <p><strong>Best for:</strong> permanent foundation homes on land you own, built to the local residential code. A small home that meets code, sits on its own land and can be appraised may qualify for conventional, FHA, VA or USDA loans, depending on the program and lender. Very small homes can be harder to appraise, so ask lenders early about minimum square footage and comparable sales.</p>

      <h3 id="chattel">6. Chattel loans</h3>
      <p><strong>Best for:</strong> manufactured homes and some park models placed on land you do not own or on leased lots. A chattel loan is secured by the home as personal property, not by land. They are common in manufactured housing but usually carry higher rates and shorter terms than mortgages.</p>

      <h3 id="builder">7. Builder or manufacturer financing — and cash</h3>
      <p>Some builders partner with lenders who understand tiny homes, which can make approval smoother. Compare those offers against your own bank or credit union. And many tiny home buyers pay cash, or combine savings with a smaller loan — one of the biggest draws of living small is owning your home outright years sooner.</p>

