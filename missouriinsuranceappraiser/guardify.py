#!/usr/bin/env python3
"""Canonical-host guard for static sites on Hostinger Agency hosting.

The host ignores .htaccess and serves real files (dir/index.html) without running the root
index.php front controller, so www. and plain-http requests for interior pages never hit the
redirect logic. This tool rewrites a built site directory IN PLACE so every page runs a guard:

  * every page dir/index.html  ->  dir/index.php starting with
        <?php require_once dirname(__DIR__, n) . '/_guard.php'; ?>
    followed by the unchanged HTML
  * writes _guard.php: 301 www. and http -> https://<host> (real domain only), sends
    X-Robots-Tag: noindex on every other host, 404 if requested directly
  * patches the root index.php: requires the guard and looks for / includes dir/index.php

Idempotent. Usage:  python3 guardify.py <site_dir> <host> [--list-converted]
Prints the converted page paths (relative, index.html form) with --list-converted, so a deploy
script can delete the stale dir/index.html files on the server.
"""
import os
import re
import sys

SKIP_DIRS = {"api", "assets", "wp-content", "wp-includes", "backup", ".h5g", "_config", "_private"}

GUARD_PHP = r"""<?php
// Canonical host guard, required by index.php and by every page's index.php (generated by guardify.py).
if (realpath($_SERVER['SCRIPT_FILENAME'] ?? '') === __FILE__) { http_response_code(404); exit; }
$cg_host  = strtolower(preg_replace('/:\d+$/', '', $_SERVER['HTTP_HOST'] ?? ''));
$cg_real  = '__HOST__';
// TLS terminates upstream: trust X-Forwarded-Proto, fall back to HTTPS.
$cg_proto = strtolower($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? ((!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http'));
// 301 www. and plain http to https://__HOST__ - only on the real domain.
if ($cg_host === 'www.' . $cg_real || ($cg_host === $cg_real && $cg_proto === 'http')) {
    header('Location: https://' . $cg_real . ($_SERVER['REQUEST_URI'] ?? '/'), true, 301);
    exit;
}
// A page requested as /dir/index.php (or /index.php) is a duplicate URL: 301 to the directory.
if (preg_match('#^(.*/)index\.php$#', strtok($_SERVER['REQUEST_URI'] ?? '/', '?'), $idx_m)) {
    $idx_q = strpos($_SERVER['REQUEST_URI'], '?') !== false ? substr($_SERVER['REQUEST_URI'], strpos($_SERVER['REQUEST_URI'], '?')) : '';
    header('Location: ' . $idx_m[1] . $idx_q, true, 301);
    exit;
}
// Keep temporary preview domains out of search results.
if ($cg_host !== $cg_real) {
    header('X-Robots-Tag: noindex, nofollow');
}
header('Content-Type: text/html; charset=utf-8');
"""

GUARD_LINE = "<?php require_once dirname(__DIR__, {n}) . '/_guard.php'; ?>\n"
GUARD_RE = re.compile(r"^<\?php require_once dirname\(__DIR__, \d+\) \. '/_guard\.php'; \?>\n")


def die(msg):
    sys.exit("guardify: " + msg)


def convert_pages(root):
    converted = []
    for dp, dns, fns in os.walk(root):
        rel_dir = os.path.relpath(dp, root)
        if rel_dir == ".":
            dns[:] = [d for d in dns if d not in SKIP_DIRS]
            continue
        dns[:] = [d for d in dns if d not in SKIP_DIRS]
        if "index.html" not in fns:
            continue
        src = os.path.join(dp, "index.html")
        html = open(src, encoding="utf-8").read()
        if not re.match(r"\s*<!doctype html", html, re.I):
            continue  # not a site page
        if "<?" in html:
            die(f"{src} contains '<?' - refusing to wrap it in PHP")
        n = rel_dir.count(os.sep) + 1
        dst = os.path.join(dp, "index.php")
        if os.path.exists(dst):
            die(f"{dst} already exists next to index.html")
        with open(dst, "w", encoding="utf-8") as f:
            f.write(GUARD_LINE.format(n=n) + html)
        os.remove(src)
        converted.append(rel_dir.replace(os.sep, "/") + "/index.html")
    return sorted(converted)


def patch_controller(root):
    p = os.path.join(root, "index.php")
    if not os.path.exists(p):
        die("no root index.php")
    s = open(p, encoding="utf-8").read()
    if "_guard.php" not in s:
        if not s.startswith("<?php\n"):
            die("root index.php does not start with '<?php\\n'")
        s = "<?php\nrequire_once __DIR__ . '/_guard.php';\n" + s[len("<?php\n"):]
    # page lookups: dir/index.html -> dir/index.php
    s = s.replace("index.html')", "index.php')")
    # serving a page must execute it, not print its source
    s = re.sub(r"readfile\(__DIR__ \. \$path \. 'index\.php'\);", "include __DIR__ . $path . 'index.php';", s)
    s = re.sub(r"\$serve\(__DIR__ \. \$path \. 'index\.php'\);", "include __DIR__ . $path . 'index.php'; exit;", s)
    if re.search(r"(readfile|\$serve)\([^)]*index\.php", s):
        die("root index.php still readfile()s a PHP page - patch it by hand")
    open(p, "w", encoding="utf-8").write(s)


def main():
    if len(sys.argv) < 3:
        die("usage: guardify.py <site_dir> <host> [--list-converted]")
    root, host = sys.argv[1], sys.argv[2].lower()
    if not re.fullmatch(r"[a-z0-9.-]+\.[a-z]{2,}", host):
        die(f"bad host {host!r}")
    conv = convert_pages(root)
    with open(os.path.join(root, "_guard.php"), "w", encoding="utf-8") as f:
        f.write(GUARD_PHP.replace("__HOST__", host))
    patch_controller(root)
    if "--list-converted" in sys.argv:
        print("\n".join(conv))
    else:
        print(f"guardify: {len(conv)} pages wrapped, _guard.php written, index.php patched", file=sys.stderr)


if __name__ == "__main__":
    main()
