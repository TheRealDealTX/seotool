<li>Cracks or creases</li>
</ul>
<p>Hail damage is random. Wear is uniform. That distinction matters.</p>
<h3>Metal Roofing Systems</h3>
<p>Metal dents. It doesn’t always fail immediately but it weakens.</p>
<p><strong>Watch for:</strong></p>
<ul>
<li>Panel dents</li>
<li>Seam distortion</li>
<li>Coating damage</li>
<li>Loose fasteners</li>
</ul>
<p>And remember damage near seams is rarely just cosmetic.</p>
<h3>Tile Roofs (Clay &amp; Concrete)</h3>
<p>Strong, but brittle.</p>
