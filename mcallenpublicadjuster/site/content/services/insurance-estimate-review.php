<h2>What a Review Looks Like</h2>
<p>A typical review starts with the summary page, then works through each area of the estimate: roof, elevations, interior rooms, and contents. Each line is compared against photos and measurements of the property, and against what a licensed contractor would need to do the work correctly and to current code. The result is a short list of questions and differences, such as missing lines, short quantities, pricing concerns, and depreciation issues, that you can decide how to handle. Sometimes the conclusion is that the estimate is reasonable, and that is useful to know too.</p>

