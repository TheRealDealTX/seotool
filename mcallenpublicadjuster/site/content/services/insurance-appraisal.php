<h2>When Appraisal May Make Sense</h2>
<p>Appraisal tends to fit best when the remaining dispute is narrow and measurable. Examples include a disagreement over whether a hail-damaged roof should be repaired or replaced, how many squares of shingles are needed, whether unit prices reflect McAllen-area labor and material costs, or how much drying and rebuild work a water loss requires. It tends to fit poorly when the insurer has denied the claim outright, when the policy has an exclusion squarely at issue, or when the gap between estimates is small compared with the cost of appraisers and an umpire. Before anyone sends a demand, it helps to list the disputed items, attach the supporting evidence for each, and confirm that the disagreement truly is about amount.</p>

<h2>Common Appraisal Issues</h2>
<ul>
<li><strong>Coverage vs. amount.</strong> If the insurer denies that a loss is covered, appraisal usually cannot resolve that. Mixed disputes can be complicated; see <a href="/services/denied-insurance-claims/">denied insurance claims</a>.</li>
<li><strong>Appraiser impartiality.</strong> Policies often require appraisers to be impartial, and challenges can arise.</li>
<li><strong>Umpire selection.</strong> Delays in agreeing on an umpire can slow the process.</li>
<li><strong>Unclear awards.</strong> Awards that do not itemize or separate categories can create later disputes about payment.</li>
</ul>

