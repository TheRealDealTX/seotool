<h2>How a Supplement Is Built</h2>
<p>A strong supplement is easy for the desk adjuster to follow. It typically includes a short cover letter that identifies the claim number and date of loss, a list of each added or corrected item, a line-item estimate that uses the same format as the insurer's estimate, and photos labeled to match each line. Where code items are involved, it cites the permit or inspector requirement. Where hidden damage is involved, it shows the condition before and after the area was opened. The goal is to make each requested item verifiable without another inspection, although the insurer may still choose to re-inspect.</p>
