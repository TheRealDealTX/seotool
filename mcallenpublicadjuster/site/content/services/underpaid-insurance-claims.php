<h2>Insurance Settlement Considerations</h2>
<h3>Recoverable depreciation</h3>
<p>On replacement cost policies, insurers typically pay actual cash value first and release recoverable depreciation after repairs are completed, often within a deadline stated in the policy. Missing that deadline can cost you the holdback, so keep track of it.</p>
<h3>Code upgrades</h3>
<p>The City of McAllen adopted the 2024 ICC codes effective January 1, 2026. Code-required work is paid only to the extent your policy includes ordinance or law coverage. See <a href="/local-building-codes/">local building codes</a>.</p>
<h3>Partial payments</h3>
<p>An insurer may pay the amount it agrees with while the rest is still disputed. That money can help you start repairs. Read any letter that comes with the check so you understand whether the insurer considers the claim closed.</p>
<h3>Supplements and appraisal</h3>
<p>Many underpayments are fixed through a <a href="/services/insurance-claim-supplements/">supplement</a> that adds missing items with supporting documentation. When the parties cannot agree on the amount, the policy's <a href="/services/insurance-appraisal/">appraisal</a> clause may be an option.</p>

