<h2>Documenting the building, component by component</h2>

<h3>Low-slope and metal roofs</h3>

<p>Many McAllen commercial buildings have flat or low-slope roofs (TPO, PVC, modified bitumen, or built-up systems) or metal panel roofs. Damage on these roofs can be subtle from the ground.</p>

