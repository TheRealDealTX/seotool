<li><strong>Soft metals:</strong> dents in vents, flashing, gutters, and HVAC fins help show hail size and direction.</li>
<li><strong>Moisture:</strong> a roof moisture survey, such as infrared or core sampling done by a qualified roofer, can show where water has entered the roof system.</li>
<li><strong>Interior:</strong> photograph ceiling tile staining, wet insulation, and water on floors directly below roof damage.</li>
