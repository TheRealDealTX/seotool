<h2>Inventory and business personal property</h2>

<p>For retailers, restaurants, distributors, and medical offices, contents can rival the building damage. A systematic approach helps:</p>

<ul>
<li>Take a continuous video walkthrough of every room and storage area before anything is moved.</li>
<li>Group damaged items by category, and photograph labels, SKUs, and quantities.</li>
<li>Pull inventory records from your point-of-sale or inventory management system as of the date of loss.</li>
<li>Separate damaged from undamaged stock and keep it, or samples, until the insurer inspects or agrees to disposal, unless health rules require removal (for example, spoiled food).</li>
<li>Record equipment serial numbers and keep purchase invoices for computers, kitchen equipment, and specialty tools.</li>
</ul>

<h2>Business income and extra expense records</h2>

<p>If the storm forced you to close or limit operations, your policy may include business income and extra expense coverage. These claims are mostly about numbers, and the insurer will usually ask for:</p>

<ul>
<li>Profit and loss statements for the period before the loss and the same period in prior years.</li>
<li>Monthly sales records and tax returns.</li>
<li>Payroll records, including employees kept on during closure.</li>
<li>Receipts for extra expenses: temporary locations, equipment rental, expedited shipping, overtime.</li>
<li>A timeline of when the business closed, partially reopened, and fully reopened.</li>
</ul>

<p>Policies vary. Many include a waiting period before business income coverage starts and define a "period of restoration" tied to how long repairs should reasonably take. Delays in getting the building repaired can affect a business income claim, so keep notes on contractor availability and permit timing. Repairs in McAllen may require permits under the City's adopted 2024 ICC codes; see our <a href="/local-building-codes/">local building codes</a> page.</p>

<h2>Tenant leases and who is responsible for what</h2>

<p>In multi-tenant buildings, the lease often decides whose insurance pays for which part of the loss. Before filing, both landlords and tenants should review:</p>

<ul>
<li><strong>Insurance clauses:</strong> who must insure the structure, the roof, and tenant improvements.</li>
<li><strong>Repair and maintenance clauses:</strong> who maintains the roof and rooftop HVAC units. Many leases put RTU maintenance on the tenant even when the roof belongs to the landlord.</li>
<li><strong>Casualty clauses:</strong> rent abatement, repair timelines, and termination rights after damage.</li>
<li><strong>Improvements and betterments:</strong> who owns the build-out, which affects whose policy may respond.</li>
<li><strong>Waiver of subrogation:</strong> provisions that affect whether one party's insurer can pursue the other.</li>
</ul>

<p>Notify every carrier that may have an interest, and share photos between landlord and tenant so both claims tell the same story. Lease interpretation questions belong with a Texas attorney.</p>

<h2>Records from mitigation vendors</h2>

<p>Water mitigation companies, board-up services, and emergency roofers create records that often carry weight in commercial claims. Ask each vendor for:</p>

<ul>
<li>Initial moisture maps and daily drying logs.</li>
<li>Photos taken on arrival and at completion.</li>
<li>Equipment lists with placement dates and removal dates.</li>
<li>Itemized invoices, not just a lump sum.</li>
<li>Notes on any materials removed and why.</li>
</ul>

<p>Read work authorizations carefully before signing, especially any assignment of benefits or direction-to-pay language, and keep copies of everything.</p>

<h2>Photo, video, and drone protocol</h2>

<p>Good photos tell a story an adjuster can follow without being there. Use a consistent protocol:</p>

<ol>
<li><strong>Wide shots first.</strong> Photograph each elevation of the building (north, south, east, west) and the full roof.</li>
<li><strong>Medium shots.</strong> Each damaged area in context, so the adjuster can tell where it is on the building.</li>
<li><strong>Close-ups with scale.</strong> Use a tape measure, coin, or chalk circle to show hail mark size and damage detail.</li>
<li><strong>Date and location.</strong> Keep original files with metadata. Do not crop or filter the originals.</li>
<li><strong>Video walkthroughs.</strong> Narrate as you walk: where you are, what you see, and when it happened.</li>
<li><strong>Drone images.</strong> Useful for large or steep roofs and roof-wide damage patterns. Commercial drone work is generally subject to FAA remote pilot rules, so use a qualified operator.</li>
<li><strong>3D imaging.</strong> Tools like Matterport can capture interior conditions in a way that is easy to revisit later.</li>
<li><strong>Organize by area.</strong> Label folders by building, elevation, roof section, and suite number.</li>
</ol>

<p>Pair your photos with weather evidence. NOAA's Storm Events Database and our <a href="/storm-lookup/">storm lookup</a> tool can help confirm hail and wind near your property on the date of loss. Our <a href="/noaa-weather-records-document-property-damage-mcallen/">guide to NOAA weather records</a> explains how to use them.</p>

<h2>Common mistakes on commercial storm claims</h2>

<ul>
<li>Waiting until a roof leak appears months later to report hail damage.</li>
<li>Throwing out damaged inventory before it is documented.</li>
<li>Reporting only the building and forgetting business income or contents.</li>
<li>Assuming the landlord's policy covers tenant improvements, or the reverse.</li>
<li>Signing a final proof of loss before all damage, including hidden roof moisture, is identified.</li>
</ul>

