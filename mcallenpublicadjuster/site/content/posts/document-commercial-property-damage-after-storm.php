<h3>Rooftop HVAC units</h3>

<p>Rooftop units (RTUs) are expensive and frequently damaged by hail and wind. Document each unit separately:</p>

<ul>
<li>Data plate photo showing make, model, serial number, and manufacture date.</li>
<li>Condenser coil fin damage, close up and at a distance.</li>
<li>Dented housings, displaced access panels, and damaged curbs or rails.</li>
<li>Unit displacement from wind and any torn ductwork or roof penetrations.</li>
<li>An HVAC contractor's written assessment of whether damage affects performance.</li>
</ul>

<h3>Signage</h3>

<p>Pylon signs, monument signs, and building-mounted signs can crack, lose faces, or bend at the supports. Photograph the sign from multiple angles, the electrical components, and any debris on the ground. Signs may be covered under building coverage, as business personal property, or under a specific sign limit, depending on the policy and whether the landlord or tenant owns the sign.</p>

<h3>Storefront glass and doors</h3>

<p>Wind-borne debris and large hail can break storefront glass and damage aluminum framing. Photograph each broken pane before boarding, with something for scale. Note glass type (tempered, laminated, insulated) and any damage to frames, door closers, and seals. Keep boarding and emergency glazing invoices.</p>

<h3>Exterior walls, fencing, and parking areas</h3>

<p>Look at stucco and EIFS for impact marks, metal wall panels for dents, fencing for leaning sections, and parking lot light poles and canopies. Some of these may have separate limits or exclusions under commercial forms, so record them even if you are unsure they are covered.</p>

