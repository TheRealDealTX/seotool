<h3>Structural damage</h3>
<p>Fire burns visible surfaces, but the larger concerns are often hidden: weakened framing and roof decking, wiring exposed to extreme heat, plumbing affected by heat, and damaged windows and doors. Estimates built only on what is visible can miss these. Inspections should include the attic, wall cavities where they are opened, and the mechanical systems. A licensed electrician’s evaluation is often warranted.</p>

<h3>Contents inventory</h3>
<p>The contents claim is often the most labor-intensive part of a fire loss. Go room by room, including closets, cabinets, drawers, the garage, and storage. For each item, list a description, quantity, approximate age, and replacement cost. Photos, receipts, bank or card statements, and old family photos showing your belongings all help. Many policies have special limits for jewelry, firearms, cash, and collectibles. Under replacement cost coverage, insurers often pay actual cash value first and release depreciation once you replace items. Our guide to <a href="/replacement-cost-vs-actual-cash-value-texas/">replacement cost vs. actual cash value</a> explains how that works.</p>

<h3>Additional living expenses (loss of use)</h3>
<p>If a covered fire makes your home uninhabitable, loss of use coverage may pay the <em>increase</em> in your living costs. That can include temporary housing, extra meals out, added mileage, and laundry. Coverage limits and time periods vary. Keep every receipt, and track your normal expenses so the increase is easy to show.</p>

<h3>Smoke and soot</h3>
<p>Smoke spreads well beyond the burned area, into wall cavities, ductwork, insulation, clothing, and upholstery. Soot residue can be corrosive and may keep damaging materials if it is not cleaned properly. Disputes often center on whether rooms away from the fire need professional cleaning, sealing, or replacement. Our <a href="/services/smoke-damage-claims/">smoke damage claims</a> page goes into more detail.</p>

<h3>Water from firefighting</h3>
<p>Firefighters use large amounts of water, and it soaks into subfloors, drywall, cabinets, and insulation. In the humid Rio Grande Valley (RGV) climate, wet materials can grow mold quickly. Make sure drying is started and documented with moisture readings. Water used to fight a covered fire is generally handled as part of the fire claim. It is not a flood claim.</p>

