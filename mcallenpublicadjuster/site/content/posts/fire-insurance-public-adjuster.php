<h2>How a fire insurance public adjuster works for you</h2>

<h3>1. On-site assessment</h3>
<p>The adjuster inspects and documents the structure, contents, smoke spread, and moisture, using photographs, moisture readings, and in some cases Matterport 3D imaging. This matters most before debris removal and demolition change the scene.</p>

<h3>2. Policy review</h3>
<p>Next is the policy: replacement cost and actual cash value provisions, ALE limits, ordinance or law coverage, contents sub-limits, and, for businesses, business income endorsements. Your declarations page and endorsements control the outcome.</p>

<h3>3. Estimates and inventories</h3>
<p>The adjuster prepares a line-item reconstruction estimate (commonly in Xactimate), a contents inventory with pricing support, and a documented smoke and water scope. Each can be compared directly with the insurer’s figures.</p>

<h3>4. Presentation and negotiation</h3>
<p>The adjuster presents the documented claim, responds to the insurer’s questions, requests re-inspections when warranted, and submits supplements when hidden damage turns up during reconstruction. If the disagreement is over the amount of loss, the appraisal clause may be an option. See insurance appraisal.</p>

