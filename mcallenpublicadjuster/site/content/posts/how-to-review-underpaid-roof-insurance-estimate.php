<h2>Step 5: Spot repair vs. full replacement</h2>

<p>Sometimes the insurer agrees there is damage but estimates a spot repair: a few shingles on one slope. Ask whether repair is realistic. Considerations include whether replacement shingles are still available in a matching color and profile, whether the existing shingles are brittle enough to break during repair, and how much of each slope is damaged. Bring photos and, ideally, a written opinion from a roofer. Our article on <a href="/roof-hail-damage-insurance-claim-mcallen/">roof hail damage claims in McAllen</a> discusses repairability in more detail.</p>

<h2>Step 6: Request a supplement or re-inspection</h2>

<p>If your review turns up missing or underpriced items, respond in writing. A clear supplement request usually includes:</p>

<ol>
<li>The claim number, date of loss, and property address.</li>
<li>A list of each item you believe is missing or underpriced, with the quantity and unit.</li>
<li>The reason each item is needed (damage, manufacturer requirement, code, measurement correction).</li>
<li>Supporting photos, measurement reports, and your contractor's estimate.</li>
<li>A request for a revised estimate or a re-inspection, and a reasonable date for a response.</li>
</ol>

<p>If you ask for a re-inspection, try to be there with your roofer so items can be pointed out on the roof. Keep notes of who attended and what was agreed. Our page on <a href="/services/insurance-claim-supplements/">insurance claim supplements</a> and the article on <a href="/hail-damage-claim-supplements/">hail damage claim supplements</a> explain the process further.</p>

<p>Texas law sets claim-handling timelines. Under Texas Insurance Code Chapter 542, after an insurer receives all the items it requested, it generally has 15 business days to accept or reject the claim, with a possible extension of up to 45 days if it notifies you it needs more time. Deadlines may be extended by 15 days after a declared weather catastrophe. Supplements are part of an ongoing claim, so keep everything in writing.</p>

<h2>Step 7: Consider appraisal if you cannot agree on the amount</h2>

<p>Many property policies include an appraisal clause for disputes about the <strong>amount</strong> of loss. Either party can demand appraisal; each side chooses an appraiser, the two appraisers choose an umpire, and an award agreed to by any two of the three is binding on the amount, as the policy language provides. Appraisal does not decide coverage questions, such as whether the damage was caused by a covered storm. See our <a href="/services/insurance-appraisal/">insurance appraisal</a> page for more.</p>

<p>If the issue is a denial or a coverage question, appraisal may not be the right tool. For legal questions, including bad faith or deadlines to sue, consult a Texas attorney.</p>

