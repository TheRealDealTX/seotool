<h2>Step 4: Look at depreciation</h2>

<p>Depreciation is often the biggest reason the first check feels low. Actual cash value equals replacement cost minus depreciation. Under a replacement-cost policy, the insurer typically pays ACV first and releases recoverable depreciation after the work is completed, often within a deadline stated in the policy.</p>

<p>Some Texas homeowners policies cover roofs only at actual cash value or use a roof payment schedule based on the roof's age. In those cases, depreciation may be non-recoverable. Check your declarations page and endorsements, and compare them with how depreciation is labeled on the estimate. Also check how depreciation was calculated: the age used for the roof, and whether depreciation was applied to labor as well as materials, can make a real difference. For more, read <a href="/replacement-cost-vs-actual-cash-value-texas/">replacement cost vs. actual cash value in Texas</a>.</p>

