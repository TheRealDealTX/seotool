<h3>Steep and high charges</h3>
<p>Working on a steep or tall roof takes more time and safety equipment. Xactimate typically breaks steep charges out by slope range, and high-roof charges apply to roof areas two stories or higher. These are separate line items, and they are often missed or applied to only part of the roof. Check that they appear for both tear-off and installation where the roof qualifies.</p>

<h3>Overhead and profit (O&amp;P)</h3>
<p>O&amp;P covers a general contractor's costs to manage the job and a reasonable profit. Insurers frequently leave it out of roof-only estimates. When the repair involves several trades, such as roofing, gutters, interior drywall, insulation, and paint, the case for O&amp;P is stronger. Whether it applies depends on the scope and your policy, so ask for an explanation if it is missing.</p>

<h3>Sales tax</h3>
<p>Material lines usually carry sales tax. Make sure tax is applied and that it is calculated on the right items.</p>

