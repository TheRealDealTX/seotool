<h2>Step 2: Check the measurements</h2>

<p>A roofing <strong>square</strong> equals 100 square feet. Shingles, tear-off, and underlayment are priced per square, while starter, ridge, drip edge, and flashing are priced per linear foot. If the base measurements are low, every line built on them is low.</p>

