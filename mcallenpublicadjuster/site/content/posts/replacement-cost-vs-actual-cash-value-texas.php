<h2>Replacement cost vs. actual cash value: the definitions</h2>

<h3>Replacement cost value (RCV)</h3>

<p>Replacement cost value is the cost to repair or replace damaged property with materials of like kind and quality, at today's prices, without a deduction for age or wear. On a roof claim, RCV includes tear-off, materials, labor, and items like underlayment, flashing, vents, and drip edge, plus contractor overhead and profit where appropriate.</p>

<h3>Actual cash value (ACV)</h3>

<p>Actual cash value is generally replacement cost minus depreciation. Depreciation reflects the portion of the item's useful life that has already been used up. A 12-year-old composition shingle roof will usually carry more depreciation than a 3-year-old one, even if the hail damaged both equally.</p>

<p>Policies define these terms themselves, and Texas policy forms vary. Read the definitions section of your own policy rather than relying on a general rule.</p>

<h3>Depreciation</h3>

<p>Depreciation is usually calculated based on the item's age, condition, and expected life. Adjusters often apply it line by line in estimating software such as Xactimate. Two numbers deserve close attention on any estimate: the depreciation percentage applied to each line, and whether it is labeled recoverable or non-recoverable.</p>

