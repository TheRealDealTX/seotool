<h2>Roof ACV endorsements and payment schedules in Texas</h2>

<p>Roof coverage is where Texas policies vary most. A policy can cover the dwelling at replacement cost but treat the roof differently. Common approaches include:</p>

<ul>
<li><strong>Roof ACV endorsement.</strong> Roof surfacing is settled at actual cash value, even though the rest of the home is covered at replacement cost. Depreciation on the roof is non-recoverable.</li>
<li><strong>Roof payment schedule.</strong> Payment for the roof is a percentage of replacement cost based on the roof's age and sometimes its material, according to a schedule in the policy.</li>
<li><strong>Cosmetic damage exclusions.</strong> Some policies exclude cosmetic hail damage to metal roofing or other surfaces that does not affect function.</li>
<li><strong>Replacement cost on the roof.</strong> Some policies still cover the roof at full replacement cost with recoverable depreciation.</li>
</ul>

<p>These terms are usually listed on the declarations page or attached as endorsements. Review them before a storm, not after. If you live in McAllen, where hail season peaks in April and May according to NOAA records, roof settlement terms are worth discussing with your agent at every renewal. Our <a href="/roof-hail-damage-insurance-claim-mcallen/">roof hail damage claim guide</a> covers the inspection side.</p>

<h2>Deadlines to complete repairs</h2>

<p>Many replacement cost policies require you to complete repairs, or at least notify the insurer of your intent to claim replacement cost, within a set time after the loss or after the ACV payment. The period differs by policy form and insurer. Some policies allow extensions on request.</p>

<p>Practical steps:</p>

<ul>
<li>Find the deadline in your policy's loss settlement or replacement cost section and put it on your calendar.</li>
<li>If repairs will be delayed by contractor backlogs, permitting, or material shortages, ask the insurer in writing for an extension before the deadline passes, and keep the response.</li>
<li>Keep the final invoice, proof of payment, photos of the completed work, and any permit inspection records.</li>
<li>Submit the depreciation release request promptly with all documents in one package.</li>
</ul>

<p>Repairs in McAllen may need a building permit, and the City adopted the 2024 ICC codes effective January 1, 2026. Code-required items may raise the repair cost. Whether the insurer pays for those upgrades depends on ordinance or law coverage. Our <a href="/local-building-codes/">local building codes</a> page explains how that works.</p>

<div class="callout callout-warn"><span class="callout-title">Policy deadlines and legal deadlines are different</span><p>The deadline to complete repairs for replacement cost benefits is separate from any deadline to file a lawsuit. Many Texas policies contain contractual limitations periods. If you are concerned about a legal deadline, consult a Texas attorney.</p></div>

<h2>How contents and other structures are often handled</h2>

<p>The same RCV and ACV concepts apply beyond the roof. Personal property (contents) may be covered at replacement cost or ACV depending on your policy and any endorsements. When contents are covered at replacement cost, insurers commonly pay ACV first and release the depreciation once you replace the item and submit a receipt. Fences, detached garages, and other structures are usually covered under a separate coverage part with its own limit, and the loss settlement terms may differ from the dwelling.</p>

<p>For a large contents claim, such as items damaged by water entering through a storm-damaged roof, keep a running inventory with descriptions, ages, and replacement prices, and save every replacement receipt. Without receipts, recovering held-back depreciation on contents can be difficult. Our <a href="/claim-documentation-checklist/">claim documentation checklist</a> includes a contents section.</p>

<h2>Common depreciation problems to look for</h2>

<ul>
<li><strong>Excessive roof age.</strong> Depreciation based on the wrong installation year. Permit records or receipts can help confirm the actual age.</li>
<li><strong>Depreciation on items that should not be depreciated</strong> under your policy wording, or applied inconsistently line to line.</li>
<li><strong>Recoverable mislabeled as non-recoverable,</strong> or the reverse.</li>
<li><strong>Missing line items</strong>, such as drip edge, starter, ridge cap, or code-required underlayment. Missing items lower both RCV and ACV.</li>
<li><strong>Deductible applied twice</strong>, once to the ACV payment and again to the depreciation release.</li>
<li><strong>Wrong deductible.</strong> Percentage wind/hail deductibles apply to storm claims, but check that the right percentage and dwelling limit were used.</li>
</ul>

