<h2>Documenting a business or rental property</h2>

<p>Commercial and rental properties need the same evidence plus a few extras. Photograph each building and roof section separately and label it with the building name or unit number. Record rooftop equipment such as HVAC units, skylights, and exhaust fans, which are common hail casualties on flat roofs. Note any interruption to operations or tenant occupancy and keep records of lost rents or extra expenses if your policy includes business income or loss-of-rents coverage. Keep tenant reports of leaks with dates. If several buildings are involved, a simple site map showing which photos belong to which roof makes the file far easier to review.</p>

<h2>What adjusters look for</h2>
<ul>
<li>Does the damage pattern match the reported storm date, size, and direction?</li>
<li>Is damage present on soft metals as well as the roof?</li>
<li>Are all slopes and elevations documented?</li>
<li>Is the damage functional (affecting water-shedding or service life) or limited to appearance?</li>
<li>Is there a clear pre-storm condition record?</li>
</ul>
<p>A good file answers these questions up front.</p>

<h2>Common documentation mistakes</h2>
<ul>
<li>Taking only a few distant photos.</li>
<li>Ignoring gutters, vents, screens, and AC units.</li>
<li>Waiting weeks to look in the attic.</li>
<li>Deleting “bad” photos. Keep everything; even blurry shots can confirm timing.</li>
<li>Relying only on the insurance company’s photos and report.</li>
<li>Making permanent repairs before the damage is documented.</li>
<li>Mixing photos from different storms without dates.</li>
</ul>

