<h2>Step 2: Document soft metals and collateral damage</h2>

<p>Soft metals are some of the most persuasive hail evidence because they dent consistently and help show hail size and direction. Photograph:</p>
<ul>
<li>Gutters, downspouts, and gutter guards.</li>
<li>Roof vents, turbines, and flashing (often visible from the ground with zoom).</li>
<li>AC condenser fins and electrical boxes.</li>
<li>Window screens, frames, and glass.</li>
<li>Stucco, painted trim, fences, mailboxes, and patio covers.</li>
<li>Vehicles parked outside during the storm (handled under auto coverage, but useful context).</li>
</ul>

