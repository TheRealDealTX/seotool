<h2>Step 3: Record notes and a timeline</h2>

<p>Photos show what. Notes explain when, where, and how. Keep a simple running log:</p>
<blockquote><p>May 8 — storm about 7 p.m., hail up to golf ball size in backyard, wind from the northwest. Gutters dented on north side; screen torn in back bedroom; water stain appeared on hallway ceiling next morning.</p></blockquote>
<p>Also log every contact with your insurer: date, name, what was said, and what was requested. That record helps if timelines become an issue. Under Texas Insurance Code Chapter 542, insurers generally must acknowledge a claim and request what they need within 15 days of notice, and accept or reject within 15 business days of receiving the requested items, with some extensions allowed.</p>

