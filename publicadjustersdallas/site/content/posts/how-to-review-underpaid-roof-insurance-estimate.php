<h2>Step 4: Go line by line through the roofing section</h2>

<h3>How to read a line item</h3>

<p>Each line shows a description, quantity, unit, unit price, tax, RCV, depreciation, and ACV. Ask three questions for every line: Is the quantity right? Is it the right item? Is anything missing next to it?</p>

<p>Items commonly missing or understated on Dallas roof estimates include:</p>
