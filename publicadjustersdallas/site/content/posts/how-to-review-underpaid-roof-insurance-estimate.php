<h2>Step 6: Check code-required items</h2>

<p>Re-roofing in Dallas generally requires a permit through the City of Dallas Planning &amp; Development Department, and suburban cities have their own permit offices. Work has to meet the city’s adopted International Residential Code, along with manufacturer installation requirements. Items such as drip edge, underlayment, flashing, and ventilation may be required by code even if the old roof lacked them. Whether the insurer pays for those upgrades often depends on ordinance or law coverage. See <a href="/building-codes-insurance-repairs-dallas/">building codes and insurance repairs in Dallas</a> for details, and our <a href="/local-building-codes/">local building codes</a> page for permit information.</p>

<h2>Step 7: Review depreciation and the deductible</h2>

<ul>
<li>Is the roof age correct? Use a roofing invoice, permit history, or home inspection report.</li>
<li>Is depreciation labeled recoverable where the policy allows?</li>
<li>Is depreciation applied to items where it may be questioned, such as permits or disposal?</li>
<li>Is the deductible applied once, and in the right amount?</li>
</ul>

<h2>Step 8: Compare with a contractor’s estimate</h2>

<p>Ask a licensed, established local roofer for a detailed written estimate, ideally itemized like the insurer’s. Line up the two side by side. Differences in quantity point to measurement issues; differences in items point to scope; differences in price point to price list or market conditions. A lump-sum bid with no breakdown is hard to use, so ask for detail.</p>

<h2>Metal, low-slope, and commercial roofs</h2>

<p>Standing seam and other metal roofs bring their own questions, including cosmetic damage exclusions that some policies apply to dents that do not affect water-shedding. Low-slope TPO and modified-bitumen roofs on Dallas apartments, offices, and warehouses are estimated very differently from shingle roofs: insulation, cover board, membrane, flashings, curbs, and drainage all need their own lines, and core samples may be needed to show what lies beneath the membrane. If you own commercial property, see <a href="/services/commercial-property-claims/">commercial property claims</a>.</p>

