<h2>Step 9: Request a revision in writing</h2>

<p>Write a clear request listing each item you disagree with, why, and what supports it: photos, measurements, the contractor estimate, code sections, or manufacturer instructions. Ask the insurer to respond in writing and to explain any item it rejects. Keep copies and a log of dates. Texas Insurance Code Chapter 542 sets general deadlines for insurers to acknowledge, investigate, and decide claims, and TDI accepts complaints if you feel a claim is not being handled properly. If disagreement remains over the amount of loss, many policies include an appraisal clause. For legal questions or lawsuits, speak with a Texas attorney.</p>

