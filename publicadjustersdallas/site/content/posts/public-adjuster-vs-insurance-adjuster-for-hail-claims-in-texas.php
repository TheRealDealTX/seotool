<h2>What is an insurance adjuster?</h2>

<p>An insurance adjuster investigates and evaluates a claim on behalf of the insurance company. On Texas hail claims, you will usually meet one of these:</p>
<ul>
<li><strong>Staff adjusters</strong>, employees of your insurer</li>
<li><strong>Independent adjusters</strong>, licensed adjusters or firms the insurer hires, often in large numbers after a major storm</li>
<li><strong>Desk adjusters</strong>, who review photos and estimates remotely and may make the payment decision</li>
</ul>

<p>The insurer may also send a roofing consultant or an engineer to assess the roof. Whatever the title, these professionals inspect the property, write an estimate (usually in Xactimate), apply the policy terms, and recommend or issue payment. They follow company guidelines, and their job is to evaluate the claim for the insurer. Many do that carefully and fairly. But they do not represent you.</p>

<h2>What is a public adjuster?</h2>

<p>A public adjuster is licensed by the Texas Department of Insurance under Texas Insurance Code Chapter 4102 to act on behalf of the policyholder. TDI describes the role simply: you can hire a public adjuster to negotiate with your insurance company to settle your claim. On a hail claim, that usually includes:</p>
<ul>
<li>Reviewing the policy, deductibles, endorsements, and exclusions</li>
<li>Inspecting and documenting the roof, exterior, and any interior damage</li>
<li>Preparing a detailed line-item estimate</li>
<li>Submitting the claim, supplements, and supporting evidence to the insurer</li>
<li>Communicating with the insurer’s adjuster and attending reinspections</li>
</ul>

<p>Texas places clear limits on public adjusters. Under TDI’s guidance, they cannot act as your contractor on the claim, practice law or give legal advice, take referral fees from contractors or attorneys involved in the claim, solicit door to door during a natural disaster or after 9 p.m., or keep you from talking with your insurance company.</p>

