<h2>The same hail claim, handled two ways</h2>

<p>Here is a simplified, hypothetical example of how one claim can unfold. Picture a brick-veneer, two-story home in Richardson with a composition shingle roof, hit by a spring storm.</p>

<h3>Path one: homeowner and insurance adjuster</h3>
<p>The insurer’s adjuster inspects, finds impacts on two slopes, and writes a repair for those slopes plus gutters. The estimate does not include steep-roof labor, drip edge, or the AC condenser. After the wind/hail deductible, the payment is modest. The homeowner can still compare the estimate with the roofer’s scope, gather photos, and submit a supplement. Many homeowners do exactly that and resolve the claim.</p>

<h3>Path two: homeowner with a public adjuster</h3>
<p>The homeowner hires a public adjuster after the first estimate. The public adjuster reviews the policy, inspects every slope and the exterior, documents brittle shingles that crack during a test lift, and writes a line-item estimate. The insurer reinspects and reviews the supplement. It may agree with some items and not others; if the remaining dispute is about the amount, the policy’s appraisal clause may come into play.</p>

<p>Neither path guarantees a particular result. The difference is who does the work of finding, documenting, and presenting the missing pieces, and what that help costs. If your claim has already been reduced or rejected, our pages on <a href="/services/underpaid-insurance-claims/">underpaid insurance claims</a> and <a href="/services/denied-insurance-claims/">denied insurance claims</a> explain the options, and <a href="/services/insurance-appraisal/">insurance appraisal</a> covers how amount disputes are resolved.</p>

<h2>Pros and cons of each approach</h2>

<h3>Working directly with the insurance adjuster</h3>
<ul>
<li><strong>Pros:</strong> no fee, often fine for small or straightforward claims, and you keep full control of communication.</li>
<li><strong>Cons:</strong> you have to spot missed items, read the policy, and build any supplement or dispute yourself, which takes time and some technical knowledge.</li>
</ul>

<h3>Hiring a public adjuster</h3>
<ul>
<li><strong>Pros:</strong> a licensed representative who documents the loss, writes a full estimate, handles the back-and-forth, and understands the claim process.</li>
<li><strong>Cons:</strong> a fee of up to 10% of the settlement. TDI notes that the fee can be based on the total settlement, not just the disputed portion, and that you may still owe the fee if the insurer does not increase its offer. It may not make financial sense on a small claim.</li>
</ul>

<p>TDI gives a useful example: if the insurer wants to pay $100,000 and you dispute $20,000, a public adjuster’s fee could be $10,000. Ask any public adjuster to explain how their fee would apply to your claim, and consider asking for it in a dollar amount, which TDI says you can request.</p>

<h2>How to decide</h2>

<p>You may not need a public adjuster if the damage is limited, the insurer’s estimate is close to your roofer’s, and communication is going well. A public adjuster may be worth considering when:</p>
<ul>
<li>The insurer’s estimate is far below your contractor’s scope</li>
<li>Part or all of the roof was denied as wear and tear</li>
<li>The loss is large, or involves the roof, interior, and other structures at once</li>
<li>Supplements have been rejected or ignored</li>
<li>You do not have the time to manage inspections, estimates, and follow-ups</li>
<li>The property is commercial or multifamily with a low-slope roof system</li>
</ul>

