<h2>How to choose a public adjuster in Dallas</h2>
<ul>
<li><strong>Verify the license.</strong> Use TDI’s <a href="https://www.tdi.texas.gov/agent/agent-lookup.html" target="_blank" rel="noopener">license lookup</a> or call 800-252-3439 to check the license and any complaints or disciplinary actions.</li>
<li><strong>Read the contract.</strong> It should use TDI-approved terms, state the fee, and include “We represent the insured only.” You have 72 hours after signing to cancel.</li>
<li><strong>Ask about the process.</strong> Will they inspect in person? Who will you communicate with? How do they handle supplements and reinspections?</li>
<li><strong>Watch for red flags.</strong> Promises of a specific result, pressure to sign immediately, door-to-door solicitation right after a storm, or anyone who also wants to be your roofer on the same claim.</li>
</ul>

<h2>What to do either way</h2>
<ol>
<li>Report the claim promptly and get the claim number and adjuster contact information.</li>
<li>Photograph the damage before repairs, and keep receipts for tarping and emergency work. See <a href="/document-hail-damage-for-an-insurance-claim/">how to document hail damage</a>.</li>
<li>Read your declarations page for the wind/hail deductible and roof coverage type.</li>
<li>Be present for every inspection and take your own notes.</li>
<li>Ask for the full line-item estimate and compare it with your contractor’s scope.</li>
<li>Keep every request and response in writing.</li>
</ol>

<h2>Texas protections every homeowner should know</h2>
<ul>
<li><strong>Prompt payment deadlines.</strong> Texas Insurance Code Chapter 542 generally requires insurers to acknowledge a claim within 15 days, decide within 15 business days after receiving requested information (with up to 45 more days if they notify you), and pay within 5 business days after accepting. Deadlines can extend 15 days after a declared weather catastrophe.</li>
<li><strong>Written reasons for denial.</strong> If a claim is denied, the insurer must tell you why in writing.</li>
<li><strong>Appraisal.</strong> Most policies let either side demand appraisal to resolve a disagreement over the amount of loss.</li>
<li><strong>TDI complaints.</strong> You can file a complaint if you believe a claim was handled unfairly.</li>
<li><strong>Legal advice.</strong> For lawsuits, bad faith, or deadlines to sue, talk to a Texas attorney.</li>
</ul>

<h2>The bottom line</h2>

<p>The insurance adjuster and the public adjuster are not two versions of the same job. One evaluates the claim for the company; the other prepares and presents it for you. Many Dallas hail claims are handled well without outside help. When the claim is large, disputed, or simply more than you have time for, a licensed public adjuster can be a useful option.</p>

