<h3>When the deductible is bigger than the ACV</h3>

<p>On smaller claims, the deductible can swallow the first payment. Suppose a fence and gutter claim has an RCV of $5,000 and 40% depreciation, for an ACV of $3,000, with a $3,500 deductible. The insurer may issue no initial check at all. Under a replacement cost policy, once the work is completed and documented, the claim may then be paid up to RCV minus the deductible, or $1,500 here. Many homeowners never file for that second step because they assume the claim closed at zero.</p>

<h3>How depreciation is set</h3>

<p>Depreciation is not a fixed national number. The adjuster typically picks an age and an expected life for each item, and the software calculates a percentage. Condition can push the number up or down. If the adjuster guessed the roof age, or used the age of the house instead of the roof, the depreciation may be wrong from the start. Permit records, a roofing invoice, or the inspection report from when you bought the home can help establish the real age.</p>

