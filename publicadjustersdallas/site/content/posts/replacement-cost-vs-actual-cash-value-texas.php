<h2>Replacement cost vs. actual cash value: the definitions</h2>

<h3>Replacement cost value (RCV)</h3>

<p>RCV is what it would cost today to repair or replace the damaged property with materials of like kind and quality, with no deduction for age. On a composition shingle roof, a common roof on Dallas brick-veneer homes, that includes tear-off and disposal, underlayment, starter, shingles, ridge cap, drip edge, flashing, vents, labor, and, where the job calls for it, general contractor overhead and profit.</p>

<h3>Actual cash value (ACV)</h3>

<p>ACV is generally replacement cost minus depreciation. Depreciation estimates how much of an item’s useful life has already been used. A 15-year-old shingle roof will normally carry far more depreciation than a 3-year-old one, even when the same storm damaged both in the same way.</p>

<h3>Recoverable and non-recoverable depreciation</h3>

<p>Insurer estimates, usually written in Xactimate, apply depreciation line by line. Each line can show a depreciation percentage and whether the amount is recoverable (paid after repairs) or non-recoverable (never paid). Those two labels often matter more than the bottom-line total, and they are easy to miss on a long estimate.</p>

