<h2>Roof endorsements and schedules in Texas</h2>

<p>Roof coverage in Texas has changed over the past several years, and many Dallas-area homeowners do not realize what their renewal changed. Common terms to look for include:</p>

<ul>
<li><strong>ACV roof endorsements</strong> that settle the roof at actual cash value even though the rest of the house is on replacement cost.</li>
<li><strong>Roof payment schedules</strong> that pay a set percentage of RCV based on roof age and sometimes roofing material.</li>
<li><strong>Cosmetic damage exclusions</strong>, often for metal roofing, that exclude dents that do not affect the roof’s ability to shed water.</li>
<li><strong>Percentage wind and hail deductibles</strong>, often 1% or 2% of the Coverage A limit, which can be thousands of dollars on a typical Dallas County home.</li>
</ul>

<p>Dallas County is not in the Texas Windstorm Insurance Association (TWIA) coverage area, so most local homes get wind and hail coverage from their regular insurer, or from the Texas FAIR Plan where applicable. Each company’s forms differ, so read your own endorsements rather than relying on a neighbor’s experience.</p>

<h2>How to get recoverable depreciation released</h2>

<ol>
<li><strong>Read the loss settlement section</strong> of your policy for the repair deadline and what proof the insurer requires.</li>
<li><strong>Keep the scope aligned.</strong> If the contractor finds more damage once the old roof is off, such as rotted decking, ask for a supplement before or during the work, not months later. Our article on <a href="/hail-damage-claim-supplements-what-carriers-miss-in-their-scope/">hail damage claim supplements</a> explains how.</li>
<li><strong>Get a final invoice</strong> that itemizes the work and matches the estimate’s scope as closely as possible.</li>
<li><strong>Send photos</strong> of the completed job and, where required, a copy of the permit and final inspection.</li>
<li><strong>Request the release in writing</strong> and keep a copy of what you sent and when.</li>
<li><strong>Compare the final payment</strong> with the depreciation listed on the estimate. If the numbers differ, ask why.</li>
</ol>

<p>Under many policies, the insurer pays the lesser of the estimate’s replacement cost or what you actually spent. If you negotiate a lower price than the estimate, the recoverable amount may drop to match.</p>

<h2>Contents and other structures</h2>

<p>The same rules often apply to personal property and to detached structures like fences, sheds, and detached garages. Contents may be settled at ACV until you replace an item and submit the receipt. After a fire, a burst pipe, or a roof leak that damaged furniture and electronics, keep an inventory with ages, original prices, and photos. Some policies settle contents at ACV only, so check the declarations page.</p>

