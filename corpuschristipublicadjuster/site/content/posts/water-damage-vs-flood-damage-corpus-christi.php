<h2>Flood insurance basics: NFIP and private flood</h2>

<p>Flood coverage is sold separately from homeowners insurance, most often through the National Flood Insurance Program. NFIP policies define “flood” in specific terms, so read the definition in your policy. A few basics from <a href="https://www.floodsmart.gov/whats-covered" target="_blank" rel="noopener">FloodSmart</a>:</p>

<ul>
<li><strong>Waiting period.</strong> Coverage generally starts 30 days after purchase. Exceptions include purchases tied to making, increasing, extending, or renewing a mortgage; coverage changes at renewal; and a 1-day wait if bought within 12 months of a flood map change to high-risk.</li>
<li><strong>Residential limits.</strong> Building coverage up to $250,000 and contents up to $100,000. They are separate coverages.</li>
<li><strong>Separate claim.</strong> A flood claim is filed with the flood insurer, separate from any homeowners or windstorm claim, with its own deductible and adjuster.</li>
<li><strong>Coverage limits for certain areas.</strong> NFIP policies limit coverage for basements and for enclosures below the lowest elevated floor of many elevated buildings, which matters for raised homes on Padre Island and Mustang Island.</li>
</ul>

<p>TWIA does not cover flood. TWIA policies cover wind and hail only. For certain properties in V, VE, or V1-30 flood zones built, altered, remodeled, or enlarged on or after Sept. 1, 2009, TWIA requires proof of NFIP flood coverage (when available) to get TWIA coverage. Our <a href="/services/flood-damage-claims/">flood damage claims</a> page has more.</p>

