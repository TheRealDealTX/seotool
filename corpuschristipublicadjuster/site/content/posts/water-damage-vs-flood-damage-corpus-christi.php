<h2>Common disputes on water and flood claims</h2>

<h3>“That was flood, not water damage”</h3>
<p>During heavy rain, a homeowners insurer may deny interior water damage as flood, even when the water came through the roof or a failed window. Photos showing where the water entered, stains that start at the ceiling, and a roof inspection are often the key evidence. The opposite also happens: a flood insurer may argue water came from above. When both sources are possible, report to both insurers and document each path.</p>

<h3>Sudden discharge vs. long-term leak</h3>
<p>Insurers sometimes argue that a plumbing leak went on for weeks or months, which many policies exclude or limit. Rot, layered staining, and corrosion can suggest a long-term leak; a clean break in a supply line and fresh, uniform wetting suggest a sudden one. A plumber’s written finding on the cause of the failure can help.</p>

<h3>Mold and drying</h3>
<p>Disputes over mold often turn on how quickly drying started and whether the mold is tied to a covered water event. Keep moisture readings, drying logs, and mitigation invoices.</p>

<h3>Scope of the flood estimate</h3>
<p>Flood estimates can leave out items such as insulation behind wet drywall, cabinets that absorbed water, flooring underlayment, or contents that were not listed. Because NFIP building and contents are separate coverages, contents need their own inventory with descriptions, ages, and photos.</p>

