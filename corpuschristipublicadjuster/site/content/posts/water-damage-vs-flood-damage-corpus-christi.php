<h2>Documenting a water or flood loss</h2>

<ol>
<li><strong>Stop the source</strong> if it is a plumbing leak, and stay out of standing water that may be energized.</li>
<li><strong>Photograph before cleanup.</strong> Capture water lines on walls, the source of the leak, wet materials, and damaged contents. A horizontal line at the same height throughout the room points to rising water; stains running down from the ceiling point to water from above.</li>
<li><strong>Start drying</strong> and keep receipts for mitigation work and equipment.</li>
<li><strong>Keep samples</strong> of damaged flooring or materials where practical.</li>
<li><strong>Report to the right insurer,</strong> or to more than one if the loss involves more than one source.</li>
</ol>

