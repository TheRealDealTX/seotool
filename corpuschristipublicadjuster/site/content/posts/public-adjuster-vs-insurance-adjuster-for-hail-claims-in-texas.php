<h2>Hail claims in Texas and on the Coastal Bend</h2>

<p>Hail claims are often harder than they look. Shingle bruising, granule loss, cracked flashing, damaged vents, and dented soft metals are easy to miss in a short inspection. Many of these items never make it into the first estimate.</p>

<p>Locally, hail is a spring problem. The NOAA NCEI Storm Events Database shows 134 hail reports in Nueces County, with 86 of them in April and May, and 28 reports of golf ball size or larger. In Kleberg County, 31 of 55 hail reports fell in May alone. Big hail days produce many claims at once, and that volume shapes how insurance adjusters work.</p>

<p>Coverage adds another layer. TWIA covers wind and hail for eligible properties in Nueces, San Patricio, Aransas, and Kleberg counties. Many homeowners policies on the coast exclude wind and hail, so a hail claim on those homes goes to TWIA, not the homeowners carrier.</p>

<h2>What is an insurance adjuster?</h2>

<p>The insurance adjuster is assigned by your insurer (or by TWIA) to investigate and evaluate your claim. Their job typically includes inspecting the property, taking photos, writing an estimate, applying the policy’s coverage terms, and recommending a settlement.</p>

<p>There are two common types:</p>
<ul>
<li><strong>Staff adjusters</strong> are employees of the insurance company.</li>
<li><strong>Independent adjusters</strong> are contracted by insurers, often brought in after large storms when claim volume spikes.</li>
</ul>

<p>Both evaluate the claim within the insurer’s guidelines. Many are knowledgeable and fair. But their role is to assess what the insurer owes, not to advocate for you.</p>

<h2>What is a public adjuster?</h2>

<p>A public adjuster is licensed by the Texas Department of Insurance and represents the policyholder (Tex. Ins. Code §4102.051). They inspect and document the damage, review the policy, prepare a detailed estimate, present the claim, and handle negotiation and supplements with the insurer.</p>

<p>Texas law sets ground rules. The contract must be on a TDI-approved form, must let you cancel in writing within 72 hours of signing, and must state "WE REPRESENT THE INSURED ONLY." Fees are disclosed in a written contract before any work begins; Texas law caps public adjuster compensation at 10% of the insurance settlement. Claim checks must name you as payee, and a public adjuster may not sign or endorse them for you (§4102.103–.104).</p>

