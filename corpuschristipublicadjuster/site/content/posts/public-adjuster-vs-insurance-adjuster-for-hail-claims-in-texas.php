<h2>What a public adjuster cannot do</h2>

<ul>
<li>Guarantee a higher settlement or any particular outcome.</li>
<li>Give legal advice or file a lawsuit.</li>
<li>Sign or endorse your claim checks.</li>
<li>Charge more than 10% of the insurance settlement in Texas.</li>
<li>Change what your policy covers. Coverage depends on the policy and the facts.</li>
