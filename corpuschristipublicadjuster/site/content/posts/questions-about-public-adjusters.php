<h2>More common questions about public adjusters</h2>

<h3>Can I hire a public adjuster after I already filed?</h3>
<p>Yes. Many people reach out after an initial estimate that does not cover their contractor’s bid. Keep in mind that deadlines keep running, especially TWIA’s 60-day window to demand appraisal after an acceptance notice.</p>

<h3>Will hiring one upset my insurance company?</h3>
<p>Insurers work with licensed public adjusters routinely. Hiring one is lawful and common. Once you sign, the insurer will often direct claim communication through your public adjuster, though you remain the policyholder and decision-maker.</p>

<h3>Do public adjusters handle flood claims?</h3>
<p>Some do. NFIP flood policies follow federal rules and their own deadlines and proof-of-loss requirements. If your loss includes flood or storm surge, ask whether the adjuster handles NFIP claims. See our <a href="/services/flood-damage-claims/">flood damage claims</a> page for more.</p>

<h3>How long does a claim take with a public adjuster?</h3>
<p>It depends on the size of the loss, how quickly the insurer responds, and whether there is a dispute. Texas law sets response deadlines for insurers, such as acknowledging a claim within 15 days under Chapter 542, and TWIA has its own 60-day decision deadline under Chapter 2210. A public adjuster cannot change those timelines, but organized documentation can help avoid repeated requests for more information.</p>

<h3>Can a public adjuster guarantee a bigger settlement?</h3>
<p>No, and you should be wary of anyone who promises one. Outcomes depend on the policy, the damage, and the evidence.</p>

<h3>Can a contractor act as my public adjuster?</h3>
<p>Treat them as separate roles. A roofer or restoration contractor repairs the property; a public adjuster must hold a Texas public adjuster license to represent you on the claim. If someone offers to "handle your insurance" as part of a repair contract, ask for their public adjuster license number before you sign anything.</p>

<h3>What if the insurer has already paid part of the claim?</h3>
<p>That is common. A public adjuster can review what was paid, compare it to the actual scope of damage, and prepare a supplement for missed items. The contract should spell out how the fee applies to amounts already paid versus amounts recovered afterward, so read that section closely.</p>

