<p>Public adjusters handle documentation, valuation, and negotiation. Attorneys handle legal questions and lawsuits. They are different roles, and a public adjuster cannot give legal advice.</p>

<h2>What does a public adjuster actually do?</h2>

<h3>Inspects the property thoroughly</h3>
<p>Beyond the obvious missing shingles, a careful inspection looks at flashing and underlayment, attic decking, moisture inside walls, HVAC equipment, interior finishes, and contents. On coastal homes it also means separating storm damage from older salt-air corrosion, and wind damage from flood or surge damage. Common tools include drone photography, Matterport 3D imaging, moisture meters, and Xactimate estimating software.</p>

<h3>Reviews the policy</h3>
<p>Policies are contracts with many moving parts: replacement cost or actual cash value, wind/hail or named-storm deductibles, loss of use or additional living expense, ordinance or law coverage, and exclusions. A policy review shows what coverage applies and what the policy requires of you.</p>

<h3>Prepares the claim</h3>
<p>That usually means a line-item repair estimate, a contents inventory where needed, organized photo and video evidence, weather data for the date of loss, and a written presentation of the claim.</p>

<h3>Communicates and negotiates with the insurer</h3>
<p>The public adjuster handles meetings, re-inspections, document requests, and back-and-forth over the estimate, and keeps you informed. If there is a dispute over the amount of the loss, they can advise you about the appraisal process.</p>

<h2>How are public adjusters paid in Texas?</h2>

<p>Most public adjusters work on a percentage of the claim settlement. Fees are disclosed in a written contract before any work begins; Texas law caps public adjuster compensation at 10% of the insurance settlement (Tex. Ins. Code §4102.104). If the insurer pays, or commits in writing to pay, policy limits within 72 hours after the loss is reported, a percentage fee is not allowed; only reasonable time-based compensation is.</p>

<p>Texas also protects you in the contract itself. Under §4102.103, the contract must be on a TDI-approved form, must let you rescind by written notice within 72 hours of signing, and must display "WE REPRESENT THE INSURED ONLY" in bold. Claim checks must name you as a payee, and you must endorse them. A public adjuster may not sign or endorse claim checks for you.</p>

<h2>Why Coastal Bend claims raise so many questions</h2>

