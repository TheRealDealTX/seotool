<h2>What is a public adjuster?</h2>

<p>A public adjuster is a licensed insurance professional who represents the policyholder in a property insurance claim. In Texas, a license from the Texas Department of Insurance is required to act as, or hold yourself out as, a public adjuster (Tex. Ins. Code §4102.051).</p>

<p>When you file a claim, your insurer assigns its own adjuster. That person may be an employee or an independent adjuster contracted by the insurer. Either way, they work for the insurance company. A public adjuster works for you.</p>

