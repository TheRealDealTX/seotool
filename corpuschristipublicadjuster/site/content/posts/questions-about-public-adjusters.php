<h2>Red flags to watch for</h2>

<ul>
<li>No Texas public adjuster license, or reluctance to give the license number.</li>
<li>Promises of a guaranteed or "huge" payout.</li>
<li>Pressure to sign on the spot, especially door to door right after a storm.</li>
<li>A contract missing the 72-hour cancellation right or the "WE REPRESENT THE INSURED ONLY" statement.</li>
<li>A fee above 10% of the settlement, or vague fee terms.</li>
<li>Requests to have claim checks sent to them or signed by them.</li>
</ul>

