<h2>Common deductible mistakes after a storm</h2>

<h3>Assuming the claim is too small to report</h3>
<p>Homeowners sometimes look at a few missing shingles, compare them with a large percentage deductible, and decide not to file. The visible damage is not always the whole picture. Lifted shingles that laid back down, damaged underlayment, interior moisture, fencing, and outbuildings can add up. Documenting the damage and reading the policy’s notice requirements before deciding is usually the safer course.</p>

<h3>Subtracting the deductible twice</h3>
<p>The deductible should come off the covered loss once per claim, as the policy describes. When reviewing a settlement letter, follow the math line by line: replacement cost, depreciation, deductible, prior payments. If the numbers do not reconcile, ask the adjuster to explain each line in writing.</p>

<h3>Forgetting what the deductible is applied to</h3>
<p>Because the deductible is subtracted from the estimate total, an incomplete estimate hurts twice. If the insurer’s estimate is $20,000 and the deductible is $8,000, the payment is $12,000. If the correct scope was $28,000, the payment should have been $20,000. Missing line items such as starter strips, drip edge, ridge vents, flashing, interior repairs, or code-required work can make the difference between a small check and a meaningful one.</p>

<h3>Not checking which deductible was used</h3>
<p>If your policy has both a wind/hail deductible and a separate named-storm or hurricane deductible, confirm which one the insurer applied and why. The trigger language, not the name of the weather event in the news, decides which applies.</p>

<h3>Paying the deductible to a contractor</h3>
<p>The deductible is your share of the covered loss. When you hire a contractor, expect the repair contract to account for it as part of the total price. Be cautious with anyone who offers to “cover” or “absorb” your deductible, and read every contract carefully before you sign it. If an offer sounds unusual, ask your insurer or an attorney before agreeing to it.</p>

<h2>A note for business owners</h2>
<p>Commercial property policies often use percentage wind or named-storm deductibles too, and they may apply per building, per location, or to the total insured value on a schedule, depending on the wording. For a business with several buildings, that can produce a very different number than a homeowner would expect. Read the commercial declarations and deductible endorsement carefully, and see our <a href="/services/commercial-property-claims/">commercial property claims</a> page for how those claims are documented.</p>

