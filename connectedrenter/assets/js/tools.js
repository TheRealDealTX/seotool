/* Connected Renter — interactive renter tools.
   Each tool is a <div class="tool" data-tool="name"> whose markup is generated by build.py;
   this file wires up the maths. All figures are planning estimates, not quotes. */
(function () {
  'use strict';
  var d = document, w = window;
  function $(s, c) { return (c || d).querySelector(s); }
  function $$(s, c) { return Array.prototype.slice.call((c || d).querySelectorAll(s)); }
  function num(el) { var v = parseFloat(String(el && el.value || '').replace(/[^0-9.\-]/g, '')); return isFinite(v) ? v : 0; }
  function usd(n, dec) { return '$' + Number(n).toLocaleString(undefined, { minimumFractionDigits: dec || 0, maximumFractionDigits: dec || 0 }); }
  function store(key, val) { try { if (val === undefined) return JSON.parse(localStorage.getItem(key) || 'null'); localStorage.setItem(key, JSON.stringify(val)); } catch (e) { return null; } }
  function radio(t, name) { var r = $('input[name="' + name + '"]:checked', t); return r ? r.value : null; }
  function on(t, fn) { t.addEventListener('input', fn); t.addEventListener('change', fn); fn(); }
  function out(t, name, v) { $$('[data-out="' + name + '"]', t).forEach(function (o) { o.textContent = v; }); }
  function bar(el, pct) { if (el) el.style.width = Math.max(0, Math.min(100, pct)) + '%'; }
  function esc(s) { return String(s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }
  var SIZES = ['studio', '1br', '2br', '3br', '4br'];

  var T = {};

  /* 1. Rent affordability */
  T.affordability = function (t) {
    on(t, function () {
      var inc = num($('[name=income]', t)), debt = num($('[name=debt]', t)), rent = num($('[name=rent]', t));
      var mo = inc / 12;
      var r30 = mo * 0.30, r40x = inc / 40, rDti = Math.max(0, mo * 0.36 - debt);
      var max = Math.max(0, Math.min(r30, r40x, rDti || r30));
      out(t, 'max', usd(Math.round(max / 5) * 5));
      out(t, 'r30', usd(r30)); out(t, 'r40', usd(r40x)); out(t, 'dti', usd(rDti));
      out(t, 'needs', usd(mo * 0.5)); out(t, 'mo', usd(mo));
      var rr = $('[name=rent]', t); if (rr) { out(t, 'rentv', usd(rent)); if (w.CRpaint) w.CRpaint(rr); }
      var pct = mo ? rent / mo * 100 : 0;
      out(t, 'pct', pct.toFixed(1) + '%');
      bar($('.meter i', t), pct / 50 * 100);
      var v = $('.verdict', t);
      if (v) {
        if (!rent || !mo) { v.className = 'verdict'; v.textContent = ''; }
        else if (pct <= 30 && rent <= max + 1) { v.className = 'verdict good'; v.textContent = 'Comfortable — within the 30% guideline'; }
        else if (pct <= 36) { v.className = 'verdict ok'; v.textContent = 'Stretch — doable with a tight budget'; }
        else { v.className = 'verdict bad'; v.textContent = 'Rent-burdened — over 36% of gross income'; }
      }
      out(t, 'qual', mo >= rent * 3 ? 'Yes — your income is at least 3× this rent' : (rent ? 'Not quite — most landlords want 3× rent (' + usd(rent * 3) + '/mo)' : '—'));
    });
  };

  /* 2. Moving cost estimator */
  T['moving-cost'] = function (t) {
    var LBS = [2000, 3500, 5500, 8000, 11000], HRS = [3, 4, 6, 8, 10], SUP = [60, 100, 160, 230, 300], CONT = [1, 1, 2, 2, 3];
    on(t, function () {
      var s = SIZES.indexOf(radio(t, 'size')); if (s < 0) s = 1;
      var mi = num($('[name=miles]', t)); out(t, 'milesv', mi.toLocaleString() + ' mi'); if (w.CRpaint) w.CRpaint($('[name=miles]', t));
      var local = mi <= 50, peak = $('[name=peak]', t).checked, pack = $('[name=pack]', t).checked, stairs = $('[name=stairs]', t).checked, heavy = $('[name=heavy]', t).checked, storage = $('[name=storage]', t).checked;
      var fuel = mi / 10 * 3.6;
      var diy = local ? (60 + s * 25) + mi * 2 * 1.09 + 60 : (180 + s * 70) + mi * (0.95 + s * 0.12) + fuel;
      var movers = local ? HRS[s] * 165 + 120 : LBS[s] * (0.32 + 0.00062 * mi) + 350;
      var cont = local ? CONT[s] * 520 : CONT[s] * (750 + mi * 0.95);
      var sup = SUP[s];
      diy += sup; cont += sup; movers += pack ? movers * 0.25 + sup : sup;
      if (stairs) { movers *= 1.1; }
      if (heavy) { diy += 120; movers += 250; cont += 150; }
      if (storage) { diy += 180; movers += 300; cont += 220; }
      if (peak) { diy *= 1.12; movers *= 1.15; cont *= 1.12; }
      var all = { diy: diy, movers: movers, container: cont }, m = radio(t, 'method') || 'movers', c = all[m];
      out(t, 'low', usd(Math.round(c * 0.85 / 10) * 10)); out(t, 'high', usd(Math.round(c * 1.2 / 10) * 10));
      var mx = Math.max(diy, movers, cont);
      ['diy', 'movers', 'container'].forEach(function (k) { bar($('[data-bar="' + k + '"]', t), all[k] / mx * 100); out(t, k, usd(Math.round(all[k] / 10) * 10)); });
      out(t, 'dist', local ? 'Local move' : 'Long-distance move');
    });
  };

  /* 3. Moving checklist & timeline */
  T.checklist = function (t) {
    var KEY = 'cr-checklist', st = store(KEY) || { date: '', done: {} }, dIn = $('[name=movedate]', t);
    if (!st.date) { var nd = new Date(Date.now() + 42 * 864e5); st.date = nd.toISOString().slice(0, 10); }
    dIn.value = st.date;
    var items = $$('.tl-item input', t);
    items.forEach(function (cb) { cb.checked = !!st.done[cb.value]; });
    function render() {
      st.date = dIn.value; var md = st.date ? new Date(st.date + 'T12:00:00') : null, today = new Date(); today.setHours(12, 0, 0, 0);
      $$('.tl-group', t).forEach(function (g) {
        var off = parseInt(g.getAttribute('data-offset'), 10), when = $('.when', g);
        if (md && when) {
          var dt = new Date(md.getTime() + off * 864e5);
          var label = dt.toLocaleDateString(undefined, { month: 'short', day: 'numeric' });
          var allDone = $$('input', g).every(function (c) { return c.checked; });
          when.textContent = (off < 0 ? 'By ' : off === 0 ? 'On ' : 'After ') + label;
          when.classList.toggle('late', dt < today && !allDone && off <= 0);
        }
      });
      var done = items.filter(function (c) { return c.checked; }).length;
      items.forEach(function (c) { st.done[c.value] = c.checked; c.closest('.tl-item').classList.toggle('done', c.checked); });
      out(t, 'done', done + ' of ' + items.length); bar($('.meter i', t), done / items.length * 100);
      if (md) { var days = Math.round((md - today) / 864e5); out(t, 'days', days > 0 ? days + ' days to go' : days === 0 ? 'Moving day is today!' : Math.abs(days) + ' days since your move'); }
      store(KEY, st);
    }
    on(t, render);
    var reset = $('[data-act=reset]', t), pr = $('[data-act=print]', t);
    if (reset) reset.addEventListener('click', function () { if (confirm('Clear all checked tasks?')) { items.forEach(function (c) { c.checked = false; }); st.done = {}; render(); } });
    if (pr) pr.addEventListener('click', function () { w.print(); });
  };

  /* 4. Renters insurance coverage */
  T['renters-insurance'] = function (t) {
    var DEF = { studio: [2500, 3000, 2500, 1000, 1000, 1500], '1br': [3500, 5000, 3500, 1500, 1500, 2500], '2br': [5000, 9000, 5000, 2500, 2000, 4000], '3br': [7000, 13000, 7000, 3500, 3000, 6000], '4br': [9000, 17000, 9000, 4500, 4000, 8000] };
    var cats = ['electronics', 'furniture', 'clothing', 'kitchen', 'jewelry', 'other'], last = null;
    on(t, function (e) {
      var sz = radio(t, 'size') || '1br';
      if (sz !== last && (!e || !e.target || e.target.name === 'size' || last === null)) {
        cats.forEach(function (c, i) { var r = $('[name=' + c + ']', t); r.value = DEF[sz][i]; });
      }
      last = sz;
      var total = 0;
      cats.forEach(function (c) { var r = $('[name=' + c + ']', t), v = num(r); total += v; out(t, c, usd(v)); if (w.CRpaint) w.CRpaint(r); });
      var cover = Math.ceil(total / 5000) * 5000;
      var rc = $('[name=rc]', t).checked, ded = radio(t, 'ded') || '500', risk = $('[name=risk]', t).checked;
      var lo = 7 + cover / 1000 * 0.32, hi = 12 + cover / 1000 * 0.55;
      if (rc) { lo *= 1.1; hi *= 1.1; }
      if (ded === '1000') { lo *= 0.9; hi *= 0.9; }
      var liab = risk ? 300000 : 100000;
      if (risk) { lo += 2; hi += 4; }
      out(t, 'total', usd(total)); out(t, 'cover', usd(cover)); out(t, 'liab', usd(liab));
      out(t, 'prem', usd(lo) + '–' + usd(hi) + '/mo');
      var j = num($('[name=jewelry]', t));
      out(t, 'jnote', j > 1500 ? 'Your jewelry & valuables exceed the typical $1,500 theft sub-limit — ask about a scheduled personal property rider.' : 'Jewelry & valuables are under the typical $1,500 theft sub-limit.');
    });
  };

  /* 5. Rent split */
  T['rent-split'] = function (t) {
    var list = $('.roommates', t), tpl = $('template', t), n = 0;
    function add(name, size, inc) {
      n++;
      var row = tpl.content.firstElementChild.cloneNode(true);
      $('[data-f=name]', row).value = name || 'Roommate ' + n;
      $('[data-f=size]', row).value = size || 120;
      $('[data-f=inc]', row).value = inc || 50000;
      $('button', row).addEventListener('click', function () { if ($$('.rm-row', list).length > 2) { row.remove(); calc(); } });
      list.appendChild(row);
    }
    add('Alex', 150, 62000); add('Jordan', 120, 48000);
    var addBtn = $('[data-act=add]', t);
    addBtn.addEventListener('click', function () { if ($$('.rm-row', list).length < 8) { add(); calc(); } });
    function calc() {
      var rent = num($('[name=rent]', t)), util = num($('[name=util]', t)), m = radio(t, 'method') || 'size', common = num($('[name=common]', t)) / 100;
      out(t, 'commonv', Math.round(common * 100) + '%'); if (w.CRpaint) w.CRpaint($('[name=common]', t));
      var rows = $$('.rm-row', list).map(function (r) { return { name: $('[data-f=name]', r).value || 'Roommate', size: num($('[data-f=size]', r)), inc: num($('[data-f=inc]', r)) }; });
      var k = rows.length, sz = rows.reduce(function (a, r) { return a + r.size; }, 0), ic = rows.reduce(function (a, r) { return a + r.inc; }, 0);
      t.classList.toggle('m-size', m === 'size');
      var shares = rows.map(function (r) {
        var s = 1 / k;
        if (m === 'size' && sz) s = common / k + (1 - common) * r.size / sz;
        if (m === 'income' && ic) s = r.inc / ic;
        return s;
      });
      var mx = Math.max.apply(null, shares);
      $('.bars', t).innerHTML = rows.map(function (r, i) {
        var amt = rent * shares[i] + util / k;
        return '<div class="bar-row"><span>' + esc(r.name) + '</span><div class="track"><i style="width:' + (shares[i] / mx * 100) + '%"></i></div><b>' + usd(amt) + '</b></div>';
      }).join('');
      out(t, 'total', usd(rent + util));
      out(t, 'each', usd((rent + util) / k));
    }
    t.addEventListener('input', calc); t.addEventListener('change', calc); calc();
  };

  /* 6. Packing supplies */
  T.packing = function (t) {
    var B = { S: [10, 15, 25, 35, 45], M: [8, 12, 20, 30, 40], L: [5, 8, 12, 18, 25], W: [1, 2, 3, 4, 5], D: [1, 2, 3, 4, 5] };
    var P = { S: 1.6, M: 2.3, L: 3.1, W: 16, D: 7 };
    on(t, function () {
      var s = SIZES.indexOf(radio(t, 'size')); if (s < 0) s = 1;
      var mult = { light: 0.75, avg: 1, heavy: 1.3 }[radio(t, 'style') || 'avg'], ppl = num($('[name=people]', t)) || 1;
      out(t, 'peoplev', ppl); if (w.CRpaint) w.CRpaint($('[name=people]', t));
      var pm = 1 + (ppl - 1) * 0.12, tot = 0, cost = 0;
      Object.keys(B).forEach(function (k) { var v = Math.ceil(B[k][s] * mult * (k === 'D' ? 1 : pm)); tot += v; cost += v * P[k]; out(t, 'b' + k, v); });
      var tape = Math.ceil(tot / 10) + 1, paper = Math.ceil(tot * 0.35), wrap = 25 + s * 25;
      cost += tape * 4 + paper * 1.2 + wrap * 0.2 + 6;
      out(t, 'tape', tape + ' rolls'); out(t, 'paper', paper + ' lb'); out(t, 'wrap', wrap + ' ft');
      out(t, 'total', tot); out(t, 'cost', usd(cost * 0.85) + '–' + usd(cost * 1.15));
    });
  };

  /* 7. Moving truck size */
  T['truck-size'] = function (t) {
    var BASE = [250, 400, 650, 950, 1300];
    var TRUCKS = [['Cargo van', 250], ['10 ft', 400], ['15 ft', 760], ['20 ft', 1015], ['26 ft', 1680]];
    on(t, function () {
      var s = SIZES.indexOf(radio(t, 'size')); if (s < 0) s = 1;
      var cu = BASE[s];
      if ($('[name=appl]', t).checked) cu += 100;
      if ($('[name=garage]', t).checked) cu += 200;
      if ($('[name=lots]', t).checked) cu *= 1.2;
      if ($('[name=minimal]', t).checked) cu *= 0.8;
      var need = cu * 1.1, pick = TRUCKS.length - 1, trips = 1;
      for (var i = 0; i < TRUCKS.length; i++) if (TRUCKS[i][1] >= need) { pick = i; break; }
      if (need > TRUCKS[TRUCKS.length - 1][1]) trips = Math.ceil(need / TRUCKS[TRUCKS.length - 1][1]);
      out(t, 'cu', Math.round(cu).toLocaleString() + ' cu ft');
      out(t, 'truck', TRUCKS[pick][0] + (pick ? ' truck' : ''));
      out(t, 'trips', trips > 1 ? trips + ' trips (or a 26 ft truck + trailer)' : 'One trip');
      $$('.truck-vis div', t).forEach(function (el, i) { el.classList.toggle('on', i === pick); });
    });
  };

  /* 8. Move-in / move-out inspection */
  T.inspection = function (t) {
    var KEY = 'cr-inspection', st = store(KEY) || {};
    $$('[data-k]', t).forEach(function (el) {
      var k = el.getAttribute('data-k');
      if (el.type === 'radio') { if (st[k] === el.value) el.checked = true; }
      else if (st[k]) el.value = st[k];
    });
    ['addr', 'idate'].forEach(function (n) { var el = $('[name=' + n + ']', t); if (el && st[n]) el.value = st[n]; });
    function calc() {
      var issues = 0, fair = 0, rated = 0;
      $$('[data-k]', t).forEach(function (el) {
        var k = el.getAttribute('data-k');
        if (el.type === 'radio') { if (el.checked) { st[k] = el.value; rated++; if (el.value === 'damaged') issues++; if (el.value === 'fair') fair++; } }
        else st[k] = el.value;
      });
      ['addr', 'idate'].forEach(function (n) { var el = $('[name=' + n + ']', t); if (el) st[n] = el.value; });
      $$('.inspect-room', t).forEach(function (r) {
        var bad = $$('input[value=damaged]:checked', r).length, c = $('.cnt', r);
        if (c) c.textContent = bad ? bad + ' issue' + (bad > 1 ? 's' : '') : '';
      });
      out(t, 'issues', issues); out(t, 'fair', fair); out(t, 'rated', rated + ' of ' + $$('.inspect-row', t).length);
      store(KEY, st);
    }
    on(t, calc);
    $('[data-act=print]', t).addEventListener('click', function () { $$('.inspect-room', t).forEach(function (r) { r.open = true; }); w.print(); });
    $('[data-act=copy]', t).addEventListener('click', function (e) {
      var lines = ['Rental inspection report', 'Address: ' + ($('[name=addr]', t).value || '—'), 'Date: ' + ($('[name=idate]', t).value || '—'), ''];
      $$('.inspect-room', t).forEach(function (r) {
        lines.push('== ' + $('summary b', r).textContent + ' ==');
        $$('.inspect-row', r).forEach(function (row) {
          var c = $('input[type=radio]:checked', row), n = $('input[type=text]', row);
          lines.push('- ' + $('.lbl-t', row).textContent + ': ' + (c ? c.value : 'not checked') + (n && n.value ? ' (' + n.value + ')' : ''));
        });
        lines.push('');
      });
      var txt = lines.join('\n'), btn = e.currentTarget;
      function done() { var o = btn.textContent; btn.textContent = 'Copied!'; setTimeout(function () { btn.textContent = o; }, 1800); }
      if (navigator.clipboard) navigator.clipboard.writeText(txt).then(done, function () { w.prompt('Copy your report:', txt); });
      else w.prompt('Copy your report:', txt);
    });
    $('[data-act=reset]', t).addEventListener('click', function () {
      if (!confirm('Clear this inspection?')) return;
      $$('input[type=radio]', t).forEach(function (r) { r.checked = false; });
      $$('input[type=text],input[type=date]', t).forEach(function (r) { r.value = ''; });
      st = {}; calc();
    });
  };

  /* 9. Electricity bill estimator */
  T.electricity = function (t) {
    var KWH = [550, 700, 900, 1150, 1400], SEAS = { mild: 1, summer: 1.45, winter: 1.15 };
    on(t, function () {
      var s = SIZES.indexOf(radio(t, 'size')); if (s < 0) s = 1;
      var ppl = num($('[name=people]', t)) || 1, rate = num($('[name=rate]', t)), base = num($('[name=base]', t)), seas = SEAS[radio(t, 'season') || 'mild'];
      out(t, 'peoplev', ppl); out(t, 'ratev', rate.toFixed(1) + '¢'); out(t, 'basev', usd(base, 2));
      $$('input[type=range]', t).forEach(function (r) { if (w.CRpaint) w.CRpaint(r); });
      var k = (KWH[s] + (ppl - 1) * 90) * seas;
      if ($('[name=wfh]', t).checked) k += 90;
      if ($('[name=ev]', t).checked) k += 280;
      var bill = k * rate / 100 + base;
      out(t, 'kwh', Math.round(k).toLocaleString() + ' kWh'); out(t, 'bill', usd(bill)); out(t, 'year', usd(bill * 12));
      var rows = [rate - 3, rate, rate + 3].map(function (r) { return Math.max(1, r); });
      var mx = (k * rows[2] / 100 + base);
      ['lo', 'mid', 'hi'].forEach(function (id, i) { var b = k * rows[i] / 100 + base; out(t, id + 'r', rows[i].toFixed(1) + '¢/kWh'); out(t, id, usd(b)); bar($('[data-bar="' + id + '"]', t), b / mx * 100); });
    });
  };

  $$('.tool[data-tool]').forEach(function (t) { t.addEventListener('submit', function (e) { e.preventDefault(); }); var f = T[t.getAttribute('data-tool')]; if (f) try { f(t); } catch (e) { if (w.console) console.error(e); } });
})();
