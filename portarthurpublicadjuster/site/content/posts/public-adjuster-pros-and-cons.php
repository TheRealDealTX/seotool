<h2>How to do the math</h2>

<p>A simple way to think about it: a public adjuster is worth the fee when the additional covered amount they can document and present is meaningfully larger than the fee itself, or when the time and stress you save matter to you. You won’t know that number for certain in advance, but you can get a sense of it by comparing the insurer’s estimate with independent contractor estimates and asking where the gaps are. Our <a href="/claim-calculator/">claim calculator</a> can help you see how deductibles and depreciation affect the payment.</p>

<p>Keep Texas’s fee rules in mind. If the insurer pays or commits in writing to pay policy limits within 72 hours after the loss is reported, a public adjuster cannot charge a percentage fee, only reasonable hourly compensation.</p>

<h2>Alternatives worth knowing about</h2>

<p>A public adjuster is not the only option when a claim isn’t going well. Depending on the problem, you might also:</p>
<ul>
<li>Ask the insurer, in writing, for a reinspection or a supervisor review of the estimate.</li>
<li>Get a detailed, line-item estimate from a reputable contractor and submit it as a supplement.</li>
<li>Use the policy’s appraisal clause if the dispute is only about the amount of loss.</li>
<li>File a complaint with the Texas Department of Insurance if deadlines are missed or communication breaks down.</li>
<li>Talk to a Texas attorney if the dispute is about coverage, bad faith, or a lawsuit deadline.</li>
</ul>
<p>These can be combined. Many homeowners start with the first two and bring in professional help only if the gap remains large.</p>

