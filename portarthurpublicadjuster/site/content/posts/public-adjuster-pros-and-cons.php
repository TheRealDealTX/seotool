<h2>What a public adjuster does</h2>

<p>A public adjuster is licensed by the Texas Department of Insurance under <a href="https://statutes.capitol.texas.gov/Docs/IN/htm/IN.4102.htm" target="_blank" rel="noopener">Texas Insurance Code Chapter 4102</a> to act for the insured on a first-party property claim. In practice that usually means:</p>
