<h2>Step 5: Weather records for your date of loss</h2>

<p>Insurers frequently question whether damage came from a specific storm or from age and wear. Weather records help answer that. Useful sources include:</p>

<ul>
<li><strong>NOAA's Storm Events Database</strong>, which lists reported wind, hail, tornado, flood, and surge events by county and date.</li>
<li><strong>National Weather Service Lake Charles</strong>, which covers Jefferson County and publishes event summaries after major storms.</li>
<li><strong>National Hurricane Center</strong> Tropical Cyclone Reports for named storms.</li>
</ul>

<p>Our <a href="/storm-lookup/">storm lookup tool</a> pulls Jefferson County storm records by date, and our <a href="/storm-history/">storm history</a> page summarizes the major events. Save or print the records that match your date of loss and include them in your claim file.</p>

<h2>Step 6: The communication log</h2>

<p>A storm claim can involve several adjusters, inspectors, engineers, and contractors. Keep one log for everything:</p>

<ul>
<li>Claim number for each policy (homeowners, TWIA, flood).</li>
<li>Date, time, name, and phone number for every call, plus a short summary.</li>
<li>Copies of every email, letter, estimate, and report.</li>
<li>Dates of inspections and who attended.</li>
<li>Any request for documents and the date you sent them.</li>
<li>Any promise or deadline given to you.</li>
</ul>

<p>Follow up important phone calls with a short email confirming what was discussed. Texas prompt payment rules give insurers set time frames to acknowledge, investigate, and decide claims, and those clocks often run from when the insurer receives requested information. A clear log helps you see whether those time frames are being met. If you believe your claim is being delayed, our <a href="/services/delayed-insurance-claims/">delayed insurance claims</a> page explains common next steps.</p>

<h2>Common documentation mistakes</h2>

<ul>
<li><strong>Cleaning up before photographing.</strong> Once it is in the dumpster, it is hard to prove.</li>
<li><strong>Only taking close-ups.</strong> Without wide shots, an adjuster cannot tell where a photo was taken.</li>
<li><strong>Forgetting the attic, crawlspace, and detached structures.</strong></li>
<li><strong>Losing mitigation reports.</strong> Ask the mitigation company for the full file, not just the invoice.</li>
<li><strong>Relying on memory for phone calls.</strong> Write it down the same day.</li>
<li><strong>Waiting too long.</strong> Report the claim promptly. TWIA requires claims to be reported within one year of the date of damage, with possible extension for good cause, and other policies have their own notice requirements.</li>
</ul>

<h2>Extra steps for rental and commercial properties</h2>

<p>Landlords and business owners in Port Arthur have a few more items to document. Many local businesses depend on the refineries, petrochemical plants, and port, and a storm that closes a building or cuts power can interrupt income for weeks.</p>

<ul>
<li><strong>Business income records.</strong> Keep sales reports, profit and loss statements, and payroll records for the months before and after the storm. Business interruption coverage, if you have it, is usually calculated from these records.</li>
<li><strong>Extra expense.</strong> Track temporary locations, equipment rentals, overtime, and expedited shipping used to keep operating.</li>
<li><strong>Rental income.</strong> Landlords should keep leases, rent rolls, and records of units that became uninhabitable.</li>
<li><strong>Building systems.</strong> Photograph HVAC units, electrical panels, and low-slope or metal roof systems, which are common on commercial and industrial buildings and can hide water damage.</li>
</ul>

