<h2>Step 1: Photos and video before you touch anything</h2>

<p>Start outside. Walk each side of the building and take a wide photo of every elevation, so an adjuster can see the whole wall or roof plane. Then move in for close-ups of each damaged area. Include something for scale, such as a tape measure or a coin.</p>

<h3>Exterior photo list</h3>
<ul>
<li>Roof from the ground with zoom: missing or creased shingles, lifted ridge caps, exposed decking, bent metal panels, damaged vents and pipe boots.</li>
<li>Gutters, downspouts, and fascia: dents, detachment, and hail spatter.</li>
<li>Siding and brick veneer: holes, cracks, missing vinyl or fiber-cement pieces.</li>
<li>Windows and doors: broken glass, damaged frames, water stains at sills.</li>
<li>Fences, sheds, carports, and detached garages.</li>
<li>Fallen trees and where they struck the structure.</li>
<li>Water lines and debris lines on exterior walls and fences.</li>
</ul>

