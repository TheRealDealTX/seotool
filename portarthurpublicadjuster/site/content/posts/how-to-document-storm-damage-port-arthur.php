<h2>Step 4: The contents inventory</h2>

<p>Personal property is often the most tedious part of a storm claim, and the part most likely to be underpaid because items are forgotten. Work room by room:</p>

<ol>
<li>Photograph each room as a whole, then each damaged item.</li>
<li>List each item with a description, brand, model, approximate age, where it was bought, and the original price or a current replacement price.</li>
<li>Photograph labels and serial numbers on appliances and electronics.</li>
<li>Pull receipts, bank and credit card statements, and online order histories to support values.</li>
<li>Do not forget closets, drawers, the garage, freezer contents, and outdoor items.</li>
</ol>

<p>A spreadsheet works well. Separate columns for quantity, age, and replacement cost make it easier for the adjuster to review and for you to track what has been paid. If you have a TWIA policy, remember that personal property has its own deductible, separate from the dwelling.</p>

