<h2>How a Port Arthur Public Adjuster documents a claim</h2>

<p>A licensed public adjuster works for the policyholder. A typical documentation process includes a full property inspection, detailed photos, moisture readings and thermal imaging where useful, 3D imaging such as Matterport in some cases, weather data for the date of loss, and a line-by-line estimate, often in Xactimate. The goal is a claim file that shows what was damaged, why, and what it costs to repair.</p>

