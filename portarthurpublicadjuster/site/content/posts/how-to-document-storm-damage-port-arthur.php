<h2>Step 2: Mitigation and the receipts that go with it</h2>

<p>Most policies require you to take reasonable steps to protect the property from further damage. In Port Arthur's heat and humidity, water damage can turn into mold within days, so prompt drying matters for both the building and the claim.</p>

<ul>
<li><strong>Tarp the roof</strong> or board openings. Photograph before and after.</li>
<li><strong>Extract water and start drying.</strong> If you hire a mitigation company, ask for their moisture readings, drying logs, and photo report.</li>
<li><strong>Remove wet materials as needed</strong>, such as carpet pad and the bottom of drywall, but photograph them first and keep samples when practical.</li>
<li><strong>Save every receipt</strong>: tarps, fasteners, pumps, fans, dehumidifiers, generator fuel, lumber, and labor.</li>
<li><strong>Track your own labor.</strong> Note hours spent on emergency work. Some policies may reimburse reasonable costs of protecting the property.</li>
</ul>

<p>Hold off on permanent repairs, such as a full re-roof, until the insurer has had a reasonable chance to inspect, unless waiting would cause more damage. In Jefferson County, roof repairs and re-roofs also need to meet TDI windstorm inspection requirements to stay eligible for TWIA coverage, and city permits generally apply. Our <a href="/local-building-codes/">local building codes</a> page explains the basics.</p>

<h2>Step 3: Moisture readings and hidden damage</h2>

<p>Water travels. It wicks up drywall, soaks insulation inside walls, runs along subfloors, and pools under cabinets. Much of that damage is invisible. Moisture readings turn invisible damage into evidence.</p>

<p>Mitigation companies and adjusters commonly use pin and pinless moisture meters, and thermal imaging cameras to spot cool, wet areas. A moisture map that marks readings across walls and floors shows the extent of wet materials and how high water wicked. Drying logs show readings over several days as materials dry. Both support the scope of tear-out and replacement in an estimate.</p>

<p>Moisture data also helps on mixed-cause storms. Readings high on walls and in ceilings, above a flood line, can support wind-driven rain damage separately from rising water. See our article on <a href="/wind-vs-flood-damage-port-arthur-insurance/">wind vs. flood damage in Port Arthur</a> for more on that split.</p>

