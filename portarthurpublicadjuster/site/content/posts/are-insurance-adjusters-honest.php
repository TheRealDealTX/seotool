<h2>How to protect yourself during a claim</h2>

<h3>1. Document everything</h3>
<ul>
<li>Photograph and video the damage before cleanup, then after any emergency repairs.</li>
<li>Keep damaged materials until the adjuster has seen them or approved disposal.</li>
<li>Save receipts for tarps, drying equipment, hotel stays, and supplies.</li>
<li>Keep communication in writing, or follow phone calls with a short email summary.</li>
</ul>
<p>Our <a href="/claim-documentation-checklist/">claim documentation checklist</a> walks through this in detail.</p>

<h3>2. Read your policy and declarations page</h3>
<p>Know your deductibles (many Texas policies have separate wind/hail or hurricane deductibles stated as a percentage of the dwelling limit), whether you have replacement cost or actual cash value coverage, and what is excluded. Many Port Arthur homes have wind and hail covered by a separate TWIA policy and flood covered by an NFIP policy. Ask questions in writing if anything is unclear.</p>

<h3>3. Do not automatically accept the first number</h3>
<p>You can request the full estimate, ask how each figure was calculated, get your own contractor estimates, and submit a supplement for missed items. Negotiation is a normal part of property claims.</p>

<h3>4. Watch the deadlines</h3>
<p>Your policy, TWIA rules, and the NFIP all have deadlines for reporting, proof of loss, recoverable depreciation, and appraisal. Many Texas policies also set a contractual deadline to sue. If you are anywhere near a lawsuit deadline, talk to a Texas attorney.</p>

<h3>5. Use the complaint process when it is warranted</h3>
<p>If an adjuster stops responding, misstates your policy, or the insurer misses statutory deadlines, you can <a href="https://www.tdi.texas.gov/consumer/complfrm.html" target="_blank" rel="noopener">file a complaint with TDI</a>. A complaint doesn’t replace a claim dispute, but it creates a record.</p>

<h2>When to consider getting help</h2>

<p>Many small, simple claims can be handled directly with the insurer. Outside help tends to be worth considering when:</p>
<ul>
<li>The damage is large or structural, such as a roof, framing, or a whole-house water loss</li>
<li>Fire or smoke damage involves contents and cleaning questions</li>
<li>You received a denial or partial denial letter (see <a href="/services/denied-insurance-claims/">denied insurance claims</a>)</li>
<li>The settlement is far below repair bids (see <a href="/services/underpaid-insurance-claims/">underpaid insurance claims</a>)</li>
<li>Multiple policies are involved, such as homeowners, TWIA, and flood after a hurricane</li>
<li>You simply don’t have the time to manage the claim while dealing with repairs, work, and family</li>
</ul>

<h2>The balanced answer</h2>

<p>Are insurance adjusters honest? Most are. Most follow the law and do not set out to mislead homeowners. But they are not neutral, and they are not your advocate. They represent the company that pays them, and that shapes how a claim is scoped, priced, and settled.</p>

