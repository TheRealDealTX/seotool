<h2>Why the first offer is often lower than expected</h2>

<p>Most of the frustration comes from the gap between the insurer’s estimate and what it actually costs to fix the house. That gap usually has ordinary explanations.</p>

<h3>1. The scope is incomplete</h3>
<p>An adjuster may scope the visible roof damage and ceiling stain but miss wet insulation, swollen subfloor on a pier-and-beam home, damaged roof decking, or moisture behind cabinets. Port Arthur’s humidity also means mold can start within days after a water loss, so damage you can’t see today may be obvious in two weeks.</p>

<h3>2. Repair versus replace</h3>
<p>A wind-damaged composition shingle roof might be scoped for spot repairs when matching shingles are unavailable or the roof cannot be repaired to code. These decisions change the estimate dramatically.</p>

<h3>3. Depreciation</h3>
<p>Under a replacement cost policy, the insurer typically pays actual cash value (replacement cost minus depreciation) first and releases recoverable depreciation after repairs are completed, within the policy’s deadline. Some Texas policies cover roofs only at actual cash value or use a roof payment schedule. How much depreciation is applied, and to which items, is a judgment call that is worth reviewing line by line.</p>

<h3>4. Pricing and missing line items</h3>
<p>Estimating software pricing is regional and updated periodically, but after a hurricane, labor and material costs in Southeast Texas can climb faster than the price list. Estimates can also leave out permits, debris removal, contractor overhead and profit, or code items covered under ordinance or law coverage.</p>

<h3>5. Catastrophe volume and delays</h3>
<p>After a storm like Hurricane Laura in 2020, thousands of claims open across Southeast Texas at once. Adjusters are reassigned, files change hands, and homeowners get asked for the same documents twice. It feels suspicious. Most of the time it is volume. Texas’s prompt payment law (<a href="https://statutes.capitol.texas.gov/Docs/IN/htm/IN.542.htm" target="_blank" rel="noopener">Chapter 542</a>) still sets deadlines for most insurers, though they can be extended by 15 days after a catastrophe declared by the Commissioner of Insurance. TWIA claims follow their own timelines under Chapter 2210.</p>

