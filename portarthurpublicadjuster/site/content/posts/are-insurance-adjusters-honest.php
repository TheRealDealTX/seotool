<h2>Signs you are dealing with a fair adjuster</h2>

<p>Plenty of adjusters take pride in getting the numbers right. Good signs include:</p>
<ul>
<li>They explain the policy language that applies, and answer questions in writing when asked.</li>
<li>They provide a full, itemized estimate, not just a payment total.</li>
<li>They return calls and emails within a reasonable time.</li>
<li>They will review additional photos, moisture readings, or contractor estimates and revise the estimate if warranted.</li>
<li>They tell you about supplements, recoverable depreciation, and how to request reinspection.</li>
</ul>

<p>Even a fair adjuster is not going to negotiate for you or point out every item they missed. That part is up to you or someone you hire.</p>

