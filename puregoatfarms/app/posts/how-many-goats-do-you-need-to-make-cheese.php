<p>You do not always need to collect all the milk in one day. This is where planning becomes easier.</p>
<p>Let’s say one goat gives 0.75 gallon per day. In one day, you have 0.75 gallon. In two days, you have 1.5 gallons. In three days, you have 2.25 gallons. Over a week, you have 5.25 gallons before any milk is reserved for kids or household use.</p>
<p>That changes everything.</p>
