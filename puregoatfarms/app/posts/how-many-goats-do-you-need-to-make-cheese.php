<p>This is one of the biggest mistakes new goat owners make.</p>
<p>They calculate based on total milk production, then realize later that the kids are drinking part of it. If you dam-raise kids or share milk, your kitchen does not receive the full daily yield.</p>
<p>For example, if a goat produces 1 gallon per day but 50% goes to her kids, you have only 0.5 gallon available. Over two days, that gives you 1 gallon of usable milk, not 2 gallons.</p>
<p>That may still be enough for a small batch of fresh cheese. But it may not be enough for semi-soft or aged cheese.</p>
<p>Here is a quick example:</p>
