<h2>Saanen: The Volume Champion</h2>
<p>Originally from Switzerland, the all-white Saanen is the “Holstein of goats.” If your main goal is the largest amount of milk per doe, start here.</p>
<ul>
<li><strong>Milk:</strong> Highest volume of any breed; mature does commonly give a gallon or more a day, with top does over 12 lb at peak.</li>
<li><strong>Butterfat:</strong> Lower, around 3–3.5%, giving a mild flavor that is great for drinking.</li>
<li><strong>Temperament:</strong> Calm and steady — a good choice for families and first-time milkers.</li>
<li><strong>Watch for:</strong> Pale skin is prone to sunburn; provide shade in hot, sunny climates.</li>
</ul>
<p>The colored version of the Saanen is recognized as a separate breed, the <strong>Sable</strong>, with the same production profile.</p>

<h2>Alpine: Reliable and Hardy</h2>
<p>Alpines come in many color patterns and are known for strong, persistent lactations — they hold production longer into the season than most breeds.</p>
<ul>
<li><strong>Milk:</strong> Close behind Saanens at roughly 7–9 lb a day, and very consistent.</li>
<li><strong>Butterfat:</strong> About 3.3–3.6%.</li>
<li><strong>Temperament:</strong> Confident and inquisitive; they tend to sit near the top of the herd order.</li>
<li><strong>Best for:</strong> Cold or variable climates and keepers who want a steady supply across the whole lactation.</li>
</ul>

<h2>Nubian: Rich, Sweet and Vocal</h2>
<p>With long floppy ears and a Roman nose, Nubians are the most recognizable dairy goats in North America — and among the most popular.</p>
<ul>
<li><strong>Milk:</strong> Moderate volume, about 5–7 lb a day.</li>
<li><strong>Butterfat:</strong> High, typically 4.5–5%, with high protein. Excellent for cheese, yogurt and soap.</li>
<li><strong>Temperament:</strong> Affectionate and people-oriented — and loud. Nubians have opinions and share them.</li>
<li><strong>Best for:</strong> Hot climates (they handle heat well) and cheesemakers who value yield per gallon.</li>
</ul>

<h2>LaMancha: The Easy-Going All-Rounder</h2>
<p>LaManchas are instantly recognizable by their tiny “gopher” or “elf” ears. Behind the unusual look is one of the best-natured dairy goats you can own.</p>
<ul>
<li><strong>Milk:</strong> Solid volume, around 6–8 lb a day.</li>
<li><strong>Butterfat:</strong> Around 4%, a nice middle ground.</li>
<li><strong>Temperament:</strong> Exceptionally calm and quiet, with a reputation for being easy on the milk stand.</li>
<li><strong>Best for:</strong> Beginners who want full-size production without drama or noise.</li>
</ul>

<h2>Oberhasli: Quiet and Efficient</h2>
<p>The bay-colored Oberhasli, with its black “chamoisee” markings, is less common but well loved by those who keep it.</p>
<ul>
<li><strong>Milk:</strong> About 6–8 lb a day with a sweet, mild flavor.</li>
<li><strong>Butterfat:</strong> Around 3.6–3.8%.</li>
<li><strong>Temperament:</strong> Gentle and quiet; does are usually easy to handle.</li>
<li><strong>Watch for:</strong> Smaller breeding population, so quality stock can be harder to find.</li>
</ul>

<h2>Toggenburg: The Original Swiss Dairy Goat</h2>
<p>Toggenburgs are one of the oldest registered dairy breeds, recognizable by their brown coat with white facial stripes.</p>
<ul>
<li><strong>Milk:</strong> About 6–8 lb a day, with good persistence in cold weather.</li>
<li><strong>Butterfat:</strong> Lower, around 3–3.3%.</li>
<li><strong>Temperament:</strong> Lively and sometimes headstrong.</li>
<li><strong>Best for:</strong> Cooler climates; their milk can have a stronger flavor that suits aged cheeses.</li>
</ul>

<h2>Nigerian Dwarf: Small Goat, Rich Milk</h2>
<p>Nigerian Dwarfs started our own herd, and they remain our favorite recommendation for small homesteads.</p>
<ul>
<li><strong>Milk:</strong> About 2–3 lb a day (1–1.5 quarts), impressive for a 60–75 lb goat.</li>
<li><strong>Butterfat:</strong> The highest of any dairy breed, 6–7% or more. Wonderful for butter, ice cream and chevre.</li>
<li><strong>Temperament:</strong> Playful and friendly; easy for kids and adults to handle.</li>
<li><strong>Best for:</strong> Small acreage, backyard herds and families who do not need gallons a day.</li>
<li><strong>Watch for:</strong> Small teats can be fiddly to hand-milk until you build the knack.</li>
</ul>
