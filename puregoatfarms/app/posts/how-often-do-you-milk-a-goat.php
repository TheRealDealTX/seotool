<h2>How Long Do You Milk a Goat Each Year?</h2>
<p>A standard lactation lasts about <strong>305 days</strong>. Most keepers rebreed in the fall and dry the doe off roughly 60 days before her next kidding. Some does can be “milked through” for 18 months or more without rebreeding — we explain how in <a href="/do-goats-produce-milk-without-being-pregnant/">do goats produce milk without being pregnant</a>.</p>
