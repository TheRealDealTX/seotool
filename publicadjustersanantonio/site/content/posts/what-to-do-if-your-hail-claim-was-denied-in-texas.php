<h2>Mistakes that hurt a denied claim</h2>
<ul>
<li>Waiting months to respond while more storms and rain change the roof</li>
<li>Replacing the roof before the insurer can reinspect, without documenting the old one thoroughly</li>
<li>Sending a long, emotional letter instead of a clear, evidence-based response</li>
<li>Resubmitting the same photos without anything new</li>
<li>Assuming the deadline to sue is far away without checking</li>
</ul>

<h2>Preventing the next denial</h2>
<ul>
<li>Keep dated photos of your roof each spring, before hail season peaks in April and May.</li>
<li>Keep records of roof inspections and repairs.</li>
<li>Review your declarations page at renewal for wind/hail deductibles, ACV roof terms, and cosmetic exclusions.</li>
<li>Report storm damage promptly and document before any repairs.</li>
</ul>

