<h2>Step 1: Read the denial letter line by line</h2>

<p>Under Texas’s <a href="https://statutes.capitol.texas.gov/Docs/IN/htm/IN.542.htm" target="_blank" rel="noopener">Prompt Payment of Claims law</a>, an insurer that rejects a claim must give the reason in writing. Read it closely and write down:</p>
<ul>
<li>The exact reason given</li>
<li>Every policy provision quoted or cited (find each one in your policy)</li>
<li>What the inspector says they found, or did not find</li>
<li>Any information the insurer says is missing</li>
<li>Any deadline or next step the letter mentions</li>
</ul>

<p>If the letter is vague, ask in writing for the inspection report, photos, and any engineer’s report the insurer relied on.</p>

<h2>Step 2: Organize your claim file</h2>

<p>Put everything in one place: the policy and declarations page, the denial letter, the insurer’s estimate, your photos and video, contractor reports, receipts, and a log of every call and email. Our <a href="/claim-documentation-checklist/">claim documentation checklist</a> has the full list.</p>

<h2>Step 3: Re-document the damage</h2>

<p>Do not stop at the roof. Hail leaves a pattern, and the more surfaces that show it, the stronger the case:</p>
<ul>
<li>Gutters, downspouts, and metal vents (dents)</li>
<li>Window screens (tears and punctures) and window trim</li>
<li>AC condenser fins</li>
<li>Siding, stucco, paint, fences, and the garage door</li>
<li>Each roof slope, photographed wide, mid-range, and close up with a tape measure</li>
</ul>

