<h2>Step 7: Know your escalation options</h2>

<h3>Appraisal</h3>
<p>Most Texas property policies include an appraisal clause for disagreements about the <em>amount</em> of loss. Each side picks an appraiser, the appraisers pick an umpire, and an award agreed to by any two is binding on the amount, as the policy language provides. Appraisal does not decide whether damage is covered, so it fits best when the insurer accepted some hail damage but undervalued it. See our <a href="/services/insurance-appraisal/">insurance appraisal</a> page.</p>

<h3>TDI complaint</h3>
<p>If you believe the insurer unfairly denied your claim or is not responding, you can <a href="https://www.tdi.texas.gov/consumer/get-help-with-an-insurance-complaint.html" target="_blank" rel="noopener">file a complaint with TDI</a> or call 800-252-3439. TDI says it can ask the company to look at the policy again to make sure it made the correct decision. It is not a guarantee of a different result.</p>

<h3>Attorney</h3>
<p>If the dispute is about coverage, or you are considering a lawsuit, talk to a Texas attorney. Weather-related claim lawsuits are subject to Insurance Code Chapter 542A, which requires written notice at least 61 days before filing suit, and many policies contain their own deadline to sue.</p>

