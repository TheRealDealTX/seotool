<h2>Step 6: Respond in writing and request a reinspection</h2>

<p>TDI’s guidance is direct: if you think the company should pay, tell it why and send supporting documents, such as a contractor’s estimate. A good response letter:</p>
<ol>
<li>References the claim number, date of loss, and denial letter date</li>
<li>States which findings you disagree with and why</li>
<li>Lists the new evidence attached (photos, reports, storm data, estimate)</li>
<li>Requests a reinspection, ideally with your roofer or representative present</li>
<li>Asks for a written response</li>
</ol>

<p>Keep copies of everything and note the date it was sent. Follow up if you do not hear back.</p>

