<h2>Step 5: Get a qualified second opinion</h2>

<p>A reputable licensed roofer can inspect and give you a written report with photos. For disputes about cause (hail versus wear, for example), an engineer’s report is sometimes used. Be cautious of anyone promising a “free roof” or offering to waive your deductible. TDI warns that waiving a homeowner’s deductible is illegal in Texas, and contractors cannot advertise that they will handle your insurance claim.</p>

