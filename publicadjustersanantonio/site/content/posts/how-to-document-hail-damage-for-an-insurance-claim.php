<h2>Common documentation mistakes</h2>
<ul>
<li>Blurry or dark photos, or close-ups with no way to tell where they were taken</li>
<li>Skipping vents, flashing, gutters, and the AC unit</li>
<li>Waiting weeks to document, after more rain and wind</li>
<li>Not recording the storm date and hail size</li>
<li>Mixing older damage with new damage; note anything that was there before</li>
<li>Making permanent repairs before the insurer inspects</li>
</ul>

<h2>What the insurer’s adjuster looks for</h2>
<p>Adjusters look for consistent evidence across photos and notes, a pattern that matches hail (random impacts, damage on soft metals on the same side of the house), measurable impacts, and a clear line between storm damage and age-related wear. If your documentation answers those questions, the review is easier. Walk the property with the adjuster if you can, and point out everything on your list.</p>

<h2>Advanced tips</h2>
<ul>
<li><strong>Before-and-after comparisons.</strong> Real estate listing photos, old phone pictures, or a recent roof inspection can show the roof’s condition before the storm.</li>
<li><strong>Neighborhood context.</strong> Photos of damage to nearby fences, cars, or roofs can show the storm’s reach, but only photograph from public areas and respect your neighbors’ privacy.</li>
<li><strong>Interior follow-up.</strong> Check ceilings and the attic again after the next heavy rain, and add any new findings to the file promptly.</li>
</ul>

<h2>Documenting for different San Antonio roofs and homes</h2>

<p>Local construction affects what you should photograph:</p>
<ul>
<li><strong>Composition shingle roofs</strong>, the most common type here, need close-ups of granule loss and bruising on every slope, plus the ridge cap and any vents.</li>
<li><strong>Standing-seam metal roofs</strong>, more common toward the Hill Country edge in places like Boerne and Helotes, show dents best in low-angle light early or late in the day. Photograph seams and trim, and note whether panels still shed water properly.</li>
<li><strong>Tile roofs</strong> need photos of cracked or displaced tiles, taken by a professional who knows how to walk them without causing more breakage.</li>
<li><strong>Stucco, brick, and limestone exteriors</strong> may show chips and spatter marks. Photograph window trim, light fixtures, and painted surfaces on the side that faced the storm.</li>
<li><strong>Flat and low-slope commercial roofs</strong> need photos of the membrane, rooftop HVAC units, drains, and any interior leaks, ideally with the date on each.</li>
</ul>

