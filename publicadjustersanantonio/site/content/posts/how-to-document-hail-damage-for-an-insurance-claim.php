<h2>Step-by-step: how to document hail damage for an insurance claim</h2>

<h3>Step 1: Stay safe</h3>
<p>Do not climb onto a wet, steep, or damaged roof. Two-story homes and tile roofs are especially dangerous. Document what you can from the ground and leave the roof surface to a qualified professional.</p>

<h3>Step 2: Record the storm</h3>
<p>Write down the date, approximate time, how long it lasted, the largest hail you saw, and wind direction if you noticed it. Photograph hailstones next to a ruler or coin as soon as possible. A quick video of hail falling, if you have it, is helpful too.</p>

<h3>Step 3: Take wide, mid-range, and close-up photos</h3>
<ul>
<li><strong>Wide:</strong> each side of the house from the street or yard, showing the roof and elevation.</li>
<li><strong>Mid-range:</strong> each slope, gutter run, window, and the AC unit, so the reader can tell where each close-up was taken.</li>
<li><strong>Close-up:</strong> individual impacts with a tape measure or coin for scale.</li>
</ul>
<p>Take more photos than you think you need. Keep them sharp and well lit, and avoid filters or edits.</p>

