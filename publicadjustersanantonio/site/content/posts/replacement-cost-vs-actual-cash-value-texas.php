<h2>How to get recoverable depreciation released</h2>

<p>Many replacement cost policies require you to complete repairs, or notify the insurer that you intend to claim replacement cost, within a set period. The deadline varies by policy and insurer. To protect the holdback:</p>
<ol>
<li><strong>Find the deadline</strong> in the loss settlement or replacement cost section of your policy, and put it on your calendar.</li>
<li><strong>Ask for an extension in writing</strong> before the deadline if repairs are delayed by contractor backlog, permits, or materials. Keep the response.</li>
<li><strong>Keep the final invoice,</strong> proof of payment, photos of the finished work, and permit records.</li>
<li><strong>Send everything in one package</strong> and ask the insurer to confirm receipt.</li>
</ol>

<p>Many policies pay the lesser of the replacement cost on the estimate or the amount actually spent. If your contractor charges less than the estimate, the released depreciation may be reduced. If the job costs more because the estimate missed items, that is a scope question and is usually handled through a <a href="/services/insurance-claim-supplements/">supplement</a>, not through depreciation.</p>

<h2>Contents and other structures</h2>

<p>The same concepts apply beyond the roof. Personal property may be covered at replacement cost or ACV, depending on your policy. When contents are covered at replacement cost, insurers commonly pay ACV first and release depreciation after you replace items and submit receipts. Fences, detached garages, and sheds usually fall under other structures coverage, with its own limit and possibly different settlement terms.</p>

<p>After a large water or fire loss, keep a running inventory with item descriptions, ages, and replacement prices, and save every receipt. Our <a href="/claim-documentation-checklist/">claim documentation checklist</a> includes a contents section.</p>

