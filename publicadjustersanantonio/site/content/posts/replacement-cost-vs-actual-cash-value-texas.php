<h2>Questions to ask at your next renewal</h2>

<p>Because roof terms can change the outcome so much, it is worth asking your agent a few direct questions each year, ideally before March, when San Antonio's hail season starts to build:</p>
<ul>
<li>Is my roof covered at replacement cost, actual cash value, or under a payment schedule?</li>
<li>What is my wind/hail deductible, and is it a flat amount or a percentage of Coverage A?</li>
<li>Does my policy exclude cosmetic damage to metal roofing or other surfaces?</li>
<li>How much ordinance or law coverage do I have?</li>
<li>Is personal property covered at replacement cost or actual cash value?</li>
<li>What is the deadline to complete repairs and claim replacement cost?</li>
</ul>

<p>Write the answers down and keep them with your policy. If the answers are not what you expected, you have time to compare options before a storm rather than after one.</p>

