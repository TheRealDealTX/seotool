<h2>The basic definitions</h2>

<h3>Replacement cost value (RCV)</h3>

<p>Replacement cost value is what it would cost today to repair or replace the damaged property with materials of like kind and quality, without a deduction for age or wear. On a roof claim, that includes tear-off, disposal, underlayment, shingles or panels, flashing, vents, drip edge, ridge cap, labor, and, where appropriate, contractor overhead and profit.</p>

<h3>Actual cash value (ACV)</h3>

<p>Actual cash value is generally replacement cost minus depreciation. Depreciation reflects the share of an item's useful life already used up. A 14-year-old composition shingle roof will usually carry more depreciation than a 4-year-old roof, even if hail damaged both the same way.</p>

<h3>Depreciation: recoverable and non-recoverable</h3>

<p>Depreciation is usually applied line by line in estimating software such as Xactimate, based on age, condition, and expected life. Each line may show a depreciation percentage and whether it is recoverable (you can get it back after repairs) or non-recoverable (you cannot). Those two details often matter more than the total.</p>

