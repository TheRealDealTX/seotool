<h3>When the deductible is larger than the ACV</h3>

<p>With percentage deductibles, it is possible for the deductible to exceed the actual cash value of the damage. Using the hypothetical numbers above, if the ACV had been $3,000 instead of $12,000, the first payment would be zero because the $3,500 deductible is larger. Under many replacement cost policies, the homeowner could still be owed recoverable depreciation after repairs, since the total replacement cost exceeds the deductible. Under ACV-only roof terms, nothing would be paid for the roof. This is one reason a "below deductible" letter deserves a careful look at the full estimate and the policy terms.</p>

<h3>How depreciation rates are set</h3>

<p>There is no single statewide depreciation table. Insurers and their adjusters typically estimate depreciation from the item's age, its expected life, and its condition, and estimating software applies a percentage to each line. Two adjusters can reach different numbers for the same roof. The inputs worth checking are the age the adjuster used, the expected life assumed for the material, and whether depreciation was applied consistently across similar lines. If the roof age is wrong, every roofing line will be off.</p>

<h2>Roof endorsements and schedules in Texas</h2>

<p>Roof coverage is where Texas policies vary most. A home can be insured at replacement cost while the roof is treated differently. Common approaches include:</p>
<ul>
<li><strong>Roof ACV endorsement.</strong> The roof surface is settled at actual cash value, and depreciation is not recoverable.</li>
<li><strong>Roof payment schedule.</strong> The roof is paid at a percentage of replacement cost tied to its age, and sometimes its material.</li>
<li><strong>Cosmetic damage exclusion.</strong> Some policies exclude hail dents to metal roofing or other surfaces that do not affect function. This is especially relevant for standing-seam metal roofs common toward the Hill Country edge of the metro area.</li>
<li><strong>Full replacement cost on the roof.</strong> Some policies still cover the roof at replacement cost with recoverable depreciation.</li>
</ul>

<p>These terms usually appear on the declarations page or as endorsements attached to the policy. If you are unsure which applies, ask your agent for a complete copy of the policy with all forms and endorsements.</p>

