<ol>
<li><strong>Make it safe.</strong> Do not enter until the fire department says it is safe. Arrange board-up and security for openings to prevent theft and weather damage. Contact CPS Energy and SAWS as needed about utilities. Keep receipts; reasonable steps to protect the property are often reimbursable.</li>
<li><strong>Report the claim promptly.</strong> Write down the claim number and the adjuster’s name, phone, and email. Under Texas’s <a href="https://statutes.capitol.texas.gov/Docs/IN/htm/IN.542.htm" target="_blank" rel="noopener">Prompt Payment of Claims law</a>, the insurer generally has 15 days after notice to acknowledge the claim, start its investigation, and request what it needs.</li>
