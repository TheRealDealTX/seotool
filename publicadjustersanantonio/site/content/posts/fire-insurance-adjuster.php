<h2>Building a contents inventory that holds up</h2>

<p>The contents portion of a fire claim is where many households lose the most time. A few habits make it more manageable:</p>
<ul>
<li><strong>Go room by room.</strong> Use the same order every time: closets, drawers, shelves, walls, floor. Phone videos you took before the fire, old photos, and social media pictures can help you remember what was there.</li>
<li><strong>Describe each item.</strong> Brand, model, size, approximate age, and where you bought it. “Samsung 55-inch TV, about 3 years old” is easier to price than “TV.”</li>
<li><strong>Look for proof of ownership.</strong> Online order histories, credit card statements, warranty registrations, and manuals all help.</li>
<li><strong>Price replacements at today’s cost.</strong> Note a comparable item and where it is sold, so the insurer can verify the price.</li>
<li><strong>Separate cleanable from non-salvageable items.</strong> Some items can be cleaned of smoke and soot; others cannot. If you disagree with the insurer’s decision on an item, say why in writing.</li>
<li><strong>Use a spreadsheet.</strong> One line per item, with room, description, age, quantity, and replacement price. Keep it updated as you remember more.</li>
</ul>

<p>Check your policy for any requirement to provide a sworn proof of loss or an inventory by a certain date if the insurer asks for one. Our <a href="/claim-documentation-checklist/">claim documentation checklist</a> includes a contents section you can follow.</p>

<h2>Common mistakes after a fire</h2>

<ul>
<li><strong>Accepting the first estimate without reading it.</strong> Check every room and every category.</li>
<li><strong>Discarding damaged items too early.</strong> Photograph and list them first, and get the insurer’s OK.</li>
<li><strong>Not reading the policy.</strong> Know your coverage limits, deductible, contents coverage, and additional living expense limits.</li>
<li><strong>Rushing the contents list.</strong> A vague list (“kitchen items”) is harder to support than a detailed one.</li>
<li><strong>Letting a contractor “handle the insurance.”</strong> Under Texas law, contractors cannot advertise that they will handle your insurance claim, and a public adjuster cannot be your contractor on the same claim.</li>
</ul>

<h2>When to consider a public adjuster for a fire claim</h2>

<p>Not every fire claim needs one. A small kitchen fire with limited smoke may be straightforward. A public adjuster in San Antonio is more often worth considering when:</p>
<ul>
<li>The home or business is heavily damaged or uninhabitable</li>
<li>Smoke damage extends well beyond the fire area</li>
<li>The contents inventory is large</li>
<li>The estimate is far below contractor bids</li>
<li>Part of the claim was denied or the claim has stalled</li>
<li>You do not have time to manage the claim while your family is displaced</li>
</ul>

