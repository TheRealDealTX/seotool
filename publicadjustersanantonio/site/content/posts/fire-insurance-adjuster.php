<h2>What the adjuster looks at after a fire</h2>

<h3>Structure</h3>
<p>Framing, roof decking, drywall, insulation, flooring, cabinets, windows, doors, and electrical wiring. Heat can damage materials well away from the flames. Wiring, plumbing, and window seals may need testing or replacement even if they look fine.</p>

<h3>Smoke and soot</h3>
<p>Smoke travels through wall cavities, attics, and ductwork. Odor can linger in insulation, carpet pad, and porous materials. Whether an item should be cleaned, sealed, or replaced is often one of the biggest disagreements in a fire claim. See our page on <a href="/services/smoke-damage-claims/">smoke damage claims</a>.</p>

<h3>Water from firefighting</h3>
<p>Fire hoses can put a large amount of water into a home. Wet drywall, subfloors, and insulation need to be dried or removed, and moisture left behind can lead to mold. This damage is part of the fire loss and should be documented as such. Our <a href="/services/water-damage-claims/">water damage claims</a> page covers drying and documentation.</p>

<h3>HVAC and mechanical systems</h3>
<p>Ducts, air handlers, and returns can pull soot through the house. HVAC cleaning or replacement is easy to overlook in a first estimate.</p>

<h3>Contents (personal property)</h3>
<p>Clothing, furniture, electronics, kitchen items, and everything else you own. Contents lists for a whole home can run to hundreds or thousands of items, and this is often the most time-consuming part of a fire claim.</p>

<h3>Additional living expenses</h3>
<p>If the home is not livable, many policies pay for reasonable additional costs such as a hotel or rental and extra food costs, within the policy limits. Keep every receipt.</p>

