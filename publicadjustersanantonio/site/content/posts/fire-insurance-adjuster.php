<h2>Replacement cost vs. actual cash value</h2>

<p>These two terms change the size of your check:</p>
<ul>
<li><strong>Replacement cost value (RCV)</strong> is what it costs today to repair or replace with materials of like kind and quality.</li>
<li><strong>Actual cash value (ACV)</strong> is replacement cost minus depreciation for age and condition.</li>
</ul>

<p>For example, a ten-year-old sofa might cost $1,800 to replace, but its ACV after depreciation will be less. Under a replacement cost policy, you can usually recover the difference after you replace it. Under an ACV-only policy, you generally cannot. Our <a href="/claim-calculator/">claim calculator</a> shows how deductible and depreciation interact.</p>

<h2>What is often missed in fire claims</h2>

<ul>
<li>Smoke damage in rooms and closets away from the fire</li>
<li>Soot inside wall cavities, attic insulation, and ductwork</li>
<li>Electrical wiring exposed to heat</li>
<li>Water damage and drying from firefighting</li>
<li>Code-required work when walls or systems are opened (paid only to the extent your policy includes ordinance or law coverage)</li>
<li>Permits and inspections through the City of San Antonio Development Services Department, or your suburban city’s permit office</li>
<li>Contents in storage areas, garages, and outbuildings</li>
<li>Debris removal and temporary protection costs</li>
</ul>

