<h2>Understanding the fee and the contract</h2>

<p>Fees are disclosed in a written contract before any work begins; Texas law caps public adjuster compensation at 10% of the insurance settlement. A few details from <a href="https://www.tdi.texas.gov/tips/public-adjusters.html" target="_blank" rel="noopener">TDI’s consumer guidance</a> are easy to miss:</p>
<ul>
<li><strong>The fee can apply to the whole settlement.</strong> TDI’s example: if the insurer wants to pay $100,000 and you are disputing $20,000, a 10% fee could be $10,000.</li>
<li><strong>You may still owe a fee</strong> if the insurer does not increase its offer after you hire the adjuster. You also still owe your deductible.</li>
<li><strong>You can ask for a dollar amount</strong> instead of a percentage, and you can try to negotiate.</li>
<li><strong>Policy-limits exception.</strong> If the insurer pays or commits in writing to pay policy limits within 72 hours after the loss is reported, the adjuster cannot take a percentage fee.</li>
<li><strong>72-hour cancellation.</strong> You can cancel within 72 hours of signing. After that, you generally cannot.</li>
</ul>

<p>Before signing, make sure the contract tells you whether the adjuster will inspect the property, whether they will communicate with the insurer for you, and roughly how long they expect the claim to take. Never sign a contract with blank spaces.</p>

<h2>Red flags to watch for</h2>

<p>Storms bring out good professionals and opportunists alike. Slow down if you see any of these:</p>
<ul>
<li><strong>Door-to-door solicitation during a disaster or late at night.</strong> TDI says public adjusters cannot knock on your door asking for business during a natural disaster or after 9 p.m.</li>
<li><strong>Guaranteed results.</strong> No one can promise a settlement amount or that a claim will be approved.</li>
<li><strong>Pressure to sign today.</strong> A legitimate adjuster will give you time to read the contract.</li>
<li><strong>Offers to waive your deductible or bundle repairs.</strong> A public adjuster cannot be your contractor on the claim, and TDI warns that waiving a homeowner’s deductible is illegal in Texas.</li>
<li><strong>Badges or official-looking IDs.</strong> TDI notes public adjusters cannot wear a badge while working as a public adjuster.</li>
<li><strong>Telling you not to talk to your insurer.</strong> They cannot keep you from talking with your insurance company.</li>
</ul>

<p>If you have a problem with a public adjuster, you can call TDI at 800-252-3439 or <a href="https://www.tdi.texas.gov/consumer/get-help-with-an-insurance-complaint.html" target="_blank" rel="noopener">file a complaint</a>.</p>

<h2>When to start looking</h2>

<p>You do not need to wait for a problem to start your search, but you also should not hire the first person who shows up after a storm. A sensible sequence for most San Antonio property owners looks like this:</p>
<ol>
<li><strong>Protect the property first.</strong> Tarp roof openings, stop active leaks, shut off water at the meter if a pipe burst, and keep receipts. Your policy may pay reasonable temporary repair costs.</li>
<li><strong>Report the claim promptly.</strong> Texas policies require timely notice, and the insurer’s Chapter 542 deadlines generally start when it receives notice of the claim.</li>
<li><strong>Document before cleanup.</strong> Photos and video of every affected area are hard to recreate later.</li>
<li><strong>Research while you wait.</strong> The days between filing and the insurer’s inspection are a good time to look up licenses and schedule a call or two.</li>
<li><strong>Decide after you see the scope.</strong> Many people make the decision once the insurer’s estimate arrives and they can compare it with a contractor’s bid.</li>
</ol>

<p>After a large hail event, such as the <a href="https://www.ncdc.noaa.gov/stormevents/eventdetails.jsp?id=623870" target="_blank" rel="noopener">April 12, 2016 storm</a> across northwest San Antonio, large numbers of claims come in at the same time. Adjusters, roofers, and public adjusters all get busy. Starting your research early keeps you from making a rushed choice when everyone is calling.</p>

<h2>How the first meeting should go</h2>

<p>Bring your policy (especially the declarations page), your claim number, any letters or estimates from the insurer, and your photos. Our <a href="/claim-documentation-checklist/">claim documentation checklist</a> lists the rest. A useful first meeting usually covers:</p>
<ol>
<li>What happened, when, and what the insurer has done so far</li>
<li>What your policy covers, including deductibles (many Texas policies have a separate wind/hail deductible) and whether you have replacement cost or actual cash value coverage</li>
<li>Where the insurer’s estimate appears incomplete, if you have one</li>
<li>Whether outside help is likely to be worth the fee in your situation</li>
</ol>

<p>For storm claims, it helps to know which events hit your area. Our <a href="/storm-lookup/">storm lookup</a> pulls NOAA storm reports by location. For instance, NOAA recorded 3.5-inch hail in <a href="https://www.ncdc.noaa.gov/stormevents/eventdetails.jsp?id=623878" target="_blank" rel="noopener">Leon Valley on April 12, 2016</a>, and 3-inch hail in <a href="https://www.ncdc.noaa.gov/stormevents/eventdetails.jsp?id=1264523" target="_blank" rel="noopener">Helotes on May 26, 2025</a>.</p>

