<h2>What is an insurance adjuster?</h2>

<p>The insurance adjuster investigates the claim for the insurer: inspecting the damage, applying the policy, writing an estimate (usually in Xactimate), and recommending payment. You will typically meet one of these:</p>
<ul>
<li><strong>Staff adjusters</strong> are employees of the insurance company.</li>
<li><strong>Independent adjusters</strong> are contracted by the insurer, often through an adjusting firm.</li>
<li><strong>Catastrophe (CAT) adjusters</strong> are independent adjusters deployed after major storms to handle the surge in claims.</li>
</ul>

<p>Insurance adjusters in Texas are licensed by TDI and are trained professionals. Their role is to resolve claims according to the policy and the insurer’s guidelines. You do not pay them directly.</p>

<h3>What that looks like on a hail claim</h3>
<ol>
<li>The insurer acknowledges the claim. Under Texas’s <a href="https://statutes.capitol.texas.gov/Docs/IN/htm/IN.542.htm" target="_blank" rel="noopener">Prompt Payment of Claims law</a>, it generally has 15 days after notice to acknowledge the claim, start the investigation, and request information.</li>
<li>An adjuster inspects, sometimes in person on the roof, sometimes from the ground, by drone, or using photos.</li>
<li>The adjuster writes an estimate and the insurer decides whether to accept or reject the claim.</li>
<li>Payment is issued, usually actual cash value first under a replacement cost policy, with recoverable depreciation released after repairs.</li>
</ol>

<h2>What is a public adjuster?</h2>

<p>A public adjuster is licensed by TDI under <a href="https://statutes.capitol.texas.gov/Docs/IN/htm/IN.4102.htm" target="_blank" rel="noopener">Insurance Code Chapter 4102</a> to represent the policyholder. Texas public adjuster contracts must use approved terms and state “WE REPRESENT THE INSURED ONLY.” A public adjuster on a hail claim typically:</p>
<ul>
<li>Reviews the policy, including the wind/hail deductible, roof coverage terms, and any cosmetic exclusion</li>
<li>Inspects and documents the roof, soft metals, elevations, and interior</li>
<li>Prepares a detailed line-item estimate</li>
<li>Communicates with the insurer, attends reinspections, and submits supplements</li>
<li>Reviews payments and depreciation holdbacks</li>
</ul>

<p>Texas also limits what public adjusters can do. According to TDI, they cannot act as your contractor on the claim, give legal advice, solicit door to door during a natural disaster or after 9 p.m., take referral fees from contractors or attorneys involved in your claim, or keep you from talking with your insurer.</p>

