<h2>Texas protections to know</h2>

<p>Fees are disclosed in a written contract before any work begins; Texas law caps public adjuster compensation at 10% of the insurance settlement. If the insurer pays or commits in writing to pay policy limits within 72 hours after the loss is reported, the adjuster cannot take a percentage fee. You can cancel a public adjuster contract within 72 hours of signing. If you have a problem with any adjuster or insurer, you can contact TDI at 800-252-3439.</p>

<p>For disagreements about the amount of loss, most policies include an appraisal clause. For disputes about coverage, lawsuits, or deadlines to sue, consult a Texas attorney.</p>

