<h2>What to do after a hailstorm in San Antonio</h2>

<ol>
<li><strong>Stay safe.</strong> Do not climb onto a wet or damaged roof. Start from the ground and from windows.</li>
<li><strong>Photograph hailstones</strong> next to a ruler or coin, and note the time.</li>
<li><strong>Check soft metals and exterior items:</strong> gutters, downspouts, roof vents, AC fins, window screens, fences, and vehicles.</li>
<li><strong>Look inside</strong> for new ceiling stains, especially after the next rain.</li>
<li><strong>Prevent further damage</strong> with tarps or temporary repairs, and keep receipts.</li>
<li><strong>Save the storm record</strong> using our <a href="/storm-lookup/">storm lookup</a> or the full <a href="/storm-history/">Bexar County storm history</a>.</li>
<li><strong>Report the claim promptly</strong> and keep a log of every call and email.</li>
</ol>

