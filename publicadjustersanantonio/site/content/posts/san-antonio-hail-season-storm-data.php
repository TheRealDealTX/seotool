<h2>What size hail damages a San Antonio roof?</h2>

<p>There is no single hail size that always damages a roof. Whether a storm causes functional damage depends on several factors working together:</p>
<ul>
<li><strong>Roofing material.</strong> Composition shingles are the most common roof covering on San Antonio homes. Standing-seam metal is common toward the Hill Country edge, and many commercial buildings have flat or low-slope membrane roofs. Each responds to hail differently. Metal may dent without leaking, which can raise cosmetic-damage questions under some policies.</li>
<li><strong>Age and condition.</strong> Shingles that have spent years under the South Texas sun often lose flexibility and granules, which can make them more vulnerable to bruising and fractures.</li>
<li><strong>Wind.</strong> Spring storms here often bring strong straight-line winds with the hail. Wind-driven stones strike at an angle and tend to concentrate damage on the slopes facing the storm.</li>
<li><strong>Stone density.</strong> Hard, dense hail can do more damage than softer stones of the same diameter.</li>
</ul>

<p>Larger hail is generally more likely to cause damage, and golf ball size or larger usually gets the attention of roofers and adjusters. But a slope-by-slope inspection is the only reliable way to know. Our article on <a href="/hail-damage-roof-insurance-claim-how-to-protect-your-roof/">hail damage roof insurance claims</a> explains what inspectors look for.</p>

