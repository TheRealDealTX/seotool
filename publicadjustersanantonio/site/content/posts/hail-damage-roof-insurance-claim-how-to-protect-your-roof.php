<h2>Common mistakes that weaken roof claims</h2>
<ul>
<li>Waiting months to report damage after a known storm</li>
<li>Making permanent repairs before the insurer inspects</li>
<li>Accepting an estimate without comparing it with a contractor’s scope</li>
<li>Signing a contractor agreement that lets the contractor “handle the claim”</li>
<li>Accepting an offer to waive or “cover” your deductible, which TDI says is illegal in Texas</li>
<li>Not keeping copies of every letter, email, and estimate</li>
</ul>

<h2>Protecting your roof before the next storm</h2>
<ul>
<li><strong>Inspect regularly.</strong> TDI suggests hiring a roof inspector every few years and checking for damaged shingles after storms.</li>
<li><strong>Keep gutters clear</strong> and trim branches that hang over the roof.</li>
<li><strong>Keep dated photos</strong> of the roof in good condition. Before-and-after photos help show what a storm changed.</li>
<li><strong>Consider impact-resistant materials</strong> when you replace the roof. TDI notes your insurer might offer a discount; ask your agent first.</li>
<li><strong>Review your policy at renewal</strong> for changes to roof coverage, deductibles, or ACV terms.</li>
</ul>

