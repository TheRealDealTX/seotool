<h2>Understanding your roof coverage</h2>

<p>Before you read the estimate, look at your policy. A few terms decide how much of the repair is paid:</p>
<ul>
<li><strong>Wind/hail deductible.</strong> Many Texas policies have a separate deductible for wind and hail, often a percentage of your dwelling (Coverage A) limit. A 2% deductible on a $300,000 dwelling limit is $6,000.</li>
<li><strong>Replacement cost value (RCV).</strong> Pays what it costs to replace the roof today. The insurer typically pays actual cash value first and releases recoverable depreciation after the work is done.</li>
<li><strong>Actual cash value (ACV).</strong> Replacement cost minus depreciation. TDI notes some insurers switch older roofs to ACV coverage at renewal.</li>
<li><strong>Roof payment schedules and cosmetic exclusions.</strong> Some policies pay a percentage based on roof age, or exclude dents that do not affect function. Read your endorsements.</li>
<li><strong>Ordinance or law coverage.</strong> Pays, up to its limit, for code-required work when repairing covered damage.</li>
</ul>

