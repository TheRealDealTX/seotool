<h2>What roof estimates commonly miss</h2>

<p>Adjusters are busy after a big storm, and inspections may be quick or partly done from the ground or by drone. Items that often need a second look include:</p>
<ul>
<li>Correct roof measurements, pitch, and waste</li>
<li>Removal of extra shingle layers</li>
<li>Starter course, ridge cap, and drip edge</li>
<li>Step and counter flashing, pipe jacks, and vents</li>
<li>Underlayment and any decking damage found during tear-off</li>
<li>Steep or high-roof labor charges</li>
<li>Gutters, downspouts, screens, and the AC condenser</li>
<li>Code-required items and permit costs, where the policy covers them</li>
</ul>

<p>Re-roofing generally requires a permit from the City of San Antonio Development Services Department, and suburban cities such as Leon Valley, Helotes, Schertz, and Boerne have their own permit offices. Code requirements do not automatically mean the insurer pays for upgrades; that depends on your ordinance or law coverage.</p>

<h2>Repair or replace? How that decision gets made</h2>

<p>One of the most common disagreements in a hail damage roof insurance claim is whether the roof should be repaired or fully replaced. The answer depends on the policy and the condition of the roof, but these factors usually come into play:</p>
<ul>
<li><strong>How many slopes are damaged.</strong> Insurers often evaluate each slope separately. Damage on every slope facing the storm is a different situation from a few isolated hits.</li>
<li><strong>Whether repairs are practical.</strong> Older or brittle shingles may crack when a roofer lifts them to replace neighbors. Ask your roofer to document this with photos or a short video if it happens.</li>
<li><strong>Matching.</strong> If the same shingle is no longer made or the color has changed, a patch may not match. How matching is handled depends on your policy language.</li>
<li><strong>Pre-existing wear.</strong> Insurers do not pay to replace a roof just because it is old or worn out. Clear evidence that tears, fractures, or bruises are fresh and storm-related is what supports the claim.</li>
</ul>

<h2>What to expect on timing</h2>

<p>Texas’s Prompt Payment of Claims law (Insurance Code Chapter 542) generally gives the insurer 15 days after notice to acknowledge the claim, begin its investigation, and request information. After it has everything it asked for, it generally has 15 business days to accept or reject the claim, or it can notify you it needs more time (up to 45 more days). Payment is generally due within 5 business days after it accepts. After a declared weather catastrophe, these deadlines can be extended by 15 days. Keep a simple log of dates, calls, and documents so you know where the claim stands.</p>

<h2>Supplements: correcting the estimate</h2>

<p>A supplement is a documented request to add missed, under-measured, or newly discovered items to the insurer’s estimate. It stays under the same claim. Hidden damage such as rotted or broken decking is often found only during tear-off. When that happens, photograph it before it is covered, notify the insurer promptly, and give it a chance to inspect.</p>

