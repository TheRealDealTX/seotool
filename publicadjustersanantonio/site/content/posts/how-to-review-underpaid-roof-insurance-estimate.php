<h3>How to read a single line item</h3>

<p>Each line in an Xactimate estimate follows a similar pattern, though column layouts vary by insurer. A typical line shows a description (for example, "Laminated comp. shingle rfg. w/out felt"), a quantity and unit (such as squares, linear feet, or each), and a unit price. Many estimates separate the price into "remove" and "replace" components, so a line marked replace-only does not include tear-off. To the right, you will often see tax, O&amp;P if applied, the replacement cost total for the line, the depreciation amount or percentage, and the actual cash value.</p>

<p>When reviewing a line, ask three questions. Is the quantity right? Is it the right material? Does it include both removal and installation where both are needed? A shingle line priced as replace-only, paired with no separate tear-off line, is an easy gap to miss.</p>

<h2>Step 5: Look beyond the roof</h2>

<p>Hail and wind rarely stop at the shingles. A storm that damages a roof in San Antonio may also damage:</p>
<ul>
<li>Gutters and downspouts (dents, separated seams, bent hangers)</li>
<li>Window screens, wraps, and glazing beads</li>
<li>Fascia and soffit, especially metal-wrapped fascia</li>
<li>AC condenser fins and other exterior equipment</li>
<li>Fences, patio covers, and outbuildings</li>
<li>Painted surfaces, siding, stucco, or garage doors</li>
<li>Interior ceilings and insulation if water entered</li>
</ul>

<p>If these items are damaged but missing from the estimate, document them with photos and ask that they be added.</p>

<h2>Step 6: Check code-required items</h2>

<p>When a roof is replaced, the work generally has to meet the city's adopted building codes. That can mean items the old roof did not have, such as drip edge or specific underlayment requirements, and limits on adding a new layer over existing layers. Whether those costs are paid depends on whether the item is part of the covered repair and on your ordinance or law coverage. Ask your roofer which items the permit and inspection will require, and see our article on <a href="/building-codes-insurance-repairs-san-antonio/">building codes and insurance repairs in San Antonio</a>.</p>

<h2>Step 7: Review depreciation and the deductible</h2>

<ul>
<li><strong>Roof age.</strong> Is the age used for depreciation correct? Permit records, invoices, or closing documents can confirm it.</li>
<li><strong>Depreciation rate.</strong> Is it applied consistently, and does it match the material's expected life?</li>
<li><strong>Recoverable vs. non-recoverable.</strong> Does the label match your policy's roof terms?</li>
<li><strong>Deductible.</strong> Is the wind/hail percentage correct, and is it based on the right Coverage A limit?</li>
</ul>

<h2>Step 8: Compare with a contractor's estimate</h2>

<p>A qualified roofer's itemized bid is a useful comparison. Ask for line items, not just a total, so you can see exactly where the two estimates differ. Differences usually fall into a few categories: measurements, missing items, pricing, and O&amp;P. Pricing differences are often smaller than scope differences, so focus first on what is missing.</p>

<h2>Metal, low-slope, and other San Antonio roof types</h2>

<p>Composition shingles are the most common roof covering on San Antonio homes, but they are not the only one. Standing-seam metal roofs are common toward the Hill Country edge of the metro area, and many commercial buildings have flat or low-slope roofs with single-ply membranes or modified bitumen. Each has its own estimate issues:</p>
<ul>
<li><strong>Metal roofs.</strong> Check whether the estimate uses the right panel type and gauge, includes trim, closures, and fasteners, and whether a cosmetic damage exclusion was applied. Dents that affect function or water-shedding are treated differently than purely cosmetic dents under many policies.</li>
<li><strong>Low-slope and flat roofs.</strong> Check for insulation, cover board, perimeter edge metal, curbs, and flashing at rooftop equipment. Moisture beneath a membrane can change the scope significantly.</li>
<li><strong>Older homes.</strong> Historic homes in neighborhoods such as King William, Monte Vista, and Tobin Hill may have multiple roof layers, older decking, or materials that require special handling, which should be reflected in the scope.</li>
</ul>

<h2>Red flags worth a closer look</h2>

<ul>
<li>The estimate repairs a few shingles per slope on a roof with widespread hail damage.</li>
<li>Only one slope is included when the storm came from a direction that affected several.</li>
<li>The estimate total is far below multiple itemized contractor bids.</li>
<li>The date of loss or cause of loss is wrong.</li>
<li>Interior water damage is visible, but the estimate includes no interior repairs.</li>
</ul>

<h2>Step 9: Request a revision in writing</h2>

<ol>
<li>Write a short letter or email listing each item you believe was missed or miscalculated.</li>
<li>Attach photos, measurement reports, the contractor's itemized estimate, and any code or manufacturer requirements.</li>
<li>Ask for a written response on each item, and request a reinspection if needed.</li>
<li>Keep a log of every call and email with dates and names.</li>
</ol>

