<h2>What Counts as Mid-Century Modern?</h2>
<p>Mid-century modern generally refers to furniture and design from roughly the mid-1940s through the late 1960s. It is defined by clean lines, organic curves, minimal ornament and a love of natural wood paired with newer materials like molded plywood, fiberglass and metal. American and Scandinavian designers led the movement, and their influence was so strong that manufacturers have been copying the look ever since. That is why learning to identify originals matters.</p>

<h2>1. Look at the Design Hallmarks</h2>
<p>Start with the overall shape. Authentic pieces usually share a few traits:</p>
<ul>
<li><strong>Tapered legs:</strong> slim, often angled outward, sometimes capped with brass sabots.</li>
<li><strong>Low, horizontal profiles:</strong> long credenzas, low dressers and sleek sideboards.</li>
<li><strong>Floating forms:</strong> case pieces raised on a separate base or legs so they appear to hover.</li>
<li><strong>Integrated pulls:</strong> handles carved or routed into drawer fronts rather than added on.</li>
<li><strong>Function first:</strong> sliding doors, hidden storage and modular pieces.</li>
</ul>
<p>Design alone does not prove age, since reproductions copy these lines. But it tells you whether a piece is worth a closer look.</p>

<h2>2. Identify the Wood</h2>
<h3>Teak</h3>
<p>Teak is strongly associated with Danish and Scandinavian mid-century furniture. It has a warm golden to medium brown color, a straight, fine grain and a slightly oily feel. Older teak often glows with a rich patina.</p>
<h3>Walnut</h3>
<p>American mid-century makers used a lot of walnut. It is darker and cooler than teak, with chocolate tones and a more varied, sometimes swirling grain.</p>
<h3>Rosewood</h3>
<p>Rosewood is the luxury option, with dramatic dark streaks of purple, red and black. It was used on higher-end pieces and is valuable. Note that trade in some rosewood species is now restricted, so ask about documentation if you are buying or shipping a rosewood piece.</p>
<h3>Other Materials</h3>
<p>Oak, birch, maple and beech also appear, along with molded plywood, fiberglass shells and chrome or steel frames.</p>
<div class="tip"><strong>Tip:</strong> Most mid-century case pieces use veneer over a stable core. Veneer is not a sign of cheap construction; it was standard and allowed for beautifully matched grain. Look at an exposed edge to see the layers.</div>

<h2>3. Examine the Joinery</h2>
<p>Construction quality is one of the clearest signals.</p>
<ul>
<li><strong>Dovetail joints</strong> on drawers, especially neatly cut ones, point to quality craftsmanship.</li>
<li><strong>Finger or box joints</strong> are also common on well-made pieces.</li>
<li><strong>Dowels and mortise-and-tenon joints</strong> in frames suggest solid construction.</li>
<li><strong>Staples, particleboard and lots of glue</strong> are warning signs of later or lower-quality pieces.</li>
</ul>
<p>Pull a drawer all the way out and look at the sides, back and bottom. Solid wood drawer boxes and smooth runners are good signs.</p>

<h2>4. Hunt for Labels and Stamps</h2>
<p>Many manufacturers marked their furniture. Check:</p>
<ol>
<li>Inside the top drawer and on drawer sides.</li>
<li>The back panel of case pieces.</li>
<li>The underside of chairs, tables and seats.</li>
<li>Inside cabinet doors.</li>
</ol>
<p>Look for paper labels, metal tags, branded or burned-in logos, ink stamps and stenciled numbers. Some include a country of origin, such as Denmark, or a date code. Missing labels do not mean a piece is fake, since paper labels often fall off, but a label is strong supporting evidence. Be wary of labels that look brand new on an otherwise aged piece.</p>

<h2>5. Spot Reproductions</h2>
<p>Reproductions range from honest, licensed reissues to cheap knockoffs. Clues that a piece is newer:</p>
<ul>
<li>Even, uniform color with no natural aging or fading.</li>
<li>Modern hardware, like plastic drawer glides or Phillips screws in visible places.</li>
<li>Particleboard or MDF exposed on the back or inside.</li>
<li>Proportions that feel slightly off: legs too thick, profiles too tall.</li>
<li>Very light weight for its size.</li>
<li>Fresh, crisp labels or a modern assembly sticker.</li>
</ul>
<p>Honest wear tells a story. Look for gentle softening on edges, slight sun fading on tops and wear where hands naturally rest.</p>

<h2>6. Assess Condition</h2>
<p>Even a genuine piece needs a careful look before you buy.</p>
<ul>
<li><strong>Veneer:</strong> check for lifting, bubbling, chips or water rings. Small lifts can be reglued; large missing sections are harder.</li>
<li><strong>Structure:</strong> wiggle legs and chairs. Loose joints are fixable; cracked legs need more work.</li>
<li><strong>Finish:</strong> dry or scratched finishes can often be revived with cleaning and oil. Avoid aggressive sanding, which can go right through veneer.</li>
<li><strong>Smell:</strong> musty odors may point to water damage or mold.</li>
<li><strong>Refinishing:</strong> some collectors prefer original finishes. A heavy, glossy refinish may lower value for purists.</li>
</ul>

