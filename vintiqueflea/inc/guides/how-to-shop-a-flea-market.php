<h2>Before You Go</h2>
<h3>Make a List, but Stay Flexible</h3>
<p>Write down what you are hunting for, along with measurements: the wall where a credenza will go, the width of a doorway, the height under a window. Snap photos of your room and keep a fabric swatch or paint chip in your bag. A list keeps you focused, but leave room for surprises. Some of the best finds are the ones you never planned on.</p>
<h3>Set a Budget</h3>
<p>Decide what you are willing to spend overall and on your top-priority item. It makes decisions easier in the moment and keeps you from blowing your budget on the first shiny thing you see.</p>
<h3>Check the Details</h3>
<p>Look up the market's hours, location, parking and admission before you head out. For Vintique Flea, check the <a href="/events/">events page</a>, browse the <a href="/vendors/">vendors</a> and see what <a href="/food-trucks/">food trucks</a> might be on hand.</p>

<h2>What to Bring</h2>
<ul>
<li><strong>Payment options:</strong> many vendors take cards, but cash is still handy and sometimes helps with negotiating.</li>
<li><strong>Tape measure:</strong> the most important tool you can carry.</li>
<li><strong>Tote bags and a rolling cart:</strong> your arms will thank you.</li>
<li><strong>Newspaper or bubble wrap:</strong> for glass, ceramics and anything fragile.</li>
<li><strong>A small flashlight or your phone light:</strong> for peering inside drawers and under tables.</li>
<li><strong>A magnifier or loupe:</strong> for marks and signatures.</li>
<li><strong>Water and comfortable shoes:</strong> you will walk more than you expect.</li>
</ul>
<p>See our <a href="/shop/flea-market-gear/">flea market gear</a> picks for more ideas.</p>

<h2>Timing Is Everything</h2>
<p><strong>Arrive early</strong> if you are after something specific, especially furniture. Dealers and serious collectors show up right at opening, and the best <a href="/shop/mid-century-modern/">mid-century modern</a> pieces often sell in the first hour.</p>
<p><strong>Arrive late</strong> if you are bargain hunting. Near closing, vendors may prefer selling a piece over packing and hauling it home, so they can be more flexible.</p>
<p>At a multi-day market like Vintique Flea, which has run over a Saturday and Sunday, the first day usually has the best selection and the second can bring better deals.</p>

<h2>Haggling Etiquette</h2>
<p>Negotiating is part of flea market culture, but there is a right way to do it.</p>
<ol>
<li><strong>Be friendly first.</strong> Say hello, ask about the piece and show genuine interest. Vendors love talking about their finds.</li>
<li><strong>Ask, do not demand.</strong> "Is there any flexibility on this?" or "What is your best price?" works far better than a lowball offer.</li>
<li><strong>Make a reasonable offer.</strong> Offering a modest discount is normal. Offering a fraction of the price can feel insulting.</li>
<li><strong>Bundle.</strong> Buying several things from one vendor is the easiest way to get a better deal.</li>
<li><strong>Respect a firm no.</strong> Some prices are already fair. Thank the vendor and move on gracefully.</li>
<li><strong>Do not haggle if you will not buy.</strong> Once a vendor agrees to your price, follow through.</li>
</ol>
<p>Want to practice? Play <a href="/play/haggle-hero/">Haggle Hero</a> for a low-stakes warm-up.</p>
<div class="tip"><strong>Tip:</strong> If you love something but need to think, ask the vendor whether they can hold it for a short time. Many will, but do not count on it at the end of the day.</div>

<h2>How to Inspect Before You Buy</h2>
<h3>Furniture</h3>
<ul>
<li>Open every drawer. Check that it slides smoothly and look at the joinery.</li>
<li>Wiggle it. A little looseness is fixable; a cracked frame is a bigger job.</li>
<li>Look underneath for labels, stamps and signs of repair or pests.</li>
<li>Check veneer for lifting, chips or water damage.</li>
</ul>
<p>Our guide on <a href="/guides/how-to-identify-mid-century-modern-furniture/">how to identify mid century modern furniture</a> goes deeper.</p>
<h3>Clothing and Textiles</h3>
<ul>
<li>Hold fabric up to the light to spot holes, thin spots and moth damage.</li>
<li>Check underarms, collars and seams for stains and stress.</li>
<li>Test zippers and buttons. Vintage sizing runs small, so try things on when you can.</li>
</ul>
<h3>Glass, Ceramics and Collectibles</h3>
<ul>
<li>Run a finger gently along rims to feel for chips.</li>
<li>Look for hairline cracks against a light.</li>
<li>Check for maker's marks on the bottom.</li>
</ul>

<h2>Getting Big Pieces Home</h2>
<ol>
<li><strong>Measure your vehicle</strong> before you go, including the hatch or door opening.</li>
<li><strong>Bring moving blankets and straps</strong> to protect finishes and keep things from shifting.</li>
<li><strong>Ask the vendor about pickup.</strong> Some can hold large pieces while you get a truck, and some may know local delivery options.</li>
<li><strong>Bring a friend.</strong> Two people make loading dramatically easier and safer.</li>
<li><strong>Remove drawers and shelves</strong> before loading so they do not slide out or break.</li>
</ol>

<h2>Enjoy the Experience</h2>
<p>The best flea market days are about more than the haul. Grab lunch from a food truck, chat with vendors, and take your time. Whatever you bring home will come with a story, and the vendor who sold it to you might just become your go-to source for the next one.</p>
