<h2>Rotate Your Collection</h2>
<p>Rotation is the secret weapon of small-space collectors. Keep only part of your collection out at a time and store the rest carefully. Swap pieces with the seasons, or when you bring home a new find from Vintique Flea. Rotation keeps the display fresh, reduces dust, limits light exposure and makes you notice your favorites all over again.</p>
<ul>
<li>Store off-display items in labeled, padded boxes.</li>
<li>Wrap glass and ceramics individually in acid-free tissue or soft cloth.</li>
<li>Keep a simple list or photos so you remember what you have.</li>
</ul>

<h2>Conservation Basics</h2>
<p>You do not have to be a museum to protect your things. A few habits go a long way, especially in Houston's heat and humidity.</p>
<h3>Light</h3>
<p>Direct sunlight fades fabrics, paper, photographs and some plastics surprisingly fast. Keep these away from bright windows or use UV-filtering glass.</p>
<h3>Humidity and Heat</h3>
<p>Our humid climate can encourage mold, rust and warping. Keep collections in climate-controlled rooms, not attics or garages, and avoid outside walls that get hot. A small dehumidifier can help in closets.</p>
<h3>Handling and Cleaning</h3>
<ul>
<li>Handle by the sturdiest part, not handles or rims.</li>
<li>Dust gently with a soft brush. Skip harsh cleaners on original finishes.</li>
<li>Do not over-polish metals or refinish antiques; patina is often part of the value.</li>
</ul>
<h3>Earthquake-Style Safety</h3>
<p>Houston is not earthquake country, but slammed doors, pets and kids are. Museum putty under fragile items keeps them from walking off shelves.</p>

