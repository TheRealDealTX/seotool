<h2>Start With What You Have</h2>
<p>Before you buy shelves or frames, lay your collection out on a table or the floor. Look at it as a whole. Sort by type, color, size or era, and notice which pieces you love most. The goal is not to display everything; it is to display the best of it in a way that tells a story. Everything else can rotate in later.</p>

<h2>Shelving That Works in Small Spaces</h2>
<h3>Go Vertical</h3>
<p>When floor space is tight, walls become your best friend. Floating shelves, picture ledges and tall narrow bookcases let you build up instead of out. A run of shelves above a doorway or window is often wasted space that is perfect for a row of vintage bottles, books or tins.</p>
<h3>Use Furniture That Doubles as Display</h3>
<ul>
<li>A <a href="/shop/mid-century-modern/">mid-century credenza</a> holds records inside and a curated group of ceramics on top.</li>
<li>A glass-front cabinet protects fragile pieces from dust and curious pets.</li>
<li>An old printer's tray or type case is made for tiny objects like thimbles, figurines and marbles.</li>
<li>A salvaged ladder leaned against the wall can hold textiles or small baskets.</li>
</ul>
<h3>Mind the Depth</h3>
<p>In small rooms, shallow shelves are better than deep ones. Items get lost at the back of deep shelves, and shallow ones keep walkways clear. Use risers to lift back-row pieces if you need two layers.</p>

<h2>Shadow Boxes and Frames</h2>
<p>Shadow boxes are ideal for flat or small items that would otherwise live in a drawer: vintage postcards, matchbooks, buttons, patches, pins, old keys or a family recipe card. Group several boxes in a tight grid for a gallery-style wall that takes up no floor space at all.</p>
<div class="tip"><strong>Tip:</strong> Use acid-free backing and mounting materials for paper and textiles, and avoid gluing anything directly to an original object. Pins, stitching or archival corners are reversible and much safer.</div>

<h2>How to Group for Impact</h2>
<p>A single small object can look like clutter. Five of the same kind grouped together look like a collection. Some simple ways to group:</p>
<ol>
<li><strong>By color:</strong> a shelf of green glass, or all-white ironstone.</li>
<li><strong>By shape:</strong> a cluster of round pottery, or a line of tall bottles.</li>
<li><strong>By odd numbers:</strong> groups of three or five feel more natural than pairs.</li>
<li><strong>By height:</strong> arrange from tall to short, or tallest in the middle, to create a pleasing line.</li>
<li><strong>With breathing room:</strong> leave space between groups so each one reads clearly.</li>
