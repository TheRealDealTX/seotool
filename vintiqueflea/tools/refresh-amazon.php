<?php
/**
 * Refresh Amazon product images/links from the Product Advertising API.
 * Run daily via cron:  php /path/to/public_html/tools/refresh-amazon.php
 * Over the web it only runs with ?token=<token printed by `php tools/refresh-amazon.php --token`>.
 */
declare(strict_types=1);
define('INC', dirname(__DIR__) . '/inc');
define('DATA_DIR', dirname(__DIR__) . '/data');
require INC . '/config.php';
require INC . '/data.php';
require INC . '/photos.php';
require INC . '/layout.php';
require INC . '/amazon.php';

$cli = PHP_SAPI === 'cli';
$token = substr(hash_hmac('sha256', 'refresh-amazon', app_secret()), 0, 24);
if ($cli && in_array('--token', $argv, true)) {
    echo $token, "\n";
    exit;
}
if (!$cli) {
    if (!hash_equals($token, (string) ($_GET['token'] ?? ''))) {
        http_response_code(404);
        exit;
    }
    header('Content-Type: text/plain; charset=UTF-8');
    @set_time_limit(600);
    ignore_user_abort(true);
}

$creds = paapi_credentials();
if (!$creds) {
    echo "No PA-API keys in data/amazon.php — nothing to do.\n";
    exit(1);
}

$cache = amazon_cache();
$resources = ['Images.Primary.Large', 'ItemInfo.Title'];
$ok = $fail = 0;
foreach (all_products() as $key => $p) {
    if (!empty($p['asin'])) {
        $r = paapi_call('GetItems', ['ItemIds' => [$p['asin']], 'Resources' => $resources], $creds);
        $item = $r['ItemsResult']['Items'][0] ?? null;
    } else {
        $r = paapi_call('SearchItems', ['Keywords' => $p['q'], 'ItemCount' => 1, 'Resources' => $resources], $creds);
        $item = $r['SearchResult']['Items'][0] ?? null;
    }
    $img = $item['Images']['Primary']['Large'] ?? null;
    if ($item && $img) {
        $cache[$key] = [
            'asin' => $item['ASIN'],
            'url' => $item['DetailPageURL'],
            'img' => $img['URL'],
            'w' => $img['Width'] ?? 500,
            'h' => $img['Height'] ?? 500,
            'title' => $item['ItemInfo']['Title']['DisplayValue'] ?? $p['name'],
            't' => time(),
        ];
        $ok++;
    } else {
        $fail++;
        echo "skip {$p['name']}: " . ($r['__error'] ?? 'no result') . "\n";
        if (str_contains($r['__error'] ?? '', 'TooManyRequests')) {
            sleep(5);
        }
        if (preg_match('/InvalidSignature|UnrecognizedClient|AccessDenied|InvalidPartnerTag|AssociateNotEligible/', $r['__error'] ?? '')) {
            echo "Stopping: credential/eligibility problem.\n";
            break;
        }
    }
    usleep(1100000); // PA-API default limit: 1 request/second
}
$out = "<?php\n// Generated by tools/refresh-amazon.php on " . gmdate('c') . "\nreturn " . var_export($cache, true) . ";\n";
file_put_contents(DATA_DIR . '/amazon-cache.php.tmp', $out, LOCK_EX);
rename(DATA_DIR . '/amazon-cache.php.tmp', DATA_DIR . '/amazon-cache.php');
echo "updated=$ok failed=$fail\n";
