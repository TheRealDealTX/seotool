<h2>Rule of thumb 1: the 30% rule</h2>
<p>The classic guideline says to spend no more than about 30% of your gross monthly income, meaning your pay before taxes, on rent.</p>
<p><strong>How to calculate it:</strong> Take your yearly salary, divide by 12, then multiply by 0.30.</p>
<ul>
<li>$36,000 a year = $3,000 a month, so about $900 for rent</li>
<li>$48,000 a year = $4,000 a month, so about $1,200 for rent</li>
<li>$60,000 a year = $5,000 a month, so about $1,500 for rent</li>
</ul>
<p>The 30% rule is easy, but it is a rough ceiling, not a target. If you have student loans, a car payment or childcare costs, you may want to aim lower. If you have no debt and split costs with a partner, you may be comfortable a little higher. If you are aiming for a lower monthly payment, browsing <a href="/apartments/under-1000/">apartments under $1,000</a> is a good place to start.</p>

<h2>Rule of thumb 2: the 50/30/20 budget</h2>
<p>The 50/30/20 approach looks at your whole take-home pay, which is what actually lands in your bank account.</p>
<ul>
<li><strong>50% for needs:</strong> rent, utilities, groceries, insurance, transportation and minimum debt payments.</li>
<li><strong>30% for wants:</strong> dining out, entertainment, subscriptions, travel and hobbies.</li>
<li><strong>20% for savings and extra debt payments:</strong> emergency fund, retirement and paying down balances faster.</li>
</ul>
<p>This method is helpful because it shows how rent competes with your other essentials. If rent alone takes up most of your 50%, there is little room left for groceries, a car payment and utilities, and something will have to give.</p>

