<h2>Splitting utilities and shared costs</h2>
<ul>
<li><strong>Decide whose name goes on each account.</strong> Spreading them out, such as electric in one name and internet in another, balances the responsibility.</li>
<li><strong>Use a payment app or shared spreadsheet</strong> so everyone can see what was paid and when.</li>
<li><strong>Set a due date</strong> a few days before the actual bill is due.</li>
<li><strong>Agree on shared supplies.</strong> Either rotate who buys them or keep a small shared fund.</li>
</ul>
<p>Heating bills can climb in an Ohio winter, so agree on a thermostat range early. That one conversation prevents a lot of arguments in January.</p>

<h2>Write a roommate agreement</h2>
<p>A roommate agreement is a simple written document between roommates. It does not replace the lease with your landlord, but it puts your expectations on paper. Include:</p>
<ul>
<li>Each person's share of rent and utilities, and how and when it is paid</li>
<li>The security deposit split and how it is divided at move-out</li>
<li>Cleaning responsibilities for shared spaces</li>
<li>Quiet hours and guest policies</li>
<li>Rules for shared food, dishes and furniture</li>
<li>What happens if someone wants to leave before the lease ends, including finding a replacement if the landlord allows it</li>
</ul>
<p>Sign it, date it and keep a copy. Revisit it every few months, especially if schedules change.</p>

