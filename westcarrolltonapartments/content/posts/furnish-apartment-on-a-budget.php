<h2>Upcycling: make thrift finds look intentional</h2>
<p>A dated dresser or scratched side table can look brand new with a weekend of work. Here are renter-friendly upcycling ideas that do not require a workshop.</p>

<h3>Paint it</h3>
<p>Chalk-style or furniture paint covers old finishes with minimal sanding. Clean the piece, scuff it lightly with a sanding sponge, apply two thin coats, and finish with a clear topcoat for durability. Work on a drop cloth in a well-ventilated area, or on your patio if your lease allows.</p>

<h3>Swap the hardware</h3>
<p>New knobs and pulls are one of the easiest and cheapest updates. Measure the distance between existing screw holes before buying pulls so they fit.</p>

<h3>Use contact paper</h3>
<p>Peel-and-stick contact paper can refresh a worn tabletop, line drawers, or add a pattern to the back of a bookcase. It is inexpensive and easy to redo.</p>

