<h2>How to avoid surprises</h2>
<ol>
<li><strong>Ask for a total monthly cost.</strong> Rent plus every required fee, in writing.</li>
<li><strong>Read the lease line by line.</strong> Fees are often listed in an addendum.</li>
<li><strong>Talk to current residents</strong> if you can, about utility bills and any recurring charges.</li>
<li><strong>Build a cushion.</strong> Set aside some money each month for irregular costs like a higher winter bill.</li>
<li><strong>Compare apples to apples.</strong> A unit with slightly higher rent but fewer fees can be cheaper overall.</li>
</ol>

<h2>The bottom line</h2>
