<h2>Questions to ask the landlord or leasing office</h2>
<ol>
<li>What is included in rent, and which utilities are in my name?</li>
<li>What fees are due at signing, and what recurring fees apply each month?</li>
<li>How much is the security deposit, and what is the process for getting it back?</li>
<li>How do I submit maintenance requests, and how fast are they usually handled? Is there an emergency line?</li>
<li>What is the pet policy, including breed or weight limits, deposits and monthly pet rent?</li>
<li>Are there rules about painting, hanging shelves or other changes?</li>
<li>What happens if I need to break the lease early?</li>
<li>Is renters insurance required, and what minimum coverage do you ask for?</li>
<li>How much notice is required before I move out or renew?</li>
</ol>
<p>Write the answers down. If something important is promised verbally, ask for it in writing or in the lease. For a deeper look at the costs that often catch renters off guard, see our guide to <a href="/blog/hidden-costs-of-renting-an-apartment/">hidden costs of renting an apartment</a>.</p>

<h2>Reading the lease before you sign</h2>
<p>A lease is a contract, and it is worth reading every page even when you are excited to move. Look closely at:</p>
<ul>
<li><strong>Term and dates:</strong> Start date, end date and what happens at the end. Does it renew automatically or convert to month-to-month?</li>
<li><strong>Rent details:</strong> Amount, due date, grace period, late fees and accepted payment methods.</li>
<li><strong>Maintenance responsibilities:</strong> What you handle (light bulbs, filters, smoke detector batteries) versus what the landlord handles.</li>
<li><strong>Entry:</strong> In Ohio, landlords generally must give reasonable notice before entering, and 24 hours is presumed reasonable except in emergencies. Our <a href="/blog/ohio-tenant-rights-guide/">Ohio tenant rights guide</a> covers this in more detail. This is not legal advice.</li>
<li><strong>Early termination and subletting:</strong> The cost to break the lease and whether subletting or lease transfers are allowed.</li>
<li><strong>Guest and occupancy rules:</strong> Limits on how long a guest can stay before they need to be on the lease.</li>
</ul>
<p>If anything is unclear, ask before signing. A good landlord would rather explain a clause now than argue about it later.</p>

<h2>Move-in day checklist</h2>
<ul>
<li>Do a walkthrough with the move-in inspection form and note every scratch, stain and dent.</li>
<li>Take dated photos and video of each room, including inside appliances and cabinets.</li>
<li>Test smoke and carbon monoxide detectors.</li>
<li>Locate the breaker panel and water shutoff.</li>
<li>Set up electricity, internet and renters insurance so they start on move-in day.</li>
<li>Submit a maintenance request right away for anything that is not working.</li>
</ul>
<p>Planning the move itself? Start booking movers or a truck a few weeks ahead, especially around the first of the month when demand peaks.</p>

