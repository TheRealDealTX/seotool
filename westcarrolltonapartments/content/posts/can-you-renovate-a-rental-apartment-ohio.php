<h2>Start with your lease</h2>
<p>Your lease is the first place to look. Most include a section on alterations, improvements or decorating. Common language includes:</p>
<ul>
<li><strong>No alterations without written consent.</strong> This is the most common clause, and it usually covers painting, drilling, changing fixtures and installing anything permanent.</li>
<li><strong>Restoration at move-out.</strong> You may be allowed to make changes as long as you return the unit to its original condition.</li>
<li><strong>Improvements become the landlord's property.</strong> Some leases say anything attached to the unit stays when you leave.</li>
<li><strong>Specific bans.</strong> Many prohibit changing locks, adding satellite dishes in certain spots, or installing washers, dishwashers or other appliances yourself.</li>
</ul>
<p>Ohio's landlord-tenant law, Ohio Revised Code chapter 5321, sets out general duties for both sides. Tenants must keep the unit safe and sanitary and must not deliberately or negligently damage the premises. Beyond that, the specifics of what you can change mostly come down to your lease. This is not legal advice, so if a clause is unclear, ask your landlord or a local legal aid office.</p>

