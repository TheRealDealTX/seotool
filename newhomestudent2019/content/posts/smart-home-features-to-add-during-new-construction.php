<h3>Water leak sensors</h3>
<p>A slow leak under a sink, behind the refrigerator or at the water heater can do serious damage before you notice it. Small, inexpensive leak sensors placed at these spots can send an alert to your phone. Some systems can also trigger an automatic water shutoff valve if one is installed.</p>

<h3>Smart smoke and CO alarms</h3>
<p>Your builder will install code-required smoke alarms, and CO alarms where required. Smart smoke and CO alarms add phone alerts, so you know about a problem even when you are away. Confirm any replacement meets local requirements, including interconnection.</p>

<h3>EV charger</h3>
<p>If you installed an EV-ready circuit, adding a Level 2 [[amz:ev_charger|home EV charger]] later is straightforward. Have a licensed electrician install it and confirm it matches the circuit's rating. Many readers coming from apartments with shared chargers, like those in our <a href="/charge-up-and-chill-ev-friendly-apartments-in-katy-and-houston/">EV-friendly apartments guide</a>, find home charging one of the best perks of a new house.</p>

<h3>Surge protectors at your equipment</h3>
<p>Whole-home surge protection works best paired with quality point-of-use surge protectors at the TV, computer, network gear and other sensitive electronics.</p>

