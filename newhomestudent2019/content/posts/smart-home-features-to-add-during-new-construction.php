<h2>Who installs what</h2>

<p>On a new build, smart-home work is split between trades, and gaps happen when nobody owns a task. Sort it out before rough-in:</p>
<ul>
<li><strong>Licensed electrician:</strong> line-voltage work, including switch boxes and neutrals, the 240V EV circuit, the whole-home surge protector and any hardwired smoke and CO alarms.</li>
<li><strong>Low-voltage or security contractor:</strong> Ethernet, camera cable, conduit, doorbell wire and speaker wire. Some electricians do this too; confirm it is in someone's written scope.</li>
<li><strong>HVAC contractor:</strong> thermostat wiring, including a C-wire for smart thermostats.</li>
<li><strong>You, after move-in:</strong> most plug-in and battery devices, like leak sensors, and app setup.</li>
</ul>
<p>Write the pre-wire list into each sub's bid so it is priced and not an afterthought. Our guide to <a href="/how-to-hire-and-manage-subcontractors/">hiring and managing subcontractors</a> covers how to keep scopes clear.</p>

