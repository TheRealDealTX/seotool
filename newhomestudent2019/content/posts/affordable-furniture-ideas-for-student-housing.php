<h3>Dining and study</h3>
<p>A small bistro table with two stools fits in a kitchen corner. A folding table can be a desk during the week and a dinner table on weekends. Stackable chairs tuck away when not in use.</p>

<h2>6. Lighting and decor on a budget</h2>
