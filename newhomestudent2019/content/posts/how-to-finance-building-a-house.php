<h2>Down payments and what lenders look for</h2>

<p>Down payment requirements vary widely. Conventional construction loans often ask for more down than a standard purchase mortgage, and some lenders want 20 percent or more of the total project cost, though requirements differ. Government-backed programs may allow less for those who qualify. Equity in land you already own may count toward the requirement.</p>

<p>Beyond the down payment, lenders commonly review:</p>
<ul>
<li>Credit score and history</li>
<li>Debt-to-income ratio, including any rent or current mortgage during construction</li>
<li>Cash reserves to cover overruns and payments during the build</li>
<li>A complete set of plans, specifications and a line-item budget</li>
<li>The builder's license, insurance, experience and references</li>
<li>An appraisal based on the plans, showing the finished value supports the loan</li>
</ul>
<p>Getting a realistic budget first makes the process smoother. Start with our breakdown of the <a href="/how-much-does-it-cost-to-build-a-house-in-texas/">cost to build a house in Texas</a>, then tighten it using our <a href="/budgeting-for-your-texas-home-build-tips-for-staying-on-track/">budgeting guide</a>.</p>

<h2>Owner-builder financing hurdles</h2>

<p>If you plan to act as your own general contractor, financing is often the hardest part. Many lenders will not lend to owner-builders at all, because they see more risk of delays, overruns and unfinished homes. Those that do often look for some combination of:</p>
<ul>
<li>Documented construction or project management experience</li>
<li>A detailed, bid-backed budget and a realistic schedule</li>
<li>Signed contracts with licensed, insured subcontractors</li>
<li>Larger down payment and reserves</li>
<li>Sometimes a construction consultant or licensed builder overseeing the project</li>
</ul>
<p>Local banks and credit unions are often more open to owner-builder loans than large national lenders, because they keep loans in-house and know the local market. Another route some owner-builders take is buying the land with cash or a lot loan, building partly with savings, and refinancing into a mortgage at completion, but that requires substantial cash and carries real risk.</p>

