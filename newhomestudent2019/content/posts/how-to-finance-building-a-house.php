<h2>Costs to plan for during construction</h2>

<p>Financing a build has costs beyond the loan amount that catch people off guard:</p>
<ul>
<li><strong>Interest during construction.</strong> You typically pay interest on drawn funds each month while the house is being built, and the payment grows as more is drawn.</li>
<li><strong>Housing while you build.</strong> Most people keep paying rent or a current mortgage during construction, which lenders count in your debt-to-income ratio. Many of our readers rent while they build; budget for a lease that can flex if the schedule slips.</li>
<li><strong>Draw inspection and loan fees.</strong> Lenders often charge for each draw inspection, plus origination and title fees.</li>
<li><strong>Rate changes.</strong> On a two-time close, the rate on your final mortgage is not known until the end.</li>
<li><strong>Overruns.</strong> Lenders rarely increase a loan mid-build, so contingency usually comes from your own cash.</li>
</ul>

<h2>Steps to line up construction financing</h2>
<ol>
<li>Check your credit and pay down debt where you can.</li>
<li>Decide whether you are using a builder or owner-building.</li>
<li>Get preliminary budgets and a plan in hand.</li>
<li>Talk to at least three lenders, including a local bank or credit union.</li>
<li>Compare one-time vs. two-time close, draw terms, inspection fees and timelines.</li>
<li>Get pre-approved before you commit to land or a builder contract.</li>
</ol>

