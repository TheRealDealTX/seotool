<p>A new construction walkthrough checklist helps you catch defects before closing and again before your builder's workmanship warranty runs out, so problems get fixed at the builder's expense instead of yours. Walk the home room by room, test everything that moves, opens, flushes or turns on, and document every issue in writing with photos. Below is the punch list I recommend for both the pre-closing "blue-tape" walkthrough and the 11-month warranty walkthrough.</p>

<h2>Understand the two walkthroughs</h2>
<h3>The pre-closing (blue-tape) walkthrough</h3>
<p>This usually happens a week or two before closing. You walk the home with the builder's superintendent or customer service rep and mark defects with blue painter's tape. The goal is a written punch list the builder agrees to complete, ideally before you close. Get a written commitment for anything left open after closing.</p>
<h3>The 11-month warranty walkthrough</h3>
<p>Many builders provide a one-year workmanship warranty, plus longer coverage for systems and structure. Your warranty document spells out the details, so read it. Around month 11, after the house has gone through a full cycle of seasons, settling and humidity changes show up: drywall cracks, nail pops, sticking doors, grout cracks. Reporting them in writing before the deadline is key.</p>
<p>For a professional opinion, hire a licensed third-party inspector for each stage. In Texas, inspectors are licensed by TREC. Our <a href="/new-construction-inspection-checklist/">new construction inspection checklist</a> explains the inspections that happen during the build.</p>

<h2>Tools to bring</h2>
<p>You do not need a contractor's truck, but a few inexpensive tools make your walkthrough far more thorough.</p>
<ul>
<li><strong>Outlet tester:</strong> Plug it into every receptacle to check wiring and test GFCI outlets.</li>
<li><strong>Laser measure:</strong> Confirm room dimensions match the plans and check appliance openings.</li>
<li><strong>Level:</strong> Check counters, shelves, windowsills and floors.</li>
<li><strong>Infrared thermometer:</strong> Check that every supply vent blows cool (or warm) air and spot cold or hot areas.</li>
<li><strong>Moisture meter:</strong> Check around tubs, showers, windows and under sinks for hidden moisture.</li>
<li><strong>Headlamp:</strong> For closets, under sinks, the attic hatch and the garage.</li>
<li><strong>Blue painter's tape, a notepad and your phone</strong> for photos.</li>
</ul>
