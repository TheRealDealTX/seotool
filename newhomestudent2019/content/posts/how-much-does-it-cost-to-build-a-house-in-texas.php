<h2>Ways to lower cost without cutting corners</h2>

<ul>
<li><strong>Simplify the shape.</strong> A rectangle or simple L with a straightforward roof is cheaper to frame and roof than a footprint full of bump-outs and valleys.</li>
<li><strong>Right-size the house.</strong> Every square foot you skip saves on structure, finishes and future utility bills. Better-designed space often beats more space.</li>
<li><strong>Stack plumbing.</strong> Grouping kitchens, baths and laundry near each other, or above one another in a two-story, shortens runs.</li>
<li><strong>Choose standard sizes.</strong> Stock window sizes, standard cabinet widths and common ceiling heights reduce waste and special orders.</li>
<li><strong>Spend on what is hard to change.</strong> Put money into the foundation, insulation, windows and HVAC. Lighting, paint and some finishes are easy to upgrade later.</li>
<li><strong>Lock selections early.</strong> Change orders mid-build are one of the fastest ways to blow a budget.</li>
</ul>

