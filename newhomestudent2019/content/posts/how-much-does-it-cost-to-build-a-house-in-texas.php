<h2>Contingency: plan for the unknown</h2>

<p>Every build has surprises: bad soil, a price increase, a rain delay, a change you decide you cannot live without. A common rule of thumb is to set aside 10 to 15 percent of construction cost as contingency. Lean toward 15 percent or more if you are owner-building, building on raw land, or using a custom plan with many unknowns.</p>

<div class="callout"><p><strong>Pro tip:</strong> Keep contingency as its own line in your budget and do not spend it on upgrades. Upgrades come from savings in other categories; contingency is for problems.</p></div>

<h2>How to get real bids</h2>

<ol>
<li><strong>Finish your plans first.</strong> Vague plans get vague bids. Have a complete set of drawings and a written specification of finishes and allowances.</li>
<li><strong>Get at least three bids per trade</strong> (or per builder, if hiring a GC), all priced on the same plans and specs so you can compare apples to apples.</li>
<li><strong>Ask what is excluded.</strong> Permits, cleanup, dumpsters, appliances, landscaping and driveways are common gaps.</li>
<li><strong>Check references and insurance.</strong> The cheapest bid is not a bargain if the sub disappears halfway through.</li>
<li><strong>Build a line-item budget</strong> from the bids, add contingency and soft costs, and compare it against what your lender will finance.</li>
</ol>

