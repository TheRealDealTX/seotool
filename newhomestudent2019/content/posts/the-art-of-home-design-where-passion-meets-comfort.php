<h3>Design for the Texas climate</h3>
<p>Passionate design still has to work in the heat. Deep porches, overhangs and shade trees protect windows from harsh afternoon sun. Light-colored exteriors and metal roofs reflect heat. Inside, ceiling fans in living areas and bedrooms make rooms feel cooler, and tile or stone floors stay pleasant underfoot in summer. Choose fabrics and finishes that handle humidity, and plan a covered outdoor room so you can enjoy mild spring and fall evenings outside.</p>

