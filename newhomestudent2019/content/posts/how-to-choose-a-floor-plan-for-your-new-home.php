<li><strong>Where do you work?</strong> Does anyone work from home full time? Do you take video calls that need a quiet room with a door?</li>
<li><strong>How do you entertain?</strong> Big gatherings, small dinners, outdoor cookouts?</li>
<li><strong>What drives you crazy now?</strong> No place to drop bags, too little storage, a laundry room on the wrong floor, a bedroom next to the TV room.</li>
