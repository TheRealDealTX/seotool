<ul>
<li><strong>Limit large west-facing glass.</strong> The afternoon sun from the west is intense and hard to shade.</li>
<li><strong>Use overhangs and porches.</strong> Deep eaves and covered porches on the south and west shade windows in summer.</li>
<li><strong>Buffer with garages and storage.</strong> Placing the garage, utility room or closets on the west side can help shield living spaces.</li>
<li><strong>Think about the backyard.</strong> A north- or east-facing patio is often more usable on summer evenings than a west-facing one.</li>
