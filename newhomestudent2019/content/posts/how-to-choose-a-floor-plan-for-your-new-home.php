<h3>Red flags</h3>
<ul>
<li>Bedrooms sharing a wall with the media room or kitchen</li>
<li>Walking through one room to reach another, especially bedrooms</li>
<li>A front door that opens directly into the living room with no entry zone</li>
<li>Long hallways that eat square footage without adding function</li>
</ul>

<p>Walk through a typical day on paper. Trace your path from waking up to leaving the house, coming home with groceries and putting kids to bed. If the line zigzags, the plan has friction.</p>

