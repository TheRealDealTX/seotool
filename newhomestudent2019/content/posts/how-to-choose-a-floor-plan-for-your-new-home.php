<h2>Step 2: Check room adjacencies</h2>

<p>Adjacency means which rooms sit next to each other and how you move between them. It matters more than square footage. A well-arranged 2,000-square-foot house can live better than a poorly arranged 2,800-square-foot one.</p>

<h3>Adjacencies that usually work</h3>
<ul>
<li>Garage to a mudroom or drop zone, then to the kitchen, so groceries travel a short path</li>
<li>Kitchen open to the main living and dining areas, with a view of the backyard</li>
<li>Laundry near the bedrooms or primary closet, where most clothes live</li>
<li>Primary suite separated from secondary bedrooms for privacy</li>
<li>A powder room guests can reach without walking through private areas</li>
