<h2>Reading a PCR without getting lost</h2>
<p>Reports can run dozens of pages. Focus on these parts first:</p>
<ul>
<li><strong>Executive summary:</strong> the inspector's overall view and the biggest concerns.</li>
<li><strong>Immediate repair table:</strong> items that need money now, often with cost ranges.</li>
<li><strong>Capital reserve schedule:</strong> expected replacements year by year.</li>
<li><strong>Remaining useful life estimates:</strong> how many years the roof, HVAC and water heaters likely have left.</li>
<li><strong>Limitations:</strong> what the inspector could not access or did not review.</li>
</ul>
<p>The limitations section is easy to skip and important to read. If units, roofs or crawlspaces were not inspected, you are carrying that unknown risk. Cost estimates are opinions too, so get contractor quotes on big-ticket items before you rely on them in negotiations.</p>

