<h2>What a property condition report covers</h2>
<p>A PCR is a snapshot of the property's physical health, usually prepared by an engineer, architect or experienced inspector. Scope varies, but a typical report looks at:</p>
<ul>
<li><strong>Site:</strong> drainage, paving, parking, walkways and landscaping</li>
<li><strong>Structure:</strong> foundation, framing and signs of movement</li>
<li><strong>Building envelope:</strong> roof, siding, windows, doors and sealants</li>
<li><strong>Mechanical, electrical and plumbing:</strong> HVAC, water heaters, panels, piping</li>
<li><strong>Life safety:</strong> fire alarms, extinguishers, exits</li>
<li><strong>Accessibility:</strong> a general look at access issues, where in scope</li>
<li><strong>Unit interiors:</strong> a sample of units in multifamily buildings</li>
</ul>
<p>Most reports include a table of immediate repairs and a longer-term capital reserve schedule, often over 10 years or more. That cost table is where condition becomes a dollar figure. Environmental concerns such as asbestos or contamination are usually handled in separate reports.</p>

