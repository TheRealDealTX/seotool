<h2>How investors use a PCR during due diligence</h2>
<ol>
<li><strong>Adjust the offer.</strong> Total the immediate repairs and near-term capital items, and factor them into your price.</li>
<li><strong>Negotiate credits or repairs.</strong> Use specific findings and estimates, not vague concerns, to ask the seller for a credit at closing.</li>
<li><strong>Plan your budget.</strong> The capital schedule becomes your reserve plan for the first several years.</li>
