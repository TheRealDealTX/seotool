<h2>Step 4: Verify licenses, insurance and references</h2>
<h3>Licenses</h3>
<p>In Texas, electricians and HVAC contractors are licensed by the Texas Department of Licensing and Regulation (TDLR), and plumbers by the Texas State Board of Plumbing Examiners. Look up the license online and make sure it is active. These trades generally pull their own permits. Many other trades have no state license, so the next two checks matter even more.</p>
<h3>Insurance certificates</h3>
