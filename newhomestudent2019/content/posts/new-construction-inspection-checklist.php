<h2>City inspections vs. hiring a third-party inspector</h2>

<p>Your permit triggers a series of required code inspections, typically including foundation, framing, rough mechanical, electrical and plumbing, energy or insulation, and final. These are performed by the city, or in some areas by the county or an approved third-party code inspection firm. They confirm the work meets the adopted code, which in most Texas cities is the International Residential Code (IRC) with local amendments. Check the current edition and amendments with your local permitting office, and see our overview of <a href="/navigating-texas-building-codes-what-you-need-to-know/">Texas building codes</a>.</p>

