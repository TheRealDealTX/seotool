<li>Under-slab plumbing is in the right places for toilets, tubs, showers and the kitchen sink, and has been tested as required.</li>
<li>Vapor retarder is continuous, lapped and taped, with minimal tears.</li>
<li>Rebar or post-tension cables are placed per the engineer's design, supported on chairs rather than lying in the dirt.</li>
<li>Beam depths and widths look consistent with the foundation plan.</li>
<li>Drainage and grading direct water away from the slab area.</li>
</ul>

<p>On expansive Texas clay soils, the foundation design from your engineer matters a great deal. Ask whether a post-pour or engineer's letter is required by your lender or jurisdiction, and keep a copy.</p>

<h2>Phase 2: Framing</h2>

