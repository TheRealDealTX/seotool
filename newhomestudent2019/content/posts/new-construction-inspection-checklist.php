<ul>
<li>Room dimensions, ceiling heights and wall locations match the plans.</li>
<li>Window and door rough openings are the right size and height.</li>
<li>Headers, beams and point loads are supported down to the foundation as designed.</li>
<li>Sheathing is nailed per the plan, and hurricane ties or straps are installed where specified.</li>
<li>Blocking is in place for grab bars, TV mounts, cabinets, handrails and heavy fixtures.</li>
<li>Lumber is not excessively wet if the frame has been rained on; check with a moisture meter.</li>
<li>House wrap or weather barrier is lapped correctly, with windows flashed shingle-style so water runs out, not in.</li>
</ul>

