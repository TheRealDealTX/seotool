<h2>What to do when something fails or looks wrong</h2>

<p>A failed city inspection is normal on a new build and not a reason to panic. The inspector leaves a correction notice listing what needs to change. Send it to the responsible sub the same day, agree on a fix date, and schedule the re-inspection once the work is done. Do not let the next trade cover the area until it passes.</p>

<p>For issues you or your private inspector find that are not code failures, such as sloppy workmanship or a detail that does not match the plans, put the request in writing with photos. Be specific about what you want corrected and by when. Keep the conversation professional; most subs will fix a clear, documented issue quickly, especially before their final payment or lien waiver. If a disagreement involves structural or engineered elements, ask your engineer for a written opinion rather than arguing it out on site.</p>

<h2>Photo documentation tips</h2>

<ul>
<li><strong>Shoot wide, then close.</strong> A wide shot shows which wall you are on; a close-up shows the detail.</li>
<li><strong>Include a reference.</strong> Put a tape measure in the frame so you can estimate distances later.</li>
<li><strong>Name folders by phase and date.</strong> For example, "2026-03 pre-drywall, kitchen".</li>
<li><strong>Keep inspection results with photos.</strong> Store green tags, correction notices and private reports together.</li>
<li><strong>Share selectively.</strong> Send photos of issues to the responsible sub with a short written note and a requested fix date.</li>
</ul>

<p>Good records help with lender draws, warranty claims and, if it ever comes to it, insurance claims.</p>

