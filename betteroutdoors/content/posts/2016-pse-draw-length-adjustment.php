<h2 id="h-how-to-find-your-correct-draw-length">How to Find Your Correct Draw Length</h2>
<p>Before adjusting, you need a target number. Guessing leads to endless tweaking.</p>
<h3 id="h-the-wingspan-method-starting-point">The Wingspan Method (Starting Point)</h3>
<ol class="steps">
  <li><strong>Stand naturally</strong> with your back against a wall and arms extended out to the sides, palms facing forward.</li>
  <li><strong>Measure fingertip to fingertip</strong> in inches. Have a friend help; don&rsquo;t stretch.</li>
  <li><strong>Divide by 2.5.</strong> A 70-inch wingspan gives a 28-inch starting draw length.</li>
</ol>
<p>That number gives you a baseline, not a final answer. Release style matters: a wrist-strap index release usually wants a slightly shorter draw than a handheld thumb release. Real shooting feedback matters more than math.</p>
