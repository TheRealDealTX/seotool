<h2 id="h-step-by-step-adjusting-draw-length-on-a-2016-pse-bow">Step-by-Step: Adjusting Draw Length on a 2016 PSE Bow</h2>
<p>This is the heart of the process. Work slowly and photograph each step.</p>
<h3 id="h-step-1-identify-your-cam-system">Step 1: Identify Your Cam System</h3>
<p>Look at the cam. You will see either a removable module with numbered positions or a rotating module held by one or two screws. Find the cam name and write down your current setting, top and bottom, before changing anything.</p>
<h3 id="h-step-2-loosen-the-module-screws">Step 2: Loosen the Module Screws</h3>
<p>Use steady pressure and the right size key. Back the screws out just enough to move the module. If a screw resists hard or the module feels loaded, stop: your bow needs a press for this change.</p>
<h3 id="h-step-3-move-to-the-new-draw-length-setting">Step 3: Move to the New Draw Length Setting</h3>
<p>Align the module with the position your chart lists for your target draw length. Most 2016 PSE cams are clearly marked. Move in ½-inch steps where you can.</p>
<h3 id="h-step-4-match-both-cams">Step 4: Match Both Cams</h3>
<p>This part is critical. On dual-cam and hybrid systems, both cams must be set to the same draw length. A mismatch throws off cam timing, which shows up as a lumpy draw cycle, inconsistent let-off and erratic arrow flight.</p>
<h3 id="h-step-5-tighten-securely">Step 5: Tighten Securely</h3>
<p>Snug, not forced. Over-tightening can strip threads in an aluminum cam. A drop of medium-strength thread locker is fine if the manufacturer allows it. Then draw the bow slowly a few times and listen for clicks or creaks before you shoot.</p>

<h2 id="h-model-notes">Notes for Popular PSE Models</h2>
<p>Search Console tells us many Better Outdoors readers own one of these bows, so here is what to expect from each family. Always confirm positions with the chart for your exact cam.</p>
<h3 id="h-pse-stinger-draw-length-adjustment">PSE Stinger and Stinger 3G Draw Length Adjustment</h3>
<p>The Stinger family was built as a grow-with-you bow. It uses a rotating module, so a Stinger draw length adjustment is usually a press-free job: remove the module screws, rotate the module to the position on the PSE Stinger draw length adjustment chart, and tighten. Because the range is wide, re-check draw weight afterward; big draw length moves can change how the bow feels at full draw.</p>
<h3 id="h-pse-mini-burner-draw-length-adjustment">PSE Mini Burner and Youth Bows (Including the PSE Guide)</h3>
<p>Youth bows such as the Mini Burner are designed to grow with a young archer, so the PSE Mini Burner draw length adjustment is meant to be easy. Change it in small steps as your child grows, and lower draw weight first if form breaks down. The same logic applies to a PSE Guide youth bow adjustment: comfort and form beat speed every time for kids.</p>
<h3 id="h-pse-brute-nxt-draw-length-adjustment">PSE Brute NXT and Hunting Bows</h3>
<p>Hunting bows like the Brute NXT often use removable modules or a module plus string-post system. A PSE Brute NXT draw length adjustment may need a bow press if the module carries load. If you are not sure, treat it as press-required.</p>
<h3 id="h-pse-ec2-cam-draw-length-chart">PSE EC, Drive and Evolve-Style Cams</h3>
<p>Performance cams such as the EC family use rotating modules with specific positions for each draw length and, on some, separate let-off settings. Use the PSE EC2 cam draw length chart (or whichever cam is named on yours) and change one variable at a time: draw length first, let-off second.</p>

<h2 id="h-can-you-adjust-without-a-bow-press">Can You Adjust Without a Bow Press?</h2>
<p>Sometimes yes, sometimes no. Many 2016 PSE bows were designed for press-free adjustments, but only within specific limits.</p>
<h3 id="h-press-free-adjustments-are-usually-safe-when">Press-Free Adjustments Are Usually Safe When:</h3>
<ul>
