<h2 id="h-the-philosophy-behind-the-bow">The Philosophy Behind the Bear Persist</h2>
<p>Bear Archery has long built bows for people who actually hunt with them. The Persist follows that thinking: a short, maneuverable platform with enough speed to flatten trajectory, plus settings that let you tune the bow to your body rather than forcing your form to fit the bow.</p>
<p>Three ideas run through the design:</p>
<ul>
  <li><strong>Compact handling.</strong> At 31 inches axle to axle, the Bear Persist 31 swings easily in a treestand or ground blind.</li>
  <li><strong>Usable speed.</strong> A 340 fps IBO rating puts it firmly in modern hunting-bow territory.</li>
  <li><strong>Personal fit.</strong> Four let-off choices and two draw weight ranges let you shape how the bow feels at full draw.</li>
</ul>
<p>It is not a target bow dressed up for hunting. It is a hunting bow that happens to be easy to tune.</p>

