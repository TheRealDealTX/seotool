<h2>What happens during the inspection</h2>
<h3>1. A conversation first</h3>
<p>A good inspection starts with questions: what you have noticed, the roof's history and what you want to learn. This shapes where the inspector focuses.</p>
<h3>2. Ground-level and perimeter check</h3>
<p>From the ground, the inspector looks at the overall roof line for sagging, checks gutters and downspouts, and looks at fascia and soffits for staining or rot that can point to water problems at the roof edge.</p>
<h3>3. The roof surface</h3>
<p>When it is safe to access, the inspector examines the roofing material itself. On shingle roofs, that means looking for missing, cracked, curled or creased shingles, granule loss, exposed fasteners and hail or wind damage. On metal roofs, it includes loose or missing fasteners, worn washers, panel damage and seam or trim issues. Weather and roof conditions affect what can be safely accessed; an inspector should not walk a roof that is wet, very steep or structurally questionable without appropriate equipment.</p>
<h3>4. Flashing, penetrations and ventilation</h3>
<p>Many leaks start at transitions rather than in the middle of a slope. The inspector checks flashing at walls, chimneys, skylights and valleys, plus pipe boots, vents and ridge ventilation. Cracked pipe boots and loose step flashing are common causes of leaks.</p>
<h3>5. The attic</h3>
<p>If accessible, the attic often tells the most honest story. The inspector looks for daylight through the deck, water stains on rafters and sheathing, damp or matted insulation, signs of condensation and whether bathroom or kitchen fans vent into the attic. Poor ventilation can shorten the life of shingles in a hot climate like ours.</p>
<h3>6. Documentation</h3>
<p>Throughout the inspection, the inspector should take photos. Photos let you see conditions on a roof you cannot safely walk, and they create a dated record.</p>

<h2>How long does a roof inspection take?</h2>
<p>Most residential roof inspections take somewhere around an hour, but a large or complex roof, extensive storm damage or a detailed attic check can take longer. Ask for an expected duration when you schedule.</p>

