<h2 id="fee-splits">How fee splits change your take-home</h2>
<p>The IA firm bills the carrier, then pays you a share. Splits commonly run from 65/35 to 75/25 in the adjuster's favor. The firm's cut covers carrier relationships, claim assignment, QA review, software access and getting you deployed in the first place.</p>
<p>On a busy hail deployment where you close three $8,000 roof claims a day, the difference adds up quickly:</p>
<ul>
<li>3 claims x $700 fee = $2,100 billed per day</li>
<li>At a 65% split: $1,365 per day to you</li>
<li>At a 75% split: $1,575 per day to you</li>
</ul>
<p>Over a 30-day deployment, that 10-point difference is worth $6,300. Some firms offer better splits to adjusters with strong QA scores and fast cycle times.</p>

<div class="callout callout-tip"><strong>Pro tip:</strong> When comparing a daily rate to a fee schedule, estimate your realistic claims per day for that storm type. Simple hail claims can run two to five a day; complex wind or water losses may take a full day or more each, which can make a daily rate the better deal.</div>

<h2 id="overtime-staff">Overtime and extra pay for staff adjusters</h2>
<p>Under federal wage rules, many experienced claims adjusters are classified as exempt, salaried employees who are not paid overtime. Classification depends on actual job duties, though, and plenty of trainees and some high-volume auto or desk adjusters are non-exempt. Those employees earn time-and-a-half for hours over 40 in a week.</p>
<p>Carriers also commonly add pay during catastrophes, such as:</p>
<ul>
<li>Overtime or straight-time pay for extra CAT hours, even for some exempt staff</li>
<li>Per diem for meals and lodging while deployed</li>
<li>Storm duty bonuses or temporary pay differentials</li>
</ul>
<p>If an offer letter is unclear, ask whether the role is exempt or non-exempt and how CAT duty is paid. It can change annual earnings by thousands.</p>

