<h2 id="independent-adjuster-fee-splits">Fee Splits: What the IA Firm Keeps</h2>

<p>The fee on the schedule is what the firm bills the carrier, not what you receive. IA firms usually split the fee with the adjuster, commonly 65/35 to 75/25 in the adjuster's favor. On a $1,200 claim fee with a 70/30 split, you earn $840.</p>

<p>Splits often improve as you prove yourself. New adjusters may start at the low end; adjusters with clean files, fast cycle times and good reviews from carrier examiners can negotiate better splits or move to firms that offer them.</p>

