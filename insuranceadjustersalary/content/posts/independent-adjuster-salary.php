<p>The hardest part of independent adjusting is that income follows the weather. A rough pattern:</p>
<ul>
<li><strong>Slow years: $30,000 - $60,000.</strong> Few landfalling hurricanes, light hail, mostly daily claims.</li>
<li><strong>Average active years: $70,000 - $120,000.</strong> Steady daily work plus one or two deployments.</li>
