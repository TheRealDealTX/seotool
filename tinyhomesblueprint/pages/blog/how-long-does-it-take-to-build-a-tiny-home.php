      <h2 id="slow">What slows a tiny house build down</h2>
      <ul>
        <li><strong>Incomplete plans.</strong> Designing as you build leads to rework. Every unanswered question becomes a pause on site.</li>
        <li><strong>Permits and inspections.</strong> Foundation homes need permits and inspections at set stages; scheduling them can add weeks. See <a href="/blog/tiny-house-zoning-laws/">tiny house zoning laws</a> for what applies where.</li>
        <li><strong>Material and trailer lead times.</strong> Custom trailers, windows and specialty appliances can take weeks to arrive.</li>
        <li><strong>Weather.</strong> Until the shell is dried in, rain, snow and cold can stop work. A covered workspace helps.</li>
        <li><strong>Design complexity.</strong> Multiple lofts, dormers, curved roofs and custom built-ins add time out of proportion to their size.</li>
        <li><strong>Systems.</strong> Off-grid solar, composting toilets, water tanks and propane each add design and installation time.</li>
        <li><strong>Skills and help.</strong> First-time builders spend time learning, and some steps go much faster with a second person.</li>
      </ul>

