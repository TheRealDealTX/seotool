      <h2 id="ranges">How long it takes, by build type</h2>
      <p>The biggest variable is who is doing the work and how many hours a week they put in. Size matters too: a 160 sq ft studio and an 800 sq ft cottage are both called tiny homes, as our guide to <a href="/blog/what-is-a-tiny-house/">what a tiny house is</a> explains, but they are very different projects.</p>
      <ul>
        <li><strong>Professional builder: about 2 to 6 months.</strong> This is the construction window after the design and contract are settled. Many builders have a queue, so the wait before your build starts can add weeks or months.</li>
        <li><strong>Builder shell, DIY finish: varies widely.</strong> A builder frames and dries in the house, then you finish the interior. The shell is often quick; your finishing time follows the DIY pace below.</li>
        <li><strong>DIY, part-time: often 6 to 18 months.</strong> Evenings and weekends, learning as you go. Most of the spread comes from available hours and skill.</li>
        <li><strong>DIY, full-time with experience: often a few months.</strong> Someone with construction skills working full days can move close to builder pace.</li>
      </ul>
      <p>For the full step-by-step process, from trailer to final finishes, our <a href="/blog/how-to-build-a-tiny-house/">how to build a tiny house guide</a> is the place to start. This post focuses on how long each part takes.</p>

