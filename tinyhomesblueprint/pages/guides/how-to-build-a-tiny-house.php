      <h2 id="step-6">Step 6: Build an insulated subfloor</h2>
      <p>On a trailer, the subfloor usually sits between or on top of the trailer's frame. A common sequence is: galvanized flashing or metal sheet on the underside to keep out road spray and rodents, floor joists or a framed platform, rigid foam or spray foam between the joists, then 3/4 in. tongue-and-groove plywood or OSB glued and screwed down. Bolt the floor framing to the trailer at the welded tabs so the house and chassis act as one unit.</p>
      <p>On a foundation, the subfloor is a standard joist floor over piers or a crawlspace, or the slab itself with a moisture barrier underneath.</p>

      <h2 id="step-7">Step 7: Frame the walls and loft</h2>
      <p>Most tiny houses use 2x4 walls at 16 in. on center, though some builders use 2x3s or steel studs on wheels to save weight, and foundation homes often move to 2x6 walls for more insulation. Frame each wall flat on the subfloor, square it by measuring the diagonals, stand it up, brace it plumb and nail it off. Then add metal straps or hold-downs that tie the walls to the floor and, on a THOW, to the trailer. A tiny house on wheels sees forces at highway speed that a regular house never does.</p>
      <p>Frame the loft floor next. Keep an eye on headroom: you need enough above the loft to sit up in bed and enough below to walk without ducking. Our <a href="/tiny-house-plans-with-loft/">tiny house plans with loft</a> page covers the clearances that tend to work.</p>

      <h2 id="step-8">Step 8: Install sheathing and house wrap</h2>
      <p>Sheath the walls with 7/16 in. OSB or 1/2 in. plywood, nailed on a tight schedule to the plans. Sheathing gives the structure its racking strength, which is critical on wheels. Then wrap it: either a separate house wrap lapped shingle-style from the bottom up, or an integrated sheathing panel with taped seams. Either way, the goal is the same: water that gets behind the siding drains out instead of into the walls.</p>

      <h2 id="step-9">Step 9: Frame and finish the roof</h2>
      <p>Cut and set rafters (or set trusses), install the ridge, sheath the roof and add underlayment. On a THOW, check your height again before you cut a single rafter: from the road to the top of the roof needs to stay at or under about 13.5 ft in most places. Standing-seam or exposed-fastener metal roofing is the usual choice for its low weight and long life. With the roof on and underlayment over the walls, the house is "dried in," and you can work inside in any weather.</p>

      <h2 id="step-10">Step 10: Windows, doors and siding</h2>
      <p>Install windows and the exterior door with a sloped sill pan, flashing tape lapped in the right order (bottom, sides, then top) and the manufacturer's instructions for shimming. Bad window flashing is the most common source of rot in small houses. Then hang siding over a rainscreen gap if your climate is wet: furring strips create a drainage and drying space behind the cladding. Lightweight choices like engineered wood lap, cedar or metal panels suit trailers; save heavier options like fiber cement or stone for foundation homes.</p>

      <h2 id="step-11">Step 11: Rough-in utilities</h2>
      <p>With the shell closed, run everything that will hide inside the walls:</p>
      <ul>
        <li><strong>Electrical:</strong> a small panel, circuits for the kitchen, bath, heating and cooling, and a shore-power inlet on a THOW (30 or 50 amp is typical). If you are going off-grid, plan the battery and inverter location now and size it with the <a href="/tools/off-grid-solar-calculator/">off-grid solar calculator</a>.</li>
        <li><strong>Plumbing:</strong> PEX supply lines, properly sloped and vented drains, and a water heater. Keep the kitchen and bath on one wet wall to save fittings.</li>
        <li><strong>Gas:</strong> propane lines for a range, water heater or heater must be installed and pressure-tested to code.</li>
        <li><strong>Ventilation:</strong> a bath fan and range hood ducted outside at minimum. Many builders add an ERV or HRV for steady fresh air.</li>
      </ul>
      <p>On a foundation home, this is the rough-in inspection stage: the inspector checks wiring, plumbing and framing before anything is covered. On a DIY THOW, have a licensed electrician at least review your work if you are not doing it under a permit.</p>

      <h2 id="step-12">Step 12: Insulate, finish the interior and pass inspections</h2>
      <h3>Insulation and air sealing</h3>
      <p>Closed-cell spray foam is popular on trailers because it adds rigidity, resists moisture and gives the most R-value per inch. Mineral wool, fiberglass or rigid foam all work too when paired with careful air sealing and the right vapor control for your climate. A tiny house holds very little air, so cooking and showers add humidity fast; plan ventilation and, in humid areas, a small dehumidifier.</p>
      <h3>Interior finishes</h3>
      <p>Tongue-and-groove pine, plywood or shiplap is common on wheels because drywall can crack when the house moves. Then flooring, cabinets, counters, the bathroom, stairs or ladder, built-ins, trim and paint. This is the longest phase for most owner-builders. For space-saving ideas, see our <a href="/blog/tiny-house-layout-ideas/">tiny house layout ideas</a>.</p>
      <h3>Inspections and sign-off</h3>
      <p>Foundation homes need a final inspection and a certificate of occupancy before anyone moves in. Tiny houses on wheels vary: builder-made homes are often certified to an RV or park model standard, while DIY builds may not be inspected at all, which can affect where you can park, insure or finance the house. Ask about this when you check zoning in step 2.</p>

