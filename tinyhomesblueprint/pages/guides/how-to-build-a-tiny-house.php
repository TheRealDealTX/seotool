      <h2 id="tools">Tools you need for a DIY tiny house</h2>
      <p>You do not need a full shop, but these are the tools most owner-builders end up using. Budget roughly $1,000&ndash;$5,000 if you are starting from nothing, less if you borrow or rent.</p>
      <ul class="check-list">
        <li><strong>Cutting:</strong> circular saw, miter saw, jigsaw, oscillating multi-tool; a table saw or track saw for paneling</li>
        <li><strong>Fastening:</strong> drill and impact driver, framing nailer and compressor, finish nailer</li>
        <li><strong>Layout:</strong> 25 ft tape, speed square, framing square, chalk line, 2 ft and 6 ft levels or a laser level</li>
        <li><strong>Roof and siding:</strong> metal snips, caulk gun, staple hammer, sturdy ladders or rented scaffolding</li>
        <li><strong>Plumbing and electrical:</strong> PEX crimp or expansion tool, wire strippers, voltage tester</li>
        <li><strong>Safety:</strong> eye and ear protection, respirator for foam and sanding, gloves, fall protection on the roof</li>
      </ul>

      <h2 id="mistakes">Common DIY tiny house mistakes</h2>
      <div class="pros-cons">
        <div class="cons"><h3>Mistakes that cost the most</h3><ul>
          <li>Buying land or a trailer before checking zoning</li>
          <li>Building over the trailer's weight rating</li>
          <li>Going over 13.5 ft tall on a THOW</li>
          <li>Poor window flashing and no rainscreen</li>
          <li>No ventilation, leading to condensation and mold</li>
          <li>Not strapping the house to the trailer</li>
        </ul></div>
        <div class="pros"><h3>What to do instead</h3><ul>
          <li>Call the planning office and get answers in writing</li>
          <li>Estimate weight before you pick materials</li>
          <li>Draw a height section and check it before framing the roof</li>
          <li>Follow flashing order: sill, sides, head</li>
          <li>Duct the bath fan and range hood outside</li>
          <li>Use the hold-downs and tie-downs in your plans</li>
        </ul></div>
      </div>
