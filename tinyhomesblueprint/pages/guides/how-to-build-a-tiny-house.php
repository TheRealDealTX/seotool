      <h2 id="step-1">Step 1: Decide on wheels or a foundation</h2>
      <p>A tiny house on wheels (THOW) is built on a trailer and is usually treated as an RV or park model; it can move, but it must stay within road limits of roughly 8.5 ft wide and 13.5 ft tall, and it must stay under the trailer's weight rating. A foundation tiny home is a small house in the eyes of the building department, built to the residential code and permitted like any other home.</p>
      <div class="table-wrap"><table>
        <thead><tr><th></th><th>Tiny house on wheels</th><th>Foundation tiny home</th></tr></thead>
        <tbody>
          <tr><td>Typical size</td><td>160&ndash;300 sq ft plus loft</td><td>300&ndash;700 sq ft</td></tr>
          <tr><td>Legal status</td><td>Usually RV or park model</td><td>Permanent dwelling or ADU</td></tr>
          <tr><td>Main constraints</td><td>Width, height, weight</td><td>Zoning, setbacks, minimum size</td></tr>
          <tr><td>Inspections</td><td>Varies; often none for DIY</td><td>Required at each stage</td></tr>
          <tr><td>Financing</td><td>RV or personal loan</td><td>Construction loan or mortgage</td></tr>
          <tr><td>Best for</td><td>Renters of land, movers, uncertain plans</td><td>Owned land, ADUs, long-term homes</td></tr>
        </tbody>
      </table></div>
      <p>If you own land and plan to stay, a foundation home like a <a href="/small-cabin-plans/">small cabin</a> or <a href="/adu-plans/">backyard ADU</a> is often simpler to legalize. If you need mobility, start with <a href="/tiny-house-on-wheels-plans/">tiny house on wheels plans</a>.</p>

      <h2 id="step-2">Step 2: Check zoning and permits first</h2>
      <p>Before you spend money, find out where your tiny house can legally sit and what approvals it needs. Many counties set minimum dwelling sizes, limit full-time living in RVs or only allow small houses as ADUs. Call the planning or zoning office with your parcel number and ask directly. Our <a href="/blog/tiny-house-zoning-laws/">tiny house zoning laws guide</a> has a list of questions to ask and a checklist to take with you.</p>
      <div class="callout wood">
        <strong>Do this before buying land</strong>
        <p>A $15,000 parcel where you cannot live in a tiny house is a $15,000 mistake. Get answers in writing, or at least note the name of the person and the date of the call.</p>
      </div>

      <h2 id="step-3">Step 3: Choose complete tiny house plans</h2>
      <p>Good plans are the cheapest insurance in the whole build. At a minimum you want dimensioned floor plans, exterior elevations, a building section, wall and roof framing details, window and door schedules, and a materials list. For a THOW, the plans should also be designed around a specific trailer length and an estimated finished weight.</p>
      <p>Browse the full set on our <a href="/tiny-house-plans/">tiny house plans</a> page, or by style: <a href="/tiny-house-plans-with-loft/">plans with a loft</a>, <a href="/a-frame-house-plans/">A-frames</a> and <a href="/shed-to-tiny-house/">shed conversions</a>. If you are weighing a free design, read <a href="/blog/free-tiny-house-plans/">what free tiny house plans leave out</a> first. Want to test a layout before you commit? Sketch it in the <a href="/tools/tiny-house-layout-planner/">tiny house layout planner</a>.</p>

      <h2 id="step-4">Step 4: Set your budget and schedule</h2>
      <p>A DIY tiny house on wheels typically costs <strong>$36,000&ndash;$78,000</strong> including the trailer, depending on size and finishes. Owner-builders usually spend about $150&ndash;$330 per sq ft on the structure and finishes, and a foundation tiny home costs more because it is bigger and needs a foundation and permanent utilities. Get a line-by-line estimate from the <a href="/tools/tiny-house-cost-calculator/">tiny house cost calculator</a> and read the full <a href="/blog/how-much-does-a-tiny-house-cost/">tiny house cost breakdown</a>.</p>
      <p>Keep a 10% contingency, and order long-lead items early. Trailers built to order and windows can take several weeks to arrive, and you do not want a framed house sitting under a tarp waiting for glass.</p>

      <h2 id="step-5">Step 5: Build or buy the trailer or foundation</h2>
      <h3>For a tiny house on wheels</h3>
      <p>Buy a trailer designed for tiny houses, sized to your plans. Look for a GVWR comfortably above your estimated finished weight (many 24 ft builds land between 8,000 and 12,000 lb), welded tie-down points, a flush deck or drop-axle design for extra headroom, and good brakes. Estimate weight first with the <a href="/tools/tiny-house-trailer-weight-calculator/">trailer weight calculator</a>, and see the <a href="/blog/tiny-house-trailer-size-guide/">tiny house trailer size guide</a> for lengths and ratings.</p>
      <h3>For a foundation tiny home</h3>
      <p>Concrete piers or helical piles suit sloped or rural sites and typically cost $4,000&ndash;$10,000. A slab suits flat, dry sites and typically runs $8,000&ndash;$20,000. Either way, the foundation will be inspected before you pour or build on it, and it needs to meet local frost depth.</p>

