      <p><strong>How do you build a tiny house?</strong> Decide between wheels and a foundation, confirm your zoning, buy a complete set of plans and set a budget. Then build in this order: trailer or foundation, subfloor, wall and loft framing, sheathing and house wrap, roof, windows and doors, utility rough-ins, insulation, interior finishes and inspections. Most first-time owner-builders take 6 to 18 months working evenings and weekends.</p>
      <p>That sounds like a lot, and it is. But a tiny house is the most approachable whole-house project there is: the framing is simple, the material quantities are small and mistakes are cheaper to fix. This guide walks through each stage the way we would explain it on site.</p>

