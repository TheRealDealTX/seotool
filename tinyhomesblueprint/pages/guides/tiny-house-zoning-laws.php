      <h2 id="min-size">Minimum dwelling size rules</h2>
      <p>Some zoning ordinances set a minimum floor area for a house, commonly somewhere in the range of 500 to 1,000+ sq ft in certain residential districts, sometimes higher in suburban subdivisions. Where that rule exists, a 300 sq ft home on a foundation cannot be the primary dwelling no matter how well it is built. Other jurisdictions have no minimum beyond what the building code requires, and a growing number have lowered or removed their minimums to allow smaller homes.</p>
      <p>The building code has its own, much smaller limits. Recent editions of the International Residential Code (IRC) require habitable rooms (other than kitchens) to be at least 70 sq ft and at least 7 ft in any horizontal dimension; older editions also required one room of at least 120 sq ft. Which edition applies depends on what your state or locality has adopted.</p>
      <p>Homeowners associations and deed restrictions can add their own minimums, regardless of what the county allows. Read the covenants before you buy.</p>

      <h2 id="appendix-aq">IRC Appendix Q and Appendix AQ: the tiny house building code</h2>
      <p>The 2018 IRC introduced <strong>Appendix Q, "Tiny Houses,"</strong> which was renumbered <strong>Appendix AQ</strong> in the 2021 edition. It applies to dwellings of <strong>400 sq ft or less</strong>, not counting lofts, and relaxes a few rules that make very small homes hard to build under the standard code. As written in the model code, its main provisions include:</p>
      <div class="table-wrap"><table>
        <thead><tr><th>Topic</th><th>General approach in Appendix Q / AQ</th></tr></thead>
        <tbody>
          <tr><td>Ceiling height</td><td>At least 6 ft 8 in. in habitable space; bathrooms, toilet rooms and kitchens may be lower (6 ft 4 in.)</td></tr>
          <tr><td>Lofts</td><td>Minimum floor area of 35 sq ft and at least 5 ft in any horizontal dimension; areas under a 3 ft ceiling height do not count toward the minimum</td></tr>
          <tr><td>Loft access</td><td>Permits compact stairs, ladders, alternating tread devices and ship's ladders, each with its own dimensional limits</td></tr>
          <tr><td>Guards</td><td>Loft guards at the lesser of 36 in. or half the clear height to the ceiling</td></tr>
          <tr><td>Emergency escape</td><td>Lofts used for sleeping need an emergency escape and rescue opening; roof access windows are addressed specifically</td></tr>
        </tbody>
      </table></div>
      <p>Two cautions. First, <strong>an appendix only applies where it is adopted.</strong> Some states and localities have adopted Appendix Q or AQ, sometimes with amendments; many have not. Second, it is a building code: it does nothing to change zoning, so a tiny house that complies with Appendix AQ still needs a zoning district where it is allowed. Ask your building department which IRC edition they use and whether the tiny house appendix is part of it. If you are designing a loft, our <a href="/tiny-house-plans-with-loft/">tiny house plans with loft</a> page covers the practical side of headroom, stairs and egress.</p>

      <h2 id="thow">Tiny houses on wheels: RV and park model laws</h2>
      <p>A tiny house on wheels (THOW) is usually not treated as a house at all. Depending on how it is built and certified, it is typically classified as one of:</p>
      <ul>
        <li><strong>Recreational vehicle (RV):</strong> built to the NFPA 1192 standard for recreational vehicles. Builders who are members of an industry certification program can label their homes as compliant.</li>
        <li><strong>Park model RV:</strong> built to ANSI A119.5, a standard for larger RVs (up to 400 sq ft in the set-up position) intended for seasonal or longer stays in parks.</li>
        <li><strong>Uncertified or self-built:</strong> a DIY THOW without third-party certification. It may be registered as a trailer, but it is often the hardest to insure, finance and place legally.</li>
      </ul>
      <p>Being an RV solves the building code question but raises a zoning one: <strong>where can you live in an RV?</strong> Many jurisdictions limit RV occupancy outside of RV parks, for example by allowing it only temporarily, only during construction of a permanent home, or only for a set number of days per year. Others, often in rural areas, allow an RV or THOW as a dwelling on private land, sometimes with conditions such as septic or sewer connection. A growing number of places have created specific rules for tiny houses on wheels as backyard units. Because these rules differ so much and change often, do not assume, and do not rely on lists of "tiny house friendly states" without checking the actual parcel.</p>
      <p>If you need mobility, design within road limits from the start. Our <a href="/tiny-house-on-wheels-plans/">tiny house on wheels plans</a> and the <a href="/blog/tiny-house-trailer-size-guide/">tiny house trailer size guide</a> cover width, height and weight.</p>

      <h2 id="adu">The ADU route: a tiny house in the backyard</h2>
      <p>An accessory dwelling unit is a second, smaller home on a lot that already has a main house. Many states and cities have loosened ADU rules in recent years, and for many people this is the most straightforward way to live legally in a tiny house, or to build one as a rental or a home for family.</p>
      <p>ADU rules typically address:</p>
      <ul class="check-list">
        <li><strong>Size:</strong> a maximum floor area, sometimes a fixed number and sometimes a percentage of the main home</li>
        <li><strong>Setbacks and height:</strong> distance from property lines and limits on overall height</li>
        <li><strong>Foundation and utilities:</strong> many require a permanent foundation and connection to water, sewer or septic and power; some now allow THOWs</li>
        <li><strong>Parking and occupancy:</strong> off-street parking, owner-occupancy requirements and short-term rental limits vary widely</li>
        <li><strong>Fees:</strong> permit, plan review and impact or connection fees</li>
      </ul>
      <p>Browse our <a href="/adu-plans/">ADU plans</a> for backyard cottage designs, and budget with the <a href="/blog/how-much-does-a-tiny-house-cost/">tiny house cost guide</a>, which covers utility and permit costs line by line.</p>

      <h2 id="communities">Tiny house communities</h2>
      <p>Tiny house communities solve the legal question by doing the zoning work up front. They are usually permitted as an RV park, a manufactured home community, a planned development or a cluster of ADU-sized homes. You rent or buy a pad with utility hookups and follow the community's rules on size, appearance and certification. Many require RV or park model certification for THOWs, so ask before you build a DIY house you plan to park there. Expect monthly lot rent that varies a lot by region and amenities.</p>

      <h2 id="research">How to research tiny house laws in your county</h2>
      <p>This is the process we suggest to anyone planning a tiny home build. Do it for the specific parcel, before you buy it.</p>
      <ol>
        <li><strong>Find the parcel's zoning district.</strong> Most counties have an online GIS or parcel viewer. Note the district code (for example, a rural, agricultural or single-family residential designation).</li>
        <li><strong>Read the zoning ordinance.</strong> Look up the district's allowed uses, the definitions of "dwelling," "recreational vehicle," "accessory dwelling unit" and "tiny house," and any minimum floor area.</li>
        <li><strong>Check the building code edition.</strong> Ask which IRC edition is adopted and whether Appendix Q or AQ is included, with any local amendments.</li>
        <li><strong>Call or visit the planning office.</strong> Bring the parcel number and a simple description or plan of your house. Use the questions below.</li>
        <li><strong>Check private restrictions.</strong> Review HOA rules, covenants and deed restrictions, which can be stricter than the county.</li>
        <li><strong>Check utilities and health rules.</strong> Ask the health department about septic and well requirements, and the utility about service to the site.</li>
        <li><strong>Get it in writing.</strong> Ask for a zoning verification letter or request a pre-application meeting. At minimum, record who you spoke with and when.</li>
      </ol>
      <h3 id="questions">Questions to ask the planning office</h3>
      <ul>
        <li>Is there a minimum dwelling size in this zoning district?</li>
        <li>Can a house of [your size] sq ft on a permanent foundation be the primary dwelling here?</li>
        <li>Are ADUs allowed on this parcel? What are the size, setback and owner-occupancy rules?</li>
        <li>Can an RV or tiny house on wheels be lived in full-time on this parcel? If so, under what conditions?</li>
        <li>Do you require RV or park model certification for a tiny house on wheels?</li>
        <li>Which IRC edition do you use, and have you adopted the tiny house appendix?</li>
        <li>What permits will I need, and roughly what are the fees and review times?</li>
        <li>What are the requirements for water, septic or sewer, and power?</li>
        <li>Are any changes to these rules being considered?</li>
      </ul>

