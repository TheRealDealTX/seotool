      <h2 id="choose">Choosing a shed worth turning into a tiny house</h2>
      <p>The single biggest factor in any shed to tiny house project is the shed you start with. A cheap kit with 2x3 walls and a plywood floor on skids may cost more to fix than to replace. Look for these specs:</p>
      <ul class="check-list">
        <li><strong>Size:</strong> 12 x 20 ft (240 sq ft) is about the smallest that fits a bath, kitchen and bed comfortably. 14 x 32 ft lofted barns are popular because the loft adds sleeping space.</li>
        <li><strong>Wall framing:</strong> 2x4 studs at 16 in. on center is the minimum. 2x6 walls are better for insulation but rare in prefab sheds.</li>
        <li><strong>Wall height:</strong> at least 7 ft to the ceiling after insulation and drywall, ideally 8 ft. Many standard sheds have 6 to 6.5 ft walls, which only works with a vaulted ceiling.</li>
        <li><strong>Floor system:</strong> pressure-treated skids and 2x6 joists at 16 in. on center. Plan to upgrade the foundation anyway (see below).</li>
        <li><strong>Roof:</strong> rafters deep enough for insulation (2x6 or more), with roof sheathing rather than metal on purlins.</li>
        <li><strong>Openings:</strong> double doors you can replace with an insulated slider or French door, and space on the walls for egress-size windows.</li>
      </ul>
      <p>Comparing a shed against a framed build? Our guide to <a href="/blog/tiny-house-kits-vs-plans/">tiny house kits vs plans</a> walks through the same trade-off for kits.</p>

      <h2 id="steps">Shed to tiny house conversion steps</h2>
      <ol class="steps">
        <li><h3>Check zoning and permits</h3><p>Confirm the shed can legally become a dwelling or ADU on your lot before you spend a dollar.</p></li>
        <li><h3>Upgrade the foundation</h3><p>Replace blocks and skids with piers, a perimeter footing or a slab set below frost depth, and anchor the shed to it.</p></li>
        <li><h3>Add weather protection</h3><p>Many prefab sheds have siding nailed straight to studs. Add a water-resistive barrier, flashing and sealed windows.</p></li>
        <li><h3>Rough in utilities</h3><p>Run electrical, water supply, drains and vents. Most areas require licensed trades or inspections for this stage.</p></li>
        <li><h3>Insulate and air-seal</h3><p>Insulate floor, walls and roof, and seal every gap. This is what makes a shed feel like a house.</p></li>
        <li><h3>Finish the interior</h3><p>Drywall or paneling, flooring, kitchen, bath and lighting, then final inspections.</p></li>
      </ol>
      <p>For the full build sequence with timelines, see <a href="/blog/how-to-build-a-tiny-house/">how to build a tiny house</a>.</p>

      <h2 id="insulation">Insulating a shed for year-round living</h2>
      <p>Shed walls and roofs are shallow, so you have to get the most out of every inch:</p>
      <ul>
        <li><strong>Walls:</strong> 2x4 cavities take R-13 to R-15 batts or mineral wool. In cold climates, closed-cell spray foam (about R-6.5 per inch) or a layer of rigid foam on the inside before drywall gets you closer to modern code.</li>
        <li><strong>Roof:</strong> this is where most heat escapes. If rafters are only 2x4 or 2x6, use closed-cell foam or rigid foam, or build the ceiling down to add depth. Leave a vent channel under the sheathing if you use batts.</li>
        <li><strong>Floor:</strong> insulate between floor joists (R-19 or more in cold areas) and close the underside with rigid foam or sheathing and hardware cloth to keep rodents out.</li>
        <li><strong>Moisture:</strong> a bathroom shower in a small, tight space produces a lot of humidity. Install a timer-controlled bath fan vented outside and a kitchen hood that exhausts outdoors.</li>
      </ul>
      <p>Heating and cooling a well-insulated 250 sq ft space is easy with a small ductless mini-split. If you plan to run off-grid, size your panels and batteries with the <a href="/tools/off-grid-solar-calculator/">off-grid solar calculator</a>.</p>

