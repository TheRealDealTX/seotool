      <h2 id="permits">Permits and zoning for shed conversions</h2>
      <p>Many towns let you put up a small storage shed (often up to 120 to 200 sq ft) without a building permit. That exemption almost never covers living in it. Once a shed gets plumbing, sleeping space or a kitchen, it becomes a dwelling, and building departments typically look for:</p>
      <ul>
        <li>A permanent foundation and anchoring that meets local frost and wind requirements</li>
        <li>Minimum ceiling heights, emergency escape windows and smoke and carbon monoxide alarms</li>
        <li>Energy-code insulation levels, and permitted electrical and plumbing work</li>
        <li>Dwelling setbacks, which are often larger than the setbacks for accessory sheds</li>
      </ul>
      <p>The cleanest legal path in many cities is to permit the converted shed as an accessory dwelling unit. Read the typical rules on our <a href="/adu-plans/">ADU plans</a> page and our <a href="/blog/tiny-house-zoning-laws/">tiny house zoning guide</a>, then call your local planning office before you start.</p>

