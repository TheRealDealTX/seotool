      <h2 id="checklist">Before you commit to a spot</h2>
      <ul class="check-list">
        <li>Zoning district confirmed for the parcel, and the use (ADU, primary home or RV occupancy) confirmed as allowed</li>
        <li>Minimum dwelling size, setbacks and any RV time limits noted</li>
        <li>Water, sewer or septic, and power available, with connection costs quoted</li>
        <li>Access confirmed for delivery: road width, turns, slope and overhead clearance</li>
        <li>HOA rules, covenants or park rules reviewed</li>
        <li>Written agreement with the landowner or community, if it is not your land</li>
