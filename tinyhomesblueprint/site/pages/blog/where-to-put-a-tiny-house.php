      <h2 id="nine-places">9 places to put a tiny house</h2>

      <h3>1. Your own backyard, as an ADU</h3>
      <p>If you already own a house, an accessory dwelling unit (ADU) behind it is often the most straightforward legal route, and many states and cities have loosened ADU rules in recent years. Expect rules on size, setbacks, height and utilities, and possibly owner-occupancy or parking. A foundation tiny home is usually the easiest to approve; some places now allow a tiny house on wheels as a backyard unit. Our post <a href="/blog/can-i-put-a-tiny-home-in-my-backyard/">can I put a tiny home in my backyard?</a> walks through the approval steps.</p>

      <h3>2. Rural or agricultural land you own</h3>
      <p>Buying land gives you the most control, and rural counties are more likely to allow small homes or RV living. But rural does not mean unregulated: many rural zones still set a minimum dwelling size, limit how long an RV can be occupied, or require septic approval before anyone lives on the site. Research the specific parcel before you buy, including road access, well and septic feasibility, and power.</p>

      <h3>3. A tiny home community</h3>
      <p>Tiny home communities do the zoning work up front, usually operating as an RV park, a manufactured home community or a planned development. You rent or buy a pad with hookups and follow community rules, which often include RV or park model certification for wheeled homes and limits on size or appearance. If none exist near you, <a href="/blog/how-to-start-a-tiny-home-community/">how to start a tiny home community</a> explains what is involved.</p>

      <h3>4. An RV park or campground</h3>
      <p>RV parks are set up for wheeled homes, with water, sewer and power at each site. Many offer monthly rates, and some welcome tiny houses. Others limit stays, require RV certification or restrict homemade units, and some campgrounds close seasonally. Call ahead and ask specifically about tiny houses, not just RVs.</p>

      <h3>5. A mobile or manufactured home park</h3>
      <p>Some manufactured home communities accept tiny houses, especially park model RVs. Lots tend to be larger than RV sites and leases longer. Policies vary a lot, and some parks accept only HUD-code manufactured homes, so ask before you assume.</p>

      <h3>6. Family or friends' land</h3>
      <p>Parking on a relative's or friend's property is popular because it is cheap and flexible. Whether it is legal depends on whether that lot allows a second dwelling or RV occupancy. If it allows an ADU, a foundation home may be possible; if not, an occupied tiny house on wheels could draw a complaint. Put the arrangement in writing, including utilities, access and what happens if either of you wants to end it.</p>

      <h3>7. Leased land</h3>
      <p>Some landowners lease a corner of their property for a tiny house, an arrangement sometimes called a land lease. It can work well, but the land still has to be zoned for what you are doing. A written lease should cover term, rent, utilities, insurance, improvements and removal when the lease ends.</p>

      <h3>8. A farm or homestead</h3>
      <p>Farms sometimes host tiny houses in exchange for rent or work. Agricultural zoning occasionally allows additional dwellings for farm workers or family, which can open a legal path that would not exist on a residential lot. Ask the county how a second dwelling is classified on that specific parcel.</p>

      <h3>9. A small lot zoned for small homes</h3>
      <p>A growing number of cities allow small homes on small lots, cottage clusters or pocket neighborhoods, sometimes with lowered minimum dwelling sizes. A foundation tiny home or small cottage can then be a primary home on its own lot. If you are thinking of grouping several units, see <a href="/blog/how-many-tiny-homes-can-fit-on-an-acre/">how many tiny homes can fit on an acre</a>.</p>

