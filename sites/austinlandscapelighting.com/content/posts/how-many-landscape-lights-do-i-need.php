<p>The intended effect matters too.</p>

<p>One uplight can create a simple vertical accent. Two fixtures placed at different angles can reveal more of the trunk and canopy. Cross-lighting can add depth. Downlighting from a mature branch can imitate moonlight and softly illuminate the ground below.</p>

<p>Viewing direction is another major factor. If the tree is visible from the street, front porch, driveway, and patio, one fixture may only make it look complete from a single angle.</p>

<p>When someone asks me, <strong>“how many landscape lights do I need for my trees?”</strong>, my first response is to identify which trees truly deserve attention. Not every tree needs to become a focal point. Choose the strongest forms, the most visible specimens, and the trees that help connect different areas of the property.</p>

