<h3>Essential Lighting</h3>

<p>An Essential plan prioritizes entrances, pathways, steps, and a few important features.</p>

<p>This approach works well for smaller budgets, rental properties, limited-use outdoor spaces, or homeowners who prefer a restrained appearance.</p>

<p>A typical Essential design might include:</p>

