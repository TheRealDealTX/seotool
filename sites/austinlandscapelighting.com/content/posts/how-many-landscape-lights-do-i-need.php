<p>Fixture distance matters too. Moving a light farther from the wall usually spreads the beam, while moving it closer can emphasize texture. A stone façade may benefit from light placed close enough to graze the surface. A smooth stucco wall may need a softer, broader wash.</p>

<h2>How Many Lights Are Needed for Outdoor Living Areas?</h2>

<p>Outdoor living spaces usually require a mix of safety, task, and ambient lighting.</p>

<h3>Patio or Deck</h3>

<p>A small patio may need three or four fixtures. A larger deck with steps, seating, planters, and nearby trees may need eight or more.</p>

<p>Useful options include step lights, under-cap lights, downlights, nearby uplights, and low-level accents around the perimeter.</p>

<p>Avoid placing bright fixtures where they shine directly into seated guests’ eyes. Comfort matters more than raw brightness.</p>

<h3>Pool or Spa</h3>

<p>A typical pool area may use four to ten landscape fixtures around the surrounding deck, planting areas, walkways, and adjacent trees. Underwater pool lights are separate and should not be included in the landscape fixture count.</p>

<p>Reflections can amplify glare, so fixture direction requires care. Lighting trees or walls beyond the pool can make the area feel deeper and more visually complete than simply placing bright lights around the water’s edge.</p>

<h3>Outdoor Kitchen</h3>

<p>An outdoor kitchen may need three to six fixtures, depending on size and layout.</p>

