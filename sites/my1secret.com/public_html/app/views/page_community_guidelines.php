  <h1>Community Guidelines</h1>
  <p class="lede">My 1 Secret works because people share honestly and help each other. These guidelines keep it that way.</p>
  <h2>1. Be kind and useful</h2>
  <p>Disagree with ideas, not people. No harassment, hate, threats or personal attacks. Answer the question that was asked, and share what you actually know or experienced.</p>
  <h2>2. No spam or self-promotion</h2>
  <p>Links are welcome when they genuinely help the conversation. Advertising, affiliate links, link-dropping for SEO, repeated promotion of your own business and copy-pasted content are removed, and repeat offenders are banned. New accounts are limited to one link per post or comment until they have been part of the community for a little while.</p>
  <h2>3. Protect privacy</h2>
  <p>Do not post anyone's personal information: home addresses, phone numbers, email addresses, policy or claim numbers, or photos that identify private people. That includes your own: keep identifying details out of insurance and landlord questions.</p>
  <h2>4. Not professional advice</h2>
  <p>Posts are opinions and experiences. Do not present yourself as a licensed professional unless you are one, and never promise outcomes. For decisions about leases, insurance claims, money or health, consult a qualified professional.</p>
  <h2>5. Stay on topic and post once</h2>
  <p>Pick the community that fits your post, put the real question in the title, and do not post the same thing in several places.</p>
  <h2>6. Vote honestly</h2>
  <p>Upvote what is helpful, downvote what is not. Do not use multiple accounts or ask others to vote.</p>
  <h2>Moderation</h2>
  <p>Use the <strong>Report</strong> link on any post or comment that breaks these rules. Moderators may remove content, lock conversations, or suspend accounts. Removed posts stay removed.</p>
