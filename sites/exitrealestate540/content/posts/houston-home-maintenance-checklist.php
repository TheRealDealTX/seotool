<h2>Keep records of everything</h2>
<p>A simple log of what you did and when pays off three ways. It helps an insurance claim by showing damage was sudden, not neglect. It helps your HVAC and roof warranties. And it helps when you sell, because buyers and inspectors in Houston ask about foundation, roof and AC history.</p>
