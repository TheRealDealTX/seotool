#!/usr/bin/env python3
"""Download the chosen CC0/public-domain photos and export responsive sizes.

  python3 scripts/process_photos.py picks.json [slot ...]

picks.json: {slot: {url, alt, source, license, landing, creator, title, focus?}}
`focus` (0-1, default 0.5) is the vertical crop centre. Writes
assets/img/photos/<slot>-{480,800,1200,1600}.{jpg,webp} and content/images.php.
"""
import io, json, os, sys, urllib.request
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets/img/photos')
WIDTHS = [480, 800, 1200, 1600]

def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (site image builder)'})
    return urllib.request.urlopen(req, timeout=90).read()

def crop169(im, focus=0.5):
    w, h = im.size
    tw, th = w, round(w * 9 / 16)
    if th > h:
        th, tw = h, round(h * 16 / 9)
    left = (w - tw) // 2
    top = max(0, min(h - th, round(focus * h - th / 2)))
    return im.crop((left, top, left + tw, top + th))

def main():
    picks = json.load(open(sys.argv[1]))
    only = set(sys.argv[2:])
    os.makedirs(OUT, exist_ok=True)
    for slot, p in picks.items():
        if only and slot not in only:
            continue
        if p.get('license') not in ('cc0', 'pdm'):
            sys.exit(f'{slot}: licence {p.get("license")} is not CC0/PDM')
        im = ImageOps.exif_transpose(Image.open(io.BytesIO(fetch(p['url'])))).convert('RGB')
        im = crop169(im, float(p.get('focus', 0.5)))
        for w in WIDTHS:
            r = im.resize((w, round(w * 9 / 16)), Image.LANCZOS) if im.width > w else im.copy()
            r.save(os.path.join(OUT, f'{slot}-{w}.jpg'), 'JPEG', quality=80, optimize=True, progressive=True)
            r.save(os.path.join(OUT, f'{slot}-{w}.webp'), 'WEBP', quality=76, method=6)
        print('ok', slot, im.size)
    reg = {s: {'alt': p['alt'], 'source': p.get('source'), 'license': p.get('license'), 'landing': p.get('landing'), 'creator': p.get('creator')} for s, p in picks.items()}
    def php(v):
        return "'" + str(v or '').replace('\\', '\\\\').replace("'", "\\'") + "'"
    lines = ["<?php", "/** Photo registry - generated by scripts/process_photos.py. All photos are CC0 or public domain (no attribution required). */", "defined('ERE') or exit;", "", "return ["]
    for s, r in sorted(reg.items()):
        lines.append(f"    {php(s)} => ['alt' => {php(r['alt'])}, 'source' => {php(r['source'])}, 'license' => {php(r['license'])}, 'creator' => {php(r['creator'])}, 'landing' => {php(r['landing'])}],")
    lines.append("];\n")
    open(os.path.join(ROOT, 'content/images.php'), 'w').write("\n".join(lines))

main()
