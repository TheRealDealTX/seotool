<p>Imagine a home in San Marcos with hail damage to the roof, gutters, and a few windows. Assume a 10% fee applied to the full settlement, which is the maximum Texas allows. To keep things simple, these examples ignore the deductible, because the insurer subtracts it either way.</p>

<h3>Hypothetical A: a large gap between the offer and the documented damage</h3>
<ul>
<li>Insurer’s initial estimate: <strong>$20,000</strong></li>
<li>Final settlement after full documentation and supplements: <strong>$32,000</strong></li>
<li>Fee at 10% of $32,000: <strong>$3,200</strong></li>
<li>Amount you keep: $32,000 − $3,200 = <strong>$28,800</strong></li>
<li>Compared with accepting the initial estimate: $28,800 − $20,000 = <strong>$8,800 more</strong></li>
</ul>

<h3>Hypothetical B: a small gap</h3>
<ul>
<li>Insurer’s initial estimate: <strong>$20,000</strong></li>
<li>Final settlement: <strong>$21,000</strong></li>
<li>Fee at 10% of $21,000: <strong>$2,100</strong></li>
<li>Amount you keep: $21,000 − $2,100 = <strong>$18,900</strong></li>
<li>Compared with accepting the initial estimate: $18,900 − $20,000 = <strong>$1,100 less</strong></li>
</ul>

<p>Same fee percentage, opposite outcomes. The difference is entirely about how much covered damage the insurer’s first estimate missed.</p>

<p>Notice what does <em>not</em> drive the result: how persuasive anyone is on the phone. In both hypotheticals the question is simply whether there was real, covered, documentable damage left out of the first estimate. On a roof claim that might mean a slope that was never inspected, drip edge and starter course left off, or gutters and window screens that were dented but not listed. On an interior claim it might be wet insulation, baseboards, or a second room that shares the same ceiling. If those items exist, careful documentation can bring them into the claim. If they do not, no amount of effort changes the outcome, and the fee simply reduces what you keep.</p>

<h3>The break-even rule of thumb</h3>
<p>If the fee is 10% of the entire settlement, you keep 90% of whatever is paid. To come out ahead of the original offer, 90% of the final settlement has to exceed that offer. Put another way, the settlement must be more than the original offer divided by 0.9, or roughly <strong>11.1% higher</strong>.</p>

