<h2>A simple way to decide</h2>

<ol>
<li><strong>Get your numbers.</strong> The insurer’s estimate and at least one detailed estimate from a reputable local contractor.</li>
<li><strong>Measure the gap.</strong> If the gap is small, you may not need help. If it is large or the claim is denied, keep going.</li>
<li><strong>Apply the break-even rule.</strong> Is the likely gap comfortably more than about 11% of the offer?</li>
<li><strong>Count your time.</strong> How many hours can you realistically give this claim over the next several weeks?</li>
<li><strong>Get a free review.</strong> A short conversation with a licensed public adjuster can tell you whether there is likely room to improve the claim. Our <a href="/how-to-find-a-public-adjuster/">guide to finding a public adjuster</a> explains how to vet one.</li>
