<h2>What a public adjuster costs in Texas</h2>

<p>Public adjusters in Texas are usually paid a percentage of the claim payments covered by their contract. Under <a href="https://statutes.capitol.texas.gov/Docs/IN/htm/IN.4102.htm" target="_blank" rel="noopener">Texas Insurance Code Chapter 4102</a>:</p>
<ul>
<li>Compensation may not exceed <strong>10% of the insurance settlement</strong> on the claim.</li>
<li>The fee must be stated in a written contract that uses TDI-approved terms, before any work begins.</li>
<li>If the insurer pays or commits in writing to pay <strong>policy limits within 72 hours</strong> after the loss is reported, the adjuster may not take a percentage fee and is limited to reasonable hourly compensation.</li>
<li>You can rescind the contract within 72 hours of signing.</li>
</ul>

<p>Ten percent is a ceiling, not a requirement. The contract will spell out the actual rate and which payments it applies to. That second detail matters a lot for the math, so ask about it directly, especially if the insurer has already paid something before you hire help.</p>

<h2>What you get for the fee</h2>

<p>The fee pays for work you would otherwise do yourself or leave undone:</p>
<ul>
<li><strong>Policy analysis.</strong> Reading your coverage, endorsements, and deductibles, including percentage wind and hail deductibles common in Central Texas.</li>
<li><strong>Thorough documentation.</strong> Photos, measurements, and notes on every damaged component, inside and out.</li>
<li><strong>An independent estimate.</strong> A line-item estimate, typically in Xactimate, that you can compare with the insurer’s.</li>
<li><strong>Estimate review and supplements.</strong> Finding missing items and adding damage discovered during repairs. See our <a href="/services/insurance-estimate-review/">insurance estimate review</a> service.</li>
<li><strong>Communication and follow-up.</strong> Handling calls, re-inspections, and requests for information, and tracking deadlines under Texas’s <a href="https://statutes.capitol.texas.gov/Docs/IN/htm/IN.542.htm" target="_blank" rel="noopener">Prompt Payment of Claims law</a>.</li>
<li><strong>Time back.</strong> Often the least discussed and most appreciated part.</li>
</ul>

<h2>Worked fee example (hypothetical numbers)</h2>

