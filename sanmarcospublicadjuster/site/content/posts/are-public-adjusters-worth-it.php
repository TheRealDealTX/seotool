<ul>
<li><strong>Large or complex losses:</strong> full roof replacements, fires, multi-room water damage, or commercial buildings. See our <a href="/services/commercial-property-claims/">commercial property claims</a> page.</li>
<li><strong>Clear underpayment:</strong> missing roof slopes, skipped interior rooms, or pricing well below local contractor bids. See <a href="/services/underpaid-insurance-claims/">underpaid insurance claims</a>.</li>
