<h2>Questions to ask before you hire</h2>

<p>A first conversation should feel like a consultation, not a closing. Here are questions that tend to separate careful professionals from salespeople:</p>

<h3>About experience and approach</h3>
<ul>
<li>What types of claims do you handle most often: hail, wind, water, fire, commercial?</li>
<li>Have you worked claims on properties like mine, such as a metal roof in the Hill Country, a slab home on clay soil, a historic home, or a multifamily building?</li>
<li>How do you document damage? What does your estimate look like?</li>
<li>Will you read my whole policy, including endorsements and deductibles, before giving an opinion?</li>
</ul>

<h3>About who does the work</h3>
<ul>
<li>Who will inspect the property, write the estimate, and talk to the insurer? Are they all licensed?</li>
<li>Who is my main point of contact, and how quickly should I expect replies?</li>
<li>How will you keep me updated, and will I get copies of what you send the insurer?</li>
</ul>

<h3>About fees and the contract</h3>
<ul>
<li>What is your fee, and is it written into the contract?</li>
<li>Which payments does the fee apply to, including money the insurer already paid before I hired you?</li>
<li>How are checks handled if my mortgage company is named on them?</li>
<li>How do I cancel within the 72-hour window, and what happens if I want to end the contract later?</li>
</ul>

<p>Texas law caps public adjuster compensation at 10% of the insurance settlement, and fees must be disclosed in a written contract before any work begins. Anyone who is vague about the fee, or who will not put it in writing, has given you your answer.</p>

