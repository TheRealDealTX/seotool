<h2>Red flags: when to walk away</h2>

<p>Most problems people run into after a storm come from skipping the vetting step under pressure. Watch for these warning signs.</p>

<h3>Storm chasers and door-knockers</h3>
<p>Large hail events bring out-of-area crews. On May 9, 2024, for example, NOAA records show 3-inch hail at San Marcos Academy west of the city and 2.5-inch hail near the outlet mall (<a href="https://www.ncdc.noaa.gov/stormevents/eventdetails.jsp?id=1181409" target="_blank" rel="noopener">NCEI event record</a>), and on May 22, 2025, baseball-size hail fell in Uhland. Events like those draw door-to-door solicitors. Someone knocking is not automatically a problem, but anyone who cannot show a Texas license, has no local track record, or wants a signature before you have had time to think should be politely sent on their way.</p>

<h3>Contractors offering to “handle the claim”</h3>
<p>A roofer or restoration company can give you a repair estimate. That is useful. But negotiating your claim with the insurer is a licensed public adjuster’s role, and Texas law does not let a public adjuster participate in the repairs on a claim they adjust. That separation exists to avoid conflicts of interest. If a contractor says they will deal with your insurance company for you, or a supposed public adjuster wants to bundle the repairs, step back.</p>

<h3>Pressure to sign today</h3>
<p>Phrases like “this offer expires tonight” or “the insurer will deny you if you wait” are sales tactics. Your claim needs prompt reporting and mitigation, but choosing a representative can wait a day or two while you check a license and read a contract.</p>

<h3>Guarantees and big numbers</h3>
<p>No one can guarantee a higher settlement. Coverage depends on the policy and the facts. Someone who promises a specific dollar result before reading your policy is guessing, or worse.</p>

<h3>Contract problems</h3>
<ul>
<li>Blank fee or claim fields.</li>
<li>No “WE REPRESENT THE INSURED ONLY” statement.</li>
<li>No explanation of your 72-hour right to cancel.</li>
<li>Pressure to sign before you receive a full copy.</li>
</ul>

<h3>Discouraging you from asking questions</h3>
<p>A good public adjuster wants you informed. If someone discourages you from reading letters from your insurer, from talking with a Texas attorney about legal questions, or from checking their license, that tells you how the relationship is likely to go.</p>

