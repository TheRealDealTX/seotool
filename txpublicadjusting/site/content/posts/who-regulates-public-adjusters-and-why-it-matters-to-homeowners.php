<tr><td>License required</td><td>Nobody may act as a public adjuster in Texas without a TDI license.</td><td>Ch. 4102</td></tr>
<tr><td>Approved contract</td><td>The contract must be on a TDI-approved form, state "WE REPRESENT THE INSURED ONLY," and let you cancel within 72 hours of signing.</td><td>§4102.103</td></tr>
<tr><td>Fee cap</td><td>The total fee cannot exceed 10% of the settlement. On a total fire loss where the insurer pays or commits in writing to pay policy limits within 72 hours of the claim being reported, a percentage fee is not allowed.</td><td>§4102.104</td></tr>
