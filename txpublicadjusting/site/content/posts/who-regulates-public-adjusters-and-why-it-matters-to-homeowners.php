<h2>How a public adjuster gets licensed in Texas</h2>

<p>The path to a Texas public adjuster license runs through TDI. In general terms, an applicant has to:</p>

<ol class="steps">
<li><strong>Apply to TDI.</strong> The application goes through TDI's agent and adjuster licensing process, which includes a background review.</li>
<li><strong>Pass the licensing exam.</strong> Texas requires a state exam covering adjusting practice and the Texas laws that govern public adjusters.</li>
<li><strong>Show financial responsibility.</strong> Texas requires public adjusters to maintain proof of financial responsibility, such as a bond, so there is recourse if an adjuster mishandles a client's claim.</li>
<li><strong>Use the approved contract.</strong> Licensed adjusters must contract with clients only on a TDI-approved form.</li>
<li><strong>Keep the license current.</strong> Licenses must be renewed, and renewal requires continuing education.</li>
</ol>

<p>The exact exam content, continuing education hours and financial responsibility amounts are set by TDI and can change, so check TDI's licensing pages for the current requirements rather than relying on a third-party summary.</p>

<div class="callout callout--tip"><p><strong>Tip:</strong> Insurance company adjusters, including the independent adjusters insurers hire after big storms, are licensed under different rules. A Texas adjuster license on its own does not make someone a public adjuster. Make sure the license type says public adjuster.</p></div>

<h2>How to verify a public adjuster's license</h2>

<p>Checking takes a couple of minutes, and you should do it before you sign anything.</p>

<ol class="steps">
<li><strong>Get the full name and license number.</strong> A licensed public adjuster will give you both without hesitation. Ours: Joseph Dittman, Texas Public Adjuster License #3356839.</li>
<li><strong>Go to TDI's licensing pages.</strong> Start at <a href="https://www.tdi.texas.gov/agent/index.html" rel="noopener" target="_blank">TDI's agent and adjuster licensing page</a> and use the license lookup to search by name or number.</li>
<li><strong>Check the license type and status.</strong> It should be a public adjuster license, and it should be active, not expired or revoked.</li>
<li><strong>Match the name.</strong> The person or firm on the contract should match the license holder. A salesperson for a firm is not automatically licensed just because the firm employs a licensed adjuster.</li>
<li><strong>Read the contract.</strong> Look for "WE REPRESENT THE INSURED ONLY," the 72-hour cancellation right, and a fee at or below 10%.</li>
</ol>

<h2>Red flags that someone is not playing by the rules</h2>

