<p>In Texas, public adjusters are regulated by the Texas Department of Insurance (TDI). Chapter 4102 of the Texas Insurance Code requires anyone who acts as a public adjuster in this state to hold a TDI license, and it sets the rules on contracts, fees, conflicts of interest and claim checks. There is no federal regulator; each state runs its own system, so a license from another state does not let someone adjust your Texas claim unless they also hold a Texas license.</p>

<p>That matters because a public adjuster handles your claim, your policy and, indirectly, your money. The license is your main protection, and it only works if you check it.</p>

<h2>What Chapter 4102 controls</h2>

<p>Chapter 4102 is short, and most of it exists to protect the homeowner or business owner who hires a public adjuster. The parts you are most likely to run into:</p>

