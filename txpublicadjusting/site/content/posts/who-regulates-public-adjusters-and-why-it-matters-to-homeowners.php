<p>The practical point: only a public adjuster or an attorney is on your side of the claim. Everyone the insurance company sends, however helpful, is evaluating the loss for the insurer. For a closer comparison of the adjuster types, see <a href="/post/public-adjuster-vs-independent-adjuster/">public adjuster vs. independent adjuster</a>.</p>

<h2>How to file a complaint with TDI</h2>

<p>You can complain to TDI about a public adjuster, an insurance company adjuster, or an insurer. The process is the same in outline:</p>

<ol class="steps">
<li><strong>Gather the paper.</strong> Your contract, the adjuster's name and license number, your claim number, and any emails, texts or letters that show the problem.</li>
<li><strong>Write a short timeline.</strong> Dates, who said what, and what you want fixed. Keep it factual.</li>
<li><strong>Submit it to TDI.</strong> TDI accepts consumer complaints online through its website at <a href="https://www.tdi.texas.gov/" rel="noopener" target="_blank">tdi.texas.gov</a>; look for the consumer complaint section.</li>
<li><strong>Keep copies.</strong> Save the confirmation and any complaint number TDI gives you, and respond promptly if TDI asks for more information.</li>
</ol>

<p>A TDI complaint can prompt an insurer to respond or a licensee to be investigated, but TDI is not your representative, and a complaint is not designed to settle how much your claim is worth. If you have a coverage dispute, a public adjuster, the appraisal clause or an attorney is usually the path to resolving it.</p>

