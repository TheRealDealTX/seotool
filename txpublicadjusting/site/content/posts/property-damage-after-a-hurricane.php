<p>On the coast, many homeowners policies exclude wind and hail, and that coverage comes from a separate TWIA policy. Inland, including most of Houston, wind is normally on the homeowners policy. Your declarations page will show which you have.</p>

<h2>Separate deductibles</h2>

<p>Hurricane claims often involve more than one deductible:</p>

<ul>
<li><strong>Wind and hail or named storm deductible.</strong> In Texas this is often a percentage of your dwelling coverage, commonly 1–2%, especially in coastal counties. On a large home that can be a substantial amount, and it is calculated from your Coverage A limit, not from the damage.</li>
<li><strong>Flood deductible.</strong> A flood policy has its own deductible, applied separately.</li>
<li><strong>All other perils deductible.</strong> A fixed-dollar deductible may apply to non-wind parts of the loss, depending on the policy.</li>
</ul>

<p>If both wind and flood damaged the home, you may pay two deductibles. Use the <a href="/tools/claim-settlement-calculator/">claim settlement calculator</a> to see how a percentage deductible and depreciation change your payment.</p>

