<p>After a hurricane in Texas, the question that decides your claim is not how bad the damage is but <strong>what caused each part of it</strong>. Wind damage and wind-driven rain through a storm-created opening are generally covered by your homeowners or windstorm policy, which may be TWIA if you are on the coast. Rising water and storm surge are flood, which a standard homeowners policy excludes and only an NFIP or private flood policy covers. One house can have all three, with a separate deductible for each.</p>

<p>Here is how the common types of hurricane damage sort out, how to document them so they land under the right policy, and what Hurricane Beryl showed Houston homeowners about the parts of a claim people forget.</p>

<h2>The types of hurricane damage</h2>

<h3>Wind damage</h3>
<p>Missing or creased shingles, lifted ridge caps, torn flashing, damaged soffit and fascia, broken windows, bent gutters, blown-down fences and damaged siding. Wind damage is the core of most hurricane claims. Check the whole roof, not just the obvious missing tabs: shingles that were lifted and resealed can lose their bond without falling off.</p>

<h3>Wind-driven rain</h3>
<p>Water that enters through an opening the storm created, such as a missing section of roof, a broken window or a torn soffit, is usually treated as part of the wind loss. Rain that enters without a storm-created opening, for example through an old window seal, is a harder argument under many policy forms. That is why the first photos of the roof and openings matter so much.</p>

<h3>Storm surge and flooding</h3>
<p>Surge pushed inland by the storm and rainwater that rises from the ground are flood. Standard homeowners policies and TWIA exclude it. Hurricane Ike brought surge damage to Galveston, and Hurricane Harvey caused widespread rain flooding in Houston and along the Coastal Bend. If water came in at floor level and left a waterline, expect the insurer to look for a flood policy.</p>

<h3>Falling trees and debris</h3>
<p>A tree that falls on the house, garage or a covered structure is generally covered, including removing the tree from the structure. A tree that falls in the yard without hitting anything is often covered only for limited debris removal, if at all. Check your policy's trees, shrubs and debris removal provisions; these limits are usually small and specific.</p>

<h3>Power outage losses</h3>
<p>Spoiled food in the refrigerator and freezer is the most common outage loss. Some policies cover it, often with a small limit, and some only when the outage traces to a covered cause on your own property. Hotel stays while the house is without power are a separate question: Additional Living Expense typically applies when the home is unlivable because of covered damage, not because of a grid outage alone.</p>

<h3>Mold</h3>
<p>Wet drywall and insulation left in a closed, hot house can grow mold within days. Mold that follows covered wind-driven rain is treated very differently from mold that follows flood or long-term moisture, and many policies cap mold with a sublimit. Prompt drying is both your best defense against mold and your best evidence that you mitigated.</p>

