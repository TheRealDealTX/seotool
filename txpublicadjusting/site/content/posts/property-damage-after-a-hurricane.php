<h2>How to document hurricane damage</h2>

<p>The goal is to show the cause of each piece of damage, not just that it exists.</p>

<ul class="checklist">
<li>Photograph the roof and every exterior elevation before tarping, plus close-ups of each opening</li>
<li>Photograph waterlines inside and out, with a tape measure for height; this separates flood from wind-driven rain</li>
<li>Photograph ceiling stains and wet insulation that sit below roof damage</li>
<li>Photograph fallen trees where they landed, before removal, with the point of impact</li>
<li>Note the date and time the power went out and came back; keep any utility notices</li>
<li>List spoiled food before throwing it out, with photos of the open refrigerator and freezer</li>
<li>Keep receipts for tarps, chainsaw work, generators, fuel, drying equipment and hotel stays</li>
<li>Look up the storm reports for your address with our <a href="/tools/storm-report-lookup/">storm report lookup</a></li>
</ul>

<p>File with each insurer that may be involved, and report each claim separately. If you have TWIA, remember that claims must be filed within one year of the date of damage. For private homeowners policies, check your own policy's duties after loss and suit conditions for the deadlines that apply.</p>

<h2>Lessons from Hurricane Beryl</h2>

<p>Hurricane Beryl came ashore in July 2024 and pushed damaging wind across the Houston area, followed by widespread power outages that lasted days for many households in summer heat. The claims that followed taught some practical lessons.</p>

<ol class="steps">
<li><strong>Wind damage was easy to underestimate.</strong> Many roofs looked intact from the ground but had lifted shingles, damaged ridge caps or torn flashing. A roof-level inspection found damage a drive-by did not.</li>
<li><strong>Interior damage showed up late.</strong> Ceiling stains and attic moisture from wind-driven rain often appeared days later, after the power came back and people looked closely. Reopen or supplement the claim when you find new damage.</li>
<li><strong>Outage losses were missed entirely.</strong> Owners threw out spoiled food without photos or a list. Whether or not your policy pays for it, document it first.</li>
<li><strong>Heat and no power meant mold.</strong> Wet materials in houses without air conditioning grew mold fast. Owners who documented their drying efforts were in a better position when mold came up.</li>
<li><strong>Flood vs. wind disputes followed heavy rain.</strong> When water entered, the cause decided coverage. Photos of the opening, the roof and the absence of a ground-level waterline made the difference.</li>
<li><strong>Adjusters were stretched.</strong> After a declared catastrophe, the Chapter 542 deadlines are extended by 15 days, and first contact often came from out-of-state independent adjusters. See <a href="/post/how-long-does-an-insurance-adjuster-have-to-contact-you/">how long an adjuster has to contact you</a>.</li>
</ol>

