<p>No. In Texas, a public adjuster may not take part in repairing or rebuilding property on a claim they adjust, and may not accept money from a repair or salvage company on that claim (Texas Insurance Code §4102.158). The reverse is also true: a contractor may not act as your public adjuster on a property they are repairing or may repair, even with a license or a power of attorney (§4102.163). What a public adjuster <em>can</em> do is coordinate with the contractor you choose, so the estimate, the scope and the repairs line up.</p>

<p>The rest of this post explains where the lines are, why they exist, and what a legitimate working relationship between your adjuster and your contractor looks like.</p>

<h2>What Texas law actually says</h2>

<p>Two sections of Chapter 4102 of the Texas Insurance Code, the chapter that governs public adjusters, deal with this directly.</p>

<div class="callout callout--law"><p><strong>Texas law:</strong> Under §4102.158, a licensed public adjuster may not participate, directly or indirectly, in the reconstruction, repair or restoration of damaged property that is the subject of a claim they are adjusting, and may not accept compensation from a person who performs that work or buys salvage on that claim.</p></div>

<div class="callout callout--law"><p><strong>Texas law:</strong> Under §4102.163, a contractor may not act as a public adjuster, or advertise to adjust claims, for any property they are repairing or may repair. Holding a public adjuster license or a power of attorney from the owner does not change this.</p></div>

<p>Put simply: one person or company cannot both price your claim against the insurer and get paid to do the repairs on that same claim. The roles have to stay separate.</p>

<h2>Why the law keeps the roles apart</h2>

<p>A public adjuster is supposed to have one interest: getting you the full amount your policy owes for the loss. A contractor has a different, legitimate interest: winning and profitably completing the repair job. When the same party holds both, the incentives blur.</p>

<ul>
<li><strong>Scope steering.</strong> An adjuster with a stake in the repair job might write the claim around what that contractor wants to build, not around what the policy covers.</li>
<li><strong>Hidden fees.</strong> A referral payment from the contractor is money taken out of the job, usually paid for by thinner repairs or a higher bill to you.</li>
<li><strong>Lost leverage.</strong> If you are unhappy with the repair work, you need someone on your side who is not also the person you are disputing with.</li>
<li><strong>Pressure to sign.</strong> Storm chasers who combine "we'll handle your insurance" with a repair contract often lock owners into a builder before the claim is even valued.</li>
</ul>

<p>The licensing rules also protect your claim check. A public adjuster must make sure you are named on every claim payment and may never sign or endorse a check for you (§4102.104). That is harder to guarantee when the adjuster and the payee contractor are the same business.</p>

<h2>What is allowed: how a public adjuster and your contractor should work together</h2>

<p>Separate does not mean hostile. On most claims we handle, the contractor is someone we talk to often. Coordination is allowed and useful as long as you choose the contractor, the contractor bills you, and nobody pays the adjuster for the referral.</p>

<div class="compare">
<div>
<h3>Allowed</h3>
<ul>
<li>You hire the contractor you want; your public adjuster talks to them about scope</li>
<li>The adjuster reviews the contractor's estimate and compares it with the insurer's Xactimate estimate</li>
<li>Meeting the contractor on the roof or in the house during the insurer's inspection</li>
<li>Using the contractor's findings (decking condition, code items, hidden damage) to support a supplement</li>
<li>Coordinating with a mitigation company drying out a water loss</li>
<li>Giving you names of several contractors when you ask, with no payment involved</li>
</ul>
</div>
<div>
<h3>Not allowed</h3>
<ul>
<li>A public adjuster who also owns, works for or is paid by the repair company on your claim</li>
<li>Referral fees or "marketing" payments from the contractor to the adjuster</li>
<li>A contractor negotiating your claim with the insurer as if they were your adjuster</li>
<li>A roofer advertising that they will "handle your insurance claim" on the roof they want to replace</li>
<li>Bundling a repair contract and a claim-representation agreement in one signature</li>
<li>An adjuster buying or brokering salvage from your loss</li>
</ul>
</div>
