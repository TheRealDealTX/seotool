<h2>Contractors who "handle the insurance"</h2>

<p>This is the version of the problem homeowners see most often in Texas, especially after hail. A roofer knocks on the door, offers a free inspection, and says they will deal with the insurance company for you. Sometimes they ask you to sign a contingency agreement or an "assignment" form on the spot.</p>

<p>A contractor can tell the insurer's adjuster what they found on your roof, and they can submit their repair estimate. That is normal. What a contractor cannot do under §4102.163 is act as your adjuster: interpreting your policy, negotiating the value of your claim, or advertising that they adjust claims, on a property they are repairing.</p>

<p>Warning signs worth taking seriously:</p>

<ul class="checklist">
<li>The paper you are asked to sign mentions both the repairs and "representing you with your insurance company"</li>
<li>The contractor tells you not to talk to your insurer, or to send all claim correspondence to them</li>
<li>You are asked to sign before anyone has inspected or estimated the damage</li>
<li>The contractor offers to "cover" or "waive" your deductible, which should make you ask how the job and the claim are really being priced</li>
<li>Someone presents themselves as both your roofer and your public adjuster, or says they "work with" a public adjuster who will be paid out of the job</li>
</ul>

<div class="callout callout--warn"><p><strong>Watch for:</strong> a "public adjuster" whose business card, truck or website belongs to a roofing or restoration company. Ask directly who pays them and whether they have any financial tie to the repair. A licensed public adjuster should be able to answer that in one sentence.</p></div>

