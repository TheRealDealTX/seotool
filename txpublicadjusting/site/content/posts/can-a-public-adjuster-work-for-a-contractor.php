<h2>How a public adjuster is paid instead</h2>

<p>Because a public adjuster cannot be paid by the contractor, the only legitimate source of their fee is you, under a written contract. In Texas that contract must be on a form approved by the Texas Department of Insurance, must say "WE REPRESENT THE INSURED ONLY," and must let you cancel within 72 hours of signing (§4102.103). The fee is usually a percentage of the claim payment, and Texas caps it at 10% of the settlement (§4102.104). Our firm works on that contingency basis with no upfront fee. You can read more about how that works in <a href="/post/the-truth-about-public-adjuster-fees/">our guide to public adjuster fees</a>.</p>

<p>If you are paying a contractor and a public adjuster on the same claim, you should see two separate agreements, two separate invoices, and no money moving between them.</p>

<h2>What this looks like on a real claim</h2>

<p>Take a hail claim on a composition shingle roof in Bell County. The insurer's adjuster writes an estimate for a partial repair. You have a roofer you trust. Here is how the roles divide:</p>

<ol class="steps">
<li><strong>You hire both, separately.</strong> The roofer gives you a repair proposal. The public adjuster signs a TDI-approved contract with you to represent the claim.</li>
<li><strong>The adjuster documents and estimates.</strong> Roof-level photos, test squares, measurements and a line-item Xactimate estimate based on the policy, not on the roofer's price.</li>
<li><strong>The two compare notes.</strong> The roofer flags things only visible once tear-off begins, such as rotted decking or a missing drip edge required by code. The adjuster turns those into documented supplement requests.</li>
<li><strong>The adjuster negotiates with the insurer.</strong> The roofer does not. If the insurer re-inspects, both may attend, but the adjuster speaks to coverage and value.</li>
<li><strong>You pay the roofer from the claim funds.</strong> Checks are made out to you (and your mortgage company if required). Nobody endorses them for you.</li>
</ol>

<h2>If you already signed with a contractor</h2>

<p>You are not stuck with a bad claim because you signed a repair contract. You can still hire a licensed public adjuster to represent the insurance claim, and your contractor can still do the repairs. Read what you signed first: look for any language assigning claim benefits or naming the contractor as your representative. If something looks like the contractor is acting as your adjuster, a licensed public adjuster or an attorney can review it with you.</p>

