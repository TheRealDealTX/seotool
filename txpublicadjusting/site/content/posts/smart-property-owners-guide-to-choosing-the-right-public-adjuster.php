<h2>Questions to ask before you hire</h2>
<p>Once someone passes the license and contract checks, these questions separate a careful adjuster from a busy one.</p>
<h3>About the work</h3>
<ul>
<li><strong>Who will inspect my property, write the estimate and talk to the insurer?</strong> You want a name, and ideally the licensed adjuster.</li>
<li><strong>How do you document damage?</strong> Look for specifics: an Xactimate estimate, roof-level or drone photos, moisture readings on water losses, a 3D scan of the interior on larger claims.</li>
<li><strong>Will you be at the re-inspection?</strong> The answer should be yes.</li>
<li><strong>Have you handled this kind of loss?</strong> A TWIA windstorm claim, a commercial fire with business income, and a cosmetic-exclusion dispute on a metal roof each need different knowledge.</li>
<li><strong>Do you think I need you?</strong> An honest adjuster will tell you when a claim is small enough to handle on your own. If you are still deciding, see <a href="/post/should-i-use-a-public-adjuster/">should I use a public adjuster</a>.</li>
</ul>
<h3>About money and communication</h3>
<ul>
<li><strong>What exactly is the fee based on?</strong> The rate is only half of it. Our <a href="/post/the-truth-about-public-adjuster-fees/">fee guide</a> lists the terms to pin down in writing.</li>
<li><strong>Who will be named on the checks?</strong> You must be. Ask who else will be, and how the fee is paid once you receive the money.</li>
<li><strong>If we go to appraisal, who pays for what?</strong> Many policies have each side pay its own appraiser and split the umpire's cost. Check yours, and know the answer in advance.</li>
<li><strong>How will you update me, and how often?</strong> You should hear about every inspection, offer and document request.</li>
<li><strong>When should I call an attorney instead?</strong> A good public adjuster knows the line between an amount dispute and a legal one.</li>
</ul>

<h2>What a good first meeting looks like</h2>
<p>You can learn a lot from the first hour. A careful public adjuster will:</p>
<ul class="checklist">
<li>Ask for your full policy and any estimate or letter from the insurer before giving an opinion.</li>
<li>Walk the property, including the roof or attic where it is relevant, rather than quoting from the driveway.</li>
<li>Tell you plainly what looks missed, what looks fairly paid, and what is not covered.</li>
<li>Explain the fee in dollars on your claim, not just as a percentage.</li>
<li>Hand you the contract to read on your own time, and answer questions about it without hurrying you.</li>
</ul>
<p>If you meet two or three adjusters, compare how specific each one was about your damage and your policy. Specifics are a good sign; general promises are not.</p>

<h2>After you sign</h2>
<p>The public adjuster typically notifies your insurer in writing that they represent you, so the insurer copies them on correspondence. Keep your own claim log anyway: dates, names, what was said. Keep up mitigation, such as tarps, drying equipment and moved contents, because most policies require you to take reasonable steps to prevent further damage. And keep every receipt; our <a href="/tools/claim-documentation-checklist/">claim documentation checklist</a> shows what to save for each loss type.</p>
