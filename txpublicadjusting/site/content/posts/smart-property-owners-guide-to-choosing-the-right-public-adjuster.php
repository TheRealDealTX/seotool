<h3>The contractor who offers to "handle your claim"</h3>
<p>After a hailstorm, roofers often knock on doors and offer to "deal with the insurance company for you." In Texas, a contractor may not act as a public adjuster, or advertise to adjust claims, for property they are repairing or may repair. That is true even if they hold an adjuster license or you sign a power of attorney (§4102.163). A roofer can explain their own estimate and meet the adjuster on the roof to point out damage. They cannot negotiate your claim. Details in <a href="/post/can-a-public-adjuster-work-for-a-contractor/">can a public adjuster work for a contractor</a>.</p>

<h3>Pressure at the curb</h3>
<p>Someone who shows up uninvited the morning after a storm and wants a signature today is relying on you being stressed. A legitimate public adjuster will leave a card, give you the license number and let you read the contract at your kitchen table. The 72-hour cancellation right exists for exactly this situation.</p>

