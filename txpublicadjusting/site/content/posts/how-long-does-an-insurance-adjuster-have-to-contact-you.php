<h2>How a catastrophe changes the clock</h2>

<p>After a major hailstorm, hurricane or freeze, the commissioner of insurance can declare a weather-related catastrophe or major natural disaster. When that happens, §542.059 extends the Chapter 542 deadlines by 15 days. So the 15-day acknowledgment window becomes 30 days, and the decision and payment windows each gain 15 days.</p>

<p>In practice, catastrophe claims also get handled by independent adjusters brought in from out of state, and the first contact may come from a vendor company you have never heard of rather than your insurer directly. Ask for the adjuster's name, company and license number, and confirm with your insurer that they are assigned to your claim.</p>

<h2>TWIA claims run on a different schedule</h2>

<p>If your windstorm and hail coverage is through the Texas Windstorm Insurance Association, which is common along the Texas coast, your claim follows the TWIA rules in Chapter 2210 of the Insurance Code:</p>

<ul>
<li><strong>Filing deadline:</strong> you must file a TWIA claim within one year of the date of damage. The commissioner may extend that by up to 180 days for good cause.</li>
<li><strong>Decision:</strong> TWIA generally has 60 days to accept or deny after it receives the claim and the information it requested.</li>
</ul>

<p>Your homeowners policy, a separate flood policy and TWIA can each be involved in one storm loss, and each runs on its own rules. See <a href="/post/property-damage-after-a-hurricane/">property damage after a hurricane</a> for how those policies split the damage.</p>

<h2>What happens if the insurer misses a deadline</h2>

<p>When an insurer fails to meet the Chapter 542 deadlines, or delays payment of a claim it is liable for, §542.060 makes it liable for penalty interest on the amount owed plus reasonable attorney's fees. For most claims the interest is 18% a year. For weather-related property claims governed by Chapter 542A, the rate is the judgment interest rate plus 5%.</p>

<p>For weather claims there is a procedural step before any lawsuit: under §542A.003 you must give the insurer written notice at least 61 days before filing suit, stating the amount you say is owed. A late adjuster call alone rarely leads to a suit, but these rules give a documented delay real weight in negotiation.</p>

