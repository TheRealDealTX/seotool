<h2>What to do if no adjuster has contacted you</h2>

<ol class="steps">
<li><strong>Confirm the claim exists.</strong> Call the claims line or check the insurer's app. Get the claim number and the date they record as the date of notice. That date starts the 15-day clock.</li>
<li><strong>Ask who is assigned.</strong> Request the adjuster's name, phone, email and company. If none is assigned yet, ask when they expect to assign one.</li>
<li><strong>Put it in writing.</strong> Send a short email to the claims address: your claim number, the date you reported, and a request for acknowledgment and a list of what they need. Email creates a dated record.</li>
<li><strong>Keep protecting the property.</strong> Do not wait on the adjuster to stop further damage. Tarp the roof, dry out water, keep receipts. Your policy expects reasonable steps to prevent further loss.</li>
<li><strong>Document everything now.</strong> Photos, video and a room-by-room list while the damage is fresh. Our <a href="/tools/claim-documentation-checklist/">claim documentation checklist</a> covers each loss type.</li>
<li><strong>Escalate if the deadline passes.</strong> Ask for a supervisor, cite the date of notice, and note that Chapter 542 deadlines have passed. If it continues, you can file a complaint with the Texas Department of Insurance.</li>
</ol>

<h2>Common reasons for delay, and how to answer them</h2>

<ul>
<li><strong>"We're waiting on documents."</strong> Ask for a written list of exactly what is outstanding. The §542.056 decision clock starts once they have everything they asked for, so close the list quickly and send items by email so the date is recorded.</li>
<li><strong>"Your adjuster changed."</strong> Reassignment is common after big storms. Ask the new adjuster to confirm they have the file, your photos and any prior estimate, so you do not start over.</li>
<li><strong>"We need an engineer."</strong> An engineering inspection can be a legitimate step, but ask when it will be scheduled and request a copy of the report when it is done.</li>
<li><strong>"It's still under review."</strong> If the decision deadline has passed, ask in writing for the reason and the date a decision will be made, as §542.056 requires when an insurer needs more time.</li>
</ul>

<h2>Keep a claim diary from day one</h2>

<p>The single most useful habit on any insurance claim is a running log. When a dispute comes up months later, a dated record of who said what is what moves it. Keep it in one notebook or one document and add to it every time anything happens.</p>

<ul class="checklist">
<li>Date and time of loss, and the date and method you reported it</li>
<li>Every call: date, time, who you spoke with, their role, and a two-line summary</li>
<li>Every document request and the date you sent each item (attach the sent email)</li>
<li>Inspection dates and who attended</li>
<li>Every payment: amount, date, check number and what the insurer says it covers</li>
<li>Mitigation and repair expenses, with receipts</li>
<li>Any promise made by the adjuster ("you'll have the estimate Friday") and whether it happened</li>
</ul>

<div class="callout callout--tip"><p><strong>Tip:</strong> After every phone call, send a short follow-up email: "Per our call today, you said..." It turns a conversation into a record the insurer has received.</p></div>

