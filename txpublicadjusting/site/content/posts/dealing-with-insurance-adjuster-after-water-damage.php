<h2>Mold limits</h2>

<p>Many Texas homeowners policies cap mold remediation with a sublimit or exclude mold unless it results from a covered water loss. The amount and wording vary, so check your endorsements. Two practical points:</p>

<ul>
<li>Mold that grows <em>because</em> of a covered sudden leak is often treated differently from mold caused by long-term humidity or neglect. Prompt mitigation is your best evidence that you did not let it grow.</li>
<li>Even where mold remediation is capped, the underlying water damage (drywall, flooring, cabinets, insulation) is usually adjusted separately. Make sure the estimate does not lump repairs into the mold limit.</li>
</ul>

<h2>How to handle the inspection meeting</h2>

<ol class="steps">
<li><strong>Prepare a one-page summary.</strong> Date you discovered the water, the source, what you did and when, and who did the mitigation. Stick to facts you know.</li>
<li><strong>Have the evidence on the table.</strong> The failed part, the moisture logs, your photos from before tear-out, and the receipts.</li>
<li><strong>Walk every affected room.</strong> Including closets, adjacent rooms and the ceiling below a second-floor leak. Point out what is out of sight.</li>
<li><strong>Do not guess about dates.</strong> If you are asked when the leak started and you do not know, say so. A guess like "maybe a few weeks" can become the basis for a long-term leakage denial.</li>
<li><strong>Ask what happens next.</strong> When will you get the estimate, and is the insurer waiting on anything from you? Follow up by email the same day.</li>
</ol>

<h2>Don't forget contents and living expenses</h2>

<p>Water claims are often adjusted as if only the building was damaged. Furniture legs that wicked water, rugs, boxes in a closet, electronics on the floor and clothing in a flooded laundry room are all personal property claims. List them room by room with photos as you remove them; the <a href="/tools/contents-inventory-builder/">contents inventory builder</a> exports a list you can send to the adjuster. If the kitchen or the only bathroom is out of service, or drying equipment makes the house unlivable, ask whether Additional Living Expense applies and keep every receipt from the first night.</p>

