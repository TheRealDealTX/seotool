<p>Many claims fall in between. A pipe can fail suddenly inside a wall where nobody sees it for weeks. In that case the policy wording matters a great deal: some policies exclude continuous or repeated leakage over a set period, and some give back coverage for hidden leaks you could not have known about. Read the exclusion and any exception carefully before accepting a denial. A slab leak also raises a separate question of whether the policy pays to access the pipe (tearing out and replacing the floor) even when the pipe itself is not covered.</p>

