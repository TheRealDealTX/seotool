<p>When an insurance adjuster looks at water damage, the first thing they decide is not how much it costs to fix. It is <strong>what caused the water</strong> and <strong>how long it was there</strong>. Most homeowners policies cover sudden and accidental discharges, such as a burst supply line or a failed water heater, and exclude damage from water that leaked, seeped or caused rot over weeks or months. Your job in the first days is to stop the water, dry the house, and preserve evidence that answers those two questions in your favor.</p>

<h2>The first 48 hours</h2>

<p>Water keeps doing damage while you wait. Drywall wicks it upward, hardwood cups, and mold can begin growing within days in a warm Texas house. Your policy also requires you to take reasonable steps to prevent further damage. So mitigate first, and document as you go.</p>

<ol class="steps">
<li><strong>Stop the source.</strong> Shut off the main water valve or the fixture valve. If water is near outlets or the panel, shut off power to that area.</li>
<li><strong>Photograph before you move anything.</strong> Wide shots of each room, then close-ups of standing water, waterlines on walls, wet cabinets and the source itself. Video helps.</li>
<li><strong>Save the failed part.</strong> Keep the cracked supply line, the split fitting, the failed water heater valve. That part is the best evidence of a sudden failure. Do not let a plumber haul it off.</li>
<li><strong>Report the claim.</strong> Call or file online, note the claim number and the date. Ask whether the insurer wants to inspect before tear-out.</li>
<li><strong>Call a mitigation company.</strong> Professional extraction and drying with dehumidifiers and air movers. You choose the company; the insurer may suggest one but you do not have to use it.</li>
<li><strong>Keep samples and receipts.</strong> Cut a small square of wet carpet and pad, keep a piece of removed baseboard, and save every receipt for fans, shop vacs, hotel nights or meals.</li>
</ol>

<div class="callout callout--warn"><p><strong>Watch for:</strong> removing wet drywall and flooring is often necessary to prevent mold, and you should not leave a house wet waiting for an inspection. But photograph every wall before it is cut, and keep the moisture map. Undocumented tear-out is one of the most common reasons water claims get cut.</p></div>

<h2>Moisture readings: the evidence most owners never see</h2>

<p>A good mitigation company takes moisture readings with meters on the first day and every day after, and records them on a moisture map of the affected rooms. Those logs do three things for your claim:</p>

<ul>
<li><strong>They define the scope.</strong> Readings show how far the water traveled under flooring and up walls, including into rooms that look dry. The repair estimate should match the map.</li>
<li><strong>They support sudden loss.</strong> High readings in fresh materials that dry down over several days look like a recent event. Old, stable moisture with rot looks like a long-term leak.</li>
<li><strong>They justify the drying bill.</strong> Equipment counts and daily readings explain why drying took the number of days it did.</li>
</ul>

<p>Ask the mitigation company for copies of the daily logs, the moisture map, photos and the equipment record. We take our own moisture readings on water losses as well, so the documentation does not depend only on the vendor.</p>

<h2>What the field adjuster is looking for</h2>

<p>Expect the adjuster to spend as much time on the cause as on the damage. Typical things they check:</p>

<ul class="checklist">
<li>The source: is there a failed part, and does the failure look sudden?</li>
<li>Staining patterns: a single fresh waterline versus rings of old tide marks</li>
<li>Rot, delamination and corrosion under sinks, around toilets and at shower pans that suggest long-term seepage</li>
<li>Mold growth, and whether it looks recent or established</li>
<li>Prior repairs or patched drywall near the leak</li>
<li>Whether the water came from outside (flood or surface water, which a homeowners policy excludes) or from a plumbing system inside the house</li>
<li>What mitigation was done, and when it started</li>
</ul>

<h2>Sudden vs. long-term leaks</h2>

<div class="compare">
<div>
<h3>Usually treated as sudden and accidental</h3>
<ul>
<li>Burst supply line or pipe, including freeze breaks like those after Winter Storm Uri</li>
<li>Failed water heater or tank</li>
<li>Washing machine hose rupture</li>
<li>Ice maker or dishwasher line failure discovered quickly</li>
<li>AC drain pan overflow that is caught right away</li>
</ul>
</div>
<div>
<h3>Often argued as long-term or excluded</h3>
<ul>
<li>A slow drip under a sink that rotted the cabinet floor</li>
<li>Shower pan or grout seepage over months</li>
<li>Recurring roof leaks with old staining</li>
<li>Foundation or slab moisture without a clear pipe failure</li>
<li>Rising water from outside, which is flood</li>
</ul>
