<h2>Freeze and burst-pipe claims</h2>
<p>Winter Storm Uri in February 2021 burst pipes across Austin, especially in attics, exterior walls and second-floor bathrooms and laundry rooms. Hard freezes since have done the same on a smaller scale. These are water claims, not weather claims, and they're won or lost on documentation:</p>
<ul class="checklist">
<li>Photograph the break itself before the plumber replaces the pipe, and keep the failed section</li>
<li>Get the plumber's invoice to state the cause and location of the break</li>
<li>Have the mitigation company take moisture readings in every affected room, including below and beside the visible damage</li>
<li>Keep the drying logs; they show how far water traveled inside walls and under flooring</li>
</ul>
<p>Watch for two common reductions. Some policies limit mold coverage, so drying needs to start quickly. And carriers sometimes argue a pipe leaked slowly over time rather than bursting; a freeze date and a plumber's statement help answer that. See <a href="/services/water-damage-claims/">water damage claims</a> for how we handle these.</p>

