<h2>Hail and thunderstorms in the Brazos Valley</h2>
<p>The Brazos Valley gets severe spring thunderstorms with hail and straight-line wind. On rental properties, the damage often goes unnoticed for a while. Tenants don't climb on the roof, and they may not report a small ceiling stain until it spreads. By the time the owner hears about it, the carrier may question when the damage happened.</p>
<p>What helps an owner prove the claim:</p>
<ul class="checklist">
<li>Move-in and move-out inspection photos showing the condition of ceilings and walls</li>
<li>Roof photos from a recent inspection, purchase or refinance</li>
<li>Tenant maintenance requests showing when a leak was first reported</li>
<li>The storm date, checked against NOAA storm reports for your address</li>
<li>Dents on gutters, vents, AC fins and window screens from the same storm</li>
</ul>
<p>Our guide to <a href="/post/how-to-document-damage-for-your-claim/">how to document damage for your claim</a> covers what photos carriers expect.</p>

<h3>Storm damage or tenant damage?</h3>
<p>Carriers sometimes attribute broken windows, damaged doors or stained ceilings to tenant wear rather than the storm. Landlord policies generally don't cover damage caused by tenants' neglect, so the distinction matters. Your move-in photos and the date of the tenant's first maintenance request are the best answer. Rooftop and ground-level AC condensers are another frequent item on rental claims: hail flattens the fins, and the estimate should address the unit, not just the roof above it.</p>

<h2>Vacancy and the gap between leases</h2>
<p>College Station rentals often turn over in late spring and summer, and a unit may sit empty between leases. Many landlord policies restrict coverage for certain losses, such as vandalism, glass breakage or freeze damage, after a property has been vacant or unoccupied for a period set in the policy. Read your policy's vacancy condition, keep utilities on, keep heat set during freezes, and check on empty units after every storm.</p>

<h2>Investors with several properties</h2>
<p>When one storm damages several rentals, each address is usually a separate claim with its own deductible, and they may be with different carriers. We inspect each property, write a separate Xactimate estimate for each, and track the claims side by side so deadlines don't slip on any of them. For larger multifamily buildings, see our page on <a href="/commercial-claims/texas-public-adjuster-for-apartment-complex/">apartment complex claims</a>.</p>

<h2>After a storm at a Bryan or College Station rental</h2>
<ol class="steps">
<li><strong>Contact the tenant.</strong> Ask for photos of every leak, broken window and damaged item, with the date and time.</li>
<li><strong>Inspect or send someone.</strong> Photograph the roof, exterior and every affected room yourself.</li>
<li><strong>Protect the unit.</strong> Tarp and dry it out; keep invoices for emergency work.</li>
