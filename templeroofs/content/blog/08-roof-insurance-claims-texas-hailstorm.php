<h2>ACV, RCV, and Depreciation in Plain English</h2>

<p>The language on a claim estimate can be confusing. These are the terms that tend to matter most for roof insurance claims:</p>

<div class="table-wrap"><table>
  <thead>
    <tr><th>Term</th><th>What it generally means</th></tr>
  </thead>
  <tbody>
    <tr><td>Replacement Cost Value (RCV)</td><td>The cost to repair or replace the damaged roof with materials of like kind and quality at today's prices.</td></tr>
    <tr><td>Depreciation</td><td>A reduction for the age and wear of the existing roof. An older roof generally carries more depreciation.</td></tr>
    <tr><td>Actual Cash Value (ACV)</td><td>RCV minus depreciation. Roughly, what the worn roof was worth when it was damaged.</td></tr>
    <tr><td>Recoverable depreciation</td><td>On many RCV policies, the depreciation held back at first and released after repairs are completed and documented.</td></tr>
    <tr><td>Deductible</td><td>The portion of the loss you pay. It is subtracted from what the insurer pays.</td></tr>
  </tbody>
</table></div>

<p>With a replacement cost policy, insurers commonly pay the ACV amount first, minus your deductible, and then release the withheld depreciation after the work is finished. With an ACV-only policy, the depreciation is generally not paid back, which means an older roof can leave a significant gap between the payout and the cost of a new roof. Some policies also treat roofs differently based on age or roof material, so look for a roof-specific schedule or endorsement in your paperwork.</p>

<h3>Code upgrades and hidden damage</h3>

<p>Sometimes the work reveals items the original estimate did not include, such as rotted decking under the shingles or code-required components that were not on the old roof. Whether those are covered often depends on your policy, including whether you have ordinance or law coverage. When we find hidden damage during a job, we photograph it and explain it in writing so you can share it with your insurer and let them decide how to handle it.</p>

<h2>Deductibles: Read Yours Before the Storm</h2>

<p>Many Texas homeowners are surprised to learn their wind and hail deductible is not a flat dollar amount. Many Texas policies use a <strong>percentage deductible</strong> for wind and hail, calculated from the home's dwelling coverage rather than from the size of the claim.</p>

<p>For example, a home insured for $300,000 with a 2% wind/hail deductible would have a $6,000 deductible for a hail claim. A 1% deductible on the same home would be $3,000. Those numbers are only illustrations; check your declarations page to see what applies to your home.</p>

<h3>No contractor can legally "cover" your deductible</h3>

<p>Texas Insurance Code Chapter 707 makes it illegal for a contractor to waive, absorb, rebate, or otherwise pay your insurance deductible, and to advertise or promise to do so. That includes disguised versions, like fake discounts, inflated invoices, or paying you for a yard sign or "referral" in an amount that happens to match your deductible. The law exists because those arrangements effectively bill the insurer for work that was not done, which raises costs for everyone.</p>

<p>Bottom line: you are responsible for paying your deductible. A roofer who offers to make it disappear is telling you something important about how they do business.</p>

<h2>Red Flags of Storm-Chasing Contractors</h2>

<p>After a big hail event, out-of-area crews often arrive in Central Texas within days. Some do legitimate work, but storm chasers are known for high-pressure tactics and leaving town before warranty problems surface. Watch out for anyone who:</p>

<ul>
  <li>Knocks on your door uninvited and pushes you to sign something the same day</li>
  <li>Offers to waive, absorb, or "work with" your deductible</li>
  <li>Says they will "handle the insurance company" or negotiate your claim for you</li>
  <li>Asks you to sign a contract or assignment before your claim has even been inspected</li>
  <li>Demands a large cash payment up front</li>
  <li>Has no local address, a vague business name, or out-of-state plates and phone numbers you cannot verify</li>
  <li>Guarantees your claim will be approved or promises a "free roof"</li>
  <li>Cannot give you a clear written estimate describing materials and scope</li>
</ul>

<p>Taking a day or two to verify a contractor rarely hurts a legitimate claim. Ask for references you can call, confirm they carry insurance, and read every document before signing.</p>

