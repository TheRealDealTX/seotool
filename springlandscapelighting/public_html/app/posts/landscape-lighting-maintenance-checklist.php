<p class="lead">Outdoor lighting in the Houston area works in tough conditions: summer heat, constant humidity, sprinklers, heavy rain, hurricane-season storms and plants that keep growing for most of the year. None of that means a system has to look tired after a few years. A short seasonal routine, most of it done with a soft cloth and a walk around the yard after dark, keeps it looking the way it did on day one.</p>

<h2>Before you start</h2>
<p>Low-voltage systems are safe for basic homeowner maintenance like cleaning lenses, re-aiming fixtures and trimming plants. A few rules still apply:</p>
<ul>
<li>Turn the system off at the transformer before opening fixtures or handling connections.</li>
<li>Leave the 120-volt side alone. Outlet, breaker and transformer internal work belongs with a licensed electrician or a lighting professional.</li>
<li>Do your inspection walk after dark. Problems that are invisible at noon are obvious at 9 p.m.</li>
</ul>
<div class="takeaways"><h3>Key takeaways</h3><ul>
<li>Clean lenses at least twice a year; sprinkler hard water is the most common cause of dim fixtures.</li>
<li>Re-aim and trim seasonally, especially from spring through early fall.</li>
<li>Check the timer after every power outage and at each daylight saving change.</li>
<li>Prepare before storms and inspect afterward.</li>
</ul></div>

<h2>Spring checklist</h2>
<p>Spring is the big reset. Plants are surging, and anything the winter knocked loose shows up now.</p>
<ol class="steps">
<li><strong>Do a night walk.</strong> Note every fixture that is out, dim, flickering or pointed at the wrong thing.</li>
<li><strong>Clean every lens.</strong> Wipe with a soft cloth and water. For white mineral film from sprinkler overspray, a diluted white vinegar solution usually lifts it; rinse and dry afterward. Avoid abrasive pads that scratch the glass.</li>
<li><strong>Trim plantings.</strong> Cut back shrubs, liriope and groundcover that have grown over path lights and uplights. A fixture buried in foliage just lights the leaves in front of it.</li>
<li><strong>Re-aim fixtures.</strong> Mowers, edgers, dogs and kids nudge fixtures all year. Restore the original angle so beams hit the wall, column or canopy they were placed for.</li>
<li><strong>Check sprinkler heads.</strong> Adjust any that spray directly onto fixtures or the transformer.</li>
</ol>

<h2>Summer checklist</h2>
<p>Summer in Southeast Texas means peak growth, peak heat and the start of hurricane season on June 1.</p>
<ol class="steps">
<li><strong>Trim again.</strong> St. Augustine runners, crape myrtle suckers and bed plantings can cover a fixture in a few weeks.</li>
<li><strong>Re-aim after mowing.</strong> Weekly mowing is the most common reason path lights lean and uplights drift.</li>
<li><strong>Check tree-mounted fixtures.</strong> Tree lights in live oaks and pines should be attached with growth loops, slack left in the cable and adjustable mounts, so the tree can grow without strangling the wire. Loosen or reposition mounts as needed.</li>
<li><strong>Look inside the transformer.</strong> Fire ants are drawn to warm electrical enclosures and can pack a housing or fixture with soil and nest material. If you find a nest, keep the system off and treat around the area with a product labeled for use near electrical equipment, or call a pro to clean it out.</li>
<li><strong>Prepare for storms.</strong> See the storm section below.</li>
</ol>

<h2>Fall checklist</h2>
<p>Fall brings shorter days, the end of daylight saving time and, for many homes, more evenings spent outside.</p>
<ol class="steps">
<li><strong>Reset timers for the time change.</strong> Daylight saving ends on the first Sunday in November. Astronomical timers and most smart controls adjust automatically; mechanical timers do not.</li>
<li><strong>Review schedules.</strong> With earlier sunsets, a fixed-time timer may now be switching on well after dark. An astronomical timer or our <a href="/tools/sunset-timer-planner/">sunset timer planner</a> helps you set sensible hours.</li>
<li><strong>Clear leaves and pine needles.</strong> Loblolly pine needles and oak leaves collect on top of in-ground well lights and around path light bases.</li>
<li><strong>Check connections.</strong> Look for green or white corrosion at splices and sockets. Corrosion causes flicker and fixtures that work one night and not the next.</li>
<li><strong>Re-bury exposed wire.</strong> Rain and settling soil expose cable along bed edges. Cover it back up before it gets cut by an edger or aerator.</li>
</ol>

<h2>Winter checklist</h2>
<p>Winter here is short, but it is a good time to look at the system with the leaves off and the beds cut back.</p>
<ol class="steps">
<li><strong>Look at the design.</strong> With deciduous trees bare, check whether uplights still frame them well, and whether any fixture is now creating glare into windows.</li>
<li><strong>Inspect the transformer.</strong> Check that the cover closes, the photocell is clean and not shaded by new growth, and the outlet's in-use cover is intact.</li>
<li><strong>Check after freezes.</strong> Hard freezes are uncommon but do happen. Afterward, look for cracked lenses and fixtures that stopped working.</li>
<li><strong>Plan upgrades.</strong> If parts of the system are halogen or failing, winter is an easy time to plan an upgrade. Our <a href="/halogen-to-led-landscape-lighting/">halogen to LED guide</a> covers what to check.</li>
</ol>

<h2>Timers and power outages</h2>
<p>Any time the power goes out, check the transformer timer. Mechanical dial timers lose time during an outage, and some digital timers without battery backup reset entirely. If your lights start coming on at 3 p.m. or not at all, an outage is the usual cause. <a href="/services/smart-lighting-controls/">Smart and astronomical controls</a> generally recover on their own, which is one of the strongest arguments for upgrading.</p>

<h2>Storm prep and post-storm inspection</h2>
<p>From June through November, keep an eye on the forecast.</p>
<h3>Before a storm</h3>
<ul>
<li>Switch the system off at the transformer if flooding or a direct hit is expected.</li>
<li>Remove or secure anything that could become debris near fixtures.</li>
<li>Note which fixtures sit in low spots that pond in heavy rain.</li>
</ul>
<h3>After a storm</h3>
<div class="callout callout--warn"><strong>Safety first:</strong> If the transformer, its outlet or the house wiring was underwater, do not turn the system back on. Have an electrician inspect the 120-volt side first.</div>
<ul>
<li>Walk the property in daylight. Look for crushed fixtures, broken lenses, torn cable and tree fixtures damaged by falling limbs.</li>
<li>Clear mud and debris from in-ground fixtures and drains.</li>
<li>Once safe, turn the system on after dark and note which fixtures are out or flickering. Water in a fixture or a connection is the usual culprit.</li>
<li>Reset the timer.</li>
</ul>

