<p>Whatever your size, tailor the kit slightly for each pitch. If you are pitching a skincare brand, put your skincare content examples and results first. A small edit makes a generic kit feel custom.</p>

<h2 id="mistakes">Common media kit mistakes</h2>
<ul>
  <li><strong>Leading with follower count only.</strong> Brands care more about views, engagement and audience fit.</li>
  <li><strong>Outdated stats.</strong> A kit showing numbers from last year undersells you and raises doubts.</li>
  <li><strong>No audience data.</strong> Without location and age, a brand cannot tell whether your followers are its customers.</li>
  <li><strong>Too much text.</strong> Paragraphs about your life story push the important numbers out of view.</li>
  <li><strong>No call to action.</strong> Always end with how to book you and who to email.</li>
  <li><strong>Unreadable design.</strong> Light grey text on pastel backgrounds looks pretty and reads badly. Prioritise contrast.</li>
</ul>

<h2 id="rates">Should you put rates in your media kit?</h2>
<p>It depends on your goal. Including a starting rate ("Packages from $400") filters out brands with no budget and anchors the negotiation. Leaving rates out lets you quote per campaign. A popular middle ground: list packages without prices in the kit and send a separate rate card when a brand asks. Use our <a href="/how-much-should-influencers-charge/">influencer rate guide</a> to set those numbers.</p>

<h2 id="design">Design tips that make you look premium</h2>
<ul class="check-list">
  <li><strong>One page if you can, two at most.</strong> Brand managers read dozens of kits a week.</li>
  <li><strong>Use your brand colours and fonts</strong> so the kit feels like your content.</li>
  <li><strong>Big numbers, small words.</strong> Stats should be the largest text after your name.</li>
  <li><strong>High-quality images</strong> that show your style, not random selfies.</li>
  <li><strong>Export as PDF</strong> and keep a web version on your site for a shareable link.</li>
  <li><strong>Name the file well:</strong> "YourName-Media-Kit-2026.pdf".</li>
</ul>

<h2 id="update">Keep it current</h2>
<p>An out-of-date media kit costs you money because it undersells your growth. Refresh your stats monthly or quarterly, swap in your newest partnership results and update demographics whenever your audience shifts. A dated footer ("Stats as of October 2026") shows brands the numbers are fresh.</p>

<h2 id="send">How to send your media kit</h2>
<p>Attach the PDF, or better, link to it, when you pitch a brand or reply to an inquiry. Mention one highlight in the email body so they have a reason to open it: "My last skincare partnership drove 1,100 link clicks in 48 hours; full results are in my media kit." For pitch wording, see our guides on <a href="/how-to-get-brand-deals/">getting brand deals</a> and <a href="/how-to-write-to-an-influencer/">writing outreach emails</a>.</p>
