<h2 id="sections">The 8 sections every media kit needs</h2>
<div class="anatomy">
  <div><b>Header and photo</b><span>Your name, handle and a clear, friendly photo. Brands are hiring a person.</span></div>
  <div><b>Bio and positioning</b><span>Two or three sentences: who you create for, what about, and what makes your content different.</span></div>
  <div><b>Platform stats</b><span>Followers, average views or reach per post, and engagement rate for each active platform.</span></div>
  <div><b>Audience demographics</b><span>Top countries or cities, age ranges and gender split, straight from your platform analytics.</span></div>
  <div><b>Content examples</b><span>Three to six thumbnails or links to your best-performing and most brand-friendly posts.</span></div>
  <div><b>Past partnerships and results</b><span>Logos or names plus one result each: views, clicks, codes used, sales.</span></div>
  <div><b>Services and packages</b><span>What you offer (Reels, TikToks, YouTube integrations, UGC, Stories) and a few packages.</span></div>
  <div><b>Contact and call to action</b><span>Business email, website and a one-line invitation: "Let's build your next campaign."</span></div>
</div>

