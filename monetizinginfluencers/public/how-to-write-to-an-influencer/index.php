<h2 id="before">Before you write: do 10 minutes of homework</h2>
<p>The fastest way to get ignored is to send a message that could have gone to anyone. Before you write to an influencer, spend ten minutes on their profile and answer four questions:</p>
<ul class="check-list">
  <li><strong>Who is their audience?</strong> Look at the comments, not just the follower count. Are these your customers?</li>
  <li><strong>What do they already promote?</strong> Past sponsored posts show which formats they like and whether they work with brands like yours.</li>
  <li><strong>How do they want to be contacted?</strong> Many creators say it outright: "Business: email only" or "Collabs via my manager".</li>
  <li><strong>What is one specific piece of content you genuinely liked?</strong> You will reference it in your opening line.</li>
</ul>
<p>Also check engagement. A creator with 40,000 followers and 3,000 comments a post is usually a better partner than one with 400,000 followers and 90 comments. Our <a href="/tools/engagement-rate-calculator/">engagement rate calculator</a> takes the guesswork out of it.</p>

<h2 id="find-contact">How to find an influencer's contact details</h2>
<p>Most creators make it easy to reach them for business. Check these places in order:</p>
<div class="card-grid cols-2">
  <div class="card"><span class="ico-badge"><?= icon('mail') ?></span><h3>The bio email</h3><p>Instagram, TikTok and YouTube all let creators list a business email. On YouTube it sits in the About section of the channel.</p></div>
  <div class="card"><span class="ico-badge"><?= icon('link') ?></span><h3>Link-in-bio page</h3><p>Creator landing pages often have a "Work with me" or contact link, sometimes with a booking form or media kit.</p></div>
  <div class="card"><span class="ico-badge"><?= icon('users') ?></span><h3>Management or agency</h3><p>Larger creators route deals through a manager. Use that address; going around a manager rarely helps.</p></div>
