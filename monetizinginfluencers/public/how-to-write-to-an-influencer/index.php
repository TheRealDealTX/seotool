<h2 id="creator-to-creator">Writing to influencers as a creator</h2>
<p>When you are writing to another influencer as a fellow creator, the offer is not money, it is value. Lead with what they get: access to your audience, a fun concept, a guest spot, or a joint giveaway that grows both accounts. Be honest about your size. A creator with 8,000 followers asking someone with 800,000 for a collab needs a sharp idea, not a long message. Pitching creators at your level, or one step above, gets far more yeses.</p>
<ul class="check-list">
  <li>Propose a concrete idea ("a 'which one would you pick' duet on budget vs luxury skincare")</li>
  <li>Show you have done the work (a rough outline, a date, who films what)</li>
  <li>Make it easy to say yes: you handle editing, scheduling or logistics</li>
</ul>

<h2 id="follow-up">When and how to follow up</h2>
<p>Silence is not always a no. Creators travel, batch-film and get buried in email. A polite follow-up recovers a surprising number of deals.</p>
<div class="flow"><span>Day 0: first message</span><?= icon('arrow') ?><span>Day 5-7: one follow-up</span><?= icon('arrow') ?><span>Day 14: final check-in</span><?= icon('arrow') ?><span>Then stop</span></div>
<p>Two follow-ups is the maximum. Each should be shorter than the last, add something new (a deadline, a higher budget, a new angle) and give them an easy out. If you still hear nothing, move on and keep them on a list for future campaigns.</p>

