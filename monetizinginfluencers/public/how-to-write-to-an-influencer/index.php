<p>Direct messages work too, especially with smaller creators, but they are easy to miss. Platform-run creator marketplaces (most major networks now offer one for branded content) are another route if you want contracts and payments handled inside the app.</p>

<h3 id="facebook">How to contact Facebook influencers</h3>
<p>Facebook works a little differently, so it deserves its own note. To contact Facebook influencers, start with the <strong>About</strong> tab of their Page, which often lists an email, website and phone number. Page messages go to an inbox the creator or their team checks, so Messenger is a legitimate first touch. For community leaders who run large Facebook Groups, message the admin directly and be explicit about what you are asking: many groups ban promotional posts without permission, and admins respond far better to a request than to a surprise. Facebook's own branded-content tools also let you find creators and propose partnerships inside Meta's systems.</p>

<h2 id="anatomy">The anatomy of a reply-worthy message</h2>
<p>Every message that gets a reply has the same five parts. Get these right and the wording barely matters.</p>
<div class="anatomy">
  <div><b>A subject line that says what it is</b><span>"Paid collab: 2 Reels for [Brand] in March" beats "Opportunity!!" every time. Creators triage by subject line; tell them it is real and paid.</span></div>
  <div><b>Personalisation in the first line</b><span>Reference one specific video, post or idea. One genuine sentence proves this is not a mass blast.</span></div>
  <div><b>Who you are, in one sentence</b><span>Your name, your role, your brand or channel and why it fits their audience. No company history.</span></div>
  <div><b>The offer, including compensation</b><span>Say what you want (deliverables), when, and what you pay. "Budget available" or a range respects their time.</span></div>
  <div><b>One clear ask</b><span>End with a single, easy next step: "Would you be open to it? If yes, I'll send the brief."</span></div>
</div>

<blockquote>A good outreach message can be read in 30 seconds and answered in one line.</blockquote>

<h2 id="dos-donts">Do's and don'ts when you write to influencers</h2>
<div class="do-dont">
