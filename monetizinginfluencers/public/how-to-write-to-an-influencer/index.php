<h2 id="after-yes">What to send after they say yes</h2>
<p>Once a creator replies with interest, send a one-page brief: campaign goal, key messages (three at most), deliverables, dates, the approval process, disclosure requirements (#ad or the platform's paid-partnership label), payment terms and usage rights. Then put it in a simple written agreement. Clear expectations protect both sides and make the creator far more likely to work with you again.</p>
