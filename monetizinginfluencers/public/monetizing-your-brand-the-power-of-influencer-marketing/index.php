<h2 id="roi">Measure what is working</h2>
<p>Treat your influence like a business and track the numbers. For each income stream, review monthly:</p>
<ul class="check-list">
  <li><strong>Revenue</strong> per stream and per platform</li>
  <li><strong>Time spent</strong>, so you know your effective hourly rate</li>
  <li><strong>Engagement</strong> on sponsored vs. organic posts, to make sure ads are not hurting trust</li>
  <li><strong>Campaign results</strong> you can share with brands to justify higher rates</li>
</ul>
<p>Data turns gut feeling into strategy. It shows you which partnerships to renew, which products to expand and where to spend your creative energy.</p>

