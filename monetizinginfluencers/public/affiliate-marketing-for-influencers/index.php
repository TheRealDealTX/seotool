<p><strong>Affiliate marketing for influencers</strong> is the simplest way to earn from content without waiting for a brand to say yes. You recommend a product with a tracked link or code, and when someone buys, you earn a commission. No negotiation, no contract, no minimum follower count. It is also the income stream that keeps paying long after a post goes up, which makes it a perfect partner to brand deals.</p>
<p>This playbook covers how affiliate programs work, which types to join, where to put your links on every platform, how to stay compliant with disclosure rules, and how to scale your earnings with a website and email list.</p>

<h2 id="how-it-works">How affiliate marketing works</h2>
<div class="flow"><span>You share a tracked link or code</span><?= icon('arrow') ?><span>A follower clicks and buys</span><?= icon('arrow') ?><span>The program records the sale</span><?= icon('arrow') ?><span>You earn a commission</span></div>
<p>When you click an affiliate link, a cookie or tracking parameter records that the visitor came from you. If they buy within the program's <strong>cookie window</strong> (it might be 24 hours, 30 days or longer), the sale is credited to you. Commission can be a percentage of the sale or a flat fee per sale or sign-up. Payments are usually made monthly once you pass a minimum threshold.</p>
<div class="table-scroll"><table>
  <thead><tr><th>Term</th><th>What it means</th></tr></thead>
  <tbody>
    <tr><td>Commission rate</td><td>Your share of each sale, as a percentage or flat amount</td></tr>
    <tr><td>Cookie duration</td><td>How long after a click a purchase still counts for you</td></tr>
    <tr><td>EPC</td><td>Earnings per click: total commission ÷ clicks. The best way to compare programs</td></tr>
    <tr><td>Conversion rate</td><td>Percentage of clicks that become sales</td></tr>
    <tr><td>Payout threshold</td><td>Minimum balance before the program pays you</td></tr>
  </tbody>
</table></div>

<h2 id="programs">Types of affiliate programs</h2>
<div class="card-grid cols-3">
  <div class="card"><span class="ico-badge"><?= icon('box') ?></span><h3>Retailer programs</h3><p>Large stores such as Amazon Associates let you link almost anything they sell. Easy to start, huge catalogues, typically lower commission rates.</p></div>
  <div class="card"><span class="ico-badge"><?= icon('tag') ?></span><h3>Brand programs</h3><p>Direct programs run by individual brands. Often higher commissions, personal discount codes and a path to paid partnerships.</p></div>
  <div class="card"><span class="ico-badge"><?= icon('globe') ?></span><h3>Affiliate networks</h3><p>Networks host thousands of brand programs in one dashboard, with one login and consolidated payments.</p></div>
</div>
<p>Platform-native options matter too: several social platforms now have built-in shops or creator affiliate tools that let followers buy without leaving the app. Read each program's terms carefully, including where you are allowed to post links and whether you may use paid ads.</p>

<h3 id="choose">How to choose what to promote</h3>
<ul class="check-list">
  <li><strong>Products you actually use.</strong> Authentic recommendations convert best and protect your audience's trust.</li>
  <li><strong>Fit with your niche.</strong> A fitness creator promoting resistance bands beats one promoting random gadgets.</li>
  <li><strong>Price and commission balance.</strong> A higher-ticket item with a modest rate can out-earn a cheap item with a high rate.</li>
  <li><strong>Recurring commissions.</strong> Software and subscriptions sometimes pay every month a customer stays.</li>
</ul>

