<h3 id="workflow">A simple weekly affiliate workflow</h3>
<ol>
  <li><strong>Monday:</strong> pick one product your audience keeps asking about.</li>
  <li><strong>Tuesday-Wednesday:</strong> create one in-depth piece (video or blog post) and two short clips from it.</li>
  <li><strong>Thursday:</strong> add the link to your link-in-bio page and resource page, with disclosure.</li>
  <li><strong>Friday:</strong> mention it in your email newsletter or Stories with a personal take.</li>
  <li><strong>Monthly:</strong> check which links earned and update your roundups.</li>
</ol>

<h2 id="disclosure">Disclosure: do it clearly, every time</h2>
<p>In the United States, the FTC requires creators to disclose a material connection, including affiliate commissions, in a way that is <strong>clear and conspicuous</strong>. Other countries have similar rules. In practice that means:</p>
<ul class="check-list">
  <li>Put the disclosure where people will see it before they click: on the video, in the first lines of a caption, next to the link.</li>
  <li>Use plain words: "I earn a commission if you buy through my link," "#ad" or "#affiliate".</li>
  <li>Do not bury it in a hashtag pile or only on your profile.</li>
  <li>Say it out loud in videos as well as writing it.</li>
  <li>Use platform paid-partnership labels when the content is sponsored.</li>
</ul>
<div class="callout"><?= icon('shield') ?><p>Disclosure builds trust rather than hurting sales. Audiences are used to it, and being upfront protects you with both regulators and the programs themselves. This is general guidance, not legal advice; check the rules in your country.</p></div>

