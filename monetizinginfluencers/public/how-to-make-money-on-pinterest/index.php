<h2 id="seo">Pinterest SEO basics</h2>
<p>Because Pinterest is a search engine, keywords decide whether your pins get found.</p>
<ul class="check-list">
  <li><strong>Research keywords</strong> by typing your topic into Pinterest search and noting the suggested phrases.</li>
  <li><strong>Optimise your profile:</strong> include your main keyword in your display name and bio ("Jess | Small Space Decor Ideas").</li>
  <li><strong>Name boards clearly</strong> with searchable phrases, not cute inside jokes.</li>
  <li><strong>Write keyword-rich titles and descriptions</strong> in natural sentences.</li>
  <li><strong>Pin consistently</strong>: fresh pins every week beat 50 pins once a month.</li>
  <li><strong>Claim your website</strong> so your pins carry your profile and you can see site analytics.</li>
</ul>

