<h2 id="creator-tools">5. Platform creator programs</h2>
<p>Pinterest has run various creator programs and shopping features over the years, and they change often. Formats change too: Idea Pins, for example, were folded into standard video and multi-image pins. Treat any platform payout program as a bonus rather than a business plan, and check Pinterest's creator resources for what is currently available in your country. The income streams above are the ones you control.</p>

