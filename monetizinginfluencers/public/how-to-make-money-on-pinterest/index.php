<h2 id="affiliate">1. Affiliate pins</h2>
<p>Affiliate marketing is the most direct way to earn on Pinterest. You create pins for products you recommend and link them, either directly to the product with your affiliate link (where the program allows it) or, more reliably, to a blog post or landing page that contains your links.</p>
<ul class="check-list">
  <li><strong>Roundups work best:</strong> "15 cosy reading nook ideas," "Best carry-on bags under $150," "Gift ideas for new runners."</li>
  <li><strong>Check program rules:</strong> some affiliate programs do not allow direct links on Pinterest, so linking to your own page is safer.</li>
  <li><strong>Disclose:</strong> add a clear disclosure in the pin description, such as "I may earn a commission from links."</li>
</ul>
<p>Our <a href="/affiliate-marketing-for-influencers/">affiliate marketing playbook</a> covers programs, tracking and disclosure in detail.</p>

<h2 id="brand-partnerships">2. Brand partnerships on Pinterest</h2>
<p>Brands in home, food, fashion, beauty, weddings, travel and DIY know Pinterest users are planners and buyers, and they pay creators to make pins that inspire purchases. A typical Pinterest deal is a set of pins (often a mix of static, video and multi-image pins) linking to the brand's site or a product, sometimes with a blog post or Instagram content bundled in.</p>
<p>Pinterest has a <strong>paid partnership</strong> label that lets you tag the brand on sponsored pins, which keeps the content transparent and can let the brand see performance or promote it. When you pitch, lead with outbound clicks and saves, because those are the numbers Pinterest-savvy brands care about. Rates for Pinterest are covered in our <a href="/how-much-should-influencers-charge/">influencer rate guide</a>.</p>

<div class="callout"><?= icon('zap') ?><p><strong>Pitch angle:</strong> "My pins drove [X] outbound clicks last month to roundup content like this." Clicks prove buying intent better than follower counts do on Pinterest.</p></div>

