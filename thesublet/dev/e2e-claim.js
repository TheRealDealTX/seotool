const { chromium } = require('playwright');
const fs = require('fs');
const BASE = process.env.BASE || 'http://127.0.0.1:8099';
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const lastLink = () => { const m = fs.readFileSync('dev/mail.log', 'utf8').match(/http:\/\/127\.0\.0\.1:8099\/auth\/[a-f0-9]+\//g); return m && m[m.length - 1]; };
(async () => {
  const b = await chromium.launch(); const p = await (await b.newContext()).newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto(BASE + '/sublets/tx/houston/');
  const dirHref = await p.getAttribute('.card:has(.badge-glass) .card-title a', 'href');
  await p.goto(BASE + dirHref);
  ok(await p.locator('text=Claim this listing').count() >= 2, 'directory page shows claim CTAs');
  ok(await p.locator('form[action$="/contact/"]').count() === 0, 'no relay form on unclaimed listing');
  const ld = await p.$$eval('script[type="application/ld+json"]', s => s.map(x => JSON.parse(x.textContent)['@type']));
  ok(ld.some(t => ['Hotel', 'ApartmentComplex', 'LodgingBusiness'].includes(t)), 'business schema ' + ld.join(','));
  await p.click('.owner-card a:has-text("Claim this listing")');
  await p.check('input[name=choice][value=free]');
  await p.fill('input[name=name]', 'Morgan Manager');
  await p.fill('input[name=email]', 'morgan@example.com');
  await p.fill('textarea[name=message]', 'I am the general manager of this property.');
  await p.check('input[name=authorized]');
  await p.click('button:has-text("Claim this listing")');
  await p.waitForSelector('.claim-done');
  ok(true, 'free claim submitted');
  // admin approves
  const a = await (await b.newContext()).newPage();
  await a.goto(BASE + '/admin/login/');
  await a.fill('input[name=user]', 'admin'); await a.fill('input[name=pass]', process.env.ADMIN_PASS || 'devpass12345');
  await a.click('button:has-text("Sign in")'); await a.waitForURL(BASE + '/admin/');
  await a.goto(BASE + '/admin/claims/');
  ok(await a.locator('text=morgan@example.com').count() === 1, 'claim shows in admin');
  a.once('dialog', d => d.accept());
  await a.click('button[value=approve]'); await a.waitForSelector('.flash-ok');
  ok(true, 'admin approved claim');
  // owner signs in from approval email
  const link = lastLink(); ok(!!link, 'approval email has magic link');
  await p.goto(link); await p.click('button:has-text("Sign in")'); await p.waitForURL(BASE + '/account/');
  ok(await p.locator('.dash-item').count() >= 1, 'claimed listing in owner dashboard');
  const lid = dirHref.match(/-(\d+)\/$/)[1];
  await p.goto(BASE + '/account/listing/' + lid + '/');
  await p.fill('input[name=rent]', '3200');
  await p.fill('textarea[name=description]', 'Fully furnished suites with kitchens, weekly housekeeping and flexible 30+ night stays — popular with travel nurses near the medical center.');
  await p.setInputFiles('input[name="photos[]"]', ['dev/test-room.jpg']);
  await p.click('button:has-text("Save changes")'); await p.waitForSelector('.flash-ok');
  ok(true, 'owner edited claimed listing with photo');
  const anon = await (await b.newContext()).newPage();
  await anon.goto(BASE + dirHref);
  ok(await anon.locator('form[action$="/contact/"]').count() === 1, 'claimed listing now has contact relay');
  ok((await anon.textContent('.facts')).includes('$3,200'), 'claimed listing shows rent');
  ok(await anon.locator('.gallery img').count() === 1, 'claimed listing shows owner photo');
  ok(errs.length === 0, 'no JS errors ' + errs.join('|'));
  await b.close(); console.log(fails ? fails + ' FAILED' : 'ALL PASSED'); process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
