<h2>Questions to ask every host</h2>
<ol>
<li>Is the unit available for my exact dates, and can I extend if offered?</li>
<li>What happens if my contract is canceled?</li>
<li>What is included in rent, and what is billed separately?</li>
<li>Is there dedicated parking?</li>
<li>How noisy and how bright is the bedroom during the day?</li>
<li>Is there laundry in the unit or building?</li>
<li>Who do I contact for maintenance problems?</li>
<li>Do you have permission from your landlord to sublet, if you are a tenant?</li>
</ol>
