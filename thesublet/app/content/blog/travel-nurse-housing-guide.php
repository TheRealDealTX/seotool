<h2>Making each place feel like home</h2>
<p>Thirteen weeks is long enough to settle in. Many travel nurses carry a small "home kit": their own pillow, a favorite mug, a throw blanket, a few photos. These take up little space and make a new place feel familiar after hard shifts. Unpack fully on day one rather than living out of a suitcase. It sounds small, but it helps.</p>
