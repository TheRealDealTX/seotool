<p>Travel nursing comes with a unique housing problem. You need a place that is furnished, available on short notice, close to a hospital you may never have seen, and rentable for roughly three months, a length that does not fit neatly into the world of year-long leases or nightly hotel stays. And you often need to sort it all out while still finishing your current assignment in another state.</p>
<p>This guide covers how to approach housing for a typical travel contract: when to start looking, what to prioritize, how to think about your housing budget, and what to ask before you commit.</p>

<h2>Understanding the 13-week rhythm</h2>
<p>Many travel nursing contracts run about 13 weeks, though shorter and longer assignments are common, and extensions happen often. That creates a few housing realities:</p>
<ul>
<li><strong>You need flexibility at both ends.</strong> Start dates can shift, and you may be offered an extension late in your contract. A host who can accommodate a few extra weeks is valuable.</li>
<li><strong>Contracts can be canceled.</strong> It is not common, but it happens. Ask every host what happens if your assignment ends early, and get the answer in writing.</li>
<li><strong>Three months sits in an awkward spot.</strong> It is long enough that a hotel gets expensive and impersonal, but short enough that most landlords will not offer a standard lease. Furnished sublets and monthly rentals fill that gap well.</li>
</ul>

<h2>When to start looking</h2>
<p>As soon as your contract is confirmed, start searching. If you have a signed offer and firm dates, a few weeks of lead time gives you real choice. Late-confirmed contracts happen too, so it is worth having a short list of backup options: an extended-stay hotel for the first week or two, or a host who is open to a flexible start date.</p>
<p>Before you accept an assignment in an unfamiliar city, it can help to browse what is available in the area. That gives you a realistic sense of options near the facility before you commit.</p>

<h2>Location: think in commute minutes, not miles</h2>
<p>After a 12-hour shift, especially a night shift, a long drive home is not just inconvenient; drowsy driving is a genuine safety concern. When you evaluate listings:</p>
<ul>
<li><strong>Map the actual commute</strong> at your shift-change times. A place three miles away can take far longer during rush hour in some cities.</li>
<li><strong>Check parking</strong> at both the rental and the hospital. Ask whether the rental includes a dedicated spot, and whether street parking is restricted.</li>
<li><strong>Consider transit</strong> if the city has a reliable system and the hospital is near a station, but confirm service runs at the hours you will need it.</li>
<li><strong>Look at the immediate surroundings.</strong> Is there a grocery store nearby? A place to walk after a shift? A gym?</li>
</ul>
<p>Proximity also matters for safety walking to and from your car at odd hours. Well-lit parking and a secure entrance are worth asking about.</p>

<h2>Sleep is non-negotiable</h2>
<p>If you work nights, the quality of your daytime sleep affects everything. Ask hosts directly:</p>
<ul>
<li>Does the bedroom have blackout curtains or can you install them?</li>
<li>Is the bedroom on a busy street, or facing a quiet side?</li>
<li>Are there roommates, and what are their schedules?</li>
<li>Is there any construction planned nearby or in the building?</li>
<li>Is there air conditioning? Sleeping through a hot afternoon is very hard without it.</li>
</ul>
<p>A short video call tour can reveal a lot about noise and light. Our guide on <a href="/blog/how-to-tour-a-sublet-remotely/">how to tour a sublet remotely</a> covers what to look at when you cannot visit in person.</p>

<h2>What "furnished" should mean for you</h2>
<p>Furnished listings vary widely. Some include everything down to the spatula; others have a bed and a couch. For a three-month stay, you will be much happier if the place has:</p>
<ul>
<li>A comfortable bed with clean linens and towels</li>
<li>A functional kitchen with pots, pans, utensils, and dishes, since meal prepping before shifts can save a lot of money</li>
<li>In-unit or on-site laundry for scrubs</li>
<li>Reliable Wi-Fi for charting courses, credentialing paperwork, and staying in touch</li>
<li>A dresser or closet space so you can actually unpack</li>
</ul>
<p>Ask for an itemized list. Then pack for what is missing. Our <a href="/blog/what-to-pack-for-a-sublet/">sublet packing guide</a> and the <a href="/tools/packing-checklist/">packing checklist tool</a> can help you avoid bringing duplicates or forgetting essentials.</p>

<h2>Budgeting and housing stipends</h2>
<p>Many travel nurse pay packages include a housing stipend or lodging allowance rather than agency-provided housing. Taking the stipend and finding your own place can give you more control over where you live. Whether it works out financially depends on local rental costs and on your own situation.</p>
<p>Stipends can have tax implications, and the rules around them are specific and depend on individual circumstances, such as whether you maintain a permanent tax home. We will not try to explain those rules here. Talk to a tax professional who works with travel healthcare workers before making decisions based on how a stipend is treated.</p>
<p>When comparing listings, look at total monthly cost, not just rent:</p>
<ul>
<li>Rent</li>
<li>Utilities, if not included</li>
<li>Internet</li>
<li>Parking</li>
<li>Cleaning or one-time fees</li>
<li>Security deposit (refundable, but tied up for months)</li>
</ul>
<p>The <a href="/tools/cost-calculator/">cost calculator</a> helps you add it all up, and the <a href="/tools/compare/">compare tool</a> lets you weigh two or three options side by side. If you are deciding between a sublet and a hotel, our <a href="/blog/sublet-vs-extended-stay-hotel/">sublet vs. extended-stay hotel</a> comparison is worth a read.</p>

<h2>Lease terms to look for</h2>
<p>Ideal terms for a travel contract include:</p>
<ul>
<li><strong>Month-to-month or a fixed term matching your contract</strong>, with a clear option to extend.</li>
<li><strong>A written early-termination clause</strong> covering canceled contracts.</li>
<li><strong>Prorated rent</strong> for partial first and last months. The <a href="/tools/proration/">proration tool</a> helps you check the math.</li>
<li><strong>Clear deposit terms</strong>, including when it will be returned after you leave.</li>
</ul>
<p>Get the agreement in writing, even if the host seems relaxed. A clear agreement protects you if something goes wrong while you are three states away from home.</p>

<h2>Staying safe while searching remotely</h2>
<p>Travel nurses are frequent targets of rental scams because they often rent sight unseen, on deadline, from far away. Scammers know this. Watch for:</p>
<ul>
<li>Requests to pay by wire transfer, gift card, cryptocurrency, or payment apps before you have verified the listing</li>
<li>A host who claims to be out of the country and cannot show the place</li>
<li>Rent that is far below comparable listings</li>
<li>Pressure to pay a deposit immediately "because so many nurses are interested"</li>
</ul>
<p>Insist on a live video tour where the host shows the unit in real time, and verify ownership or authority to rent if you can. Read our full guide on <a href="/blog/how-to-avoid-rental-scams/">how to avoid rental scams</a> and visit our <a href="/safety/">safety page</a>.</p>
