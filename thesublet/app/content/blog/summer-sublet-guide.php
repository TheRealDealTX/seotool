<p>Summer is the busiest season for sublets in much of the country. Students head home or abroad, interns and seasonal workers pour into cities, and lots of people take a few months to travel or try a new place. The result is a market where supply and demand both spike at roughly the same time.</p>
<p>Whether you are searching for a summer place or trying to sublet your own apartment while you are away, this guide covers how the season works and how to make it go smoothly.</p>

<h2>How the summer sublet season works</h2>
<p>The typical summer sublet runs from some point in May or June through August. The exact shape depends on who is involved:</p>
<ul>
<li><strong>University students</strong> often finish spring semester in May and return in late August or early September. Their apartments may be available for three months or more.</li>
<li><strong>Summer interns</strong> usually need housing for ten to twelve weeks, starting late May through mid-June.</li>
<li><strong>Seasonal workers</strong> in tourist areas may need housing that matches the summer season.</li>
<li><strong>Remote workers and travelers</strong> sometimes take a summer somewhere new.</li>
</ul>
<p>These groups do not always line up perfectly. A student's apartment might be free from May 10, while an intern starts June 2. Flexibility on dates, and fair proration of partial months, helps everyone. The <a href="/tools/proration/">proration tool</a> makes partial-month math easy.</p>

<h2>For renters: finding a summer sublet</h2>

<h3>Start early</h3>
<p>In popular cities and college towns, summer listings start appearing in early spring as people make plans. The earlier you start, the more choice you have. That said, plans change constantly, and new listings keep popping up through May and even June as people's situations shift. If you are searching late, do not give up.</p>

<h3>Know your must-haves</h3>
<p>Before you start browsing, decide what matters most:</p>
<ul>
<li><strong>Exact dates,</strong> and how flexible you can be</li>
<li><strong>Commute</strong> to your job, internship, or campus</li>
<li><strong>Air conditioning.</strong> In many parts of the country, this is not optional in July.</li>
<li><strong>Private room or entire place</strong></li>
<li><strong>Laundry</strong></li>
<li><strong>Budget,</strong> including utilities</li>
</ul>
<p>Our guide to <a href="/blog/questions-to-ask-before-subletting/">questions to ask before subletting</a> is a good companion as you start talking to hosts.</p>

<h3>Look near universities</h3>
<p>College neighborhoods often have the most summer availability, because so many students leave. Even if you are not a student, these areas can be a great option: they tend to be walkable and close to transit, and they may have more options during summer than at other times of year.</p>

<h3>Check the end date carefully</h3>
<p>In some college towns, many leases turn over at the same time, often around the end of August or the beginning of September. If your sublet is tied to a student's lease, the end date is probably fixed. Make sure it works for your plans.</p>

<h3>Stay alert for scams</h3>
