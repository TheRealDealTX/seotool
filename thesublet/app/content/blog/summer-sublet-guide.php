<h2>For hosts: subletting your place for the summer</h2>

<h3>Get permission first</h3>
<p>Check your lease and ask your landlord in writing before you list. Many leases require landlord consent for any sublet, and some prohibit it outright. Our guide on <a href="/blog/how-to-sublet-your-apartment-legally/">how to sublet your apartment legally</a> walks through the process. If your building or city has rules about short-term rentals, check those too; see <a href="/blog/short-term-rental-laws-what-hosts-should-know/">short-term rental laws</a>.</p>

<h3>List early, but be honest about dates</h3>
<p>The best renters often plan ahead, so listing in early spring can attract organized, reliable people. Be precise about your available dates, and say whether you can be flexible on move-in or move-out.</p>

<h3>Know your audience</h3>
<p>Think about who is likely to rent your place:</p>
<ul>
<li>Near a university? Visiting students and summer research staff.</li>
<li>Near downtown or business districts? Interns and young professionals.</li>
<li>Near a hospital? Travel nurses and medical rotations.</li>
</ul>
<p>Write your listing to highlight what those people care about, like commute times, Wi-Fi, a desk, or quiet bedrooms. Our guide on <a href="/blog/how-to-write-a-sublet-listing-that-rents/">how to write a sublet listing that rents</a> has more detail. Whatever your audience, apply the same criteria to every applicant, in line with fair housing law.</p>

<h3>Price it right</h3>
<p>Summer demand can support solid pricing in busy markets, but overpricing can leave your place empty while you are still paying rent. Look at comparable summer listings in your area, factor in furnishings and utilities, and consider whether you want a quick, reliable renter or the highest possible price. Our guide on <a href="/blog/how-to-price-your-sublet/">how to price your sublet</a> covers this in depth.</p>

<h3>Prepare the space</h3>
<ul>
<li>Clear out a dresser and some closet space.</li>
<li>Lock personal valuables away or take them with you.</li>
<li>Leave clean linens and towels.</li>
<li>Write a short "house guide" with Wi-Fi details, appliance quirks, trash day, and who to call for maintenance.</li>
<li>Make sure the air conditioning works before you leave.</li>
</ul>

<h3>Put it in writing</h3>
<p>A written sublease protects everyone. At minimum, cover dates, rent, deposit, utilities, house rules, and what happens if plans change. See our <a href="/blog/sublease-agreement-what-to-include/">sublease agreement checklist</a>.</p>

<h2>College towns: a special case</h2>
<p>In college towns, the summer market can look very different from the rest of the year. A huge share of residents may leave in May, and demand for summer housing may come from a smaller group: summer session students, researchers, visiting faculty, and people working local summer jobs.</p>
<p>What that can mean:</p>
<ul>
<li><strong>For renters:</strong> more choice and room to negotiate in some college towns, especially for full summer stays.</li>
<li><strong>For hosts:</strong> more competition from other students subletting. A clean, well-photographed listing, a fair price, and flexibility on dates help you stand out.</li>
</ul>
<p>Big cities with large universities, like Boston or New York, behave differently: there is plenty of student supply, but also strong demand from interns and professionals.</p>

<h2>Utilities in summer</h2>
<p>Summer electricity bills can climb fast when the air conditioning runs all day. Hosts and renters should agree up front on how utilities are handled:</p>
<ul>
<li><strong>Included in rent:</strong> simplest, but the host carries the risk of high bills. Some hosts include utilities up to a cap.</li>
<li><strong>Split based on actual bills:</strong> fairest, but requires sharing statements.</li>
<li><strong>Transferred to the renter:</strong> uncommon for short sublets, and not always possible.</li>
</ul>
