<li>Gather five to ten comparable listings for the same months.</li>
<li>Adjust for season, furnishings, and amenities.</li>
<li>Decide how to handle utilities and build them into your price.</li>
<li>Pick a proration method for partial months.</li>
<li>Set a reasonable deposit and disclose any fees.</li>
<li>Watch the response and adjust within a week or two.</li>
