<p>Pricing a sublet is a balancing act. Set the price too high, and your listing sits while you keep paying rent on an empty apartment. Set it too low, and you leave money on the table, or attract a flood of inquiries you cannot keep up with. The right number is usually somewhere in between, and finding it takes a little research rather than guesswork.</p>
<p>This guide walks through a practical method for pricing your sublet: starting from comparable listings, adjusting for season and furnishings, deciding how to handle utilities, and calculating partial months fairly.</p>

<h2>Step 1: Check what you are allowed to charge</h2>
<p>Before you think about market rates, check your lease and local rules. Some leases limit what a tenant may charge a subtenant, and some local laws do too, particularly for rent-stabilized, rent-controlled, or subsidized apartments. In those situations, charging more than your own rent, even with furniture included, may not be allowed or may be capped.</p>
<p>If you have not already, read our guide on <a href="/blog/how-to-sublet-your-apartment-legally/">how to sublet your apartment legally</a>. <em>This is general information, not legal advice; check your lease and local law.</em></p>

<h2>Step 2: Find comparable listings</h2>
<p>Comparable listings, or "comps," are the foundation of a good price. You are looking for places that a renter would realistically consider instead of yours. Search for listings that match yours on:</p>
<ul>
<li><strong>Location:</strong> the same neighborhood, or one with a similar commute to the same places</li>
<li><strong>Size:</strong> number of bedrooms and bathrooms, rough square footage</li>
<li><strong>Type:</strong> entire place versus private room in a shared unit</li>
<li><strong>Furnishing level:</strong> fully furnished, partially furnished, or empty</li>
<li><strong>Dates and length:</strong> a three-month summer sublet competes with other summer sublets, not with year-long leases</li>
<li><strong>Amenities:</strong> laundry, air conditioning, parking, outdoor space, elevator</li>
</ul>
<p>Collect five to ten comps if you can, and note their prices and key features. Ignore outliers on both ends: the listing that is suspiciously cheap may be a scam, and the one that is far above everything else may have been sitting unrented for weeks.</p>
<p>Also look at your own rent as a reference point. It tells you what a landlord charges for a year-long, usually unfurnished lease, which is a different product from a furnished, short-term sublet. Market sublet prices can land above or below it depending on the season and local demand.</p>

<h2>Step 3: Adjust for seasonality</h2>
<p>Demand for sublets rises and falls during the year, and the patterns vary by place:</p>
<ul>
<li><strong>Big cities with internship programs</strong> often see strong summer demand from interns and seasonal workers.</li>
<li><strong>College towns</strong> can be the opposite. When students leave in May, there may be many more sublets than renters, which pushes prices down. Demand picks back up before the fall semester.</li>
<li><strong>Areas near hospitals</strong> may see steadier demand from travel nurses and medical rotations year-round.</li>
<li><strong>Vacation and seasonal areas</strong> follow their own tourism calendar.</li>
</ul>
<p>Look at comps for the same months you are offering, not for a different season. If you are listing in a slow period, pricing a little below the competition can help you fill the place quickly. Our <a href="/blog/summer-sublet-guide/">summer sublet guide</a> covers seasonal dynamics in more depth.</p>

<h2>Step 4: Factor in furnishings and convenience</h2>
<p>A furnished place saves a renter the cost and hassle of buying or renting furniture for a few months. That convenience has real value, and furnished sublets often command higher prices than comparable unfurnished rentals, though by how much depends on the market and on what you include.</p>
<p>Features that renters tend to value include:</p>
<ul>
<li>A comfortable bed with linens and towels provided</li>
<li>A fully equipped kitchen</li>
<li>Fast, reliable Wi-Fi already set up</li>
<li>A real desk and chair for remote work</li>
<li>In-unit laundry</li>
<li>Air conditioning in summer</li>
<li>Parking, in car-dependent areas or dense cities where it is scarce</li>
</ul>
<p>Be honest with yourself: a bed and a couch is not the same as a turnkey apartment. See <a href="/blog/furnished-vs-unfurnished-short-term-rentals/">furnished vs. unfurnished short-term rentals</a> for how renters think about the difference.</p>

<h2>Step 5: Decide how to handle utilities</h2>
<p>Utilities can make a big difference in how your price compares to others. You have a few options:</p>
<table>
<thead><tr><th>Approach</th><th>Pros</th><th>Cons</th></tr></thead>
<tbody>
<tr><td>All utilities included</td><td>Simple, attractive to renters, easy to compare</td><td>You carry the risk of high bills, especially for summer air conditioning or winter heating</td></tr>
<tr><td>Included up to a cap</td><td>Predictable for both sides, limits your risk</td><td>Requires sharing bills if the cap is exceeded</td></tr>
<tr><td>Split by actual bills</td><td>Fair to both parties</td><td>More admin, less predictable for renters</td></tr>
</tbody>
</table>
<p>For most short sublets, including utilities, or including them up to a reasonable cap, is the most renter-friendly choice. If you include them, look at your past bills for the same months and build the expected cost into your price. Whatever you choose, state it clearly in your listing and in your sublease.</p>
<p>Renters often use the <a href="/tools/cost-calculator/">cost calculator</a> to add up rent, utilities, and fees for each listing they consider, so a clear "utilities included" can make your total look more competitive than a slightly lower rent plus unknown bills.</p>

<h2>Step 6: Prorate partial months fairly</h2>
<p>Sublet dates rarely line up perfectly with calendar months. When a renter moves in on the 10th or leaves on the 20th, you need a fair way to charge for the partial month. Common methods include:</p>
<ul>
<li><strong>Daily rate based on the actual month:</strong> monthly rent divided by the number of days in that month, multiplied by the days occupied.</li>
<li><strong>Daily rate based on a standard year:</strong> monthly rent multiplied by 12, divided by 365, multiplied by the days occupied.</li>
</ul>
<p>Either is reasonable; just pick one and write it into the agreement. The <a href="/tools/proration/">proration calculator</a> does the math for you.</p>

<h2>Step 7: Consider the deposit and fees</h2>
<p>A security deposit protects you against damage and unpaid rent, but an unusually large one can scare off good renters. Check your state's rules on deposit limits and return deadlines. If you charge a cleaning fee, state it upfront. Surprise fees create bad first impressions. See our guide on <a href="/blog/security-deposits-for-sublets/">security deposits for sublets</a>.</p>

<h2>Step 8: Test and adjust</h2>
<p>Once your listing is live, pay attention to the response:</p>
<ul>
<li><strong>Lots of inquiries quickly?</strong> Your price may be on the low side. You do not have to raise it, but it is useful to know for next time.</li>
<li><strong>Some inquiries, but people hesitate?</strong> Ask what they are comparing with. You may need better photos or clearer details, not a lower price.</li>
<li><strong>Few or no inquiries after a week or two?</strong> Revisit your comps. A modest price cut, or adding utilities, can make a real difference.</li>
</ul>
<p>Remember the math of an empty month: an unrented month costs you a full month of rent, which usually outweighs a small discount spread across a whole stay.</p>

<h2>Discounts that make sense</h2>
<ul>
<li><strong>Length-of-stay discounts:</strong> A slightly lower monthly rate for a longer stay can be worth it for fewer vacancies and less turnover.</li>
<li><strong>Flexible dates:</strong> If a renter can match your exact dates, that has value to you.</li>
<li><strong>Last-minute pricing:</strong> If your move-out date is approaching and the place is still empty, a modest reduction is usually better than nothing.</li>
</ul>

<h2>Presentation affects price</h2>
<p>Two identical apartments can rent at very different prices depending on how they are presented. Bright, well-composed photos, a clear and honest description, and quick replies all help renters feel confident about paying your asking price. Read our guide on <a href="/blog/how-to-write-a-sublet-listing-that-rents/">how to write a sublet listing that rents</a>.</p>

