<p>Subletting a room in a shared apartment is one of the most affordable ways to live somewhere for a few months. It is also a slightly unusual social situation. You are moving into a household that already has its own rhythms, with people you may have met only once on a video call, and you will be there just long enough for small irritations to matter.</p>
<p>The good news is that most roommate friction comes from unspoken expectations, not bad people. A bit of upfront conversation and some basic courtesy go a long way. This guide covers the etiquette for subtenants moving in, and a few notes for the roommates and hosts on the other side.</p>

<h2>Private room vs. shared room</h2>
<p>Before anything else, be clear about what you are renting.</p>
<ul>
<li><strong>A private room</strong> means your own bedroom, with shared common areas like the kitchen, living room, and often the bathroom. This is the most common type of roommate sublet.</li>
<li><strong>A shared room</strong> means sharing a bedroom with someone else. It is cheaper, but requires much more coordination around sleep schedules, privacy, and belongings.</li>
<li><strong>A private room with private bath</strong> is the most independent option, with only the kitchen and living areas shared.</li>
</ul>
<p>Each setup calls for a different level of coordination. A shared bedroom needs explicit agreements about lights-out times, alarms, phone calls, and guests. A private room needs fewer, but still some.</p>

<h2>Before you move in</h2>
<h3>Meet the roommates</h3>
<p>Ask the host if you can meet the people you will be living with, in person or by video. This is not an interview of anyone's personality. It is a chance for everyone to talk about schedules and expectations. Good questions include:</p>
<ul>
<li>What are your usual schedules? Does anyone work nights or early mornings?</li>
<li>How do you handle cleaning and shared supplies?</li>
<li>How often do people have guests over?</li>
<li>Are there quiet hours?</li>
<li>Is there anything that has caused friction in the past that I should know about?</li>
</ul>
<p>That last question is gold. People will often tell you exactly what matters to them.</p>

<h3>Ask for the house rules</h3>
<p>Many shared apartments have unwritten rules. Ask the host or roommates to spell them out. Better yet, suggest writing them down. Also ask about any rules in the main lease that apply to you, such as pets, smoking, or guest limits. Our list of <a href="/blog/questions-to-ask-before-subletting/">questions to ask before subletting</a> covers the lease and payment side of things.</p>

<h3>Confirm the money</h3>
<p>Be clear on who you pay rent to, how utilities are split, and whether shared items like internet, cleaning supplies, or streaming services are included. Money is a common source of tension in shared housing, and most of it is avoidable with a clear agreement at the start.</p>

<h2>Everyday etiquette</h2>
<h3>The kitchen</h3>
<ul>
<li><strong>Clean as you go.</strong> Wash, dry, and put away your dishes promptly. Dishes left in the sink are one of the most common roommate complaints.</li>
<li><strong>Label or separate your food.</strong> Ask which fridge shelf and cabinet space are yours.</li>
<li><strong>Do not use others' food or condiments without asking.</strong> If you borrow something, replace it.</li>
<li><strong>Ask about shared staples.</strong> Some households split oil, salt, coffee, and dish soap. Others keep everything separate. Follow the house norm.</li>
<li><strong>Wipe down counters and the stove</strong> after cooking.</li>
</ul>

<h3>The bathroom</h3>
<ul>
<li>Keep your toiletries in your own space, or in the area you have been given.</li>
<li>Be mindful of how long you spend there during busy morning hours.</li>
<li>Clean up after yourself: hair in the drain, water on the floor, toothpaste in the sink.</li>
<li>Replace toilet paper when you use the last roll, or follow whatever system the household has.</li>
</ul>

<h3>Common areas</h3>
<ul>
<li>Do not leave your belongings spread across the living room.</li>
<li>Ask before rearranging furniture or putting up decorations.</li>
<li>Share the TV and couch fairly, and check before taking over the space for a long call or a movie night.</li>
</ul>

<h3>Noise</h3>
<p>Respect quiet hours, use headphones for music and videos, and take phone calls in your room. If you work from home and take video calls, find out when roommates are usually around and agree on how to share the space.</p>

<h2>Chores</h2>
<p>Every shared household needs some system for chores, even an informal one. If there is already a rotation or chart, join it. If there is not, offer to take on specific tasks: taking out trash and recycling, cleaning the bathroom on a set schedule, or vacuuming common areas.</p>
<p>A simple shared calendar or note on the fridge works well. The key is that everyone knows what they are responsible for. As a subtenant, it helps to do slightly more than your share early on. It builds goodwill quickly.</p>

<h2>Guests</h2>
<p>Guests are where many roommate conflicts begin. Sensible norms include:</p>
<ul>
<li><strong>Give a heads-up</strong> before having anyone over, especially for groups or late nights.</li>
<li><strong>Ask before overnight guests.</strong> In a shared room, this is essential. In a private room, it is still courteous, and the main lease may limit how long guests can stay.</li>
<li><strong>Your guests are your responsibility.</strong> That includes noise, mess, and respecting house rules.</li>
<li><strong>Do not let a guest become an extra roommate.</strong> A partner who stays five nights a week is effectively living there and using utilities, and it can violate the lease.</li>
</ul>

<h2>Communication</h2>
<p>The best roommate relationships rely on talking about small things before they become big things.</p>
<ul>
<li><strong>Set up a group chat</strong> for practical matters: packages, bills, maintenance, and "I'm having a friend over Friday."</li>
<li><strong>Raise issues early and kindly.</strong> "Hey, could we figure out a dish system? The sink has been piling up" lands far better than a passive-aggressive note.</li>
<li><strong>Use "I" statements.</strong> "I have trouble sleeping when there's noise after midnight" is easier to hear than "You're always loud."</li>
<li><strong>Listen, too.</strong> If someone brings up a concern with you, assume good faith and work on a fix together.</li>
<li><strong>Keep the host informed</strong> about anything that affects the apartment, like a repair issue or a serious conflict.</li>
</ul>

<h2>Respecting the host's space</h2>
<p>If you are living in someone else's room, you are using their furniture, and sometimes their bedding and kitchenware. Treat their things as carefully as you would want yours treated. Do not go through closets or drawers that have been set aside for their belongings. If something breaks, tell the host promptly. It is far better than them discovering it after you have left.</p>

