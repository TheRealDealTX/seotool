<p>You have permission from your landlord, you have figured out your dates, and you have a fair price in mind. Now you need a listing that gets the right people to reach out. A great sublet listing does two jobs at once: it helps good renters quickly see that your place fits their needs, and it helps people for whom it is not a fit move on without wasting anyone's time.</p>
<p>This guide breaks down each part of a strong listing, from the title to the house rules, with practical examples.</p>

<h2>Start with a clear, specific title</h2>
<p>Your title is the first thing renters see in search results. It should answer the most important questions at a glance: what kind of space, where, and when.</p>
<p>Compare these:</p>
<ul>
<li><strong>Weak:</strong> "Amazing apartment, must see!!"</li>
<li><strong>Better:</strong> "Furnished 1BR near downtown, June to August"</li>
<li><strong>Best:</strong> "Sunny furnished 1BR, 5 min walk to subway, in-unit laundry, Jun 1 to Aug 31"</li>
</ul>
<p>Good titles usually include the type of space (studio, 1BR, private room), one or two standout features, and the dates. Skip the exclamation points and all caps; they make a listing look less trustworthy, not more exciting.</p>

<h2>Photos: the most important part of your listing</h2>
<p>Renters decide whether to read your listing based largely on photos. You do not need a professional photographer, just some care.</p>

<h3>Before you shoot</h3>
<ul>
<li><strong>Clean and declutter.</strong> Clear countertops, make the bed, hide cables, put away personal items.</li>
<li><strong>Open every curtain and turn on every light.</strong> Bright photos look more inviting.</li>
<li><strong>Shoot in daytime</strong> when natural light is best.</li>
</ul>

<h3>What to photograph</h3>
<ol>
<li>The main living space, from a corner to show the whole room</li>
<li>The bedroom, with the bed made</li>
<li>The kitchen, showing appliances and counter space</li>
<li>The bathroom</li>
<li>Any workspace, such as a desk by a window</li>
<li>Laundry, outdoor space, parking, or building amenities</li>
<li>The view or the street, if it is a selling point</li>
</ol>

<h3>Shooting tips</h3>
<ul>
<li>Hold your phone horizontally and at about chest height.</li>
<li>Keep vertical lines straight. Tilted walls look odd.</li>
<li>Take several shots of each room and pick the best.</li>
<li>Avoid heavy filters. Renters want to see what the place really looks like.</li>
</ul>

<h2>Write a description that answers questions before they are asked</h2>
<p>A good description is organized, specific, and honest. Many renters skim, so use short paragraphs or a clear structure. Here is a format that works well:</p>

<h3>1. A short summary</h3>
<p>Two or three sentences describing the space and who it suits. For example: "A quiet, furnished one-bedroom on a tree-lined street, ideal for a summer intern or remote worker. Five minutes from the subway and close to groceries and coffee shops."</p>

<h3>2. The space</h3>
<p>Describe the layout and size, and what is included. Be specific: "queen bed," "full kitchen with dishwasher," "desk and ergonomic chair," "window AC in the bedroom."</p>

<h3>3. What is included</h3>
<p>List furnishings and supplies. Renters want to know whether they need to bring sheets, towels, or kitchen gear. A simple list is easiest to read:</p>
<ul>
<li>Linens and towels</li>
<li>Fully equipped kitchen</li>
<li>Wi-Fi (already set up)</li>
<li>In-unit washer and dryer</li>
</ul>

<h3>4. Costs</h3>
<p>Be crystal clear about money: monthly rent, deposit, any fees, and how utilities work. "Utilities included" or "utilities split based on actual bills" should be stated plainly. Renters often compare total costs using tools like our <a href="/tools/cost-calculator/">cost calculator</a>, so clarity works in your favor. If you are unsure about pricing, see <a href="/blog/how-to-price-your-sublet/">how to price your sublet</a>.</p>

<h3>5. Dates and flexibility</h3>
<p>State exact available dates and whether there is any flexibility on move-in or move-out. If you can prorate partial months, say so.</p>

<h3>6. Location and commute</h3>
<p>Describe the neighborhood and nearby transit, groceries, parks, and major employers, campuses, or hospitals. Commute times are especially helpful to interns, travel nurses, and students. Mention parking situations honestly.</p>

<h2>Be honest, especially about the downsides</h2>
<p>It is tempting to gloss over drawbacks, but honesty pays off. A renter who arrives to find a fourth-floor walk-up you described as "easy access" will be unhappy for the entire stay, and may leave early. Being upfront also builds trust and filters out people who would not be a good fit.</p>
<p>Mention things like:</p>
<ul>
<li>Stairs and no elevator</li>
<li>Street noise or a busy nearby bar</li>
<li>No air conditioning, or AC only in certain rooms</li>
<li>Shared laundry in the basement</li>
<li>Roommates who will be staying, and a little about the living arrangement</li>
<li>Any construction nearby</li>
</ul>
<p>Pair each downside with context where you can: "Third-floor walk-up, but the stairs are wide and well lit," or "Street-facing living room, but the bedroom is at the back and quiet."</p>

<h2>Set clear, fair house rules</h2>
<p>House rules help renters understand your expectations. Keep them reasonable, consistent with your master lease, and focused on behavior and care of the home. Common examples:</p>
<ul>
<li>No smoking or vaping indoors</li>
<li>Pets allowed or not allowed, consistent with your lease</li>
<li>Guest policy, such as overnight guests limited to a certain number of nights</li>
<li>Quiet hours</li>
<li>Specific care instructions for plants or special appliances</li>
</ul>
<p><strong>Fair housing matters.</strong> Never include rules or preferences in your listing based on race, color, religion, sex, national origin, disability, familial status, or any other characteristic protected under federal, state, or local law. Describe the space and the rules, not the "ideal" person. If you have roommates who are staying, describe the household's habits and expectations ("we are quiet on weeknights and share cleaning duties") instead of describing who should apply. Be aware that federal, state, and local laws may also restrict how even shared-housing listings are worded. When in doubt, focus on the property and the rules.</p>
