<h2>Build trust</h2>
<p>Renters are rightly cautious about scams, especially when renting remotely. You can help them feel confident:</p>
<ul>
<li>Use real, current photos of your actual place.</li>
<li>Offer a live video tour.</li>
<li>Be willing to share a written sublease before any money changes hands.</li>
<li>Avoid asking for payment by wire, gift card, or crypto.</li>
<li>Mention that your landlord has approved the sublet, if they have.</li>
</ul>
