<p>The temporary phase has its own costs. Plan for:</p>
<ul>
<li>Temporary rent, possibly overlapping with your old place</li>
<li>Storage for your belongings, if you are not moving them yet</li>
<li>Travel to the new city</li>
<li>Application fees and deposits for your long-term apartment</li>
<li>Moving costs for the final move</li>
</ul>
