<h2>If you are a host: scams target you too</h2>
<p>Hosts can be scammed as well. Watch for:</p>
<ul>
<li>Renters who offer to pay more than you asked, or send a check for too much and ask for a refund of the difference</li>
<li>Renters who want to book without asking any questions or seeing the place</li>
<li>Requests to use a specific, unfamiliar payment service</li>
<li>Pressure to hand over keys before payment has fully cleared</li>
</ul>
<p>Wait until funds have actually cleared, not just "appeared," before handing over keys. Banks can make funds available before a check has truly cleared, and a fraudulent check can be reversed days later.</p>

<h2>What to do if you think you have been scammed</h2>
<p>Act quickly. The sooner you act, the better your chances of limiting the damage.</p>
<ol>
<li><strong>Stop all communication and payments</strong> with the suspected scammer.</li>
<li><strong>Contact your bank or payment provider</strong> immediately. Ask whether the payment can be stopped or reversed. For wire transfers, call the sending bank right away.</li>
<li><strong>If you paid with a gift card</strong>, contact the company that issued the card, tell them it was used in a scam, and ask whether they can freeze the funds.</li>
<li><strong>Report it to the Federal Trade Commission</strong> at <strong>ReportFraud.ftc.gov</strong>. Reports help law enforcement track patterns and pursue scammers.</li>
<li><strong>File a report with your local police.</strong> A police report may also be useful for your bank.</li>
<li><strong>Report the listing</strong> to the site where you found it so it can be removed and others are protected.</li>
<li><strong>Keep records</strong> of every message, receipt, screenshot, and payment confirmation.</li>
<li><strong>If you shared personal information</strong> like your Social Security number, visit IdentityTheft.gov for steps to protect yourself.</li>
</ol>
<p>Being scammed is not a sign of foolishness. These schemes are designed by people who do this full-time, and they fool careful, smart people every day. Reporting helps protect the next person.</p>

<h2>The short version</h2>
<ul>
<li>Never pay by wire, gift card, or crypto.</li>
<li>Always see the place live before paying.</li>
<li>Be skeptical of prices far below market.</li>
<li>Slow down when someone pressures you.</li>
<li>Get everything in writing.</li>
<li>Report fraud at ReportFraud.ftc.gov and to local police.</li>
</ul>
