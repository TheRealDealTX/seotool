<p>Rental scams are frustratingly common, and short-term housing is a favorite target. People looking for sublets are often searching from another city, working against a deadline, and renting from an individual rather than a company. Scammers know all of this and design their schemes around it.</p>
<p>The good news is that most rental scams follow a few predictable patterns. Once you know the red flags, they become much easier to spot. This guide covers the warning signs, how to verify a listing before you pay anything, and what to do if you think you have been targeted.</p>

<h2>How rental scams usually work</h2>
<p>Most rental scams fall into a few categories:</p>
<ul>
<li><strong>The phantom listing.</strong> A scammer copies photos and descriptions from a real listing, or invents one entirely, and posts it at an attractive price. There is no apartment, or the apartment exists but the scammer has no right to rent it.</li>
<li><strong>The hijacked listing.</strong> The scammer finds a real home that is for sale or rent and pretends to be the owner, often swapping in their own contact details.</li>
<li><strong>The deposit grab.</strong> The scammer collects a deposit or first month's rent, sometimes from multiple people for the same unit, and disappears.</li>
<li><strong>The overpayment trick.</strong> Common when you are the host. A "renter" sends a check for more than the agreed amount and asks you to send back the difference. The original check later bounces.</li>
</ul>

<h2>Red flags to watch for</h2>
<p>Any one of these should slow you down. Several together should stop you.</p>

<h3>Unusual payment methods</h3>
<p>Be extremely cautious if you are asked to pay by:</p>
<ul>
<li>Wire transfer</li>
<li>Gift cards</li>
<li>Cryptocurrency</li>
<li>Money orders or cash sent by mail</li>
<li>Peer-to-peer payment apps, before you have verified the person and the property</li>
</ul>
<p>These methods are hard or impossible to reverse once money is sent. Legitimate landlords and hosts rarely insist on them. Asking for payment in gift cards, in particular, is a hallmark of fraud.</p>

<h3>"I'm overseas" or "I'm out of town"</h3>
<p>A classic story: the owner is abroad for work, missionary service, or a family emergency, so they cannot show you the place. They will mail you the keys once you send a deposit. This story is used constantly by scammers. A real host who is away can still arrange a live video tour or have a friend, neighbor, or property manager show the unit.</p>

<h3>No tour, or only pre-recorded video</h3>
<p>If the host will not show you the unit in person or on a live video call, be suspicious. Pre-recorded videos and photos can be copied from anywhere. During a live tour, ask the host to show something specific, like the view out a particular window or the inside of a kitchen cabinet, so you know it is happening in real time. Our guide on <a href="/blog/how-to-tour-a-sublet-remotely/">touring a sublet remotely</a> has more tips.</p>

<h3>Rent that is too good to be true</h3>
<p>Scammers often price listings well below comparable places to attract lots of interest quickly. If one listing is dramatically cheaper than everything else in the same neighborhood with similar features, ask yourself why.</p>

<h3>Pressure and urgency</h3>
<p>"Lots of people are interested, so I need the deposit today." "I can only hold it until tonight." Pressure is designed to keep you from thinking clearly or checking details. A legitimate host will usually give you a reasonable amount of time to decide.</p>

<h3>Other warning signs</h3>
<ul>
<li>The host wants to move the conversation off the platform immediately.</li>
<li>Emails or messages contain inconsistent details: a different address, a different name, a different number of bedrooms.</li>
<li>The host asks for sensitive personal information, like your Social Security number or bank login, before you have even seen the unit.</li>
<li>The host does not ask you anything about yourself. Real hosts usually want to know who will be living in their home.</li>
<li>You find the same photos on a different listing with a different name or city.</li>
</ul>

<h2>How to verify a listing and host</h2>
<p>Before you send any money, take these steps:</p>
<ol>
<li><strong>Do a reverse image search</strong> on listing photos. If they show up on a different site under a different address or name, that is a serious warning sign.</li>
<li><strong>Search the address.</strong> Make sure the building exists and matches the listing. Look at it on a map and street-level imagery.</li>
<li><strong>Insist on a live tour</strong>, in person or by video, with the host or a representative inside the actual unit.</li>
<li><strong>Ask about the landlord.</strong> If the host is a tenant subletting, ask whether their landlord has approved the sublet and whether they can show you the relevant part of their lease. You can also check public property records in many counties to see who owns the property.</li>
<li><strong>Get a written agreement</strong> before paying anything. It should include the host's full name, the address, dates, rent, and deposit terms. See our <a href="/blog/sublease-agreement-what-to-include/">sublease agreement checklist</a>.</li>
<li><strong>Pay with a traceable method</strong> that offers some protection, and never pay more than necessary up front.</li>
<li><strong>Trust your instincts.</strong> If something feels off, walk away. There will be other listings.</li>
</ol>

