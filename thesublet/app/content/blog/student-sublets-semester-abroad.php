<p>A semester abroad is one of the best things you can do in college. Paying rent on an empty room back home for four months is one of the worst. On the flip side, every semester brings students who need a place for just a few months: visiting students, co-op students, transfer students waiting for housing, and students coming back from their own time away.</p>
<p>Those two groups need each other. This guide covers both sides: how to sublet your room while you are away, and how to find a semester sublet when you are the one arriving. It also covers the part people most often get wrong, which is timing.</p>

<h2>Part 1: Subletting your room while you study abroad</h2>

<h3>Start with your lease and your roommates</h3>
<p>Before you post anything, read your lease. Many student leases, especially at large off-campus apartment complexes, have specific rules about subletting. Some allow it with written approval, some charge a fee, some require the subtenant to apply, and some prohibit it. If you live in university housing, subletting is often not allowed at all, though some schools have their own room-swap or release process. Check with your housing office.</p>
<p>If you are on a joint lease with roommates, they deserve a say. They will be living with your subtenant, and on many joint leases, all tenants can be on the hook if rent goes unpaid. Talk to them early, agree on what kind of subtenant would work for the household, and keep them in the loop. Our guide to <a href="/blog/how-to-sublet-your-apartment-legally/">subletting legally</a> explains the basics, and <a href="/blog/subletting-vs-assigning-a-lease/">subletting vs. assigning a lease</a> is worth reading if you are not planning to come back.</p>

<h3>Know your academic calendar, and theirs</h3>
<p>Timing is where student sublets succeed or fail. Your program abroad may start before or after your home school's semester, and it may end on a completely different date. Map out:</p>
<ul>
<li>The date you need to move out (and pack, and store your things)</li>
<li>The date you will be back</li>
<li>The start and end dates of the semester your subtenant is likely to follow</li>
</ul>
<p>Most US schools run either semesters (roughly late August to December and January to May) or quarters (fall, winter, spring, summer, each about ten to eleven weeks). If your school is on quarters and you are gone for one quarter, your ideal subtenant is someone on the same schedule. If you are gone from January to May, look for a spring semester student, a visiting researcher, or an intern starting a winter co-op.</p>

<h3>Post early</h3>
<p>Students arriving for spring semester often start looking in October and November. Students arriving in fall start in the spring or summer before. If you post just two weeks before you leave, you will be competing with everyone else who waited too long, and you may need to drop your price. Posting a couple of months ahead gives you time to find the right person.</p>

<h3>Price it fairly</h3>
<p>A room near campus during the semester is in demand. A room near campus in the middle of summer, at many schools, is not. Look at comparable listings and price for the season. Our <a href="/blog/how-to-price-your-sublet/">sublet pricing guide</a> walks through it. Many students offer their room at or slightly below their own rent, especially if it is furnished and utilities are included, simply to avoid paying for an empty room.</p>

<h3>Prepare the room</h3>
<ul>
<li>Clear at least half the closet and a few drawers, or more if you can.</li>
<li>Store valuables, important documents, and anything sentimental elsewhere: with family, a friend, or a storage unit.</li>
<li>Leave clean sheets and a towel if you are offering the room furnished.</li>
<li>Write a short house guide: Wi-Fi password, trash day, how the thermostat works, and roommate norms.</li>
<li>Take dated photos of the room's condition before you go.</li>
</ul>

<h3>Handle the money and paperwork before you fly</h3>
<p>Once you are overseas, a time difference and spotty connectivity make everything harder. Before you leave, sign a <a href="/blog/sublease-agreement-what-to-include/">written sublease agreement</a>, collect the deposit and first month's rent, and set up a payment method that works internationally. Name a local contact (a roommate, friend, or family member) who can hand off keys and deal with any in-person issue while you are gone.</p>

<h3>Mail and packages</h3>
<p>Ask a roommate to collect your mail, or set up mail forwarding to a family member's address. Let your subtenant know what to do with anything addressed to you.</p>

<h2>Part 2: Finding a semester sublet</h2>

<h3>Who is looking</h3>
<p>Semester sublet seekers include visiting and exchange students, students on co-op or clinical rotations, graduate students starting mid-year, students who did not get campus housing, and students returning from abroad whose original lease ended. Visiting researchers and short-term faculty often look for the same kinds of places.</p>

<h3>When to start</h3>
<ul>
<li><strong>For fall:</strong> Start looking in late spring or early summer. Inventory can be thin because many students sign new twelve-month leases for fall.</li>
<li><strong>For spring:</strong> Start in October or November. This is when many students headed abroad start posting.</li>
<li><strong>For summer:</strong> Start in March or April. Summer is often the easiest time to find a sublet near campus, because so many students leave. Our <a href="/blog/summer-sublet-guide/">summer sublet guide</a> covers it.</li>
</ul>

<h3>Match the dates carefully</h3>
<p>Your semester and the host's semester may not line up. If you need a place from mid-January through mid-May, and the host is away from early January through late June, you may be able to negotiate a shorter stay or a lower price for the dates you actually need. Ask about prorating partial months; our <a href="/tools/proration/">proration calculator</a> helps you agree on fair numbers.</p>

<h3>Ask the right questions</h3>
<p>Beyond the usual questions about rent and utilities, ask:</p>
<ul>
<li>Has the landlord or property manager approved the sublet?</li>
<li>Who are the roommates, and can I meet them by video?</li>
<li>How far is it from campus, and how do people usually get there?</li>
<li>Is the room furnished? Is there a desk?</li>
<li>Is there a quiet place to study?</li>
</ul>
<p>Our full list is in <a href="/blog/questions-to-ask-before-subletting/">questions to ask before subletting</a>, and if you will be sharing an apartment, read up on <a href="/blog/roommate-sublets-shared-housing-etiquette/">roommate sublet etiquette</a>.</p>

<h3>Watch for scams</h3>
<p>Students are frequent targets of rental scams, partly because many are arriving from far away and cannot see a place in person. Never pay a deposit before verifying the person actually has the right to rent the room. Ask for a live video tour, not just photos, and be wary of anyone who pressures you to pay by wire or gift card. Our <a href="/blog/how-to-tour-a-sublet-remotely/">remote tour guide</a> and <a href="/safety/">safety page</a> explain what to look for.</p>

