<p>Many sublets are rented sight unseen in person. Travel nurses accept contracts weeks before they arrive, interns line up summer housing from campus, and people relocating for work often cannot fly out just to see an apartment. Remote tours make this possible, but they also create an opening for scammers who rely on renters not being able to check things for themselves.</p>
<p>The good news: a well-run remote tour, plus a few verification steps, gets you most of the confidence of an in-person visit. Here is how to do it.</p>

<h2>The golden rule</h2>
<p><strong>Do not send any money, not a deposit, not a holding fee, not first month's rent, until you have seen the place on a live video call and verified the person has the right to rent it.</strong></p>
<p>Almost every sublet scam depends on breaking this rule. The scammer copies photos from a real listing, offers a great price, and creates urgency so you pay before you have time to check. If you hold firm on this one point, you avoid most of the risk.</p>

<h2>Step 1: Insist on a live video tour</h2>
<p>Photos and pre-recorded videos can be copied from anywhere. A live video call is much harder to fake, because the person has to actually be inside the apartment and respond to you in real time.</p>
<h3>Set it up</h3>
<ul>
<li>Use any common video calling app. FaceTime, Zoom, Google Meet, or WhatsApp video all work.</li>
<li>Schedule it in daylight if possible, so you can see natural light and the view.</li>
<li>Ask the host to use the rear camera and move slowly.</li>
<li>Have your questions written down in advance.</li>
</ul>
<h3>What to ask them to show you</h3>
<ol>
<li><strong>Start outside.</strong> Ask them to show the building entrance and the street sign or a nearby landmark. Compare with a map's street view.</li>
<li><strong>The unit number on the door.</strong> Make sure it matches the listing.</li>
<li><strong>Every room,</strong> including closets, the bathroom, and the kitchen.</li>
<li><strong>Turn things on.</strong> Run a faucet, flush the toilet, open the fridge, turn on the stove. It tells you things work and confirms the tour is live.</li>
<li><strong>The view out the windows.</strong> This is surprisingly useful for matching to a map.</li>
<li><strong>Something specific and unscripted.</strong> "Can you open the second kitchen drawer?" or "Can you hold up three fingers next to the thermostat?" A real host will laugh and do it. Someone playing back a video cannot.</li>
<li><strong>Noise and light.</strong> Ask them to stay quiet for a moment so you can hear street noise.</li>
</ol>
<p>Compare what you see with the listing photos. Different furniture is not necessarily a red flag if the listing is old, but a completely different layout is.</p>

<h2>Step 2: Verify the person has access and the right to rent</h2>
<p>A live tour proves someone is inside the apartment. It does not prove they are the tenant or owner, or that they are allowed to sublet. A few more checks help close that gap.</p>
<h3>Ask for proof of tenancy or ownership</h3>
<p>It is reasonable to ask a host to show something that ties them to the address: the relevant page of their lease with their name and the address (they can cover rent amounts and other sensitive details), a recent utility bill, or the landlord's written approval of the sublet. Hosts who are legitimate usually understand why you ask.</p>
<h3>Ask about landlord approval</h3>
<p>Many leases require landlord permission to sublet. Ask whether they have it, and whether you can see it. Even when a host is genuine, an unapproved sublet can end abruptly. Our guide to <a href="/blog/how-to-sublet-your-apartment-legally/">subletting legally</a> explains why this matters.</p>
<h3>Check public records</h3>
<ul>
<li><strong>Property records.</strong> Many counties make property ownership records searchable online through the assessor or recorder's office. If someone claims to own a home, see whether the name matches. Not every county offers this, and records may list an LLC or trust, so a mismatch is a reason to ask questions, not automatic proof of fraud.</li>
<li><strong>The building.</strong> For an apartment, look up the building or management company. Search the address together with words like "scam" or "rental fraud" to see if the listing has been reported.</li>
<li><strong>Reverse image search.</strong> Run the listing photos through a reverse image search. If the same photos appear in a listing in a different city or under a different name, be very cautious.</li>
</ul>
<h3>Talk to someone else connected to the place</h3>
<p>If there are roommates staying, ask to meet them on the video call. If the building has a front desk or management office, you can call to confirm basic facts, such as whether the unit exists. Do not expect them to share private information about tenants.</p>

<h2>Step 3: Watch for red flags</h2>
<ul>
<li>The host refuses a live video tour, or keeps postponing it.</li>
<li>They say they are out of the country and will mail you the keys after you pay.</li>
<li>They ask for payment by wire transfer, gift cards, cryptocurrency, or a payment app set to "friends and family."</li>
<li>The price is far below comparable listings, and there is pressure to decide today.</li>
<li>They want to move the conversation off-platform immediately.</li>
<li>Their story keeps changing, or they cannot answer basic questions about the building.</li>
<li>They ask for sensitive personal information early, such as your Social Security number or bank login.</li>
</ul>
<p>One red flag might have an innocent explanation. Two or more is a strong signal to walk away. Our guide to <a href="/blog/how-to-avoid-rental-scams/">avoiding rental scams</a> covers more patterns, and our <a href="/safety/">safety page</a> lists what to do if something feels wrong.</p>

<h2>Step 4: Get it in writing and pay safely</h2>
<p>Once you are satisfied, sign a written <a href="/blog/sublease-agreement-what-to-include/">sublease agreement</a> that names both parties, the address, the dates, rent, deposit, and what is included. Pay with a method that leaves a record and, ideally, offers some recourse. Keep copies of every message, receipt, and the agreement.</p>
<p>If you can, ask a local friend or colleague to drop by and see the place in person before you move. It is not always possible, but it is a strong extra check.</p>

<h2>Other things a remote tour should cover</h2>
<p>Verification is the priority, but you also want to know whether you will like living there. During the call, ask about:</p>
<ul>
<li>Water pressure and hot water</li>
<li>Heating and cooling, and how well they work</li>
<li>Wi-Fi speed (ask them to run a quick speed test)</li>
<li>Cell signal inside the unit</li>
<li>Laundry, parking, and package delivery</li>
<li>Noise from neighbors, the street, or nearby businesses</li>
<li>Closet and drawer space that will be free for you</li>
</ul>
<p>For more, see our full list of <a href="/blog/questions-to-ask-before-subletting/">questions to ask before subletting</a>. If you are measuring whether your things will fit, the <a href="/tools/room-planner/">room planner</a> can help you sketch the space from the dimensions the host gives you.</p>

