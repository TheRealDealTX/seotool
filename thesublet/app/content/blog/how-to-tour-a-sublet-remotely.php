<h2>Quick checklist</h2>
<ul>
<li>Live video tour, starting outside the building</li>
<li>Unscripted requests to confirm it is live</li>
<li>Proof the host lives there or owns it</li>
<li>Landlord approval of the sublet</li>
<li>Public records and reverse image search</li>
<li>Written agreement</li>
<li>Traceable payment, and no money until all of the above</li>
</ul>
