<h2>Special situations</h2>

<h3>Travel nurses</h3>
<p>Pack scrubs, comfortable work shoes, compression socks if you use them, blackout curtains or a sleep mask for night shifts, and copies of your licenses and certifications. Our <a href="/blog/travel-nurse-housing-guide/">travel nurse housing guide</a> covers more.</p>

<h3>Interns</h3>
<p>Prioritize work clothes and a garment steamer or wrinkle spray. Many offices are business casual, but it is better to arrive with a couple of sharper outfits. See the <a href="/blog/intern-housing-guide-by-city/">intern housing guide</a>.</p>

<h3>Students</h3>
<p>Bring school supplies, a laptop stand, and anything you need for your program. If you are subletting during a semester abroad, our guide to <a href="/blog/student-sublets-semester-abroad/">student sublets</a> has helpful tips.</p>

<h3>Relocating for work</h3>
<p>If you are using a sublet as a landing pad while you find a permanent home, keep most of your belongings in storage and pack only what you need for a few months. Read more in <a href="/blog/relocating-for-work-temporary-housing/">relocating for work: temporary housing</a>.</p>

<h2>Arrival day checklist</h2>
<ol>
<li>Do a walkthrough and take date-stamped photos of every room before unpacking.</li>
