<li>Test the Wi-Fi, appliances, locks, and smoke detectors.</li>
<li>Find the circuit breaker, water shutoff, and fire extinguisher.</li>
<li>Make a quick grocery and supplies run.</li>
<li>Unpack fully. Living out of a suitcase for three months is no fun.</li>
