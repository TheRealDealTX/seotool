<p>One of the best things about a furnished sublet is that you do not have to move your whole life. No couch to haul, no bed frame to assemble, no truck to rent. But "furnished" means different things to different hosts, and the difference between a smooth first week and a frustrating one often comes down to a few small items you either remembered or did not.</p>
<p>This guide will help you pack smart for a stay of one to twelve months. For an interactive version you can check off as you go, try our <a href="/tools/packing-checklist/">packing checklist tool</a>.</p>

<h2>Step 1: Ask your host exactly what is included</h2>
<p>Before you pack anything, get a clear list from your host. "Fully furnished" might mean a stocked kitchen, fresh linens, and a hair dryer, or it might mean a bed, a couch, and a table. Ask specifically about:</p>
<ul>
<li>Bed linens, pillows, and blankets</li>
<li>Towels</li>
<li>Kitchen basics: pots, pans, knives, cutting board, dishes, glasses, utensils</li>
<li>Small appliances: coffee maker, microwave, toaster, kettle</li>
<li>Cleaning supplies and a vacuum</li>
<li>Laundry: in-unit machines, building laundry room, or neither</li>
<li>Iron and ironing board, or steamer</li>
<li>Hangers and drawer space</li>
<li>Wi-Fi, and whether it is already set up</li>
<li>Desk and chair, if you will work from home</li>
<li>Fans, heaters, or air conditioning</li>
</ul>
<p>Write the answers down. This one conversation can save you from carrying a heavy bag of towels across the country, or from arriving at midnight to find there are no sheets on the bed. Our guide on <a href="/blog/furnished-vs-unfurnished-short-term-rentals/">furnished vs. unfurnished short-term rentals</a> explains more about what to expect.</p>

<h2>Step 2: Pack the essentials</h2>
<p>These are items almost everyone should bring, regardless of what the host provides.</p>

<h3>Documents and money</h3>
<ul>
<li>Government-issued ID</li>
<li>A copy of your sublease agreement and the host's contact information</li>
<li>Offer letter or work contract, if relevant (useful for parking permits or proving local employment)</li>
<li>Health insurance card</li>
<li>Credit or debit cards, plus a little cash</li>
<li>Any prescriptions, with enough supply to last until you can refill locally</li>
</ul>

<h3>Clothing</h3>
<ul>
<li>Work or school clothes for your typical week</li>
<li>Casual clothes and pajamas</li>
<li>Layers for the local climate and season, including a rain jacket</li>
<li>Comfortable walking shoes, plus any work-specific footwear</li>
<li>Workout clothes if you exercise</li>
<li>One nicer outfit for unexpected events</li>
</ul>
<p>If laundry is available, pack about one to two weeks of clothing, no matter how long your stay. You can do laundry. For longer stays across seasons, consider shipping a box of seasonal clothes later instead of packing everything up front.</p>

<h3>Toiletries and health</h3>
<ul>
<li>Daily toiletries, in travel sizes to get started (you can buy full sizes when you arrive)</li>
<li>Medications and a basic first aid kit</li>
<li>Glasses, contacts, and solution</li>
<li>Any personal care items that are hard to find</li>
</ul>

<h3>Tech</h3>
<ul>
<li>Phone, laptop, and chargers</li>
<li>A power strip or extension cord, since older apartments often have few outlets where you need them</li>
<li>Headphones</li>
<li>A portable battery pack</li>
</ul>

<h2>Step 3: Pack the "comfort" items</h2>
<p>These small things make a temporary place feel like yours. They take up little space and pay off every day.</p>
<ul>
<li><strong>Your own pillow,</strong> or at least a pillowcase. Sleep is everything in a new place.</li>
<li><strong>A favorite mug or water bottle.</strong></li>
<li><strong>A throw blanket</strong> for the couch.</li>
<li><strong>A few photos</strong> or small decorations that do not need nails.</li>
<li><strong>A small speaker</strong> for music while you cook.</li>
<li><strong>A sleep mask and earplugs</strong> if you are a light sleeper or working nights.</li>
</ul>

<h2>Step 4: Fill the gaps the host does not cover</h2>
<p>Based on your host's answers, you may want to bring or buy on arrival:</p>
<ul>
<li>A set of sheets and a towel, if not provided or if you prefer your own</li>
<li>A good kitchen knife, if you love to cook (rental kitchens are notorious for dull knives)</li>
<li>Coffee gear you cannot live without</li>
<li>Hangers, which are cheap but surprisingly often missing</li>
<li>A small desk lamp if you will be working from home</li>
<li>A fan for summer stays in older buildings</li>
</ul>
<p>Before buying anything bulky, ask whether the host has it stored somewhere. Many hosts have spare items in a closet.</p>

<h2>What not to pack</h2>
<ul>
<li><strong>Furniture.</strong> That is the point of a furnished sublet.</li>
<li><strong>Full-size bottles</strong> of shampoo, detergent, and cleaners. Buy them locally.</li>
<li><strong>Your whole kitchen.</strong> Bring one or two favorite tools at most.</li>
<li><strong>Large decorative items.</strong> You probably cannot hang things on walls anyway.</li>
<li><strong>Anything you would be devastated to lose.</strong> Keep valuables to a minimum.</li>
</ul>

