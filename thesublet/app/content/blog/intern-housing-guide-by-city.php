<p>Landing a summer internship in a big city is exciting. Figuring out where you are going to live for ten or twelve weeks is usually less exciting. Most landlords want a year-long lease, hotels are out of the question for a full summer, and you may be searching from a dorm room hundreds of miles away.</p>
