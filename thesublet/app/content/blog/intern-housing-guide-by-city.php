<h3>San Francisco Bay Area</h3>
<p>Bay Area internships are spread across San Francisco, the Peninsula, and the South Bay, so the first question is where your office actually is.</p>
<ul>
<li>If your office is in San Francisco, look at neighborhoods with good Muni or BART access to it.</li>
<li>If your office is on the Peninsula or in the South Bay, living in San Francisco and commuting can be long. Check whether your company runs shuttles, and compare with living closer to work.</li>
<li>San Francisco summers can be cool and foggy, especially on the west side of the city. Pack layers.</li>
