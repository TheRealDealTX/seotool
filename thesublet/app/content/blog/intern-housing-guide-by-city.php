<h2>Shared vs. private: a trade-off worth considering</h2>
<p>Many interns save significantly by renting a private room in a shared apartment rather than a whole studio. You get a lower rent, often a better location, and built-in company in a new city. The trade-off is less privacy and the need to get along with roommates. If you go that route, our guide to <a href="/blog/roommate-sublets-shared-housing-etiquette/">roommate sublet etiquette</a> will help.</p>

<h2>City-by-city notes</h2>
<p>These tips are general and focus on patterns that tend to hold year after year. Always check current listings and commute times for your specific office.</p>

<h3>New York City</h3>
<p>New York has one of the deepest summer sublet markets in the country, thanks to its huge student population and the number of residents who leave for the summer. It is also competitive and fast-moving.</p>
<ul>
<li>Focus on commute rather than borough. A place in Brooklyn or Queens near the right subway line can get you to a Midtown or Lower Manhattan office faster than a Manhattan apartment on the wrong line.</li>
<li>Many NYC apartments do not have in-unit laundry or elevators. Ask.</li>
<li>Summers are hot and humid. Confirm there is air conditioning, at least in the bedroom.</li>
<li>Many universities in the city empty out in summer, which can open up sublet options near campuses.</li>
</ul>
