<h2>Start with the basics: timing</h2>
<p>Most summer internships start between late May and mid-June and run ten to twelve weeks. Housing searches tend to follow a rough pattern:</p>
<ul>
<li><strong>As soon as your offer is signed:</strong> Figure out your dates, your office address, and your budget. Ask your employer whether they offer a housing stipend, corporate housing, or a list of recommended options. Some do.</li>
<li><strong>Early spring:</strong> Many summer sublets get listed as students and young professionals make their own summer plans. This is a good time to start browsing seriously.</li>
<li><strong>Four to eight weeks before your start date:</strong> Aim to have your housing locked in by now. You can find places later, but options thin out and stress goes up.</li>
</ul>
<p>Our <a href="/blog/summer-sublet-guide/">summer sublet guide</a> covers seasonal timing in more depth.</p>

<h2>Budgeting for an internship summer</h2>
<p>Rent will likely be your biggest expense, but it is not the only one. Before you set a housing budget, add up:</p>
<ul>
<li>Your expected take-home pay after taxes, or your stipend</li>
<li>Any housing stipend or relocation support from your employer</li>
<li>Commuting costs (transit passes, parking, bike share)</li>
<li>Food, including the inevitable team lunches and happy hours</li>
<li>Travel to and from the city</li>
<li>A cushion for surprises</li>
