<p>The end of a sublet sneaks up on you. One week you are settled in, and the next you are juggling a new job, a flight, or the start of a semester, with a bag of someone else's towels to wash and a deposit you would very much like back.</p>
<p>A smooth move-out protects your deposit, keeps things friendly with your host, and saves you from frantic texts after you have left town. This checklist walks through what to do from two weeks out to the day after you leave.</p>

<h2>Two weeks before</h2>
<h3>Confirm the details with your host</h3>
<ul>
<li><strong>Your move-out date and time.</strong> Make sure you both have the same date. If the host is returning that day, agree on a time that gives you room to clean and pack.</li>
<li><strong>How keys will be returned.</strong> In person, a lockbox, a neighbor, the front desk, or by mail.</li>
<li><strong>Whether a walkthrough will happen,</strong> and with whom.</li>
<li><strong>Cleaning expectations.</strong> Does the host want linens washed? Should the fridge be empty? Is there a cleaning fee already, or are you expected to clean?</li>
<li><strong>Deposit return.</strong> Re-read your <a href="/blog/sublease-agreement-what-to-include/">sublease agreement</a> for the timeline and method, and confirm where the money should go.</li>
</ul>
<p>Put the answers in a message so there is a written record.</p>

<h3>Book your move</h3>
<p>If you are taking more than a couple of suitcases, reserve a moving van, movers, or shipping now. If the building requires booking an elevator or loading dock, do that too.</p>

<h3>Start using up food</h3>
<p>Plan meals around what is in the fridge and pantry so you are not throwing away groceries on the last day.</p>

<h2>One week before</h2>
<h3>Set up mail forwarding</h3>
<p>If you had mail sent to the sublet, update your address with anyone who sends you mail: your bank, employer, school, subscriptions, and online stores. The US Postal Service offers mail forwarding; you can request it online or at a post office. Since a sublet is often temporary, think about whether a temporary forwarding request makes sense for you. Also, leave a note for your host or roommates with your forwarding address in case anything slips through.</p>

<h3>Cancel or transfer anything in your name</h3>
<p>If you set up utilities, internet, or a parking permit in your name, arrange to cancel or transfer it effective on your move-out date. Check whether any equipment, like a modem or router, needs to be returned to the provider.</p>

<h3>Start packing</h3>
<p>Pack anything you will not need in the final week. Keep a running list of items to double-check: chargers, things in the shower, items in the freezer, coats in the hall closet. Our <a href="/tools/packing-checklist/">packing checklist</a> works for moving out as well as moving in.</p>

<h3>Separate your things from the host's</h3>
<p>After a few months, it is easy to lose track of what is yours. Go through drawers, closets, and the kitchen and make sure you are not packing the host's items, or leaving yours behind.</p>

<h2>The last few days: cleaning</h2>
<p>Aim to leave the place at least as clean as you found it. Check your move-in photos to remember what "as you found it" looked like.</p>

<h3>Kitchen</h3>
<ul>
<li>Empty, wipe out, and remove anything spoiled from the fridge and freezer</li>
<li>Clean the stovetop, oven (if used), and microwave</li>
<li>Wash, dry, and put away all dishes, pots, and utensils in their original spots</li>
<li>Wipe counters, cabinet fronts, and the sink</li>
<li>Empty and clean the trash can</li>
</ul>

<h3>Bathroom</h3>
<ul>
<li>Clean the toilet, sink, shower or tub, and mirror</li>
<li>Clear hair from drains</li>
<li>Remove all your toiletries, including from the shower and under the sink</li>
<li>Wipe surfaces and mop the floor</li>
</ul>

<h3>Bedroom and living areas</h3>
<ul>
<li>Wash the bedding and towels you used, and remake the bed if the host prefers</li>
<li>Vacuum or sweep and mop floors, including under the bed</li>
<li>Dust surfaces and wipe light switches and door handles</li>
<li>Return furniture to its original positions</li>
<li>Remove any adhesive hooks or wall decorations carefully, following the product's removal instructions</li>
</ul>

<h3>Everywhere</h3>
<ul>
<li>Take out all trash and recycling</li>
<li>Check every closet, drawer, cabinet, and outlet for your belongings</li>
<li>Close and lock all windows</li>
<li>Set the thermostat as the host requested</li>
</ul>

<h2>Repairs and damage</h2>
<p>If something broke during your stay, tell your host before you leave rather than leaving it to be discovered. Being upfront usually leads to a fairer outcome. Small fixes, like patching a nail hole or tightening a loose cabinet handle, are often worth doing yourself if your agreement allows it. For anything bigger, discuss it with the host.</p>
<p>Remember that normal wear and tear, the ordinary aging that comes from living somewhere, is generally different from damage. Our guide to <a href="/blog/security-deposits-for-sublets/">security deposits for sublets</a> explains the difference and how deposits typically work.</p>

<h2>Move-out day</h2>
<h3>Take condition photos and video</h3>
<p>Once everything is clean and packed, walk through every room and take photos and a video, ideally from the same angles as your move-in photos. Include the inside of the fridge, oven, and cabinets, and close-ups of any spots that were already damaged when you moved in. Send them to your host the same day, so you both have a dated record.</p>

<h3>Do the walkthrough</h3>
<p>If the host or their representative can do a walkthrough, great. If everything looks good, ask them to confirm it in a message. If they spot an issue, discuss it then and there while you can both see it.</p>

<h3>Return every key</h3>
<p>Return all keys, fobs, garage remotes, mailbox keys, and parking passes. Count them against what you received. If you are leaving keys in a lockbox or with a neighbor, send a message and photo confirming you have done so.</p>

<h3>Final sweep</h3>
<p>Before closing the door for the last time, do one more pass of every room. Check the shower, the back of the closet, behind doors, and the freezer. Chargers and items in the freezer are some of the most commonly forgotten things.</p>

<h2>After you leave</h2>
<ul>
<li><strong>Follow up on the deposit.</strong> If the agreed return date passes without word, send a polite reminder with your photos attached.</li>
<li><strong>Check on mail forwarding.</strong> Make sure mail is arriving at your new address.</li>
<li><strong>Confirm any canceled services</strong> have a final bill and are closed.</li>
<li><strong>Leave a kind note or review</strong> if the host was great. It helps future subtenants and builds a culture of trust.</li>
</ul>

