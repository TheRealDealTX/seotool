<p>Security deposits cause more friction in sublets than almost anything else. The amounts are not always huge, but the arrangements are often informal, the people involved may not know each other well, and the person holding the money may live across the country by the time it is due back. A little structure up front prevents most of the stress.</p>
<p>This guide covers common practices for sublet deposits, how to document condition, and how hosts and subtenants can both protect themselves. It is general information, not legal advice. Deposit rules are set largely by state and sometimes local law, and they vary, so check your lease and the rules where the property is located.</p>

<h2>Why sublet deposits are different</h2>
<p>In a standard lease, the landlord collects the deposit and is responsible for returning it under the applicable law. In a sublet, there are often two deposits in play:</p>
<ul>
<li><strong>The original tenant's deposit,</strong> held by the landlord under the main lease.</li>
<li><strong>The subtenant's deposit,</strong> usually held by the original tenant (the host).</li>
</ul>
<p>The landlord typically looks to the original tenant for any damage when the main lease ends. That is why hosts collect their own deposit from the subtenant: it protects them if something is damaged during the sublet. It also means the subtenant's deposit is in the hands of an individual, not a property management company, which is why clear terms matter.</p>
<p>Whether state deposit laws apply to a tenant who sublets to another person can depend on the state and the specifics. If the amount is significant or a dispute arises, a local tenant resource or attorney can tell you how the rules apply.</p>

<h2>Common practices</h2>

<h3>How much?</h3>
<p>There is no universal amount. Many sublet deposits fall around one month's rent, but it varies with the length of stay, the value of the furnishings, and local norms. Some states cap how much a landlord can collect as a deposit. If you are the host, it is wise to stay within any cap that applies where you live and to keep the amount reasonable for a short stay.</p>

<h3>What can it cover?</h3>
<p>Deposits generally exist to cover unpaid rent and damage beyond normal wear and tear. Normal wear and tear means the ordinary aging that happens when people live in a space: light scuffs, minor carpet wear, small nail holes from hanging a picture, faded paint. Damage means things like broken furniture, large stains, holes in walls, or pet damage where pets were not allowed. Where exactly the line falls is often the subject of disputes, so describe expectations clearly in your agreement.</p>

<h3>When is it returned?</h3>
<p>Many states set a deadline for landlords to return deposits or provide an itemized list of deductions, often within a few weeks of move-out. Even if you are not sure those rules apply to your sublet, a clear return date in your agreement avoids confusion. A reasonable sublease will specify the timeline, the payment method, and that any deductions will be itemized with explanation.</p>

<h2>Put it in writing</h2>
<p>Your <a href="/blog/sublease-agreement-what-to-include/">sublease agreement</a> should state:</p>
<ul>
<li>The deposit amount and the date it was paid</li>
<li>Who holds it</li>
<li>What it can be used for</li>
<li>How and when it will be returned</li>
<li>How deductions will be documented</li>
<li>A forwarding address or payment details for the return</li>
</ul>
