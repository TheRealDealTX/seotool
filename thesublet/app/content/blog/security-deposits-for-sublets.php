<h2>Document the condition at move-in</h2>
<p>Photos and video at move-in are the single best tool for avoiding deposit disputes. They protect both sides: the host can show what was damaged, and the subtenant can show what was already there.</p>
<h3>How to do it well</h3>
<ol>
<li><strong>Walk through together if you can.</strong> If not, the subtenant should do it within the first day and send the results to the host.</li>
<li><strong>Take a video walkthrough of every room.</strong> Narrate as you go: "Small scratch on the dresser top, stain on the left side of the rug."</li>
<li><strong>Take close-up photos of existing damage.</strong> Include something for scale, like a coin or your hand.</li>
<li><strong>Check inside things.</strong> Fridge, oven, microwave, cabinets, drawers, closets, under the sink.</li>
<li><strong>Test appliances and fixtures.</strong> Faucets, toilets, lights, heat, AC, and anything electronic that comes with the place.</li>
<li><strong>Write a short inventory.</strong> List furniture, kitchenware, linens, and electronics included, especially in a <a href="/blog/furnished-vs-unfurnished-short-term-rentals/">furnished rental</a>.</li>
<li><strong>Send it in writing.</strong> Email or message the photos, video link, and inventory to the other party so there is a dated record both of you have.</li>
</ol>
<p>Phone photos typically carry a date in their metadata, but sending them to each other on move-in day creates a clearer shared record.</p>

<h2>During the stay</h2>
<ul>
<li><strong>Report problems promptly.</strong> If the dishwasher leaks or a window cracks, tell the host right away in writing. A small issue reported early is less likely to become a deposit dispute later.</li>
<li><strong>Do not make changes without permission.</strong> Painting, mounting a TV, or rearranging furniture into storage can all cause problems at move-out.</li>
<li><strong>Keep rent current.</strong> Unpaid rent is a common reason for deductions.</li>
</ul>

<h2>Document the condition at move-out</h2>
<p>Repeat the same process when you leave. Clean first, then photograph and video every room from the same angles as at move-in. Return all keys and get confirmation in writing. Our <a href="/blog/moving-out-checklist-for-sublets/">moving-out checklist for sublets</a> covers cleaning and the rest of the final steps.</p>
<p>Ideally, do a final walkthrough with the host or their representative. If you agree that everything is fine, ask them to confirm that in a message. That one sentence can save you weeks of back-and-forth.</p>

<h2>For hosts: returning the deposit fairly</h2>
<ul>
<li>Inspect promptly after move-out and compare with the move-in record.</li>
<li>Deduct only for damage beyond normal wear and tear or unpaid amounts under your agreement.</li>
<li>Itemize any deduction with a brief description and the cost, and keep receipts or quotes.</li>
<li>Return the balance by the date in your agreement, and by any legal deadline that applies.</li>
<li>If you are unsure about a deduction, a conversation usually works better than a surprise.</li>
</ul>
<p>Hosts who are fair and prompt about deposits tend to get better subtenants over time, because word gets around and reviews matter.</p>

<h2>If there is a dispute</h2>
<ol>
<li><strong>Start with a calm, written conversation.</strong> Share your photos and ask for the specifics behind any deduction.</li>
<li><strong>Offer a compromise if the issue is genuinely ambiguous.</strong> Splitting the cost of a disputed item is often cheaper than escalating.</li>
<li><strong>Send a written demand.</strong> If that does not work, a clear letter stating the amount, the reason, and a deadline can move things along.</li>
<li><strong>Look into local resources.</strong> Many areas have tenant unions, legal aid organizations, or mediation services. Small claims court is an option in many places for modest amounts.</li>
</ol>
<p>Again, this is general information, not legal advice. If a significant amount is at stake, talk to someone who knows the law where the property is located.</p>

<h2>A quick checklist</h2>
<ul>
<li>Agree on the amount, holder, uses, and return timeline in writing</li>
<li>Pay by a traceable method and get a receipt</li>
<li>Photograph and video everything at move-in, and share it</li>
<li>Report issues during the stay in writing</li>
<li>Clean, photograph, and return keys at move-out</li>
<li>Get written confirmation of condition and the return date</li>
</ul>
