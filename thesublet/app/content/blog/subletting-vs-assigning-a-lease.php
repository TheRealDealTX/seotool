<h2>Which one fits your situation?</h2>

<h3>Subletting usually fits when:</h3>
<ul>
<li>You are leaving temporarily, for a summer internship, a semester abroad, a travel assignment, or extended family time.</li>
<li>You want to keep your apartment and come back to it.</li>
<li>You are renting out one room in your apartment while you stay.</li>
<li>You want control over who lives in your home while you are gone.</li>
</ul>

<h3>Assignment usually fits when:</h3>
<ul>
<li>You are moving away permanently, such as relocating for a new job.</li>
<li>There is a long time left on your lease.</li>
<li>Someone wants to take over the apartment for the remaining term.</li>
<li>You do not want an ongoing relationship with the new occupant.</li>
</ul>
<p>If you are relocating and need temporary housing at the other end, our guide on <a href="/blog/relocating-for-work-temporary-housing/">relocating for work</a> may help.</p>

<h2>Other options to consider</h2>
<p>Subletting and assignment are not the only ways out of a lease. Depending on your lease and local law, you might also:</p>
<ul>
<li><strong>Negotiate an early termination</strong> with your landlord, sometimes in exchange for a fee or helping find a replacement tenant.</li>
<li><strong>Use a lease-break clause</strong> if your lease includes one.</li>
<li><strong>Rely on specific legal protections</strong> that some places provide in certain situations, such as for active-duty military members under federal law, or for survivors of domestic violence in some states.</li>
</ul>
<p>In some states, landlords also have a duty to make reasonable efforts to re-rent a unit if a tenant leaves early, which can limit what the departing tenant owes. Whether this applies to you depends on local law.</p>

<h2>Questions to ask your landlord</h2>
<p>Whatever you choose, ask in writing and keep records. Useful questions:</p>
<ol>
<li>Does my lease allow subletting, assignment, or both?</li>
<li>What is your approval process, and is there a fee?</li>
<li>Will you screen the new person, and what criteria do you use?</li>
<li>If I assign, will you release me from future liability in writing?</li>
<li>Would you prefer to sign a new lease with the incoming tenant instead?</li>
<li>What happens to my security deposit?</li>
</ol>

<h2>What about the security deposit?</h2>
<p>Deposits get tricky in both arrangements.</p>
<ul>
<li><strong>Subletting:</strong> Your original deposit usually stays with the landlord, tied to your lease. You may collect a separate deposit from your subtenant. See <a href="/blog/security-deposits-for-sublets/">security deposits for sublets</a>.</li>
<li><strong>Assignment:</strong> Some tenants arrange for the assignee to reimburse them for the deposit, with the landlord continuing to hold it for the new tenant. Others ask the landlord to return their deposit and collect a new one from the assignee. Get whatever you agree to in writing, with the landlord's sign-off.</li>
</ul>

<h2>Practical tips either way</h2>
<ul>
<li><strong>Read your lease first.</strong> Look for sections on subletting, assignment, and occupancy.</li>
<li><strong>Get landlord consent in writing,</strong> naming the new person and dates.</li>
<li><strong>Screen fairly.</strong> Apply consistent, lawful criteria to every candidate and never reject someone based on a protected characteristic.</li>
<li><strong>Document the unit's condition</strong> with date-stamped photos at handover.</li>
<li><strong>Keep copies</strong> of every agreement, email, and payment record.</li>
</ul>
