<p>If you need to leave your apartment before your lease ends, you will probably hear two terms: <strong>subletting</strong> and <strong>assigning</strong> your lease. They sound similar, and people often use them interchangeably, but they generally work quite differently, especially when it comes to who is responsible if something goes wrong.</p>
<p>Understanding the difference helps you choose the right option, ask your landlord for the right thing, and avoid surprises later.</p>
<p><em>This article is general information, not legal advice. The legal definitions and consequences of subletting and assignment vary by state, and your lease may define these terms in its own way. Check your lease and local law, and consult a local attorney or tenant organization for advice about your situation.</em></p>

<h2>The short answer</h2>
<p>In general terms:</p>
<ul>
<li><strong>Subletting</strong> means you rent all or part of your place to someone else for part of your remaining lease term, while you remain the tenant. You become, in effect, the subtenant's landlord. Usually you plan to come back, or at least you keep your relationship with the landlord.</li>
<li><strong>Assigning</strong> means you transfer your entire remaining interest in the lease to someone else. The new person (the "assignee") steps into your shoes and deals directly with the landlord for the rest of the lease. You are not coming back.</li>
</ul>

<h2>How subletting usually works</h2>
<p>In a typical sublet:</p>
<ul>
<li>You keep your lease with the landlord.</li>
<li>You sign a separate agreement, a sublease, with the subtenant.</li>
<li>The subtenant usually pays rent to you, and you keep paying the landlord.</li>
<li>The sublet ends on or before the end date of your lease, often when you return.</li>
<li>Your landlord may need to approve the arrangement, depending on your lease and local law.</li>
</ul>
<p>The key point: <strong>you generally remain responsible to the landlord.</strong> If the subtenant stops paying, damages the unit, or breaks building rules, the landlord typically looks to you. You may then have a claim against your subtenant under your sublease, but that does not usually change what you owe the landlord.</p>
<p>That is why careful screening and a written sublease matter so much. See our <a href="/blog/sublease-agreement-what-to-include/">sublease agreement checklist</a> for what to include.</p>

<h2>How assignment usually works</h2>
<p>In a typical lease assignment:</p>
<ul>
<li>You transfer your remaining rights and obligations under the lease to the assignee.</li>
<li>The assignee pays rent directly to the landlord.</li>
<li>The assignee generally deals with the landlord directly for maintenance and other issues.</li>
<li>The assignment lasts for the rest of the lease term.</li>
<li>Landlord consent is very often required.</li>
</ul>
<p>Here is the part many people miss: <strong>assignment does not automatically release you from liability.</strong> In many places, unless the landlord specifically agrees to release you, the original tenant can remain responsible if the assignee fails to pay. The exact rules depend on your state's law and your lease.</p>
<p>If you want to be fully off the hook, ask the landlord for a written <strong>release</strong>, sometimes called a novation, in which the landlord agrees to accept the new tenant in your place and releases you from future obligations. Some landlords prefer to simply sign a new lease with the incoming tenant, which can have a similar effect.</p>

