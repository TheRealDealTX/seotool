<p>A sublease agreement is the document that turns "you can stay at my place this summer" into an arrangement both people actually understand. It does not need to be long or full of legal jargon. It does need to be specific. Most sublet disputes come from things nobody wrote down: who pays the electric bill, whether the deposit covers a cleaning fee, what happens if the subtenant needs to leave a month early.</p>
<p>This checklist walks through the clauses a solid sublease usually contains and explains why each one matters. Use it whether you are the original tenant (the "sublessor") or the person moving in (the "subtenant").</p>
<p><em>This is general information, not legal advice. Sublease rules vary by state and city, and your master lease may impose its own requirements. Check your lease and local law, and consider having a local attorney or tenant organization review your agreement.</em></p>

<h2>1. The parties</h2>
<p>List the full legal names of the sublessor and every adult subtenant who will live in the unit. Include current contact information for each. If the landlord has approved the sublet, it is helpful to name the landlord or management company too, so there is no confusion about who owns the property and who is renting from whom.</p>
<p><strong>Why it matters:</strong> If someone not named in the agreement moves in, the arrangement gets murky fast. Naming everyone also matters if you ever need to enforce the agreement.</p>

<h2>2. The property</h2>
<p>Give the full address, including unit number. If the sublet covers only part of a home, such as one bedroom in a shared apartment, describe exactly which room and which common areas the subtenant may use. Mention parking spaces, storage units, or bike rooms if they are included, and spell out anything that is off-limits, like a locked closet where you have stored your belongings.</p>

<h2>3. The term (dates)</h2>
<p>State the exact move-in date and move-out date, plus a time of day for each. "June 1 to August 31" is good; "June 1 at 3 p.m. to August 31 at 11 a.m." is better. Make sure the end date falls on or before the end of your own lease.</p>
<p>Address whether the subtenant can extend, and how. A common approach is that any extension must be agreed in writing and, if required, approved by the landlord.</p>

<h2>4. Rent: amount, due date, and method</h2>
<ul>
<li>The monthly rent amount, or the total for the full term.</li>
<li>The due date each month, and any grace period.</li>
<li>How rent should be paid. Traceable methods leave a clear record for both sides.</li>
<li>Any late fee, stated as a specific amount. Some places cap late fees, so check local rules.</li>
<li>How partial months are calculated. If the subtenant arrives mid-month, write down the prorated amount. The <a href="/tools/proration/">proration calculator</a> can do the math.</li>
</ul>
<p><strong>Why it matters:</strong> Ambiguity about money is the fastest way to sour a sublet. Writing down the exact dollar amounts removes most of the room for disagreement.</p>

<h2>5. Security deposit</h2>
<p>State the deposit amount, when it is due, where it will be held, and when and how it will be returned. List what the deposit may be used for, such as unpaid rent, damage beyond normal wear and tear, or replacing lost keys, and what it will not be used for. Many states have rules on deposit limits, return deadlines, and itemized deductions, and those rules may apply to sublets too.</p>
<p>For a deeper look, see our guide to <a href="/blog/security-deposits-for-sublets/">security deposits for sublets</a>.</p>

<h2>6. Utilities and other services</h2>
<p>This is where many sublets go wrong. Make a list of every recurring cost and say who pays it:</p>
<ul>
<li>Electricity and gas</li>
<li>Water, sewer, and trash (if not included in rent)</li>
<li>Internet and Wi-Fi</li>
<li>Streaming services or cable, if you are leaving them active</li>
<li>Parking, laundry cards, or amenity fees</li>
</ul>
<p>Decide whether utilities are included in rent at a flat rate, split by actual bills, or transferred to the subtenant's name. Flat-rate inclusion is simplest for short sublets, though it puts the risk of a high summer air-conditioning bill on you. If utilities are billed separately, say how the subtenant will see the bills and when payment is due.</p>

<h2>7. Reference to the master lease</h2>
<p>Attach a copy of your lease, or the relevant sections, and include a clause stating that the subtenant has read it and agrees to follow its terms. This covers building rules, pet policies, noise rules, and anything else in the original lease that the landlord expects every occupant to follow.</p>
<p>It is also smart to state that the sublease cannot give the subtenant any rights greater than what you have under the master lease, and that the sublease ends automatically if the master lease ends.</p>

<h2>8. Landlord consent</h2>
<p>If your lease requires landlord approval, attach the written consent or note the date it was given. Some landlords want to sign the sublease themselves. Either way, having consent documented protects both the sublessor and the subtenant.</p>

<h2>9. Condition report and inventory</h2>
<p>Before move-in, do a walkthrough together. Note the condition of floors, walls, appliances, fixtures, and furniture, and take date-stamped photos. For a furnished sublet, create a simple inventory: furniture, kitchen items, linens, electronics. Both people sign the report, and you repeat the process at move-out.</p>
<p><strong>Why it matters:</strong> Without a baseline, every scratch becomes an argument. With one, deposit decisions are usually straightforward.</p>

<h2>10. House rules</h2>
<p>Write down the expectations that matter to you and that are allowed under your lease. Typical topics:</p>
<ul>
<li>Guests and overnight visitors, including how long a guest may stay</li>
<li>Smoking and vaping</li>
<li>Pets (only if your lease allows them)</li>
<li>Quiet hours, especially in shared buildings</li>
<li>Care instructions for plants, special appliances, or delicate furniture</li>
<li>Rules for shared spaces if you have roommates who are staying</li>
</ul>
<p>Keep house rules reasonable and apply them to everyone equally. Rules must not discriminate based on characteristics protected by fair housing law. If roommates are staying in the unit, our guide to <a href="/blog/roommate-sublets-shared-housing-etiquette/">roommate sublet etiquette</a> has more ideas.</p>

<h2>11. Maintenance and repairs</h2>
<p>Explain who the subtenant should contact for a broken appliance, a leak, or a lockout. Usually the subtenant reports to the sublessor, who coordinates with the landlord, but for emergencies it can be faster to give the subtenant the building's maintenance line directly. State that the subtenant is responsible for damage they or their guests cause, beyond normal wear and tear.</p>

<h2>12. Keys and access</h2>
<p>List how many keys, fobs, or access codes are handed over, and what happens if they are lost. Agree on how much notice you will give before entering the unit yourself, and respect any notice requirements in your local law.</p>

<h2>13. Early termination</h2>
<p>Plans change. Decide in advance what happens if:</p>
<ul>
<li>The subtenant needs to leave early. Is there a notice period? Do they owe rent until a replacement is found?</li>
<li>The sublessor needs to return early. Is that allowed at all? With how much notice?</li>
<li>Either party seriously breaks the agreement, such as non-payment or a major rule violation.</li>
</ul>
<p>Any termination process must also comply with local law. A sublessor generally cannot simply change the locks on a subtenant, even with a short sublet.</p>

<h2>14. Move-out procedure</h2>
<p>Spell out what "moved out" means: keys returned, belongings removed, unit cleaned to a stated standard, trash taken out. Agree on a time for the final walkthrough. Our <a href="/blog/moving-out-checklist-for-sublets/">moving out checklist</a> is a handy attachment.</p>

<h2>15. Signatures and copies</h2>
<p>Everyone named signs and dates the agreement, and everyone keeps a copy. Electronic signatures are widely used and convenient.</p>

